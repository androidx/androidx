package androidx.build.vscode

import androidx.build.BuildEnvironment
import androidx.build.ProjectLayoutType
import androidx.build.ide.ManagedIdeTask
import androidx.build.ide.installVSCodeExtensions
import java.io.File
import java.net.URI
import org.gradle.api.GradleException
import org.gradle.api.Project
import org.gradle.api.provider.ValueSource
import org.gradle.api.provider.ValueSourceParameters

fun Project.configureVSCodeTask(task: ManagedIdeTask) {
    task.ideName.convention("VSCode")
    task.requiresProjectList.convention(false)

    val vsCodeConfigBaseDir =
        layout.dir(providers.environmentVariable("HOME").map { File(it, ".VSCodeAndroidX") })
    val userDataDir = vsCodeConfigBaseDir.map { it.dir("user-data") }
    val extensionsDir = vsCodeConfigBaseDir.map { it.dir("extensions") }

    val vsCodeVersionProvider = providers.of(LatestVSCodeVersionSource::class.java) {}

    val ext = if (task.osName == "linux") "tar.gz" else "zip"
    task.ideArchiveName.convention(
        vsCodeVersionProvider.map { version -> "vscode-$version-${task.osName}.$ext" }
    )

    val vscodePlatform = task.vscodePlatform
    task.archiveUrl.convention(
        vsCodeVersionProvider.map { version ->
            "https://update.code.visualstudio.com/$version/$vscodePlatform/stable"
        }
    )
    task.licenseAgreementPath.convention("https://code.visualstudio.com/license")

    task.ideBinaryRelativePath.convention(
        if (task.osName == "linux") "bin/code" else "Contents/Resources/app/bin/code"
    )

    val projectDir = layout.projectDirectory.asFile
    val dirs = userDataDir.zip(extensionsDir) { uDir, eDir -> Pair(uDir, eDir) }
    task.launchArguments.convention(
        dirs.map { (uDir, eDir) ->
            listOf(
                "--user-data-dir",
                uDir.asFile.absolutePath,
                "--extensions-dir",
                eDir.asFile.absolutePath,
                projectDir.absolutePath,
            )
        }
    )

    task.provisionAction.set {
        val jdkPath =
            it.providers.environmentVariable(BuildEnvironment.ANDROIDX_JDK21).orNull
                ?: throw GradleException(
                    "${BuildEnvironment.ANDROIDX_JDK21} is not set; " +
                        "VS Code must be launched via ./gradlew :vscode"
                )
        val settingsFile =
            File(it.projectRoot, ".vscode/settings.json").apply { parentFile.mkdirs() }
        val escapedJdk = jdkPath.replace("\\", "\\\\").replace("\"", "\\\"")
        settingsFile.writeText(
            """
            // Generated by ./gradlew :vscode - do not edit.
            {
                "java.jdt.ls.java.home": "$escapedJdk",
                "java.import.gradle.java.home": "$escapedJdk",
                "gradle.javaHome": "$escapedJdk"
            }
            """
                .trimIndent()
        )

        it.installVSCodeExtensions(
            extensionsDir = extensionsDir.get().asFile.apply { mkdirs() },
            userDataDir = userDataDir.get().asFile.apply { mkdirs() },
            extensionIds = listOf("jetbrains.kotlin-server", "vscjava.vscode-gradle"),
        )
    }
}

fun Project.registerVSCodeTask() {
    if (ProjectLayoutType.from(this) == ProjectLayoutType.PLAYGROUND) return
    tasks.register("vscode", ManagedIdeTask::class.java) { task -> configureVSCodeTask(task) }
}

abstract class LatestVSCodeVersionSource : ValueSource<String, ValueSourceParameters.None> {
    override fun obtain(): String? {
        try {
            val url = URI.create("https://update.code.visualstudio.com/api/releases/stable").toURL()
            val connection = url.openConnection()
            val json = connection.getInputStream().bufferedReader().use { it.readText() }
            val match = Regex("\"([^\"]+)\"").find(json)
            val version = match?.groupValues?.get(1)
            return version
                ?: throw GradleException("Could not parse VSCode version from API response: $json")
        } catch (e: Exception) {
            throw GradleException("Failed to fetch latest VSCode version from API", e)
        }
    }
}

private val ManagedIdeTask.vscodePlatform: String
    get() =
        when (osName) {
            "mac_arm" -> "darwin-arm64"
            "mac" -> "darwin"
            "linux" -> "linux-x64"
            else -> throw GradleException("Unsupported OS: $osName")
        }
