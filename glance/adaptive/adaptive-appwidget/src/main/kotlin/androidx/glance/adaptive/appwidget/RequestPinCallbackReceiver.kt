package androidx.glance.adaptive.appwidget

import android.app.PendingIntent
import android.appwidget.AppWidgetManager
import android.content.BroadcastReceiver
import android.content.Context
import android.content.Intent
import android.net.Uri
import android.os.Bundle
import android.util.Log
import java.util.UUID
import kotlin.coroutines.CoroutineContext
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.delay

/**
 * Stores the widgetId and options requested through [requestPin] once the launcher has pinned the
 * widget.
 *
 * [AppWidgetManager.requestPinAppWidget] only hands its extras to the launcher, and the appWidgetId
 * of the pinned widget is not known until the launcher accepts the request. The requested options
 * therefore travel inside the request's callback instead, which the platform sends once, with the
 * new appWidgetId, and are written to the options of the new widget here.
 *
 * The write uses [updateOptionsAndRerender], so that the widget is updated for its requested
 * widgetId even if [GlanceAdaptiveWidgetReceiver] already updated it with a fallback one. A failed
 * write is retried a few times while the broadcast is kept alive, then logged: no developer code
 * runs here to report it to. The widget then keeps its fallback widgetId, as when the platform
 * never sends the callback.
 *
 * This receiver is not exported, so other apps cannot change the options of this app's widgets
 * through it.
 */
internal class RequestPinCallbackReceiver
internal constructor(
    private val appWidgetManagerProvider: (Context) -> AppWidgetManager,
    private val coroutineContext: CoroutineContext,
    private val retryDelayMillis: Long,
) : BroadcastReceiver() {

    constructor() : this(AppWidgetManager::getInstance, Dispatchers.Default, RETRY_DELAY_MILLIS)

    override fun onReceive(context: Context, intent: Intent) {
        val appWidgetId =
            intent.getIntExtra(
                AppWidgetManager.EXTRA_APPWIDGET_ID,
                AppWidgetManager.INVALID_APPWIDGET_ID,
            )
        if (appWidgetId == AppWidgetManager.INVALID_APPWIDGET_ID) {
            Log.e(
                TAG,
                "The launcher pinned a widget without reporting its appWidgetId, so the " +
                    "requested widgetId and options cannot be stored. The widget keeps the " +
                    "widgetId generated by GlanceAdaptiveWidgetReceiver.",
            )
            return
        }
        val options = intent.getBundleExtra(EXTRA_OPTIONS)
        if (options == null) {
            // Not expected from callbacks created by createCallback, but never ignored silently.
            Log.e(
                TAG,
                "The pin callback for appWidgetId $appWidgetId carries no options to store. The " +
                    "widget keeps the widgetId generated by GlanceAdaptiveWidgetReceiver.",
            )
            return
        }
        val appWidgetManager = appWidgetManagerProvider(context)
        val firstFailure =
            try {
                storeOptions(context, appWidgetManager, appWidgetId, options)
                return
            } catch (e: Exception) {
                e
            }
        goAsync(coroutineContext) {
            retryStoringOptions(context, appWidgetManager, appWidgetId, options, firstFailure)
        }
    }

    /**
     * Stores [options] in the options of [appWidgetId] and updates the widget with them, unless the
     * widget was removed in the meantime, leaving nothing to store.
     */
    private fun storeOptions(
        context: Context,
        appWidgetManager: AppWidgetManager,
        appWidgetId: Int,
        options: Bundle,
    ) {
        val provider = appWidgetManager.getAppWidgetInfo(appWidgetId)?.provider ?: return
        appWidgetManager.updateOptionsAndRerender(context, provider, appWidgetId, options)
    }

    /**
     * Retries storing [options] after the first attempt failed with [firstFailure], with a growing
     * delay, and logs the last failure if every attempt fails.
     */
    private suspend fun retryStoringOptions(
        context: Context,
        appWidgetManager: AppWidgetManager,
        appWidgetId: Int,
        options: Bundle,
        firstFailure: Exception,
    ) {
        var lastFailure = firstFailure
        for (attempt in 2..MAX_ATTEMPTS) {
            delay(retryDelayMillis * (attempt - 1))
            try {
                storeOptions(context, appWidgetManager, appWidgetId, options)
                return
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                lastFailure = e
            }
        }
        Log.e(
            TAG,
            "Error storing widgetId " +
                "${options.getString(GlanceAdaptiveWidgetReceiver.EXTRA_WIDGET_ID)} for " +
                "appWidgetId $appWidgetId after $MAX_ATTEMPTS attempts. The widget keeps the " +
                "widgetId generated by GlanceAdaptiveWidgetReceiver.",
            lastFailure,
        )
    }

    companion object {
        private const val TAG = "RequestPinCallback"
        private const val EXTRA_OPTIONS = "androidx.glance.adaptive.appwidget.extra.PIN_OPTIONS"

        /** Number of attempts to store the requested options, including the first one. */
        internal const val MAX_ATTEMPTS = 3

        /** Delay before the first retry, which grows linearly with every further retry. */
        private const val RETRY_DELAY_MILLIS = 50L

        /**
         * Creates the callback of a pin request, which stores [options] in the options of the
         * pinned widget.
         */
        fun createCallback(context: Context, options: Bundle): PendingIntent {
            val intent =
                Intent(context, RequestPinCallbackReceiver::class.java)
                    // Unique data keeps concurrent requests from sharing, and overwriting, a single
                    // PendingIntent.
                    .setData(Uri.parse("androidx-glance-adaptive-pin://${UUID.randomUUID()}"))
                    // Nested in a single extra, so that the platform can add the appWidgetId
                    // without unparcelling the options.
                    .putExtra(EXTRA_OPTIONS, options)
            return PendingIntent.getBroadcast(
                context,
                /* requestCode= */ 0,
                intent,
                // Mutable so that the platform can add the new appWidgetId, which is safe because
                // the intent is explicit. One shot, as the request is accepted at most once.
                PendingIntent.FLAG_MUTABLE or PendingIntent.FLAG_ONE_SHOT,
            )
        }
    }
}
