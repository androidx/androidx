package androidx.camera.core.processing.util

import androidx.camera.core.DynamicRange
import androidx.camera.core.processing.util.GLUtils.InputFormat
import com.google.common.truth.Truth.assertThat
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config
import org.robolectric.annotation.internal.DoNotInstrument

/**
 * Unit tests for the shader source generated by [ShaderProviders].
 *
 * Compiling and running the shaders requires a GPU and is covered by the instrumentation tests.
 */
@RunWith(RobolectricTestRunner::class)
@DoNotInstrument
@Config(sdk = [Config.ALL_SDKS])
class ShaderProvidersTest {

    @Test
    fun hdrYuvFragmentShader_selectsConversionByInputRange() {
        val shader =
            ShaderProviders.createFragmentShaderInternal(
                samplerVarName = "sTexture",
                fragCoordsVarName = "vTextureCoord",
                isHdr = true,
                isYuvHdr = true,
            )
        assertThat(shader).contains("uniform int ${ShaderProviders.UNIFORM_IS_INPUT_FULL_RANGE};")
        assertThat(shader).contains("BT2020_FULL_RANGE_YUV_TO_RGB")
        assertThat(shader).contains("BT2020_LIMITED_RANGE_YUV_TO_RGB")
        // Full range (uniform == 1) has no Y black level offset; limited range has 64/1024. Check
        // that each offset and matrix is in the right branch, not only that they exist.
        val fullRangeBranch =
            shader
                .substringAfter("${ShaderProviders.UNIFORM_IS_INPUT_FULL_RANGE} == 1) {")
                .substringBefore("} else {")
        val limitedRangeBranch = shader.substringAfter("} else {").substringBefore("}")
        assertThat(fullRangeBranch).contains("vec3(0.0, 0.5, 0.5)")
        assertThat(fullRangeBranch).contains("BT2020_FULL_RANGE_YUV_TO_RGB")
        assertThat(limitedRangeBranch).contains("vec3(0.0625, 0.5, 0.5)")
        assertThat(limitedRangeBranch).contains("BT2020_LIMITED_RANGE_YUV_TO_RGB")
    }

    @Test
    fun sdrFragmentShader_doesNotDeclareInputRangeUniform() {
        val shader =
            ShaderProviders.createFragmentShaderInternal(
                samplerVarName = "sTexture",
                fragCoordsVarName = "vTextureCoord",
                isHdr = false,
            )
        assertThat(shader).doesNotContain(ShaderProviders.UNIFORM_IS_INPUT_FULL_RANGE)
    }

    @Test
    fun isYuvHdr_onlyTrueForHdrYuvInput() {
        assertThat(ShaderProviders.isYuvHdr(DynamicRange.HLG_10_BIT, InputFormat.YUV)).isTrue()
        assertThat(ShaderProviders.isYuvHdr(DynamicRange.HLG_10_BIT, InputFormat.DEFAULT)).isFalse()
        assertThat(ShaderProviders.isYuvHdr(DynamicRange.SDR, InputFormat.YUV)).isFalse()
    }
}
