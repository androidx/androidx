/**
 * Machine-generated exhaustive branch-coverage tests for [AnnotatedString], [ParagraphStyle],
 * [SpanStyle], and [TextStyle].
 *
 * ### Generation Methodology
 * These test cases were generated by running the Kex symbolic and concolic bytecode analysis engine
 * backed by KSMT SMT solvers (`Z3` and `Bitwuzla`) on the compiled JVM bytecode both **before**
 * (`kex_before_*`) and **after** (`kex_after_*`) the bit-packed representation changes:
 * 1. **Bytecode-to-SMT Lifting**: Kex lifts each target method's JVM bytecode into Static Single
 *    Assignment (`SSA`) form and encodes every `if`, `when`, bitmask check, and IEEE-754 float
 *    comparison as a quantifier-free bit-vector and floating-point (`QF_BVFP`) path predicate.
 * 2. **All-Path Symbolic Exploration**: For every conditional branch in the control-flow graph, the
 *    SMT solver searches for a concrete input assignment (including boundary values such as
 *    `Int.MIN_VALUE`, `Float.NaN`, `-0.0f`, `Color.Unspecified`, and packed bitfield combinations)
 *    that forces execution through that exact branch.
 * 3. **1:1 Test Synthesis**: Each solver witness model is emitted as a deterministic,
 *    reflection-free JUnit `@Test` method named `kex_<before|after>_<Class>_<method>_<pathId>_*`.
 *
 * ### Purpose of Checking Before/After All-Path Conditional Branches
 * Packing [ParagraphStyle], [SpanStyle], and [AnnotatedString] replaces field-by-field conditional
 * trees with branchless SWAR bit arithmetic, sentinel encodings, and optional `Extras` sidecars,
 * which restructures the control-flow graph:
 * - **`kex_before_*` tests** replay the exhaustive branch witness inputs derived from the legacy
 *   field-per-property control flow against the new implementation, proving that every conditional
 *   corner case of the original code continues to produce the exact same observable result.
 * - **`kex_after_*` tests** exercise every newly introduced conditional branch in the packed fast
 *   paths, `Extras` sidecar deduplication checks, and `Legacy*` fallback guards, ensuring 100% of
 *   reachable branches in both the old and new control-flow graphs are verified.
 */
