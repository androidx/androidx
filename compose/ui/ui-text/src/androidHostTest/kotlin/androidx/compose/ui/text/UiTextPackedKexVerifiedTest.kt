    @Test
    fun kex_after_JvmAnnotatedStringHarness_transformRangesPostMerge_178350032714_lazyOffsetMapBackfillAndRemap() {
        // Kex: JvmAnnotatedStringHarness_transformRangesPostMerge_178350032714
        // Verifies lazy offsetMap allocation when a segment changes length after an identity
        // prefix,
        // backfilling cuts[0 until i] as identity (cuts[j] -> cuts[j]) and remapping subsequent
        // cuts.
        val b = AnnotatedString.Builder("aaabbbccc")
        b.addStyle(SpanStyle(color = Color.Red), 0, 3) // [0, 3]: "aaa" -> "AAA" (len 3, 1:1 prefix)
        b.addStyle(
            SpanStyle(color = Color.Blue),
            3,
            6,
        ) // [3, 6]: "bbb" -> "BBBBBB" (len 6, triggers offsetMap allocation & backfill of 0, 3)
        b.addStyle(
            SpanStyle(color = Color.Green),
            6,
            9,
        ) // [6, 9]: "ccc" -> "C" (len 1, maps 9 -> 10)
        b.addStringAnnotation("tag", "full", 0, 9)
        b.addStringAnnotation("tag", "midToEnd", 3, 9)
        val input = b.toAnnotatedString()

        val transformed = input.transform { str, start, end ->
            when (start) {
                0 -> str.substring(start, end).uppercase()
                // length 6 (cut=6 != resultStr.length=9 -> allocates offsetMap, backfills 0->0,
                // 3->3, puts 6->9)
                3 -> "BBBBBB"
                6 -> "C"
                else -> error("Unexpected slice $start..$end")
            }
        }

        assertEquals("AAABBBBBBC", transformed.text)
        assertEquals(
            listOf(
                AnnotatedString.Range(SpanStyle(color = Color.Red), 0, 3),
                AnnotatedString.Range(SpanStyle(color = Color.Blue), 3, 9),
                AnnotatedString.Range(SpanStyle(color = Color.Green), 9, 10),
            ),
            transformed.spanStyles,
        )
        assertEquals(
            listOf(
                AnnotatedString.Range("full", 0, 10, "tag"),
                AnnotatedString.Range("midToEnd", 3, 10, "tag"),
            ),
            transformed.getStringAnnotations(0, 10),
        )
    }
