package androidx.compose.remote.creation.compose.modifier

import androidx.annotation.IntRange
import androidx.annotation.RestrictTo
import androidx.compose.remote.creation.compose.state.RemoteStateScope
import androidx.compose.remote.creation.modifiers.RecordingModifier
import androidx.compose.runtime.Stable

/** Sentinel component ID indicating no explicit ID was assigned (auto-generated by the writer). */
internal const val UNSET_COMPONENT_ID: Int = -1

internal data class ComponentIdModifier(val id: Int) : RemoteModifier.Element {
    init {
        require(id > 0) { "Component ID must be greater than 0, got $id" }
    }

    override fun RemoteStateScope.toRecordingModifier(): RecordingModifier =
        RecordingModifier().componentId(id)

    override fun RemoteStateScope.toRecordingModifierElement(): RecordingModifier.Element =
        throw UnsupportedOperationException(
            "ComponentIdModifier cannot be represented as a RecordingModifier.Element; " +
                "use toRecordingModifier() instead."
        )
}

/**
 * Assigns an explicit component [id] to this layout component.
 *
 * * Note: [id] must be strictly positive (`> 0`). `0` and negative IDs are reserved (`0` is used as
 *   a sentinel for unset/disabled references, `-1` is the auto-generation sentinel, and `-2`, `-3`,
 *   ... are auto-generated component IDs).
 * * Note: If multiple `componentId` modifiers are chained, the first (outermost) one takes
 *   precedence.
 *
 * @param id positive identifier (`> 0`) to assign to this component
 * @return a [RemoteModifier] that assigns [id] to the component
 * @throws IllegalArgumentException if [id] is not greater than `0`
 */
// TODO(b/590744731): Address componentId collision issues before making this public.
@RestrictTo(RestrictTo.Scope.LIBRARY_GROUP)
@Stable
public fun RemoteModifier.componentId(@IntRange(from = 1) id: Int): RemoteModifier =
    then(ComponentIdModifier(id))
