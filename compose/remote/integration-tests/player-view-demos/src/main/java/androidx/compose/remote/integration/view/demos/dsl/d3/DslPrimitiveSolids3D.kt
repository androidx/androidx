private const val QPI = (Math.PI / 4.0).toFloat()
private const val HPI = (Math.PI / 2.0).toFloat()

// A small turned-urn profile (radius-from-axis, height) for the lathe tile, centered on y=0.
private val LATHE_URN =
    floatArrayOf(
        0.00f,
        -0.45f, // base center (closes the bottom)
        0.28f,
        -0.45f, // base rim
        0.22f,
        -0.22f,
        0.12f,
        0.00f, // waist
        0.28f,
        0.24f, // shoulder
        0.16f,
        0.42f, // neck
        0.00f,
        0.48f, // top (closes)
    )

/**
 * Demo of the `MeshPrimitive` op: a gallery of parametric solids — sphere, cylinder, cone, cube,
 * rounded cube, spherical dome, spherical sector, tube, capped tube, torus, **icosphere**
 * (geodesic, uniform triangles), a **lathe** (a profile revolved into an urn), a **sweep** (a
 * square section lofted up a path with twist → a twisted column) and a **helix** (a spring) — each
 * generated by the single op (geometry math in `Primitive3D`), colored, and spun in place. The
 * whole set is one launch, so it doubles as a quick visual smoke-test that every generator works.
 * Smooth-shaded software backend.
 */
@Suppress("RestrictedApiAndroidX")
public fun primitiveSolids3D(mode: RcMeshMode): ByteArray {
    val colors =
        intArrayOf(
            0xFFE0492E.toInt(), // sphere – red
            0xFFE8902E.toInt(), // cylinder – orange
            0xFFE8C72E.toInt(), // cone – yellow
            0xFF5FB033.toInt(), // cube – green
            0xFF36A89A.toInt(), // rounded cube – teal
            0xFF3D7FE0.toInt(), // dome – blue
            0xFF8E4CE0.toInt(), // sector – purple
            0xFFE0509A.toInt(), // tube – pink
            0xFF9098A4.toInt(), // cap tube – gray
            0xFFD23B6E.toInt(), // torus – magenta
            0xFF2EB8C7.toInt(), // icosphere – cyan
            0xFFB5832E.toInt(), // lathe – bronze
            0xFF8E5BE0.toInt(), // sweep – violet
            0xFFBFC4CC.toInt(), // helix – silver
        )

    return createRcBuffer(RcProfile(RcPlatformProfiles.ANDROIDX, isExperimental = true)) {
        val spin = continuousSeconds() * 0.6f
        Box(modifier = Modifier.fillMaxSize()) {
            Canvas(modifier = Modifier.fillMaxSize().background(0xFF12151B.toInt())) {
                paint { color(0xFFFFFFFF.toInt()) }
                scene3D {
                    // Tube/cap-tube share a wavy path.
                    val path =
                        floatArrayOf(
                            -0.45f,
                            -0.4f,
                            0f,
                            -0.15f,
                            0.35f,
                            0.1f,
                            0.2f,
                            -0.25f,
                            -0.1f,
                            0.45f,
                            0.4f,
                            0f,
                        )
                    // Sweep tile: a square cross-section swept up a straight path with a half-turn
                    // of per-station twist + end caps → a twisted square column.
                    val barStations = 11
                    val barPath = FloatArray(barStations * 3)
                    val barTwist = FloatArray(barStations)
                    for (s in 0 until barStations) {
                        val f = s / (barStations - 1f)
                        barPath[s * 3 + 1] = -0.45f + 0.9f * f
                        barTwist[s] = f * Math.PI.toFloat()
                    }
                    val barSection =
                        floatArrayOf(-0.16f, -0.16f, 0.16f, -0.16f, 0.16f, 0.16f, -0.16f, 0.16f)

                    // `segments` divides each shape: e.g. cylinder=3 → triangular prism,
                    // cone=4 → square pyramid. The two tubes contrast the legacy faceted polyline
                    // (pink) with the default monotonic-spline path, disks normal to the tangent
                    // (gray, smooth curve through the same points).
                    val meshes: Array<RcMesh> =
                        arrayOf(
                            primitiveSphere(1, 0.45f, segments = 20f),
                            primitiveCylinder(2, 0.28f, 0f, -0.5f, 0f, 0f, 0.5f, 0f, segments = 3f),
                            primitiveCone(3, 0.4f, 0.9f, 0f, -0.45f, 0f, segments = 4f),
                            primitiveCube(4, 0.7f, 0.7f, 0.7f),
                            primitiveRoundedCube(5, 0.75f, 0.75f, 0.75f, 0.16f),
                            primitiveSphericalDome(6, 0.5f, HPI, 0f, -0.3f, 0f),
                            primitiveSphericalSector(7, 0.5f, QPI, segments = 6f),
                            primitiveTube(8, 0.13f, path, capped = false, legacy = true),
                            primitiveTube(9, 0.13f, path, segments = 23f, capped = true),
                            primitiveTorus(10, 0.42f, 0.16f),
                            // Geodesic sphere — uniform triangles (compare with the lat/long sphere
                            // in the top-left); and a lathe (a small turned urn from a profile).
                            primitiveIcosphere(11, 0.45f, segments = 2f),
                            primitiveLathe(12, LATHE_URN, segments = 40f),
                            primitiveSweep(
                                13,
                                barSection,
                                barPath,
                                closed = true,
                                caps = true,
                                twists = barTwist,
                            ),
                            // A coil/spring: a tube swept along a generated helix (built on sweep).
                            primitiveHelix(14, 0.30f, 0.07f, 0.22f, 3f, segments = 10f),
                        )

                    perspectiveCameraDeg(
                        fovYDeg = 36f,
                        aspect = 1f,
                        near = 0.1f,
                        far = 100f,
                        eye = vec(RcFloat(1.7f), RcFloat(1.4f), RcFloat(9.8f)),
                        center = vec(RcFloat(0f), RcFloat(0f), RcFloat(0f)),
                        up = floatArrayOf(0f, 1f, 0f),
                    )

                    clearDepth()
                    clearLights()
                    directionalLight(
                        direction = vec(RcFloat(-0.35f), RcFloat(-0.6f), RcFloat(-0.7f)),
                        color = 0xFFFFFFFF.toInt(),
                        intensity = RcFloat(0.85f),
                    )
                    directionalLight(
                        direction = vec(RcFloat(0.6f), RcFloat(-0.1f), RcFloat(0.4f)),
                        color = 0xFF8090C0.toInt(),
                        intensity = RcFloat(0.4f),
                    )

                    val cols = 5
                    val rows = (meshes.size + cols - 1) / cols
                    val pitch = 1.3f
                    for (i in meshes.indices) {
                        val col = i % cols
                        val row = i / cols
                        val gx = (col - (cols - 1) * 0.5f) * pitch
                        val gy = ((rows - 1) * 0.5f - row) * pitch
                        color(colors[i])
                        identity()
                        translate(gx, gy, 0f)
                        rotate(angleRad = spin, ax = 0f, ay = 1f, az = 0f)
                        drawMesh(meshes[i], mode = mode)
                    }
                }
            }
        }
    }
}

@Suppress("RestrictedApiAndroidX")
public fun primitiveSolids3DSoftware(): ByteArray = primitiveSolids3D(RcMeshMode.SoftwareSmooth)

@Suppress("RestrictedApiAndroidX")
public fun primitiveSolidsCanvas(): ByteArray = primitiveSolids3D(RcMeshMode.CanvasSmooth)

