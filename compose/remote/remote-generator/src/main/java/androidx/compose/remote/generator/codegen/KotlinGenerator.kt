    private fun appendReadBody(
        sb: StringBuilder,
        className: String,
        fields: List<SchemaField>,
        sparseParameters: List<SchemaSparseParam>?,
        props: List<AstProperty>,
    ) {
        val byteOrShortNames =
            fields.filter { it.type == "byte" || it.type == "short" }.map { it.name }.toSet()
        for (f in fields) {
            val bits = f.bits
            if (bits != null && f.unpackBits) {
                val rawVar = "raw_${f.name}"
                sb.append("            val $rawVar = buffer.readInt()\n")
                for (b in bits) {
                    val bName = sanitizeIdentifier(b.name)
                    val extract = CodegenExprUtils.extractBitExpr(rawVar, b, ExprLang.KOTLIN)
                    sb.append("            val $bName = $extract\n")
                }
                continue
            }

            val fName = sanitizeIdentifier(f.name)
            val isNullable =
                f.derivedFrom == null &&
                    f.presentIf != null &&
                    !f.type.endsWith("[]") &&
                    f.defaultValue == null
            val fallback = mapToKotlinDefault(f.type, isNullable, f.defaultValue)

            if (f.presentIf != null) {
                val cond =
                    CodegenExprUtils.translateCondition(
                        f.presentIf,
                        ExprLang.KOTLIN,
                        needsKotlinIntCast = { it in byteOrShortNames },
                    ) {
                        sanitizeIdentifier(it)
                    }
                if (f.type.endsWith("[]")) {
                    sb.append("            val $fName =\n")
                    appendFormattedIfHeader(sb, "                ", cond)
                    appendArrayReadLines(sb, f, "                    ")
                    sb.append("                } else {\n")
                    sb.append("                    $fallback\n")
                    sb.append("                }\n")
                } else {
                    val readExpr = mapToKotlinScalarReadExpr(f.type, f.maxLength)
                    sb.append("            val $fName =\n")
                    appendFormattedIfHeader(sb, "                ", cond)
                    if (f.strictEnum && !f.enumValues.isNullOrEmpty()) {
                        sb.append("                    val parsed = $readExpr\n")
                        appendStrictEnumCheck(sb, className, f, "parsed", "                    ")
                        sb.append("                    parsed\n")
                    } else {
                        sb.append("                    $readExpr\n")
                    }
                    sb.append("                } else {\n")
                    sb.append("                    $fallback\n")
                    sb.append("                }\n")
                }
            } else if (f.addedVersion != null) {
                val readExpr = mapToKotlinScalarReadExpr(f.type, f.maxLength)
                sb.append("            val $fName =\n")
                sb.append(
                    "                if (apiLevel >= ${f.addedVersion} && buffer.available()) {\n"
                )
                if (f.strictEnum && !f.enumValues.isNullOrEmpty()) {
                    sb.append("                    val parsed = $readExpr\n")
                    appendStrictEnumCheck(sb, className, f, "parsed", "                    ")
                    sb.append("                    parsed\n")
                } else {
                    sb.append("                    $readExpr\n")
                }
                sb.append("                } else {\n")
                sb.append("                    $fallback\n")
                sb.append("                }\n")
            } else if (f.type.endsWith("[]")) {
                sb.append("            val $fName = run {\n")
                appendArrayReadLines(sb, f, "                ")
                sb.append("            }\n")
            } else {
                val readExpr = mapToKotlinScalarReadExpr(f.type, f.maxLength)
                sb.append("            val $fName = $readExpr\n")
                if (f.strictEnum && !f.enumValues.isNullOrEmpty()) {
                    appendStrictEnumCheck(sb, className, f, fName, "            ")
                }
            }
        }

        val usesSharedSparse =
            sparseParameters != null &&
                sharedSparseParams.isNotEmpty() &&
                sharedSparseParams.all { s ->
                    sparseParameters.any {
                        it.id == s.id && it.name == s.name && it.type == s.type
                    }
                }

        if (sparseParameters != null && usesSharedSparse) {
            val uniqueSparse = sparseParameters.filter { it.id !in sharedSparseIds }
            for (sp in uniqueSparse) {
                val spName = sanitizeIdentifier(sp.name)
                val spType = mapToKotlinType(sp.type, isNullable = true)
                sb.append("            var $spName: $spType = null\n")
            }
            sb.append("            val sharedSparse = SharedSparseParams()\n")
            sb.append("            val sparseCount = buffer.readShort() and 0xFFFF\n")
            sb.append("            require(sparseCount <= buffer.remaining() / 2) {\n")
            sb.append(
                "                \"Sparse count \$sparseCount exceeds buffer (\${buffer.remaining()})\"\n"
            )
            sb.append("            }\n")
            sb.append("            repeat(sparseCount) {\n")
            sb.append("                val paramId = buffer.readByte() and 0xFF\n")
            sb.append("                if (!sharedSparse.read(paramId, buffer)) {\n")
            if (uniqueSparse.isEmpty()) {
                sb.append(
                    "                    throw IllegalArgumentException(\"Unknown sparse parameter ID: \$paramId\")\n"
                )
            } else {
                sb.append("                    when (paramId) {\n")
                for (sp in uniqueSparse) {
                    appendSparseWhenBranch(sb, sp, "                        ")
                }
                sb.append("                        else ->\n")
                sb.append(
                    "                            throw IllegalArgumentException(\"Unknown sparse parameter ID: \$paramId\")\n"
                )
                sb.append("                    }\n")
            }
            sb.append("                }\n")
            sb.append("            }\n")
            val nonSharedNames = sharedSparseParams.map { sanitizeIdentifier(it.name) }.toSet()
            val nonSharedProps = props.filter { sanitizeIdentifier(it.name) !in nonSharedNames }
            val argsStr =
                nonSharedProps.joinToString(", ") {
                    val pName = sanitizeIdentifier(it.name)
                    "$pName = $pName"
                }
            val singleCall = "            return sharedSparse.to$className($argsStr)"
            if (singleCall.length <= 100) {
                sb.append("$singleCall\n")
            } else {
                sb.append("            return sharedSparse.to$className(\n")
                for (p in nonSharedProps) {
                    val pName = sanitizeIdentifier(p.name)
                    sb.append("                $pName = $pName,\n")
                }
                sb.append("            )\n")
            }
            return
        }

        if (sparseParameters != null) {
            for (sp in sparseParameters) {
                val spName = sanitizeIdentifier(sp.name)
                val spType = mapToKotlinType(sp.type, isNullable = true)
                sb.append("            var $spName: $spType = null\n")
            }
            sb.append("            val sparseCount = buffer.readShort() and 0xFFFF\n")
            sb.append("            require(sparseCount <= buffer.remaining() / 2) {\n")
            sb.append(
                "                \"Sparse count \$sparseCount exceeds buffer (\${buffer.remaining()})\"\n"
            )
            sb.append("            }\n")
            sb.append("            repeat(sparseCount) {\n")
            sb.append("                when (val paramId = buffer.readByte() and 0xFF) {\n")
            for (sp in sparseParameters) {
                appendSparseWhenBranch(sb, sp, "                    ")
            }
            sb.append(
                "                    else -> throw IllegalArgumentException(\"Unknown sparse parameter ID: \$paramId\")\n"
            )
            sb.append("                }\n")
            sb.append("            }\n")
        }

        if (props.isEmpty()) {
            sb.append("            return $className()\n")
        } else if (props.size == 1) {
            val pName = sanitizeIdentifier(props[0].name)
            val single = "            return $className($pName = $pName)"
            if (single.length <= 100) {
                sb.append("$single\n")
            } else {
                sb.append("            return $className(\n")
                sb.append("                $pName = $pName,\n")
                sb.append("            )\n")
            }
        } else {
            sb.append("            return $className(\n")
            for (p in props) {
                val pName = sanitizeIdentifier(p.name)
                sb.append("                $pName = $pName,\n")
            }
            sb.append("            )\n")
        }
    }

    private fun appendSparseWhenBranch(
        sb: StringBuilder,
        sp: SchemaSparseParam,
        indent: String,
    ) {
        val spName = sanitizeIdentifier(sp.name)
        if (sp.type.endsWith("[]")) {
            sb.append("$indent${sp.id} -> {\n")
            val syntheticField =
                SchemaField(
                    name = sp.name,
                    type = sp.type,
                    description = sp.description,
                    enumValues = null,
                    lengthType = "ushort",
                )
            sb.append("$indent    $spName = run {\n")
            appendArrayReadLines(sb, syntheticField, "$indent        ")
            sb.append("$indent    }\n")
            sb.append("$indent}\n")
        } else {
            val readExpr = mapToKotlinScalarReadExpr(sp.type)
            val branchLine = "$indent${sp.id} -> $spName = $readExpr"
            if (branchLine.length <= 100) {
                sb.append("$branchLine\n")
            } else {
                sb.append("$indent${sp.id} ->\n")
                sb.append("$indent    $spName = $readExpr\n")
            }
        }
    }

    private fun appendSharedSparseHelper(sb: StringBuilder) {
        if (sharedSparseParams.isEmpty()) return
        sb.append("\n\nprivate class SharedSparseParams {\n")
        for (sp in sharedSparseParams) {
            val spName = sanitizeIdentifier(sp.name)
            val spType = mapToKotlinType(sp.type, isNullable = true)
            sb.append("    var $spName: $spType = null\n")
        }
        sb.append("\n    fun read(paramId: Int, buffer: WireBuffer): Boolean {\n")
        sb.append("        when (paramId) {\n")
        for (sp in sharedSparseParams) {
            appendSparseWhenBranch(sb, sp, "            ")
        }
        sb.append("            else -> return false\n")
        sb.append("        }\n")
        sb.append("        return true\n")
        sb.append("    }\n")

        val sharedNames = sharedSparseParams.map { sanitizeIdentifier(it.name) }.toSet()
        for (op in schema.operations) {
            val spList = op.sparseParameters ?: continue
            val matchesAll = sharedSparseParams.all { s ->
                spList.any { it.id == s.id && it.name == s.name && it.type == s.type }
            }
            if (!matchesAll) continue
            val className = "${op.name}Node"
            val props = op.astProperties
            val nonSharedProps = props.filter { sanitizeIdentifier(it.name) !in sharedNames }
            val paramsSig =
                nonSharedProps.joinToString(", ") { p ->
                    val pName = sanitizeIdentifier(p.name)
                    val pType = mapToKotlinType(p.type, p.isNullable)
                    "$pName: $pType"
                }
            val sigLine = "    fun to$className($paramsSig): $className ="
            if (sigLine.length <= 100) {
                sb.append("\n$sigLine\n")
            } else {
                sb.append("\n    fun to$className(\n")
                for (p in nonSharedProps) {
                    val pName = sanitizeIdentifier(p.name)
                    val pType = mapToKotlinType(p.type, p.isNullable)
                    sb.append("        $pName: $pType,\n")
                }
                sb.append("    ): $className =\n")
            }
            sb.append("        $className(\n")
            for (p in props) {
                val pName = sanitizeIdentifier(p.name)
                sb.append("            $pName = $pName,\n")
            }
            sb.append("        )\n")
        }
        sb.append("}\n")
    }

    private fun appendFormattedIfHeader(sb: StringBuilder, indent: String, cond: String) {
        val single = "${indent}if ($cond) {"
        if (single.length <= 100) {
            sb.append("$single\n")
        } else {
            val orParts = cond.split(" || ")
            sb.append("${indent}if (\n")
            for ((index, part) in orParts.withIndex()) {
                val partIndent = if (index == 0) "$indent    " else "$indent        "
                val suffix = if (index < orParts.size - 1) " ||" else ""
                sb.append("$partIndent$part$suffix\n")
            }
            sb.append("$indent) {\n")
        }
    }

    private fun appendStrictEnumCheck(
        sb: StringBuilder,
        className: String,
        f: SchemaField,
        varName: String,
        indent: String,
    ) {
        val enumValues = f.enumValues ?: return
        val sortedValues = enumValues.values.distinct().sorted()
        val checkExpr = if (f.type == "byte" || f.type == "short") "$varName.toInt()" else varName
        sb.append("${indent}when ($checkExpr) {\n")
        val caseIndent = "$indent    "
        sb.append("$caseIndent${sortedValues.joinToString(",\n$caseIndent")} -> Unit\n")
        val elseSingle =
            "$indent    else -> throw IllegalArgumentException(\"Invalid $className.${f.name}: \$$varName\")"
        if (elseSingle.length <= 100) {
            sb.append("$elseSingle\n")
        } else {
            sb.append("$indent    else ->\n")
            val msgExpr = "\"Invalid $className.${f.name}: \$$varName\""
            val throwSingle = "$indent        throw IllegalArgumentException($msgExpr)"
            if (throwSingle.length <= 100) {
                sb.append("$throwSingle\n")
            } else {
                sb.append("$indent        throw IllegalArgumentException(\n")
                sb.append("$indent            $msgExpr\n")
                sb.append("$indent        )\n")
            }
        }
        sb.append("$indent}\n")
    }

    private fun appendArrayReadLines(sb: StringBuilder, f: SchemaField, indent: String) {
        val lenExpr =
            if (f.countFrom != null) {
                sanitizeIdentifier(f.countFrom)
            } else {
                when (f.effectiveLengthType) {
                    "int" -> "buffer.readInt()"
                    "ushort" -> "buffer.readShort() and 0xFFFF"
                    else -> "buffer.readShort()"
                }
            }
        val elemType = f.type.removeSuffix("[]")
        val elemMinBytes = CodegenExprUtils.minWireElementBytes(elemType, schema)
        val remainingCap =
            if (elemMinBytes > 1) "buffer.remaining() / $elemMinBytes" else "buffer.remaining()"
        sb.append("${indent}val count = $lenExpr\n")
        sb.append("${indent}require(count >= 0) { \"Negative array length: \$count\" }\n")
        if (f.maxLength != null) {
            val maxSingle =
                "${indent}require(count <= ${f.maxLength}) { \"Array length \$count exceeds maximum (${f.maxLength})\" }"
            if (maxSingle.length <= 100) {
                sb.append("$maxSingle\n")
            } else {
                sb.append("${indent}require(count <= ${f.maxLength}) {\n")
                sb.append("$indent    \"Array length \$count exceeds maximum (${f.maxLength})\"\n")
                sb.append("$indent}\n")
            }
        }
        sb.append("${indent}require(count <= $remainingCap) {\n")
        sb.append("$indent    \"Array length \$count exceeds buffer (\${buffer.remaining()})\"\n")
        sb.append("$indent}\n")
        val elemCreation =
            when (f.type) {
                "int[]" -> "IntArray(count) { buffer.readInt() }"
                "short[]" -> "ShortArray(count) { buffer.readShort().toShort() }"
                "float[]",
                "float_or_id[]" -> "FloatArray(count) { Float.fromBits(buffer.readInt()) }"
                else -> "List(count) { $elemType.read(buffer, apiLevel) }"
            }
        sb.append("$indent$elemCreation\n")
    }

    private fun generateStructWriter(structDef: SchemaStruct): String {
        val sb = StringBuilder()
        val className = structDef.name
        sb.append("/** Serializes this [$className] into [buffer]. */\n")
        val sig =
            "internal fun $className.write(buffer: WireBuffer, targetApiLevel: Int = DEFAULT_DOCUMENT_API_LEVEL) {"
        if (sig.length <= 100) {
            sb.append("$sig\n")
        } else {
            sb.append("internal fun $className.write(\n")
            sb.append("    buffer: WireBuffer,\n")
            sb.append("    targetApiLevel: Int = DEFAULT_DOCUMENT_API_LEVEL,\n")
            sb.append(") {\n")
        }
        appendWriteFields(sb, structDef.fields, null, structDef.astProperties)
        sb.append("}")
        return sb.toString()
    }

    private fun generateOperationWriter(op: SchemaOperation): String {
        val sb = StringBuilder()
        val className = "${op.name}Node"
        val props = op.astProperties
        sb.append("/** Serializes this [$className] into [buffer]. */\n")
        val sig =
            "internal fun $className.write(buffer: WireBuffer, targetApiLevel: Int = DEFAULT_DOCUMENT_API_LEVEL) {"
        if (sig.length <= 100) {
            sb.append("$sig\n")
        } else {
            sb.append("internal fun $className.write(\n")
            sb.append("    buffer: WireBuffer,\n")
            sb.append("    targetApiLevel: Int = DEFAULT_DOCUMENT_API_LEVEL,\n")
            sb.append(") {\n")
        }
        val callArgs = mutableListOf("buffer", "targetApiLevel")
        for (p in props) {
            callArgs.add(sanitizeIdentifier(p.name))
        }
        val singleCall = "    write${op.name}Operation(${callArgs.joinToString(", ")})"
        if (singleCall.length <= 100) {
            sb.append("$singleCall\n")
        } else {
            sb.append("    write${op.name}Operation(\n")
            for (arg in callArgs) {
                sb.append("        $arg,\n")
            }
            sb.append("    )\n")
        }
        sb.append("}\n\n")

        val hasByteOrShort = props.any { it.type == "byte" || it.type == "short" }
        if (hasByteOrShort) {
            sb.append("@Suppress(\"NoByteOrShort\")\n")
        }
        val paramDecls = mutableListOf("buffer: WireBuffer", "targetApiLevel: Int")
        for (p in props) {
            val pName = sanitizeIdentifier(p.name)
            val ktType = mapToKotlinType(p.type, p.isNullable)
            paramDecls.add("$pName: $ktType")
        }
        val helperSig = "internal fun write${op.name}Operation(${paramDecls.joinToString(", ")}) {"
        if (helperSig.length <= 100) {
            sb.append("$helperSig\n")
        } else {
            sb.append("internal fun write${op.name}Operation(\n")
            for (decl in paramDecls) {
                sb.append("    $decl,\n")
            }
            sb.append(") {\n")
        }
        sb.append("    buffer.start($className.OPCODE)\n")
        appendWriteFields(sb, op.fields, op.sparseParameters, props)
        sb.append("}")
        return sb.toString()
    }

    private fun appendWriteFields(
        sb: StringBuilder,
        fields: List<SchemaField>,
        sparseParameters: List<SchemaSparseParam>?,
        props: List<AstProperty>,
    ) {
        val propByName = props.associateBy { it.name }
        val byteOrShortNames =
            fields.filter { it.type == "byte" || it.type == "short" }.map { it.name }.toSet()

        val omitZeroFields =
            fields.filter { it.omitIf != null && it.type == "float_or_id" }.map { it.name }.toSet()

        for (rawName in omitZeroFields) {
            val pName = sanitizeIdentifier(rawName)
            sb.append(
                "    val effective_$pName =\n" +
                    "        if ($pName != null && !$pName.isVariable && $pName.floatValue == 0f) {\n" +
                    "            null\n" +
                    "        } else {\n" +
                    "            $pName\n" +
                    "        }\n"
            )
        }

        fun effectiveVar(rawName: String): String {
            val base = sanitizeIdentifier(rawName)
            return if (rawName in omitZeroFields) "effective_$base" else base
        }

        for (f in fields) {
            val bits = f.bits
            if (bits != null && f.unpackBits) {
                val terms = mutableListOf<Pair<String, SchemaBitField>>()
                for (b in bits) {
                    val bName = sanitizeIdentifier(b.name)
                    if (b.derivedFrom != null) {
                        val expr =
                            derivedExprToKotlin(
                                DerivedExpr.parse(b.derivedFrom),
                                propByName,
                                ::effectiveVar,
                            )
                        sb.append("    val $bName = $expr\n")
                        terms.add(bName to b)
                    } else {
                        terms.add(bName to b)
                    }
                }
                val packed = CodegenExprUtils.packBitsExpr(terms, ExprLang.KOTLIN)
                val writeLine = "    buffer.writeInt($packed)"
                if (writeLine.length <= 100) {
                    sb.append("$writeLine\n")
                } else {
                    sb.append("    buffer.writeInt(\n")
                    sb.append("        $packed\n")
                    sb.append("    )\n")
                }
                continue
            }

            if (f.derivedFrom != null) {
                val fName = sanitizeIdentifier(f.name)
                val derivedVal =
                    derivedExprToKotlin(
                        DerivedExpr.parse(f.derivedFrom),
                        propByName,
                        ::effectiveVar,
                    )
                if (f.presentIf != null) {
                    val cond =
                        CodegenExprUtils.translateCondition(
                            f.presentIf,
                            ExprLang.KOTLIN,
                            needsKotlinIntCast = { it in byteOrShortNames },
                        ) {
                            sanitizeIdentifier(it)
                        }
                    appendFormattedIfHeader(sb, "    ", cond)
                    val writeStmt = mapToKotlinScalarWriteExpr(f.type, derivedVal)
                    sb.append("        $writeStmt\n")
                    sb.append("    }\n")
                } else {
                    sb.append("    val $fName = $derivedVal\n")
                    val writeStmt = mapToKotlinScalarWriteExpr(f.type, fName)
                    sb.append("    $writeStmt\n")
                }
                continue
            }

            val fName = effectiveVar(f.name)
            val prop = propByName[f.name]
            val isNullable = prop?.isNullable == true

            if (f.presentIf != null) {
                val cond =
                    CodegenExprUtils.translateCondition(
                        f.presentIf,
                        ExprLang.KOTLIN,
                        needsKotlinIntCast = { it in byteOrShortNames },
                    ) {
                        sanitizeIdentifier(it)
                    }
                if (isNullable) {
                    val localVal = "local_${sanitizeIdentifier(f.name)}"
                    val safeCond = if (" || " in cond) "($cond)" else cond
                    sb.append("    val $localVal = $fName\n")
                    appendFormattedIfHeader(sb, "    ", "$safeCond && $localVal != null")
                    appendFieldWriteBody(sb, f, localVal, "        ")
                    sb.append("    }\n")
                } else {
                    appendFormattedIfHeader(sb, "    ", cond)
                    appendFieldWriteBody(sb, f, fName, "        ")
                    sb.append("    }\n")
                }
            } else if (f.addedVersion != null) {
                sb.append("    if (targetApiLevel >= ${f.addedVersion}) {\n")
                appendFieldWriteBody(sb, f, fName, "        ")
                sb.append("    }\n")
            } else {
                appendFieldWriteBody(sb, f, fName, "    ")
            }
        }

        if (sparseParameters != null) {
            sb.append("    var sparseCount = 0\n")
            for (sp in sparseParameters) {
                val spName = sanitizeIdentifier(sp.name)
                sb.append("    if ($spName != null) sparseCount++\n")
            }
            sb.append("    buffer.writeShort(sparseCount)\n")
            for (sp in sparseParameters) {
                val spName = sanitizeIdentifier(sp.name)
                val localVar = "sp_$spName"
                sb.append("    val $localVar = $spName\n")
                sb.append("    if ($localVar != null) {\n")
                sb.append("        buffer.writeByte(${sp.id})\n")
                val syntheticField =
                    SchemaField(
                        name = sp.name,
                        type = sp.type,
                        description = sp.description,
                        enumValues = null,
                        lengthType = "short",
                    )
                appendFieldWriteBody(sb, syntheticField, localVar, "        ")
                sb.append("    }\n")
            }
        }
    }

    private fun appendFieldWriteBody(
        sb: StringBuilder,
        f: SchemaField,
        varExpr: String,
        indent: String,
    ) {
        if (f.type.endsWith("[]")) {
            if (f.countFrom == null) {
                when (f.effectiveLengthType) {
                    "int" -> sb.append("${indent}buffer.writeInt($varExpr.size)\n")
                    else -> sb.append("${indent}buffer.writeShort($varExpr.size)\n")
                }
            }
            sb.append("${indent}for (item in $varExpr) {\n")
            when (f.type) {
                "int[]" -> sb.append("$indent    buffer.writeInt(item)\n")
                "short[]" -> sb.append("$indent    buffer.writeShort(item.toInt())\n")
                "float[]",
                "float_or_id[]" -> sb.append("$indent    buffer.writeInt(item.toRawBits())\n")
                else -> sb.append("$indent    item.write(buffer, targetApiLevel)\n")
            }
            sb.append("$indent}\n")
        } else {
            val writeStmt = mapToKotlinScalarWriteExpr(f.type, varExpr)
            sb.append("$indent$writeStmt\n")
        }
    }

    private fun derivedExprToKotlin(
        expr: DerivedExpr,
        propByName: Map<String, AstProperty>,
        resolveTarget: (String) -> String = { sanitizeIdentifier(it) },
    ): String {
        val target = resolveTarget(expr.targetName)
        return when (expr) {
            is DerivedExpr.LengthOf -> "$target.size"
            is DerivedExpr.PresentOf -> "if ($target != null) 1 else 0"
            is DerivedExpr.NonEmptyOf -> {
                val prop = propByName[expr.targetName]
                if (prop?.type?.startsWith("List<") == true || prop?.type?.endsWith("[]") == true) {
                    val isList =
                        prop.type !in setOf("int[]", "short[]", "float[]", "float_or_id[]", "bytes")
                    if (isList) "if ($target.isNotEmpty()) 1 else 0"
                    else "if ($target.isNotEmpty()) 1 else 0"
                } else {
                    "if ($target.isNotEmpty()) 1 else 0"
                }
            }
        }
    }

    private fun equalsCheckExpr(prop: AstProperty, lhs: String, rhs: String): String =
        when (prop.type) {
            "bytes",
            "int[]",
            "short[]" -> "$lhs.contentEquals($rhs)"
            "float[]",
            "float_or_id[]" -> "floatArrayRawEquals($lhs, $rhs)"
            "float" ->
                if (prop.isNullable) "$lhs?.toRawBits() == $rhs?.toRawBits()"
                else "$lhs.toRawBits() == $rhs.toRawBits()"
            else -> "$lhs == $rhs"
        }

    private fun hashArgExpr(prop: AstProperty, name: String): String =
        when (prop.type) {
            "bytes",
            "int[]",
            "short[]" -> "$name.contentHashCode()"
            "float[]",
            "float_or_id[]" -> "floatArrayRawHashCode($name)"
            else -> name
        }

    private fun formatKDoc(
        description: String,
        props: List<AstProperty>,
        enumByProp: Map<String, Map<String, Int>?>,
        isStruct: Boolean,
    ): String {
        val cleanDesc =
            if (isStruct) {
                val d = description.trim()
                if (d.isEmpty()) "Wire payload element."
                else {
                    val cap = d.replaceFirstChar { it.uppercaseChar() }
                    if (cap.endsWith('.')) cap else "$cap."
                }
            } else {
                cleanOperationDescription(description)
            }

        val sb = StringBuilder()
        sb.append("/**\n")
        sb.append(" * Represents an element of the RemoteCompose binary format.\n")
        if (cleanDesc.isNotEmpty()) {
            sb.append(" *\n")
            appendWrappedLines(sb, " * ", cleanDesc, 100)
        }

        if (props.isNotEmpty()) {
            sb.append(" *\n")
            for (p in props) {
                val paramName = sanitizeIdentifier(p.name)
                val paramDesc =
                    p.description.trim().let {
                        if (it.isEmpty()) {
                            paramName
                        } else {
                            val decap = it.replaceFirstChar { ch -> ch.lowercaseChar() }
                            decap.trimEnd('.')
                        }
                    }
                val enumVals = enumByProp[p.name]
                val enumSuffix =
                    if (enumVals != null && enumVals.isNotEmpty()) {
                        val opts = enumVals.entries.joinToString(", ") { "${it.key}=${it.value}" }
                        " (values: $opts)"
                    } else {
                        ""
                    }
                val line = "@param $paramName $paramDesc$enumSuffix"
                appendWrappedLines(sb, " * ", line, 100, " *   ")
            }
        }

        sb.append(" */\n")
        return sb.toString()
    }

