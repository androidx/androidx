    private fun appendWrappedLines(
        sb: StringBuilder,
        firstPrefix: String,
        text: String,
        maxLength: Int,
        continuationPrefix: String = firstPrefix,
    ) {
        val words = text.split(" ")
        var currentPrefix = firstPrefix
        val currentLine = StringBuilder(currentPrefix)

        for (word in words) {
            if (word.isEmpty()) continue
            if (
                currentLine.length + 1 + word.length > maxLength &&
                    currentLine.length > currentPrefix.length
            ) {
                sb.append(currentLine.toString()).append("\n")
                currentPrefix = continuationPrefix
                currentLine.clear()
                currentLine.append(currentPrefix).append(word)
            } else {
                if (currentLine.length > currentPrefix.length) {
                    currentLine.append(" ")
                }
                currentLine.append(word)
            }
        }
        if (currentLine.length > currentPrefix.length) {
            sb.append(currentLine.toString()).append("\n")
        }
    }

