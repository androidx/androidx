            setOf("bytes", "int[]", "short[]", "float[]", "float_or_id[]")

        private val KOTLIN_KEYWORDS =
            setOf(
                "in",
                "is",
                "as",
                "fun",
                "val",
                "var",
                "class",
                "object",
                "interface",
                "package",
