    private fun appendToString(sb: StringBuilder, className: String, props: List<AstProperty>) {
        val parts = props.map {
            val pName = sanitizeIdentifier(it.name)
            if (it.type in ARRAY_TO_STRING_TYPES) {
                "$pName=\${$pName.contentToString()}"
            } else {
                "$pName=\${$pName}"
            }
        }
        val fieldString = parts.joinToString(", ")
        val singleLine = "    override fun toString(): String = \"$className($fieldString)\""
        val nextLine = "        \"$className($fieldString)\""
        if (singleLine.length <= 100) {
            sb.append("$singleLine\n\n")
        } else if (nextLine.length <= 100) {
            sb.append("    override fun toString(): String =\n")
            sb.append("$nextLine\n\n")
        } else {
            sb.append("    override fun toString(): String =\n")
            sb.append("        \"$className(\" +\n")
            for ((index, part) in parts.withIndex()) {
                val suffix = if (index < parts.size - 1) ", \" +" else ")\""
                sb.append("            \"$part$suffix\n")
            }
            sb.append("\n")
        }
    }

    private fun appendCopy(sb: StringBuilder, className: String, props: List<AstProperty>) {
        val hasByteOrShort = props.any { it.type == "byte" || it.type == "short" }
        val suppressAnnotation = if (hasByteOrShort) "    @Suppress(\"NoByteOrShort\")\n" else ""

        if (props.isEmpty()) {
            sb.append("    /** Returns a copy of this instance. */\n")
            sb.append("    public fun copy(): $className = this\n\n")
        } else if (props.size == 1) {
            val p = props[0]
            val pName = sanitizeIdentifier(p.name)
            val ktType = mapToKotlinType(p.type, p.isNullable)
            sb.append("    /** Returns a copy with optional updated fields. */\n")
            sb.append(suppressAnnotation)
            val copySig = "    public fun copy($pName: $ktType = this.$pName): $className {"
            if (copySig.length <= 100) {
                sb.append("$copySig\n")
            } else {
                sb.append("    public fun copy(\n")
                sb.append("        $pName: $ktType = this.$pName\n")
                sb.append("    ): $className {\n")
            }
            val check = equalsCheckExpr(p, pName, "this.$pName")
            val singleCheck = "        if ($check) return this"
            val singleIfBrace = "        if ($check) {"
            if (singleCheck.length <= 100) {
                sb.append("$singleCheck\n")
            } else if (singleIfBrace.length <= 100) {
                sb.append("$singleIfBrace\n")
                sb.append("            return this\n")
                sb.append("        }\n")
            } else {
                sb.append("        if (\n")
                sb.append("            $check\n")
                sb.append("        ) {\n")
                sb.append("            return this\n")
                sb.append("        }\n")
            }
            val returnSingle = "        return $className($pName = $pName)"
            if (returnSingle.length <= 100) {
                sb.append("$returnSingle\n")
            } else {
                sb.append("        return $className(\n")
                sb.append("            $pName = $pName,\n")
                sb.append("        )\n")
            }
            sb.append("    }\n\n")
        } else {
            sb.append("    /** Returns a copy with optional updated fields. */\n")
            sb.append(suppressAnnotation)
            sb.append("    public fun copy(\n")
            for (p in props) {
                val pName = sanitizeIdentifier(p.name)
                val ktType = mapToKotlinType(p.type, p.isNullable)
                val paramLine = "        $pName: $ktType = this.$pName,"
                if (paramLine.length <= 100) {
                    sb.append("$paramLine\n")
                } else {
                    sb.append("        $pName: $ktType =\n")
                    sb.append("            this.$pName,\n")
                }
            }
            sb.append("    ): $className {\n")

            val checks = props.map { prop ->
                val pName = sanitizeIdentifier(prop.name)
                equalsCheckExpr(prop, pName, "this.$pName")
            }
            val singleLine = checks.joinToString(" && ")
            val singleLineCheck = "        if ($singleLine) return this"
            val singleLineIfBrace = "        if ($singleLine) {"
            if (singleLineCheck.length <= 100) {
                sb.append("$singleLineCheck\n")
            } else if (singleLineIfBrace.length <= 100) {
                sb.append("$singleLineIfBrace\n")
                sb.append("            return this\n")
                sb.append("        }\n")
            } else if ("            $singleLine".length <= 100) {
                sb.append("        if (\n")
                sb.append("            $singleLine\n")
                sb.append("        ) {\n")
                sb.append("            return this\n")
                sb.append("        }\n")
            } else {
                sb.append("        if (\n")
                for ((index, check) in checks.withIndex()) {
                    val indent = if (index == 0) "            " else "                "
                    val suffix = if (index < checks.size - 1) " &&" else ""
                    sb.append("$indent$check$suffix\n")
                }
                sb.append("        ) {\n")
                sb.append("            return this\n")
                sb.append("        }\n")
            }

            sb.append("        return $className(\n")
            for (p in props) {
                val pName = sanitizeIdentifier(p.name)
                sb.append("            $pName = $pName,\n")
            }
            sb.append("        )\n")
            sb.append("    }\n\n")
        }
