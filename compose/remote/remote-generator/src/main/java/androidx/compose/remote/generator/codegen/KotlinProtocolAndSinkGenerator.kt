    private fun appendIntSetConstant(sb: StringBuilder, name: String, ids: List<Int>) {
        sb.append("    private val $name: Set<Int> =\n")
        sb.append("        setOf(\n")
        for (id in ids) {
            sb.append("            $id,\n")
        }
        sb.append("        )\n")
    }

    private fun appendWhenOpcodeBranch(
        sb: StringBuilder,
        indent: String,
        ids: List<Int>,
        rhs: String,
    ) {
        if (ids.size == 1) {
            sb.append("$indent${ids[0]} -> $rhs\n")
            return
        }
        for (i in 0 until ids.size - 1) {
            sb.append("$indent${ids[i]},\n")
        }
        val lastLine = "$indent${ids.last()} -> $rhs"
        if (lastLine.length <= 100) {
            sb.append("$lastLine\n")
        } else {
            sb.append("$indent${ids.last()} ->\n")
            sb.append("$indent    $rhs\n")
        }
    }

    private fun appendFloatRpnObject(sb: StringBuilder) {
        val rpn = checkNotNull(schema.rpnOperators) { "Missing rpnOperators in schema" }
        val maxV6 = rpn.operators.filter { it.addedVersion <= 6 }.maxOfOrNull { it.id } ?: 50
        val maxId = rpn.operators.maxOfOrNull { it.id } ?: 79

        sb.append(
            """
            /**
             * Floating-point RPN expression operator NaN tokens matching `AnimatedFloatExpression`.
             *
             * Each operator is encoded as a negative quiet NaN `Float.fromBits((OFFSET + id) or -0x800000)`.
             * Always compare RPN float tokens using [Float.toRawBits] rather than `==`.
             */
            @RestrictTo(RestrictTo.Scope.LIBRARY_GROUP)
            public object FloatRpn {
                public const val OFFSET: Int = 0x${rpn.offset.toString(16).uppercase()}
                public const val API_LEVEL_6_MAX_ID: Int = $maxV6
                public const val MAX_ID: Int = $maxId
                private const val NAN_PREFIX: Int = -0x800000
                private const val PAYLOAD_MASK: Int = 0x3FFFFF
            """
                .trimIndent()
        )
        sb.append("\n\n")

        for (op in rpn.operators) {
            sb.append("    public const val ID_${op.name}: Int = ${op.id}\n")
        }
        if ("DEG_TO_RAD" in rpn.operatorsByName && "DEG" !in rpn.operatorsByName) {
            sb.append("    public const val ID_DEG: Int = ID_DEG_TO_RAD\n")
        }
        if ("RAD_TO_DEG" in rpn.operatorsByName && "RAD" !in rpn.operatorsByName) {
            sb.append("    public const val ID_RAD: Int = ID_RAD_TO_DEG\n")
        }
        if ("STORE_RO" in rpn.operatorsByName && "STORE_R0" !in rpn.operatorsByName) {
            sb.append("    public const val ID_STORE_R0: Int = ID_STORE_RO\n")
        }
        sb.append("\n")

        for (op in rpn.operators) {
            sb.append(
                "    public val ${op.name}: Float = Float.fromBits((OFFSET + ${op.id}) or NAN_PREFIX)\n"
            )
        }
        if ("DEG_TO_RAD" in rpn.operatorsByName && "DEG" !in rpn.operatorsByName) {
            sb.append("    public val DEG: Float = DEG_TO_RAD\n")
        }
        if ("RAD_TO_DEG" in rpn.operatorsByName && "RAD" !in rpn.operatorsByName) {
            sb.append("    public val RAD: Float = RAD_TO_DEG\n")
        }
        if ("STORE_RO" in rpn.operatorsByName && "STORE_R0" !in rpn.operatorsByName) {
            sb.append("    public val STORE_R0: Float = STORE_RO\n")
        }
        sb.append("\n")

        sb.append(
            """
                /** Encodes a float RPN operator [id] (`1..MAX_ID`) as a NaN [Float] token. */
                public fun tokenFromId(id: Int): Float {
                    require(id in 1..MAX_ID && id != 68 && id != 69) {
                        "Invalid float RPN operator id: ${'$'}id"
                    }
                    return Float.fromBits((OFFSET + id) or NAN_PREFIX)
                }

                /** Returns true if [token] is a NaN-encoded float RPN operator. */
                public fun isOperator(token: Float): Boolean {
                    val bits = token.toRawBits()
                    if ((bits and NAN_PREFIX) != NAN_PREFIX) return false
                    val id = (bits and PAYLOAD_MASK) - OFFSET
                    return id in 1..MAX_ID && id != 68 && id != 69
                }

                /** Extracts the operator ID (`1..MAX_ID`) from [token], or `-1` if not an operator. */
                public fun operatorId(token: Float): Int {
                    if (!isOperator(token)) return -1
                    return (token.toRawBits() and PAYLOAD_MASK) - OFFSET
                }

                /** Returns true if [token] (if an RPN operator) is supported at [apiLevel]. */
                public fun isSupportedAtApiLevel(token: Float, apiLevel: Int): Boolean {
                    val id = operatorId(token)
                    if (id == -1) return true
                    return if (apiLevel <= 6) id <= API_LEVEL_6_MAX_ID else id <= MAX_ID
                }
            }
            """
                .trimIndent()
        )
    }

