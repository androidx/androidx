    private fun appendSinkInterface(sb: StringBuilder, sinkOps: List<SchemaOperation>) {
        sb.append(
            """
            /**
             * Typed low-level operation sink for emitting RemoteCompose wire operations into either a streaming
             * [WireBuffer] ([WireBufferOperationSink]) or an AST list ([NodeListOperationSink]).
             */
            @RestrictTo(RestrictTo.Scope.LIBRARY_GROUP)
            public interface RemoteOperationSink {
            """
                .trimIndent()
        )
        sb.append("\n")

        for ((index, op) in sinkOps.withIndex()) {
            if (index > 0) sb.append("\n")
            val methodName = methodNameForOp(op)
            val props = op.astProperties
            appendMethodSignature(
                sb = sb,
                indent = "    ",
                modifiers = "public",
                methodName = methodName,
                props = props,
                includeDefaults = true,
                openBrace = false,
            )

            // Generate unpacked default convenience overload if op has unpackBits=false fields
            val hasPackedBitField = op.fields.any { it.bits != null && !it.unpackBits }
            if (hasPackedBitField) {
                sb.append("\n")
                appendUnpackedDefaultOverload(sb, op, methodName)
            }
        }
        sb.append("}")
    }

    private fun appendUnpackedDefaultOverload(
        sb: StringBuilder,
        op: SchemaOperation,
        methodName: String,
    ) {
        val unpackedParams = mutableListOf<AstProperty>()
        for (f in op.fields) {
            if (f.derivedFrom != null) continue
            val bits = f.bits
            if (bits != null) {
                for (b in bits) {
                    if (b.derivedFrom != null) continue
                    unpackedParams.add(
                        AstProperty(
                            name = b.name,
                            type = "int",
                            description = b.description.ifEmpty { f.description },
                            isNullable = false,
                            defaultValue = "0",
                        )
                    )
                }
            } else {
                val isNullable =
                    f.presentIf != null && !f.type.endsWith("[]") && f.defaultValue == null
                unpackedParams.add(
                    AstProperty(
                        name = f.name,
                        type = f.type,
                        description = f.description,
                        isNullable = isNullable,
                        defaultValue = f.defaultValue,
                    )
                )
            }
        }

        appendMethodSignature(
            sb = sb,
            indent = "    ",
            modifiers = "public",
            methodName = methodName,
            props = unpackedParams,
            includeDefaults = true,
            openBrace = true,
        )

        val callArgs = mutableListOf<String>()
        for (f in op.fields) {
            if (f.derivedFrom != null) continue
            val bits = f.bits
            if (bits != null && !f.unpackBits) {
                val terms = mutableListOf<Pair<String, SchemaBitField>>()
                for (b in bits) {
                    if (b.derivedFrom == null) {
                        terms.add(KotlinGenerator.sanitizeIdentifier(b.name) to b)
                    }
                }
                val packedExpr = CodegenExprUtils.packBitsExpr(terms, ExprLang.KOTLIN)
                val fName = KotlinGenerator.sanitizeIdentifier(f.name)
                val singleAssign = "        val packed_$fName = $packedExpr"
                if (singleAssign.length <= 100) {
                    sb.append("$singleAssign\n")
                } else {
                    sb.append("        val packed_$fName =\n")
                    sb.append("            $packedExpr\n")
                }
                callArgs.add("$fName = packed_$fName")
            } else if (bits != null && f.unpackBits) {
                for (b in bits) {
                    if (b.derivedFrom == null) {
                        val bName = KotlinGenerator.sanitizeIdentifier(b.name)
                        callArgs.add("$bName = $bName")
                    }
                }
            } else {
                val fName = KotlinGenerator.sanitizeIdentifier(f.name)
                callArgs.add("$fName = $fName")
            }
        }

        appendCallStatement(sb, "        ", methodName, callArgs)
        sb.append("    }\n")
    }

    private fun appendEmitExtensions(sb: StringBuilder, sinkOps: List<SchemaOperation>) {
        sb.append(
            """
            /** Replays this [OperationNode] into [sink] without manual `when` dispatch in callers. */
            @RestrictTo(RestrictTo.Scope.LIBRARY_GROUP)
            public fun OperationNode.emitTo(sink: RemoteOperationSink) {
                when (this) {
            """
                .trimIndent()
        )
        sb.append("\n")
        sb.append(
            "        is HeaderNode ->\n" +
                "            throw IllegalArgumentException(\n" +
                "                \"HeaderNode must be written via DocumentHeader, not RemoteOperationSink\"\n" +
                "            )\n"
        )
        for (op in sinkOps) {
            val methodName = methodNameForOp(op)
            val props = op.astProperties
            val args = props.map { KotlinGenerator.sanitizeIdentifier(it.name) }
            val single = "        is ${op.name}Node -> sink.$methodName(${args.joinToString(", ")})"
            if (single.length <= 100) {
                sb.append("$single\n")
            } else {
                sb.append("        is ${op.name}Node ->\n")
                appendCallStatement(sb, "            ", "sink.$methodName", args)
            }
        }
        sb.append(
            """
                    else -> error("Unsupported OperationNode: ${'$'}{this::class.java.name}")
                }
            }

            /** Emits [node] into this [RemoteOperationSink]. */
            @RestrictTo(RestrictTo.Scope.LIBRARY_GROUP)
            public fun RemoteOperationSink.emit(node: OperationNode) {
                node.emitTo(this)
            }
            """
                .trimIndent()
        )
    }

    private fun appendWireBufferOperationSink(sb: StringBuilder, sinkOps: List<SchemaOperation>) {
        sb.append(
            """
            /**
             * [RemoteOperationSink] implementation that writes wire bytes directly into [buffer] without
             * allocating intermediate [OperationNode] instances.
             *
             * @param buffer destination [WireBuffer]
             * @param targetApiLevel target wire protocol API level (defaults to 8)
             * @param supportedOpcodes optional set of allowed opcodes for profile validation
             * @param onOpcode optional callback invoked before each opcode is written
             */
            @RestrictTo(RestrictTo.Scope.LIBRARY_GROUP)
            public class WireBufferOperationSink(
                public val buffer: WireBuffer = WireBuffer(),
                public val targetApiLevel: Int = DEFAULT_DOCUMENT_API_LEVEL,
                public val supportedOpcodes: Set<Int>? = null,
                private val onOpcode: ((Int) -> Unit)? = null,
            ) : RemoteOperationSink {

                /** Total bytes written to [buffer] so far. */
                public val bytesWritten: Int
                    get() = buffer.size()

                private fun validateOpcode(opcode: Int, operationName: String) {
                    val allowed = supportedOpcodes
                    if (allowed != null && opcode !in allowed) {
                        throw IllegalArgumentException(
                            "Operation ${'$'}operationName (opcode=${'$'}opcode) is not supported by active profile"
                        )
                    }
                    onOpcode?.invoke(opcode)
                }

                /**
                 * Starts a `Skip` (`236`) block with a placeholder byte-length field and returns the buffer
                 * offset to pass to [endSkip].
                 */
                public fun beginSkip(conditionType: Int, value: Int): Int {
                    validateOpcode(SkipNode.OPCODE, "Skip")
                    buffer.start(SkipNode.OPCODE)
                    buffer.writeInt(conditionType)
                    buffer.writeInt(value)
                    val skipOffset = buffer.index
                    buffer.writeInt(0)
                    return skipOffset
                }

                /** Backpatches the skipped byte length at [skipOffset] opened by [beginSkip]. */
                public fun endSkip(skipOffset: Int) {
                    buffer.overwriteInt(skipOffset, buffer.size() - (skipOffset + 4))
                }

                /**
                 * Starts a `PatternDefine` (`246`) container with a placeholder body byte-length field and
                 * returns the buffer offset to pass to [endPatternDefine].
                 */
                public fun beginPatternDefine(id: Int, paramIds: IntArray): Int {
                    validateOpcode(PatternDefineNode.OPCODE, "PatternDefine")
                    buffer.start(PatternDefineNode.OPCODE)
                    buffer.writeInt(id)
                    buffer.writeInt(paramIds.size)
                    for (item in paramIds) {
                        buffer.writeInt(item)
                    }
                    val skipOffset = buffer.index
                    buffer.writeInt(0)
                    return skipOffset
                }

                /**
                 * Backpatches the pattern body byte length at [skipOffset] opened by [beginPatternDefine] and
                 * emits the closing `ContainerEnd` (`214`) operation.
                 */
                public fun endPatternDefine(skipOffset: Int) {
                    buffer.overwriteInt(skipOffset, buffer.size() - (skipOffset + 4))
                    containerEnd()
                }
            """
                .trimIndent()
        )
        sb.append("\n")

        for (op in sinkOps) {
            sb.append("\n")
            val methodName = methodNameForOp(op)
            val props = op.astProperties
            appendMethodSignature(
                sb = sb,
                indent = "    ",
                modifiers = "override",
                methodName = methodName,
                props = props,
                includeDefaults = false,
                openBrace = true,
            )
            appendCallStatement(
                sb,
                "        ",
                "validateOpcode",
                listOf("${op.name}Node.OPCODE", "\"${op.name}\""),
            )
            val callArgs = mutableListOf("buffer", "targetApiLevel")
            for (p in props) {
                callArgs.add(KotlinGenerator.sanitizeIdentifier(p.name))
            }
            appendCallStatement(sb, "        ", "write${op.name}Operation", callArgs)
            sb.append("    }\n")
        }
        sb.append("}")
    }

    private fun appendNodeListOperationSink(sb: StringBuilder, sinkOps: List<SchemaOperation>) {
        sb.append(
            """
            /**
             * [RemoteOperationSink] implementation that instantiates and appends [OperationNode] AST instances
             * directly to a mutable list without serializing bytes.
             *
             * @param mutableNodes backing list receiving emitted [DocumentNode] elements
             * @param supportedOpcodes optional set of allowed opcodes for profile validation
             * @param onOpcode optional callback invoked before each node is appended
             */
            @RestrictTo(RestrictTo.Scope.LIBRARY_GROUP)
            public class NodeListOperationSink(
                private val mutableNodes: MutableList<DocumentNode> = ArrayList(),
                public val supportedOpcodes: Set<Int>? = null,
                private val onOpcode: ((Int) -> Unit)? = null,
            ) : RemoteOperationSink {

                /** Emitted [DocumentNode] list in stream order. */
                public val nodes: List<DocumentNode>
                    get() = mutableNodes

                /** Number of [DocumentNode] elements emitted so far. */
                public val size: Int
                    get() = mutableNodes.size

                private fun validateOpcode(opcode: Int, operationName: String) {
                    val allowed = supportedOpcodes
                    if (allowed != null && opcode !in allowed) {
                        throw IllegalArgumentException(
                            "Operation ${'$'}operationName (opcode=${'$'}opcode) is not supported by active profile"
                        )
                    }
                    onOpcode?.invoke(opcode)
                }

                /** Validates and appends an existing [node] directly to [nodes]. */
                public fun appendNode(node: DocumentNode) {
                    if (node is OperationNode) {
                        validateOpcode(node.opcode, node.operationName)
                    }
                    mutableNodes.add(node)
                }
            """
                .trimIndent()
        )
        sb.append("\n")

        for (op in sinkOps) {
            sb.append("\n")
            val methodName = methodNameForOp(op)
            val props = op.astProperties
            appendMethodSignature(
                sb = sb,
                indent = "    ",
                modifiers = "override",
                methodName = methodName,
                props = props,
                includeDefaults = false,
                openBrace = true,
            )
            appendCallStatement(
                sb,
                "        ",
                "validateOpcode",
                listOf("${op.name}Node.OPCODE", "\"${op.name}\""),
            )

            val omitZeroFields =
                op.fields
                    .filter { it.omitIf != null && it.type == "float_or_id" }
                    .map { it.name }
                    .toSet()

            for (fNameRaw in omitZeroFields) {
                val pName = KotlinGenerator.sanitizeIdentifier(fNameRaw)
                sb.append(
                    "        val effective_$pName =\n" +
                        "            if ($pName != null && !$pName.isVariable && $pName.floatValue == 0f) {\n" +
                        "                null\n" +
                        "            } else {\n" +
                        "                $pName\n" +
                        "            }\n"
                )
            }

            val ctorArgs = props.map { p ->
                val pName = KotlinGenerator.sanitizeIdentifier(p.name)
                if (p.name in omitZeroFields) "$pName = effective_$pName" else "$pName = $pName"
            }
            if (ctorArgs.isEmpty()) {
                sb.append("        mutableNodes.add(${op.name}Node())\n")
            } else {
                val single =
                    "        mutableNodes.add(${op.name}Node(${ctorArgs.joinToString(", ")}))"
                if (single.length <= 100) {
                    sb.append("$single\n")
                } else {
                    sb.append("        mutableNodes.add(\n")
                    sb.append("            ${op.name}Node(\n")
                    for (arg in ctorArgs) {
                        sb.append("                $arg,\n")
                    }
                    sb.append("            )\n")
                    sb.append("        )\n")
                }
            }
            sb.append("    }\n")
        }
        sb.append("}")
    }

    private fun appendMethodSignature(
        sb: StringBuilder,
        indent: String,
        modifiers: String,
        methodName: String,
        props: List<AstProperty>,
        includeDefaults: Boolean,
        openBrace: Boolean,
    ) {
        val hasByteOrShort = props.any { it.type == "byte" || it.type == "short" }
        if (hasByteOrShort) {
            sb.append("${indent}@Suppress(\"NoByteOrShort\")\n")
        }
        val braceSuffix = if (openBrace) " {" else ""
        if (props.isEmpty()) {
            sb.append("$indent$modifiers fun $methodName()$braceSuffix\n")
            return
        }
        if (props.size == 1) {
            val p = props[0]
            val pName = KotlinGenerator.sanitizeIdentifier(p.name)
            val ktType = KotlinGenerator.mapToKotlinType(p.type, p.isNullable)
            val defPart =
                if (includeDefaults) {
                    " = ${KotlinGenerator.mapToKotlinDefault(p.type, p.isNullable, p.defaultValue)}"
                } else {
                    ""
                }
            val single = "$indent$modifiers fun $methodName($pName: $ktType$defPart)$braceSuffix"
            if (single.length <= 100) {
                sb.append("$single\n")
                return
            }
        }
        sb.append("$indent$modifiers fun $methodName(\n")
        val trailingComma = if (props.size == 1) "" else ","
        for (p in props) {
            val pName = KotlinGenerator.sanitizeIdentifier(p.name)
            val ktType = KotlinGenerator.mapToKotlinType(p.type, p.isNullable)
            if (includeDefaults) {
                val defVal =
                    KotlinGenerator.mapToKotlinDefault(p.type, p.isNullable, p.defaultValue)
                val paramLine = "$indent    $pName: $ktType = $defVal$trailingComma"
                if (paramLine.length <= 100) {
                    sb.append("$paramLine\n")
                } else {
                    sb.append("$indent    $pName: $ktType =\n")
                    sb.append("$indent        $defVal$trailingComma\n")
                }
            } else {
                sb.append("$indent    $pName: $ktType$trailingComma\n")
            }
        }
        sb.append("$indent)$braceSuffix\n")
    }

    private fun appendCallStatement(
        sb: StringBuilder,
        indent: String,
        callee: String,
        args: List<String>,
    ) {
        val single = "$indent$callee(${args.joinToString(", ")})"
        if (single.length <= 100) {
            sb.append("$single\n")
        } else {
            sb.append("$indent$callee(\n")
            for (arg in args) {
                sb.append("$indent    $arg,\n")
            }
            sb.append("$indent)\n")
        }
    }

    companion object {
        fun methodNameForOp(op: SchemaOperation): String =
            KotlinGenerator.sanitizeIdentifier(op.name.replaceFirstChar { it.lowercaseChar() })
    }
}
