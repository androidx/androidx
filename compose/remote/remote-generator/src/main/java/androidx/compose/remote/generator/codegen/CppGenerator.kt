/**
 * Generator that transforms an [OperationSchema] into idiomatic C++17 bindings:
 * - OpCode enum class
 * - Auxiliary wire payload structs
 * - Abstract Operation base class
 * - Concrete typed Operation classes with WireBuffer serialization/deserialization
 * - RemoteDocument container and factory functions
 * - Self-contained WireBuffer reader/writer header and source
 */
internal class CppGenerator(private val schema: OperationSchema) {

    /** Generates RemoteComposeOps.h */
    fun generateHeader(): String = buildCode {
        line(
            """
            // Generated by RemoteCompose Schema Codegen. DO NOT EDIT.
            #ifndef ANDROIDX_REMOTE_COMPOSE_OPS_H
            #define ANDROIDX_REMOTE_COMPOSE_OPS_H

            #include <cstdint>
            #include <string>
            #include <algorithm>
            #include <string_view>
            #include <vector>
            #include <memory>
            #include <optional>
            #include <stdexcept>
            #include "WireBuffer.h"

            // Profile compilation configuration:
            // Normalize profile macros to 0/1 so -DRC_PROFILE_*=0 disables the profile.
            #ifndef RC_PROFILE_BASELINE
            #define RC_PROFILE_BASELINE 0
            #endif
            #ifndef RC_PROFILE_WIDGETS
            #define RC_PROFILE_WIDGETS 0
            #endif
            #ifndef RC_PROFILE_ANDROIDX
            #define RC_PROFILE_ANDROIDX 0
            #endif
            #ifndef RC_PROFILE_EXPERIMENTAL
            #define RC_PROFILE_EXPERIMENTAL 0
            #endif
            #ifndef RC_PROFILE_DEPRECATED
            #define RC_PROFILE_DEPRECATED 0
            #endif
            #ifndef RC_PROFILE_OEM
            #define RC_PROFILE_OEM 0
            #endif
            #ifndef RC_PROFILE_ALL
            #define RC_PROFILE_ALL 0
            #endif
            // If no profile macro is explicitly enabled, enable all profiles.
            #if !RC_PROFILE_ALL && !RC_PROFILE_BASELINE && !RC_PROFILE_WIDGETS && \
                !RC_PROFILE_ANDROIDX && !RC_PROFILE_EXPERIMENTAL && \
                !RC_PROFILE_DEPRECATED && !RC_PROFILE_OEM
            #undef RC_PROFILE_ALL
            #define RC_PROFILE_ALL 1
            #endif

            // Writer compilation configuration:
            // Enabled by default (1) unless RC_ENABLE_WRITER is explicitly set
            // or RC_NO_WRITER is defined.
            #if !defined(RC_ENABLE_WRITER)
            #if defined(RC_NO_WRITER)
            #define RC_ENABLE_WRITER 0
            #else
            #define RC_ENABLE_WRITER 1
            #endif
            #endif

            namespace androidx::compose::remote {
            """
                .trimIndent()
        )
        line()
        line("/**")
        line(" * Wire protocol opcodes for RemoteCompose operations.")
        line(" */")
        block("enum class OpCode : uint8_t", close = "};") {
            for (op in schema.operations) {
                val desc = op.description.replace("\n", " ").trim()
                if (desc.isNotEmpty()) {
                    line("/// $desc")
                }
                line("${op.name} = ${op.id},")
            }
        }
        line()
        line("const char* getOpCodeName(OpCode op);")
        line()
        line("/**")
        line(" * Abstract base class for all RemoteCompose operations.")
        line(" */")
        block("class Operation", close = "};") {
            rawLine("public:")
            line("virtual ~Operation() = default;")
            line("/** Returns the wire protocol opcode for this operation. */")
            line("virtual OpCode getOpCode() const = 0;")
            line("/** Deserializes this operation from the wire buffer. */")
            line("virtual void read(WireBuffer& buffer) = 0;")
            rawLine("#if $WRITER_GUARD")
            line("/** Serializes this operation to the wire buffer. */")
            line("virtual void write(WireBuffer& buffer) const = 0;")
            rawLine("#endif")
        }
        line()

        for ((_, structDef) in schema.structs) {
            emitStructDeclaration(this, structDef)
            line()
        }

        for (op in schema.operations) {
            emitClassDeclaration(this, op)
            line()
        }

        line("/**")
        line(" * In-memory container representing a parsed RemoteCompose document.")
        line(" */")
        block("class RemoteDocument", close = "};") {
            rawLine("public:")
            line("static constexpr size_t kMaxHeaderProperties = 1000;")
            line("static constexpr size_t kDefaultMaxOperations = 100000;")
            line()
            line("int32_t majorVersion = 1;")
            line("int32_t minorVersion = 1;")
            line("int32_t patchVersion = 0;")
            line("int32_t width = 0;")
            line("int32_t height = 0;")
            line("int64_t capabilities = 0;")
            line("std::vector<std::shared_ptr<Operation>> operations;")
            line()
            line("/** Deserializes a RemoteDocument from the provided buffer. */")
            line("static std::shared_ptr<RemoteDocument> load(")
            indent {
                line("WireBuffer& buffer,")
                line("size_t maxOperations = kDefaultMaxOperations);")
            }
            rawLine("#if $WRITER_GUARD")
            line("/** Serializes this document into the provided buffer. */")
            line("void save(WireBuffer& buffer) const;")
            rawLine("#endif")
        }
        line()
        line("/** Factory function to create an Operation given its OpCode. */")
        line("std::shared_ptr<Operation> createOperation(OpCode op);")
        line()
        line("} // namespace androidx::compose::remote")
        line()
        rawLine("#endif // ANDROIDX_REMOTE_COMPOSE_OPS_H")
    }

    /** Generates RemoteComposeOps.cpp */
    fun generateSource(): String = buildCode {
        line("// Generated by RemoteCompose Schema Codegen. DO NOT EDIT.")
        rawLine("#include \"RemoteComposeOps.h\"")
        line()
        line("namespace androidx::compose::remote {")
        line()
        block("const char* getOpCodeName(OpCode op)") {
            block("switch (op)") {
                for (op in schema.operations) {
                    val guard = getProfileGuard(op)
                    if (guard != null) {
                        rawLine("#if $guard")
                    }
                    line("case OpCode::${op.name}: return \"${op.name}\";")
                    if (guard != null) {
                        rawLine("#endif")
                    }
                }
                line("default: return \"Unknown\";")
            }
        }
        line()

        for ((_, structDef) in schema.structs) {
            emitStructImplementation(this, structDef)
            line()
        }

        for (op in schema.operations) {
            emitClassImplementation(this, op)
            line()
        }

        block("std::shared_ptr<Operation> createOperation(OpCode op)") {
            block("switch (op)") {
                for (op in schema.operations) {
                    val guard = getProfileGuard(op)
                    if (guard != null) {
                        rawLine("#if $guard")
                    }
                    line("case OpCode::${op.name}: return std::make_shared<${op.name}>();")
                    if (guard != null) {
                        rawLine("#endif")
                    }
                }
                line("default: return nullptr;")
            }
        }
        line()

        emitRemoteDocumentMethods(this)
        line()
        line("} // namespace androidx::compose::remote")
    }

    private fun emitRemoteDocumentMethods(w: CodeWriter) {
        w.line("std::shared_ptr<RemoteDocument> RemoteDocument::load(")
        w.indent {
            line("WireBuffer& buffer,")
            line("size_t maxOperations")
        }
        w.block(")") {
            line("auto doc = std::make_shared<RemoteDocument>();")
            line("if (!buffer.available()) return doc;")
            line()
            line("uint8_t headerOp = buffer.readByte();")
            block("if (headerOp != static_cast<uint8_t>(OpCode::Header))") {
                line(
                    "throw std::runtime_error(\"Expected Header operation at start of document\");"
                )
            }
            line("int32_t rawMajor = buffer.readInt();")
            line("doc->minorVersion = buffer.readInt();")
            line("doc->patchVersion = buffer.readInt();")
            block(
                "if ((static_cast<uint32_t>(rawMajor) & 0xFFFF0000u) == 0x048C0000u)",
                close = null,
            ) {
                line("doc->majorVersion = rawMajor & 0xFFFF;")
                line("doc->width = 256;")
                line("doc->height = 256;")
                line("int32_t numProps = buffer.readInt();")
                block("if (numProps < 0 || static_cast<size_t>(numProps) > kMaxHeaderProperties)") {
                    line("throw std::runtime_error(\"Invalid numProps in header\");")
                }
                block("if (static_cast<size_t>(numProps) > buffer.remaining() / 4)") {
                    line("throw std::runtime_error(")
                    indent {
                        line("\"Header property count exceeds remaining buffer size\");")
                    }
                }
                block("for (int32_t i = 0; i < numProps; i++)") {
                    line("int16_t tag = buffer.readShort();")
                    line("buffer.readShort(); // itemLen (read and ignored)")
                    line("int32_t dataType = static_cast<int32_t>(tag) >> 10;")
                    line("int32_t key = static_cast<int32_t>(tag) & 0x3F;")
                    block("switch (dataType)") {
                        block("case 0:", openSuffix = " { // INT") {
                            line("int32_t val = buffer.readInt();")
                            line("if (key == 5) doc->width = val;")
                            line("else if (key == 6) doc->height = val;")
                            block("else if (key == 14)", close = null) {
                                line("doc->capabilities =")
                                indent {
                                    line("static_cast<int64_t>(static_cast<uint32_t>(val));")
                                }
                            }
                            block("} else if (key == 31 && val != 0)") {
                                line("throw std::runtime_error(")
                                indent {
                                    line(
                                        "\"Compressed RemoteCompose documents are not supported\");"
                                    )
                                }
                            }
                            line("break;")
                        }
                        block("case 1:", openSuffix = " { // FLOAT") {
                            line("buffer.readFloat();")
                            line("break;")
                        }
                        block("case 2:", openSuffix = " { // LONG") {
                            line("int64_t val = buffer.readLong();")
                            line("if (key == 14) doc->capabilities = val;")
                            block("else if (key == 31 && val != 0)") {
                                line("throw std::runtime_error(")
                                indent {
                                    line(
                                        "\"Compressed RemoteCompose documents are not supported\");"
                                    )
                                }
                            }
                            line("break;")
                        }
                        block("case 3:", openSuffix = " { // STRING") {
                            line("buffer.readStringView(4000);")
                            line("break;")
                        }
                        block("default:") {
                            line("break;")
                        }
                    }
                }
            }
            block("} else if (rawMajor >= 0 && rawMajor < 0x10000)", close = null) {
                line("doc->majorVersion = rawMajor;")
                line("doc->width = buffer.readInt();")
                line("doc->height = buffer.readInt();")
                line("doc->capabilities = buffer.readLong();")
            }
            block("} else") {
                line("throw std::runtime_error(\"Invalid header magic number\");")
            }
            line()
            block("while (buffer.available())") {
                line("uint8_t opByte = buffer.readByte();")
                block("if (opByte == static_cast<uint8_t>(OpCode::Header))") {
                    line("throw std::runtime_error(\"Unexpected Header opcode in document body\");")
                }
                block("if (doc->operations.size() >= maxOperations)") {
                    line("throw std::runtime_error(")
                    indent {
                        line("\"Document exceeds maximum allowed operation count\");")
                    }
                }
                line("auto op = createOperation(static_cast<OpCode>(opByte));")
                block("if (!op)") {
                    line("throw std::runtime_error(")
                    indent {
                        line("\"Unknown or unsupported opcode: \" + std::to_string(opByte));")
                    }
                }
                line("op->read(buffer);")
                line("doc->operations.push_back(op);")
            }
            line("return doc;")
        }
        w.line()
        w.rawLine("#if $WRITER_GUARD")
        w.block("void RemoteDocument::save(WireBuffer& buffer) const") {
            line("buffer.writeByte(static_cast<uint8_t>(OpCode::Header));")
            line("buffer.writeInt(majorVersion);")
            line("buffer.writeInt(minorVersion);")
            line("buffer.writeInt(patchVersion);")
            line("buffer.writeInt(width);")
            line("buffer.writeInt(height);")
            line("buffer.writeLong(capabilities);")
            line()
            block("for (const auto& op : operations)") {
                block("if (op)") {
                    line("op->write(buffer);")
                }
            }
        }
        w.rawLine("#endif")
    }

    private fun getProfileGuard(op: SchemaOperation): String? {
        if (op.profiles.contains("baseline") || op.profiles.isEmpty()) {
            return null
        }
        val platformTerms = mutableListOf<String>()
        if (op.profiles.contains("androidx")) {
            platformTerms.add("RC_PROFILE_ANDROIDX")
        }
        if (op.profiles.contains("widgets")) {
            platformTerms.add("RC_PROFILE_WIDGETS")
        }
        if (op.profiles.contains("oem")) {
            platformTerms.add("RC_PROFILE_OEM")
        }
        val modifierTerms = mutableListOf<String>()
        if (op.profiles.contains("experimental")) {
            modifierTerms.add("RC_PROFILE_EXPERIMENTAL")
        }
        if (op.profiles.contains("deprecated")) {
            modifierTerms.add("RC_PROFILE_DEPRECATED")
        }
        val clauses = mutableListOf<String>()
        if (platformTerms.isNotEmpty()) {
            clauses.add(
                if (platformTerms.size == 1) platformTerms[0]
                else "(${platformTerms.joinToString(" || ")})"
            )
        }
        clauses.addAll(modifierTerms)
        if (clauses.isEmpty()) {
            return "RC_PROFILE_ALL"
        }
        val combined = if (clauses.size == 1) clauses[0] else "(${clauses.joinToString(" && ")})"
        return "RC_PROFILE_ALL || $combined"
    }

    private fun emitStructDeclaration(w: CodeWriter, structDef: SchemaStruct) {
        val props = structDef.astProperties
        val desc = structDef.description.replace("\n", " ").trim()
        if (desc.isNotEmpty()) {
            w.line("/** $desc */")
        }
        w.block("struct ${structDef.name}", close = "};") {
            emitCppMemberFields(this, props)
            line()
            line("${structDef.name}() = default;")
            emitCppConstructor(this, structDef.name, props)
            emitCppComputedBitGetters(this, structDef.computedBitProperties, props)
            line()
            line("void read(WireBuffer& buffer);")
            rawLine("#if $WRITER_GUARD")
            line("void write(WireBuffer& buffer) const;")
            rawLine("#endif")
        }
    }

    private fun emitClassDeclaration(w: CodeWriter, op: SchemaOperation) {
        val guard = getProfileGuard(op)
        if (guard != null) {
            w.rawLine("#if $guard")
        }
        val props = op.astProperties
        val desc = op.description.replace("\n", " ").trim()
        val hasZeroCopyViews = props.any { it.type == "string" || it.type == "bytes" }
        if (desc.isNotEmpty() || hasZeroCopyViews) {
            w.line("/**")
            if (desc.isNotEmpty()) {
                w.line(" * $desc")
            }
            if (hasZeroCopyViews) {
                w.line(" *")
                w.line(" * NOTE: Contains non-owning view fields (std::string_view or BufferView).")
                w.line(" * Backing memory must outlive this operation instance.")
            }
            w.line(" */")
        }
        w.block("class ${op.name} : public Operation", close = "};") {
            rawLine("public:")
            line("static constexpr OpCode OP_CODE = OpCode::${op.name};")
            line()
            emitCppMemberFields(this, props)
            line()
            line("${op.name}() = default;")
            emitCppConstructor(this, op.name, props)
            emitCppComputedBitGetters(this, op.computedBitProperties, props)
            line()
            line("OpCode getOpCode() const override { return OP_CODE; }")
            line("void read(WireBuffer& buffer) override;")
            rawLine("#if $WRITER_GUARD")
            line("void write(WireBuffer& buffer) const override;")
            rawLine("#endif")
        }
        if (guard != null) {
            w.rawLine("#endif // $guard")
        }
    }

    private fun emitCppMemberFields(w: CodeWriter, props: List<AstProperty>) {
        for (prop in props) {
            val cppType = mapToCppType(prop.type, prop.isNullable)
            val fieldName = sanitizeIdentifier(prop.name)
            val fieldDesc = prop.description.replace("\n", " ").trim()
            if (fieldDesc.isNotEmpty()) {
                w.line("/// $fieldDesc")
            }
            val initSuffix = mapToCppInitSuffix(prop.type, prop.isNullable, prop.defaultValue)
            w.line("$cppType $fieldName$initSuffix;")
        }
    }

    private fun emitCppConstructor(
        w: CodeWriter,
        className: String,
        props: List<AstProperty>,
    ) {
        if (props.isEmpty()) return
        val params =
            props.joinToString(", ") {
                "${mapToCppType(it.type, it.isNullable)} _${sanitizeIdentifier(it.name)}"
            }
        val inits =
            props.joinToString(", ") {
                val fn = sanitizeIdentifier(it.name)
                "$fn(_$fn)"
            }
        val ctorDecl = "$className($params) : $inits {}"
        if (ctorDecl.length <= 95) {
            w.line(ctorDecl)
        } else {
            w.block("$className(", openSuffix = "", close = ") :") {
                for (i in props.indices) {
                    val prop = props[i]
                    val p =
                        "${mapToCppType(prop.type, prop.isNullable)} _${sanitizeIdentifier(prop.name)}"
                    val comma = if (i < props.size - 1) "," else ""
                    line("$p$comma")
                }
            }
            w.indent {
                for (i in props.indices) {
                    val fn = sanitizeIdentifier(props[i].name)
                    val suffix = if (i < props.size - 1) "," else " {}"
                    line("$fn(_$fn)$suffix")
                }
            }
        }
    }

    private fun emitCppComputedBitGetters(
        w: CodeWriter,
        computedBits: List<Pair<String, SchemaBitField>>,
        props: List<AstProperty>,
    ) {
        if (computedBits.isEmpty()) return
        val nullableNames = props.filter { it.isNullable }.map { it.name }.toSet()
        w.line()
        for ((parentName, bit) in computedBits) {
            val getterName = "get" + bit.name.replaceFirstChar { it.uppercaseChar() }
            val ident = sanitizeIdentifier(parentName)
            if (parentName in nullableNames) {
                val expr = CodegenExprUtils.extractBitExpr("(*$ident)", bit, ExprLang.CPP)
                w.line(
                    "std::optional<int32_t> $getterName() const { return $ident.has_value() ? std::optional<int32_t>($expr) : std::nullopt; }"
                )
            } else {
                val expr = CodegenExprUtils.extractBitExpr(ident, bit, ExprLang.CPP)
                w.line("int32_t $getterName() const { return $expr; }")
            }
        }
    }

    private fun emitStructImplementation(w: CodeWriter, structDef: SchemaStruct) {
        w.block("void ${structDef.name}::read(WireBuffer& buffer)") {
            emitCppReadFields(this, structDef.fields, null)
        }
        w.line()
        w.rawLine("#if $WRITER_GUARD")
        w.block("void ${structDef.name}::write(WireBuffer& buffer) const") {
            emitCppWriteFields(this, structDef.fields, null, structDef.astProperties)
        }
        w.rawLine("#endif // RC_ENABLE_WRITER")
    }

    private fun emitClassImplementation(w: CodeWriter, op: SchemaOperation) {
        val guard = getProfileGuard(op)
        if (guard != null) {
            w.rawLine("#if $guard")
        }
        w.block("void ${op.name}::read(WireBuffer& buffer)") {
            emitCppReadFields(
                this,
                op.fields,
                op.sparseParameters,
                op.sparseCountType,
                op.sparseKeyType,
            )
        }
        w.line()
        w.rawLine("#if $WRITER_GUARD")
        w.block("void ${op.name}::write(WireBuffer& buffer) const") {
            line("buffer.writeByte(static_cast<uint8_t>(OP_CODE));")
            emitCppWriteFields(
                this,
                op.fields,
                op.sparseParameters,
                op.astProperties,
                op.sparseCountType,
                op.sparseKeyType,
            )
        }
        w.rawLine("#endif // RC_ENABLE_WRITER")
        if (guard != null) {
            w.rawLine("#endif // $guard")
        }
    }

    private fun emitCppReadFields(
        w: CodeWriter,
        fields: List<SchemaField>,
        sparseParameters: List<SchemaSparseParam>?,
        sparseCountType: String? = null,
        sparseKeyType: String? = null,
    ) {
        for (field in fields) {
            val bits = field.bits
            if (bits != null && field.unpackBits) {
                val rawVar = "raw_${sanitizeIdentifier(field.name)}"
                w.line("int32_t $rawVar = buffer.readInt();")
                for (b in bits) {
                    val bName = sanitizeIdentifier(b.name)
                    val extract = CodegenExprUtils.extractBitExpr(rawVar, b, ExprLang.CPP)
                    if (b.derivedFrom != null) {
                        w.line("int32_t $bName = $extract;")
                    } else {
                        w.line("$bName = $extract;")
                    }
                    if (b.strictEnum && !b.enumValues.isNullOrEmpty()) {
                        val allowed = b.enumValues.values.distinct().sorted()
                        val cond = allowed.joinToString(" && ") { "$bName != $it" }
                        w.block("if ($cond)") {
                            line("throw std::runtime_error(\"Invalid enum value for ${b.name}\");")
                        }
                    }
                }
                continue
            }

            val fieldName = sanitizeIdentifier(field.name)
            val isLocalDerived = field.derivedFrom != null
            val isNullable =
                !isLocalDerived &&
                    field.presentIf != null &&
                    !field.type.endsWith("[]") &&
                    field.defaultValue == null

            if (field.presentIf != null) {
                val cond =
                    CodegenExprUtils.translateCondition(field.presentIf, ExprLang.CPP) {
                        sanitizeIdentifier(it)
                    }
                if (isLocalDerived) {
                    val cppType = mapToCppType(field.type, false)
                    val readExpr = mapToCppScalarReadExpr(field.type)
                    w.line("$cppType $fieldName = ($cond) ? ($readExpr) : 0;")
                } else {
                    w.block("if ($cond)", close = null) {
                        emitCppFieldReadAssign(this, field, fieldName, isOptional = isNullable)
                    }
                    w.block("} else") {
                        if (field.type.endsWith("[]")) {
                            line("$fieldName.clear();")
                        } else if (isNullable) {
                            line("$fieldName = std::nullopt;")
                        } else {
                            val fallback = mapToCppFallbackLiteral(field.type, field.defaultValue)
                            line("$fieldName = $fallback;")
                        }
                    }
                }
            } else if (isLocalDerived) {
                val cppType = mapToCppType(field.type, false)
                val readExpr = mapToCppScalarReadExpr(field.type)
                w.line("$cppType $fieldName = $readExpr;")
            } else {
                emitCppFieldReadAssign(w, field, fieldName)
            }
        }

        if (sparseParameters != null) {
            for (sp in sparseParameters) {
                w.line("${sanitizeIdentifier(sp.name)} = std::nullopt;")
            }
            val effectiveCountType = sparseCountType ?: "ushort"
            val effectiveKeyType = sparseKeyType ?: "ubyte"
            when (effectiveCountType) {
                "int" -> {
                    w.line("int32_t sparseCount = buffer.readInt();")
                    w.block("if (sparseCount < 0)") {
                        line("throw std::runtime_error(\"Negative sparse parameter count\");")
                    }
                }
                "short" -> {
                    w.line("int32_t sparseCount = static_cast<int32_t>(buffer.readShort());")
                    w.block("if (sparseCount < 0)") {
                        line("throw std::runtime_error(\"Negative sparse parameter count\");")
                    }
                }
                "byte" -> {
                    w.line(
                        "int32_t sparseCount = static_cast<int32_t>(static_cast<int8_t>(buffer.readByte()));"
                    )
                    w.block("if (sparseCount < 0)") {
                        line("throw std::runtime_error(\"Negative sparse parameter count\");")
                    }
                }
                "ubyte" -> w.line("int32_t sparseCount = static_cast<int32_t>(buffer.readByte());")
                else -> w.line("int32_t sparseCount = static_cast<uint16_t>(buffer.readShort());")
            }
            val minEntryBytes =
                when (effectiveKeyType) {
                    "int" -> 5
                    "short",
                    "ushort" -> 3
                    else -> 2
                }
            w.block("if (static_cast<size_t>(sparseCount) > buffer.remaining() / $minEntryBytes)") {
                line(
                    "throw std::runtime_error(\"Sparse parameter count exceeds remaining buffer size\");"
                )
            }
            w.block("for (int32_t s = 0; s < sparseCount; ++s)") {
                when (effectiveKeyType) {
                    "int" -> line("int32_t paramId = buffer.readInt();")
                    "ushort" ->
                        line(
                            "int32_t paramId = static_cast<int32_t>(static_cast<uint16_t>(buffer.readShort()));"
                        )
                    "short" -> line("int32_t paramId = static_cast<int32_t>(buffer.readShort());")
                    "byte" ->
                        line(
                            "int32_t paramId = static_cast<int32_t>(static_cast<int8_t>(buffer.readByte()));"
                        )
                    else -> line("uint8_t paramId = buffer.readByte();")
                }
                block("switch (paramId)") {
                    for (sp in sparseParameters) {
                        val spName = sanitizeIdentifier(sp.name)
                        block("case ${sp.id}:") {
                            if (sp.type.endsWith("[]")) {
                                val vecType = mapToCppType(sp.type, false)
                                val tmpName = "tmp_$spName"
                                line("$vecType $tmpName;")
                                val synField =
                                    SchemaField(
                                        name = sp.name,
                                        type = sp.type,
                                        description = sp.description,
                                        enumValues = null,
                                        lengthType = sp.lengthType ?: "ushort",
                                    )
                                emitCppFieldReadAssign(this, synField, tmpName)
                                line("$spName = std::move($tmpName);")
                            } else {
                                val readExpr = mapToCppScalarReadExpr(sp.type)
                                line("$spName = $readExpr;")
                            }
                            line("break;")
                        }
                    }
                    line("default: throw std::runtime_error(\"Unknown sparse parameter ID\");")
                }
            }
        }
    }

    private fun emitCppFieldReadAssign(
        w: CodeWriter,
        field: SchemaField,
        targetVar: String,
        isOptional: Boolean = false,
    ) {
        if (field.type.endsWith("[]")) {
            val lenExpr =
                if (field.countFrom != null) {
                    sanitizeIdentifier(field.countFrom)
                } else {
                    when (field.effectiveLengthType) {
                        "int" -> "buffer.readInt()"
                        "ushort" ->
                            "static_cast<int32_t>(static_cast<uint16_t>(buffer.readShort()))"
                        "ubyte" -> "static_cast<int32_t>(buffer.readByte())"
                        "byte" -> "static_cast<int32_t>(static_cast<int8_t>(buffer.readByte()))"
                        else -> "static_cast<int32_t>(buffer.readShort())"
                    }
                }
            val lenVar = "${targetVar}_len"
            val elemType = field.type.removeSuffix("[]")
            val elemMinBytes = CodegenExprUtils.minWireElementBytes(elemType, schema)
            w.line("int32_t $lenVar = $lenExpr;")
            w.block("if ($lenVar < 0)") {
                line("throw std::runtime_error(\"Negative array length\");")
            }
            if (field.maxLength != null) {
                w.block("if ($lenVar > ${field.maxLength})") {
                    line(
                        "throw std::runtime_error(\"Array length exceeds maximum (${field.maxLength})\");"
                    )
                }
            }
            w.block("if (static_cast<size_t>($lenVar) > buffer.remaining() / $elemMinBytes)") {
                line("throw std::runtime_error(\"Array length exceeds remaining buffer size\");")
            }
            w.line("$targetVar.clear();")
            w.line("$targetVar.reserve(std::min<size_t>(static_cast<size_t>($lenVar), 4096));")
            w.block("for (int32_t i = 0; i < $lenVar; ++i)") {
                if (schema.structs.containsKey(elemType)) {
                    line("$elemType item;")
                    line("item.read(buffer);")
                    line("$targetVar.push_back(std::move(item));")
                } else {
                    val elemRead = mapToCppScalarReadExpr(elemType)
                    line("$targetVar.push_back($elemRead);")
                }
            }
        } else {
            val elemType = field.type
            if (schema.structs.containsKey(elemType)) {
                if (isOptional) {
                    w.line("$targetVar.emplace();")
                    w.line("$targetVar->read(buffer);")
                } else {
                    w.line("$targetVar.read(buffer);")
                }
            } else {
                val readExpr = mapToCppScalarReadExpr(field.type, field.maxLength)
                w.line("$targetVar = $readExpr;")
                val checkVar = if (isOptional) "(*$targetVar)" else targetVar
                if (field.strictEnum && !field.enumValues.isNullOrEmpty()) {
                    val allowed = field.enumValues.values.distinct().sorted()
                    val cond = allowed.joinToString(" && ") { "$checkVar != $it" }
                    w.block("if ($cond)") {
                        line("throw std::runtime_error(\"Invalid enum value for ${field.name}\");")
                    }
                }
                val bits = field.bits
                if (bits != null && !field.unpackBits) {
                    for (b in bits) {
                        if (b.strictEnum && !b.enumValues.isNullOrEmpty()) {
                            val bVar = "bit_${sanitizeIdentifier(b.name)}"
                            val extract = CodegenExprUtils.extractBitExpr(checkVar, b, ExprLang.CPP)
                            val allowed = b.enumValues.values.distinct().sorted()
                            val cond = allowed.joinToString(" && ") { "$bVar != $it" }
                            w.line("int32_t $bVar = $extract;")
                            w.block("if ($cond)") {
                                line(
                                    "throw std::runtime_error(\"Invalid enum value for ${b.name}\");"
                                )
                            }
                        }
                    }
                }
            }
        }
    }

    private fun emitCppWriteFields(
        w: CodeWriter,
        fields: List<SchemaField>,
        sparseParameters: List<SchemaSparseParam>?,
        props: List<AstProperty>,
        sparseCountType: String? = null,
        sparseKeyType: String? = null,
    ) {
        val propByName = props.associateBy { it.name }

        for (field in fields) {
            val bits = field.bits
            if (bits != null && field.unpackBits) {
                val terms = mutableListOf<Pair<String, SchemaBitField>>()
                for (b in bits) {
                    val bName = sanitizeIdentifier(b.name)
                    if (b.derivedFrom != null) {
                        val expr = derivedExprToCpp(DerivedExpr.parse(b.derivedFrom), propByName)
                        w.line("int32_t $bName = $expr;")
                        terms.add(bName to b)
                    } else {
                        terms.add(bName to b)
                    }
                }
                val packed = CodegenExprUtils.packBitsExpr(terms, ExprLang.CPP)
                w.line("buffer.writeInt($packed);")
                continue
            }

            if (field.derivedFrom != null) {
                val derivedVal = derivedExprToCpp(DerivedExpr.parse(field.derivedFrom), propByName)
                if (field.presentIf != null) {
                    val cond =
                        CodegenExprUtils.translateCondition(field.presentIf, ExprLang.CPP) {
                            sanitizeIdentifier(it)
                        }
                    w.block("if ($cond)") {
                        line("${mapToCppScalarWriteExpr(field.type, derivedVal)};")
                    }
                } else {
                    w.line("${mapToCppScalarWriteExpr(field.type, derivedVal)};")
                }
                continue
            }

            val fieldName = sanitizeIdentifier(field.name)
            val isNullable = propByName[field.name]?.isNullable == true

            if (field.presentIf != null) {
                val cond =
                    CodegenExprUtils.translateCondition(field.presentIf, ExprLang.CPP) {
                        sanitizeIdentifier(it)
                    }
                w.block("if ($cond)") {
                    if (isNullable) {
                        block("if (!$fieldName.has_value())") {
                            line(
                                "throw std::runtime_error(\"Missing required field ${field.name}\");"
                            )
                        }
                        emitCppFieldWriteBody(this, field, "(*$fieldName)")
                    } else {
                        emitCppFieldWriteBody(this, field, fieldName)
                    }
                }
            } else {
                emitCppFieldWriteBody(w, field, fieldName)
            }
        }

        if (sparseParameters != null) {
            w.line("int32_t sparseCount = 0;")
            for (sp in sparseParameters) {
                w.line("if (${sanitizeIdentifier(sp.name)}.has_value()) ++sparseCount;")
            }
            when (sparseCountType ?: "ushort") {
                "int" -> w.line("buffer.writeInt(sparseCount);")
                "ubyte",
                "byte" -> w.line("buffer.writeByte(static_cast<uint8_t>(sparseCount));")
                else -> w.line("buffer.writeShort(static_cast<int16_t>(sparseCount));")
            }
            val effectiveKeyType = sparseKeyType ?: "ubyte"
            for (sp in sparseParameters) {
                val spName = sanitizeIdentifier(sp.name)
                w.block("if ($spName.has_value())") {
                    when (effectiveKeyType) {
                        "int" -> line("buffer.writeInt(${sp.id});")
                        "ushort",
                        "short" -> line("buffer.writeShort(static_cast<int16_t>(${sp.id}));")
                        else -> line("buffer.writeByte(static_cast<uint8_t>(${sp.id}));")
                    }
                    val synField =
                        SchemaField(
                            name = sp.name,
                            type = sp.type,
                            description = sp.description,
                            enumValues = null,
                            lengthType = sp.lengthType ?: "ushort",
                        )
                    emitCppFieldWriteBody(this, synField, "(*$spName)")
                }
            }
        }
    }

    private fun emitCppFieldWriteBody(
        w: CodeWriter,
        field: SchemaField,
        varExpr: String,
    ) {
        if (field.type.endsWith("[]")) {
            if (field.countFrom == null) {
                when (field.effectiveLengthType) {
                    "int" -> w.line("buffer.writeInt(static_cast<int32_t>($varExpr.size()));")
                    "ubyte",
                    "byte" -> w.line("buffer.writeByte(static_cast<uint8_t>($varExpr.size()));")
                    else -> w.line("buffer.writeShort(static_cast<int16_t>($varExpr.size()));")
                }
            }
            val elemType = field.type.removeSuffix("[]")
            w.block("for (const auto& item : $varExpr)") {
                if (schema.structs.containsKey(elemType)) {
                    line("item.write(buffer);")
                } else {
                    line("${mapToCppScalarWriteExpr(elemType, "item")};")
                }
            }
        } else if (schema.structs.containsKey(field.type)) {
            w.line("$varExpr.write(buffer);")
        } else {
            w.line("${mapToCppScalarWriteExpr(field.type, varExpr)};")
        }
    }

    private fun derivedExprToCpp(
        expr: DerivedExpr,
        propByName: Map<String, AstProperty>,
    ): String {
        val target = sanitizeIdentifier(expr.targetName)
        return when (expr) {
            is DerivedExpr.LengthOf -> "static_cast<int32_t>($target.size())"
            is DerivedExpr.PresentOf -> "($target.has_value() ? 1 : 0)"
            is DerivedExpr.NonEmptyOf -> {
                val prop = propByName[expr.targetName]
                if (prop?.isNullable == true) {
                    "($target.has_value() && !$target->empty() ? 1 : 0)"
                } else {
                    "(!$target.empty() ? 1 : 0)"
                }
            }
        }
    }

    private fun sanitizeIdentifier(name: String): String =
        CodegenExprUtils.cleanSchemaIdentifier(name)

