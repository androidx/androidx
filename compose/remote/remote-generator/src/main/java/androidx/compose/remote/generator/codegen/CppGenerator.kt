    companion object {
        private const val WRITER_GUARD = "defined(RC_ENABLE_WRITER) && RC_ENABLE_WRITER"

        fun mapToCppType(type: String, isNullable: Boolean = false): String {
            val base =
                when (type) {
                    "int" -> "int32_t"
                    "short" -> "int16_t"
                    "byte" -> "uint8_t"
                    "long" -> "int64_t"
                    "float",
                    "float_or_id" -> "float"
                    "boolean" -> "bool"
                    "string" -> "std::string_view"
                    "color" -> "uint32_t"
                    "bytes" -> "BufferView"
                    "int[]" -> "std::vector<int32_t>"
                    "short[]" -> "std::vector<int16_t>"
                    "float[]",
                    "float_or_id[]" -> "std::vector<float>"
                    else ->
                        if (type.endsWith("[]")) {
                            "std::vector<${type.removeSuffix("[]")}>"
                        } else {
                            type
                        }
                }
            return if (isNullable) "std::optional<$base>" else base
        }

        fun mapToCppInitSuffix(
            type: String,
            isNullable: Boolean,
            defaultValue: String?,
        ): String {
            if (isNullable || defaultValue == null) return "{}"
            return " = ${mapToCppFallbackLiteral(type, defaultValue)}"
        }

        fun mapToCppFallbackLiteral(type: String, defaultValue: String?): String {
            if (defaultValue == null) {
                return when (type) {
                    "float",
                    "float_or_id" -> "0.0f"
                    "boolean" -> "false"
                    "string" -> "\"\""
                    "bytes" -> "BufferView{}"
                    else -> "0"
                }
            }
            val dv = defaultValue.trim()
            return when (type) {
                "float",
                "float_or_id" -> if (dv.endsWith("f") || dv.endsWith("F")) dv else "${dv}f"
                "string" -> "\"$dv\""
                else -> dv
            }
        }

        fun mapToCppScalarReadExpr(type: String, maxLength: Int? = null): String =
            when (type) {
                "int" -> "buffer.readInt()"
                "short" -> "buffer.readShort()"
                "byte" -> "buffer.readByte()"
                "long" -> "buffer.readLong()"
                "float",
                "float_or_id" -> "buffer.readFloat()"
                "boolean" -> "buffer.readBoolean()"
                "string" ->
                    if (maxLength != null) "buffer.readStringView($maxLength)"
                    else "buffer.readStringView()"
                "color" -> "static_cast<uint32_t>(buffer.readInt())"
                "bytes" ->
                    if (maxLength != null) "buffer.readBufferView($maxLength)"
                    else "buffer.readBufferView()"
                else -> "buffer.readInt()"
            }

        fun mapToCppScalarWriteExpr(type: String, varName: String): String =
            when (type) {
                "int" -> "buffer.writeInt($varName)"
                "short" -> "buffer.writeShort($varName)"
                "byte" -> "buffer.writeByte($varName)"
                "long" -> "buffer.writeLong($varName)"
                "float",
                "float_or_id" -> "buffer.writeFloat($varName)"
                "boolean" -> "buffer.writeBoolean($varName)"
                "string" -> "buffer.writeStringView($varName)"
                "color" -> "buffer.writeInt(static_cast<int32_t>($varName))"
                "bytes" -> "buffer.writeBufferView($varName)"
                else -> "buffer.writeInt($varName)"
            }
    }
