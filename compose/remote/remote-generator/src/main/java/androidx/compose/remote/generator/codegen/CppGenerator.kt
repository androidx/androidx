/**
 * Generator that transforms an [OperationSchema] into idiomatic C++17 bindings:
 * - OpCode enum class
 * - Auxiliary wire payload structs
 * - Abstract Operation base class
 * - Concrete typed Operation classes with WireBuffer serialization/deserialization
 * - RemoteDocument container and factory functions
 * - Self-contained WireBuffer reader/writer header and source
 */
internal class CppGenerator(private val schema: OperationSchema) {

    /** Generates RemoteComposeOps.h */
    fun generateHeader(): String {
        val sb = StringBuilder()
        sb.append(
            """
            // Generated by RemoteCompose Schema Codegen. DO NOT EDIT.
            #ifndef ANDROIDX_REMOTE_COMPOSE_OPS_H
            #define ANDROIDX_REMOTE_COMPOSE_OPS_H

            #include <cstdint>
            #include <string>
            #include <algorithm>
            #include <string_view>
            #include <vector>
            #include <memory>
            #include <optional>
            #include <stdexcept>
            #include "WireBuffer.h"

            // Profile compilation configuration:
            // Normalize profile macros to 0/1 so -DRC_PROFILE_*=0 disables the profile.
            #ifndef RC_PROFILE_BASELINE
            #define RC_PROFILE_BASELINE 0
            #endif
            #ifndef RC_PROFILE_WIDGETS
            #define RC_PROFILE_WIDGETS 0
            #endif
            #ifndef RC_PROFILE_ANDROIDX
            #define RC_PROFILE_ANDROIDX 0
            #endif
            #ifndef RC_PROFILE_EXPERIMENTAL
            #define RC_PROFILE_EXPERIMENTAL 0
            #endif
            #ifndef RC_PROFILE_DEPRECATED
            #define RC_PROFILE_DEPRECATED 0
            #endif
            #ifndef RC_PROFILE_OEM
            #define RC_PROFILE_OEM 0
            #endif
            #ifndef RC_PROFILE_ALL
            #define RC_PROFILE_ALL 0
            #endif
            // If no profile macro is explicitly enabled, enable all profiles.
            #if !RC_PROFILE_ALL && !RC_PROFILE_BASELINE && !RC_PROFILE_WIDGETS && \
                !RC_PROFILE_ANDROIDX && !RC_PROFILE_EXPERIMENTAL && \
                !RC_PROFILE_DEPRECATED && !RC_PROFILE_OEM
            #undef RC_PROFILE_ALL
            #define RC_PROFILE_ALL 1
            #endif

            // Writer compilation configuration:
            // Enabled by default (1) unless RC_ENABLE_WRITER is explicitly set
            // or RC_NO_WRITER is defined.
            #if !defined(RC_ENABLE_WRITER)
            #if defined(RC_NO_WRITER)
            #define RC_ENABLE_WRITER 0
            #else
            #define RC_ENABLE_WRITER 1
            #endif
            #endif

            namespace androidx::compose::remote {

            /**
             * Wire protocol opcodes for RemoteCompose operations.
             */
            enum class OpCode : uint8_t {
            """
                .trimIndent()
        )
        sb.append("\n")

        for (op in schema.operations) {
            val desc = op.description.replace("\n", " ").trim()
            if (desc.isNotEmpty()) {
                sb.append("    /// $desc\n")
            }
            sb.append("    ${op.name} = ${op.id},\n")
        }

        sb.append(
            """
            };

            const char* getOpCodeName(OpCode op);

            /**
             * Abstract base class for all RemoteCompose operations.
             */
            class Operation {
            public:
                virtual ~Operation() = default;
                /** Returns the wire protocol opcode for this operation. */
                virtual OpCode getOpCode() const = 0;
                /** Deserializes this operation from the wire buffer. */
                virtual void read(WireBuffer& buffer) = 0;
            #if defined(RC_ENABLE_WRITER) && RC_ENABLE_WRITER
                /** Serializes this operation to the wire buffer. */
                virtual void write(WireBuffer& buffer) const = 0;
            #endif
            };
            """
                .trimIndent()
        )
        sb.append("\n\n")

        for ((_, structDef) in schema.structs) {
            sb.append(generateStructDeclaration(structDef))
            sb.append("\n\n")
        }

        for (op in schema.operations) {
            sb.append(generateClassDeclaration(op))
            sb.append("\n\n")
        }

        sb.append(
            """
            /**
             * In-memory container representing a parsed RemoteCompose document.
             */
            class RemoteDocument {
            public:
                static constexpr size_t kMaxHeaderProperties = 1000;
                static constexpr size_t kDefaultMaxOperations = 100000;

                int32_t majorVersion = 1;
                int32_t minorVersion = 1;
                int32_t patchVersion = 0;
                int32_t width = 0;
                int32_t height = 0;
                int64_t capabilities = 0;
                std::vector<std::shared_ptr<Operation>> operations;

                /** Deserializes a RemoteDocument from the provided buffer. */
                static std::shared_ptr<RemoteDocument> load(
                    WireBuffer& buffer,
                    size_t maxOperations = kDefaultMaxOperations);
            #if defined(RC_ENABLE_WRITER) && RC_ENABLE_WRITER
                /** Serializes this document into the provided buffer. */
                void save(WireBuffer& buffer) const;
            #endif
            };

            /** Factory function to create an Operation given its OpCode. */
            std::shared_ptr<Operation> createOperation(OpCode op);

            } // namespace androidx::compose::remote

            #endif // ANDROIDX_REMOTE_COMPOSE_OPS_H
            """
                .trimIndent()
        )
        sb.append("\n")
        return sb.toString()
    }

    /** Generates RemoteComposeOps.cpp */
    fun generateSource(): String {
        val sb = StringBuilder()
        sb.append(
            """
            // Generated by RemoteCompose Schema Codegen. DO NOT EDIT.
            #include "RemoteComposeOps.h"

            namespace androidx::compose::remote {

            const char* getOpCodeName(OpCode op) {
                switch (op) {
            """
                .trimIndent()
        )
        sb.append("\n")

        for (op in schema.operations) {
            val guard = getProfileGuard(op)
            if (guard != null) {
                sb.append("#if $guard\n")
                sb.append("        case OpCode::${op.name}: return \"${op.name}\";\n")
                sb.append("#endif\n")
            } else {
                sb.append("        case OpCode::${op.name}: return \"${op.name}\";\n")
            }
        }

        sb.append(
            """
                    default: return "Unknown";
                }
            }
            """
                .trimIndent()
        )
        sb.append("\n\n")

        for ((_, structDef) in schema.structs) {
            sb.append(generateStructImplementation(structDef))
            sb.append("\n\n")
        }

        for (op in schema.operations) {
            sb.append(generateClassImplementation(op))
            sb.append("\n\n")
        }

        sb.append(
            """
            std::shared_ptr<Operation> createOperation(OpCode op) {
                switch (op) {
            """
                .trimIndent()
        )
        sb.append("\n")

        for (op in schema.operations) {
            val guard = getProfileGuard(op)
            if (guard != null) {
                sb.append("#if $guard\n")
                sb.append(
                    "        case OpCode::${op.name}: return std::make_shared<${op.name}>();\n"
                )
                sb.append("#endif\n")
            } else {
                sb.append(
                    "        case OpCode::${op.name}: return std::make_shared<${op.name}>();\n"
                )
            }
        }

        sb.append(
            """
                    default: return nullptr;
                }
            }

            std::shared_ptr<RemoteDocument> RemoteDocument::load(
                WireBuffer& buffer,
                size_t maxOperations) {
                auto doc = std::make_shared<RemoteDocument>();
                if (!buffer.available()) return doc;

                uint8_t headerOp = buffer.readByte();
                if (headerOp != static_cast<uint8_t>(OpCode::Header)) {
                    throw std::runtime_error("Expected Header operation at start of document");
                }
                int32_t rawMajor = buffer.readInt();
                doc->minorVersion = buffer.readInt();
                doc->patchVersion = buffer.readInt();
                if ((static_cast<uint32_t>(rawMajor) & 0xFFFF0000u) == 0x048C0000u) {
                    doc->majorVersion = rawMajor & 0xFFFF;
                    int32_t numProps = buffer.readInt();
                    if (numProps < 0 || static_cast<size_t>(numProps) > kMaxHeaderProperties) {
                        throw std::runtime_error("Invalid numProps in header");
                    }
                    if (static_cast<size_t>(numProps) > buffer.remaining() / 4) {
                        throw std::runtime_error(
                            "Header property count exceeds remaining buffer size");
                    }
                    for (int32_t i = 0; i < numProps; i++) {
                        uint16_t tag = static_cast<uint16_t>(buffer.readShort());
                        uint16_t itemLen = static_cast<uint16_t>(buffer.readShort());
                        int32_t dataType = (tag >> 10) & 0x3F;
                        int32_t key = tag & 0x3FF;
                        switch (dataType) {
                            case 0: { // INT
                                int32_t val = buffer.readInt();
                                if (key == 5) doc->width = val;
                                else if (key == 6) doc->height = val;
                                else if (key == 14) {
                                    doc->capabilities =
                                        static_cast<int64_t>(static_cast<uint32_t>(val));
                                } else if (key == 31 && val != 0) {
                                    throw std::runtime_error(
                                        "Compressed RemoteCompose documents are not supported");
                                }
                                break;
                            }
                            case 1: { // FLOAT
                                buffer.readFloat();
                                break;
                            }
                            case 2: { // LONG
                                int64_t val = buffer.readLong();
                                if (key == 14) doc->capabilities = val;
                                else if (key == 31 && val != 0) {
                                    throw std::runtime_error(
                                        "Compressed RemoteCompose documents are not supported");
                                }
                                break;
                            }
                            case 3: { // STRING
                                buffer.readStringView();
                                break;
                            }
                            default: {
                                if (itemLen > buffer.remaining()) {
                                    throw std::runtime_error(
                                        "Header property length exceeds remaining buffer size");
                                }
                                buffer.setIndex(buffer.getIndex() + itemLen);
                                break;
                            }
                        }
                    }
                } else if (rawMajor >= 0 && rawMajor < 0x10000) {
                    doc->majorVersion = rawMajor;
                    doc->width = buffer.readInt();
                    doc->height = buffer.readInt();
                    doc->capabilities = buffer.readLong();
                } else {
                    throw std::runtime_error("Invalid header magic number");
                }

                while (buffer.available()) {
                    uint8_t opByte = buffer.readByte();
                    if (opByte == static_cast<uint8_t>(OpCode::Header)) {
                        throw std::runtime_error("Unexpected Header opcode in document body");
                    }
                    if (doc->operations.size() >= maxOperations) {
                        throw std::runtime_error(
                            "Document exceeds maximum allowed operation count");
                    }
                    auto op = createOperation(static_cast<OpCode>(opByte));
                    if (!op) {
                        throw std::runtime_error(
                            "Unknown or unsupported opcode: " + std::to_string(opByte));
                    }
                    op->read(buffer);
                    doc->operations.push_back(op);
                }
                return doc;
            }

            #if defined(RC_ENABLE_WRITER) && RC_ENABLE_WRITER
            void RemoteDocument::save(WireBuffer& buffer) const {
                buffer.writeByte(static_cast<uint8_t>(OpCode::Header));
                buffer.writeInt(majorVersion);
                buffer.writeInt(minorVersion);
                buffer.writeInt(patchVersion);
                buffer.writeInt(width);
                buffer.writeInt(height);
                buffer.writeLong(capabilities);

                for (const auto& op : operations) {
                    if (op) {
                        op->write(buffer);
                    }
                }
            }
            #endif

            } // namespace androidx::compose::remote
            """
                .trimIndent()
        )
        sb.append("\n")
        return sb.toString()
    }

    private fun getProfileGuard(op: SchemaOperation): String? {
        if (op.profiles.contains("baseline") || op.profiles.isEmpty()) {
            return null
        }
        val platformTerms = mutableListOf<String>()
        if (op.profiles.contains("androidx")) {
            platformTerms.add("RC_PROFILE_ANDROIDX")
        }
        if (op.profiles.contains("widgets")) {
            platformTerms.add("RC_PROFILE_WIDGETS")
        }
        if (op.profiles.contains("oem")) {
            platformTerms.add("RC_PROFILE_OEM")
        }
        val modifierTerms = mutableListOf<String>()
        if (op.profiles.contains("experimental")) {
            modifierTerms.add("RC_PROFILE_EXPERIMENTAL")
        }
        if (op.profiles.contains("deprecated")) {
            modifierTerms.add("RC_PROFILE_DEPRECATED")
        }
        val clauses = mutableListOf<String>()
        if (platformTerms.isNotEmpty()) {
            clauses.add(
                if (platformTerms.size == 1) platformTerms[0]
                else "(${platformTerms.joinToString(" || ")})"
            )
        }
        clauses.addAll(modifierTerms)
        if (clauses.isEmpty()) {
            return "RC_PROFILE_ALL"
        }
        val combined = if (clauses.size == 1) clauses[0] else "(${clauses.joinToString(" && ")})"
        return "RC_PROFILE_ALL || $combined"
    }

    private fun generateStructDeclaration(structDef: SchemaStruct): String {
        val sb = StringBuilder()
        val props = structDef.astProperties
        val desc = structDef.description.replace("\n", " ").trim()
        if (desc.isNotEmpty()) {
            sb.append("/** $desc */\n")
        }
        sb.append("struct ${structDef.name} {\n")
        appendCppMemberFields(sb, props)
        sb.append("\n")
        sb.append("    ${structDef.name}() = default;\n")
        appendCppConstructor(sb, structDef.name, props)
        appendCppComputedBitGetters(sb, structDef.computedBitProperties)
        sb.append("\n")
        sb.append("    void read(WireBuffer& buffer);\n")
        sb.append("#if defined(RC_ENABLE_WRITER) && RC_ENABLE_WRITER\n")
        sb.append("    void write(WireBuffer& buffer) const;\n")
        sb.append("#endif\n")
        sb.append("};")
        return sb.toString()
    }

    private fun generateClassDeclaration(op: SchemaOperation): String {
        val sb = StringBuilder()
        val guard = getProfileGuard(op)
        if (guard != null) {
            sb.append("#if $guard\n")
        }
        val props = op.astProperties
        val desc = op.description.replace("\n", " ").trim()
        val hasZeroCopyViews = props.any { it.type == "string" || it.type == "bytes" }
        if (desc.isNotEmpty() || hasZeroCopyViews) {
            sb.append("/**\n")
            if (desc.isNotEmpty()) {
                sb.append(" * $desc\n")
            }
            if (hasZeroCopyViews) {
                sb.append(" *\n")
                sb.append(" * NOTE: Contains non-owning view fields ")
                sb.append("(std::string_view or BufferView).\n")
                sb.append(" * Backing memory must outlive this operation instance.\n")
            }
            sb.append(" */\n")
        }
        sb.append("class ${op.name} : public Operation {\n")
        sb.append("public:\n")
        sb.append("    static constexpr OpCode OP_CODE = OpCode::${op.name};\n\n")

        appendCppMemberFields(sb, props)
        sb.append("\n")
        sb.append("    ${op.name}() = default;\n")
        appendCppConstructor(sb, op.name, props)
        appendCppComputedBitGetters(sb, op.computedBitProperties)

        sb.append("\n")
        sb.append("    OpCode getOpCode() const override { return OP_CODE; }\n")
        sb.append("    void read(WireBuffer& buffer) override;\n")
        sb.append("#if defined(RC_ENABLE_WRITER) && RC_ENABLE_WRITER\n")
        sb.append("    void write(WireBuffer& buffer) const override;\n")
        sb.append("#endif\n")
        sb.append("};")
        if (guard != null) {
            sb.append("\n#endif // $guard")
        }
        return sb.toString()
    }

    private fun appendCppMemberFields(sb: StringBuilder, props: List<AstProperty>) {
        for (prop in props) {
            val cppType = mapToCppType(prop.type, prop.isNullable)
            val fieldName = sanitizeIdentifier(prop.name)
            val fieldDesc = prop.description.replace("\n", " ").trim()
            if (fieldDesc.isNotEmpty()) {
                sb.append("    /// $fieldDesc\n")
            }
            val initSuffix = mapToCppInitSuffix(prop.type, prop.isNullable, prop.defaultValue)
            sb.append("    $cppType $fieldName$initSuffix;\n")
        }
    }

    private fun appendCppConstructor(
        sb: StringBuilder,
        className: String,
        props: List<AstProperty>,
    ) {
        if (props.isEmpty()) return
        val params =
            props.joinToString(", ") {
                "${mapToCppType(it.type, it.isNullable)} _${sanitizeIdentifier(it.name)}"
            }
        val inits =
            props.joinToString(", ") {
                val fn = sanitizeIdentifier(it.name)
                "$fn(_$fn)"
            }
        val ctorLine = "    $className($params) : $inits {}\n"
        if (ctorLine.length <= 100) {
            sb.append(ctorLine)
        } else {
            sb.append("    $className(\n")
            for (i in props.indices) {
                val prop = props[i]
                val p =
                    "${mapToCppType(prop.type, prop.isNullable)} _${sanitizeIdentifier(prop.name)}"
                val comma = if (i < props.size - 1) "," else ""
                sb.append("        $p$comma\n")
            }
            sb.append("    ) :\n")
            for (i in props.indices) {
                val fn = sanitizeIdentifier(props[i].name)
                val comma = if (i < props.size - 1) "," else " {}"
                sb.append("        $fn(_$fn)$comma\n")
            }
        }
    }

    private fun appendCppComputedBitGetters(
        sb: StringBuilder,
        computedBits: List<Pair<String, SchemaBitField>>,
    ) {
        if (computedBits.isEmpty()) return
        sb.append("\n")
        for ((parentName, bit) in computedBits) {
            val getterName = "get" + bit.name.replaceFirstChar { it.uppercaseChar() }
            val expr =
                CodegenExprUtils.extractBitExpr(sanitizeIdentifier(parentName), bit, ExprLang.CPP)
            sb.append("    int32_t $getterName() const { return $expr; }\n")
        }
    }

    private fun generateStructImplementation(structDef: SchemaStruct): String {
        val sb = StringBuilder()
        sb.append("void ${structDef.name}::read(WireBuffer& buffer) {\n")
        appendCppReadFields(sb, structDef.fields, null)
        sb.append("}\n\n")
        sb.append("#if defined(RC_ENABLE_WRITER) && RC_ENABLE_WRITER\n")
        sb.append("void ${structDef.name}::write(WireBuffer& buffer) const {\n")
        appendCppWriteFields(sb, structDef.fields, null, structDef.astProperties)
        sb.append("}\n")
        sb.append("#endif // RC_ENABLE_WRITER")
        return sb.toString()
    }

    private fun generateClassImplementation(op: SchemaOperation): String {
        val sb = StringBuilder()
        val guard = getProfileGuard(op)
        if (guard != null) {
            sb.append("#if $guard\n")
        }
        sb.append("void ${op.name}::read(WireBuffer& buffer) {\n")
        appendCppReadFields(sb, op.fields, op.sparseParameters)
        sb.append("}\n\n")

        sb.append("#if defined(RC_ENABLE_WRITER) && RC_ENABLE_WRITER\n")
        sb.append("void ${op.name}::write(WireBuffer& buffer) const {\n")
        sb.append("    buffer.writeByte(static_cast<uint8_t>(OP_CODE));\n")
        appendCppWriteFields(sb, op.fields, op.sparseParameters, op.astProperties)
        sb.append("}\n")
        sb.append("#endif // RC_ENABLE_WRITER")
        if (guard != null) {
            sb.append("\n#endif // $guard")
        }
        return sb.toString()
    }

    private fun appendCppReadFields(
        sb: StringBuilder,
        fields: List<SchemaField>,
        sparseParameters: List<SchemaSparseParam>?,
    ) {
        for (field in fields) {
            val bits = field.bits
            if (bits != null && field.unpackBits) {
                val rawVar = "raw_${sanitizeIdentifier(field.name)}"
                sb.append("    int32_t $rawVar = buffer.readInt();\n")
                for (b in bits) {
                    val bName = sanitizeIdentifier(b.name)
                    val extract = CodegenExprUtils.extractBitExpr(rawVar, b, ExprLang.CPP)
                    if (b.derivedFrom != null) {
                        sb.append("    int32_t $bName = $extract;\n")
                    } else {
                        sb.append("    $bName = $extract;\n")
                    }
                }
                continue
            }

            val fieldName = sanitizeIdentifier(field.name)
            val isLocalDerived = field.derivedFrom != null
            val isNullable =
                !isLocalDerived &&
                    field.presentIf != null &&
                    !field.type.endsWith("[]") &&
                    field.defaultValue == null

            if (field.presentIf != null) {
                val cond =
                    CodegenExprUtils.translateCondition(field.presentIf, ExprLang.CPP) {
                        sanitizeIdentifier(it)
                    }
                if (isLocalDerived) {
                    val cppType = mapToCppType(field.type, false)
                    val readExpr = mapToCppScalarReadExpr(field.type)
                    sb.append("    $cppType $fieldName = ($cond) ? ($readExpr) : 0;\n")
                } else {
                    sb.append("    if ($cond) {\n")
                    appendCppFieldReadAssign(sb, field, fieldName, "        ")
                    sb.append("    } else {\n")
                    if (field.type.endsWith("[]")) {
                        sb.append("        $fieldName.clear();\n")
                    } else if (isNullable) {
                        sb.append("        $fieldName = std::nullopt;\n")
                    } else {
                        val fallback = mapToCppFallbackLiteral(field.type, field.defaultValue)
                        sb.append("        $fieldName = $fallback;\n")
                    }
                    sb.append("    }\n")
                }
            } else if (isLocalDerived) {
                val cppType = mapToCppType(field.type, false)
                val readExpr = mapToCppScalarReadExpr(field.type)
                sb.append("    $cppType $fieldName = $readExpr;\n")
            } else {
                appendCppFieldReadAssign(sb, field, fieldName, "    ")
            }
        }

        if (sparseParameters != null) {
            for (sp in sparseParameters) {
                sb.append("    ${sanitizeIdentifier(sp.name)} = std::nullopt;\n")
            }
            sb.append("    int32_t sparseCount = static_cast<uint16_t>(buffer.readShort());\n")
            sb.append("    if (static_cast<size_t>(sparseCount) > buffer.remaining() / 2) {\n")
            sb.append(
                "        throw std::runtime_error(\"Sparse parameter count exceeds remaining buffer size\");\n"
            )
            sb.append("    }\n")
            sb.append("    for (int32_t s = 0; s < sparseCount; ++s) {\n")
            sb.append("        uint8_t paramId = buffer.readByte();\n")
            sb.append("        switch (paramId) {\n")
            for (sp in sparseParameters) {
                val spName = sanitizeIdentifier(sp.name)
                sb.append("            case ${sp.id}: {\n")
                if (sp.type.endsWith("[]")) {
                    val vecType = mapToCppType(sp.type, false)
                    val tmpName = "tmp_$spName"
                    sb.append("                $vecType $tmpName;\n")
                    val synField =
                        SchemaField(
                            name = sp.name,
                            type = sp.type,
                            description = sp.description,
                            enumValues = null,
                            lengthType = "ushort",
                        )
                    appendCppFieldReadAssign(sb, synField, tmpName, "                ")
                    sb.append("                $spName = std::move($tmpName);\n")
                } else {
                    val readExpr = mapToCppScalarReadExpr(sp.type)
                    sb.append("                $spName = $readExpr;\n")
                }
                sb.append("                break;\n")
                sb.append("            }\n")
            }
            sb.append(
                "            default: throw std::runtime_error(\"Unknown sparse parameter ID\");\n"
            )
            sb.append("        }\n")
            sb.append("    }\n")
        }
    }

    private fun appendCppFieldReadAssign(
        sb: StringBuilder,
        field: SchemaField,
        targetVar: String,
        indent: String,
    ) {
        if (field.type.endsWith("[]")) {
            val lenExpr =
                if (field.countFrom != null) {
                    sanitizeIdentifier(field.countFrom)
                } else {
                    when (field.effectiveLengthType) {
                        "int" -> "buffer.readInt()"
                        "ushort" ->
                            "static_cast<int32_t>(static_cast<uint16_t>(buffer.readShort()))"
                        else -> "static_cast<int32_t>(buffer.readShort())"
                    }
                }
            val lenVar = "${targetVar}_len"
            val elemType = field.type.removeSuffix("[]")
            val elemMinBytes = CodegenExprUtils.minWireElementBytes(elemType, schema)
            sb.append("${indent}int32_t $lenVar = $lenExpr;\n")
            sb.append("${indent}if ($lenVar < 0) {\n")
            sb.append("${indent}    throw std::runtime_error(\"Negative array length\");\n")
