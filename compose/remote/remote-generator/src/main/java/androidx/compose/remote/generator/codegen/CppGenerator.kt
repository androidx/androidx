                        enumValues = null,
                        lengthType = "short",
                    )
                appendCppFieldWriteBody(sb, synField, "(*$spName)", "        ")
                sb.append("    }\n")
            }
        }
    }

    private fun appendCppFieldWriteBody(
        sb: StringBuilder,
        field: SchemaField,
        varExpr: String,
        indent: String,
    ) {
        if (field.type.endsWith("[]")) {
            if (field.countFrom == null) {
                when (field.effectiveLengthType) {
                    "int" ->
                        sb.append(
                            "${indent}buffer.writeInt(static_cast<int32_t>($varExpr.size()));\n"
                        )
                    else ->
                        sb.append(
                            "${indent}buffer.writeShort(static_cast<int16_t>($varExpr.size()));\n"
                        )
                }
            }
            val elemType = field.type.removeSuffix("[]")
            if (schema.structs.containsKey(elemType)) {
                sb.append("${indent}for (const auto& item : $varExpr) {\n")
                sb.append("$indent    item.write(buffer);\n")
                sb.append("$indent}\n")
            } else {
                sb.append("${indent}for (const auto& item : $varExpr) {\n")
                sb.append("$indent    ${mapToCppScalarWriteExpr(elemType, "item")};\n")
                sb.append("$indent}\n")
            }
        } else if (schema.structs.containsKey(field.type)) {
            sb.append("$indent$varExpr.write(buffer);\n")
        } else {
            sb.append("$indent${mapToCppScalarWriteExpr(field.type, varExpr)};\n")
        }
    }

    private fun derivedExprToCpp(
        expr: DerivedExpr,
        propByName: Map<String, AstProperty>,
    ): String {
        val target = sanitizeIdentifier(expr.targetName)
        return when (expr) {
            is DerivedExpr.LengthOf -> "static_cast<int32_t>($target.size())"
            is DerivedExpr.PresentOf -> "($target.has_value() ? 1 : 0)"
            is DerivedExpr.NonEmptyOf -> {
                val prop = propByName[expr.targetName]
                if (prop?.isNullable == true) {
                    "($target.has_value() && !$target->empty() ? 1 : 0)"
                } else {
                    "(!$target.empty() ? 1 : 0)"
                }
            }
        }
    }

