/**
 * Generator that transforms an [OperationSchema] into TypeScript bindings:
 * - OpCode enum
 * - Auxiliary struct classes and typed Operation classes with WireBuffer serialization
 * - RemoteDocument container
 * - Browser/Node compatible WireBuffer implementation
 */
internal class TypeScriptGenerator(private val schema: OperationSchema) {

    private val multiLang = MultiLangProtocolGenerator(schema)

    fun generate(): String =
        buildCode(indentUnit = "  ") {
            line("// Generated by RemoteCompose Schema Codegen. DO NOT EDIT.")
            line()
            line("/**")
            line(" * Operation wire identifiers for RemoteCompose.")
            line(" */")
            block("export enum OpCode") {
                for (op in schema.operations) {
                    val desc = op.description.replace("\n", " ").trim()
                    if (desc.isNotEmpty()) {
                        line("/** $desc */")
                    }
                    line("${op.name} = ${op.id},")
                }
            }
            line()
            line("/**")
            line(" * Base interface for all RemoteCompose operations.")
            line(" */")
            block("export interface Operation") {
                line("readonly opCode: OpCode;")
                line("write(buffer: WireBuffer): void;")
            }
            line()
            emitWireBuffer(this)
            line()
            multiLang.emitTsProtocol(this)
            for ((_, structDef) in schema.structs) {
                emitAuxClass(this, structDef)
                line()
            }
            for (op in schema.operations) {
                emitClass(this, op)
                line()
            }
            emitCreateOperation(this)
            line()
            emitRemoteDocument(this)
        }

    private fun emitWireBuffer(w: CodeWriter) {
        w.block("export class WireBuffer") {
            block(
                "private static readonly utf8Decoder = new TextDecoder(\"utf-8\",",
                close = "});",
            ) {
                line("fatal: true,")
                line("ignoreBOM: true,")
            }
            line("private buffer: Uint8Array;")
            line("private view: DataView;")
            line("private index: number = 0;")
            line("private size: number = 0;")
            line()
            block("constructor(initialCapacity: number = 1024)") {
                line("this.buffer = new Uint8Array(initialCapacity);")
                line("this.view = new DataView(this.buffer.buffer);")
            }
            line()
            block("static fromBytes(bytes: Uint8Array): WireBuffer") {
                line("const wb = new WireBuffer(bytes.length);")
                line("wb.buffer.set(bytes);")
                line("wb.size = bytes.length;")
                line("wb.index = 0;")
                line("return wb;")
            }
            line()
            block("getBytes(): Uint8Array") { line("return this.buffer.slice(0, this.size);") }
            line()
            block("available(): boolean") { line("return this.index < this.size;") }
            line()
            block("remaining(): number") {
                line("return this.index < this.size ? this.size - this.index : 0;")
            }
            line()
            block("private checkRemaining(needed: number, label: string): void") {
                block("if (needed < 0 || needed > this.remaining())") {
                    block("throw new RangeError(", openSuffix = "", close = ");") {
                        line(
                            "\"WireBuffer underflow reading \" + label + \": needed \" + needed + \", remaining \" + this.remaining()"
                        )
                    }
                }
            }
            line()
            block("private ensureCapacity(needed: number)") {
                block("if (this.index + needed > this.buffer.length)") {
                    line("const newCap = Math.max(this.buffer.length * 2, this.index + needed);")
                    line("const newBuf = new Uint8Array(newCap);")
                    line("newBuf.set(this.buffer);")
                    line("this.buffer = newBuf;")
                    line("this.view = new DataView(this.buffer.buffer);")
                }
            }
            line()
            block("writeByte(val: number): void") {
                line("this.ensureCapacity(1);")
                line("this.view.setUint8(this.index++, val);")
                line("this.size = Math.max(this.size, this.index);")
            }
            line()
            block("readByte(): number") {
                line("this.checkRemaining(1, \"byte\");")
                line("return this.view.getUint8(this.index++);")
            }
            line()
            block("writeShort(val: number): void") {
                line("this.ensureCapacity(2);")
                line("this.view.setInt16(this.index, val, false);")
                line("this.index += 2;")
                line("this.size = Math.max(this.size, this.index);")
            }
            line()
            block("readShort(): number") {
                line("this.checkRemaining(2, \"short\");")
                line("const val = this.view.getInt16(this.index, false);")
                line("this.index += 2;")
                line("return val;")
            }
            line()
            block("writeInt(val: number): void") {
                line("this.ensureCapacity(4);")
                line("this.view.setInt32(this.index, val, false);")
                line("this.index += 4;")
                line("this.size = Math.max(this.size, this.index);")
            }
            line()
            block("readInt(): number") {
                line("this.checkRemaining(4, \"int\");")
                line("const val = this.view.getInt32(this.index, false);")
                line("this.index += 4;")
                line("return val;")
            }
            line()
            block("writeLong(val: bigint): void") {
                line("this.ensureCapacity(8);")
                line("this.view.setBigInt64(this.index, val, false);")
                line("this.index += 8;")
                line("this.size = Math.max(this.size, this.index);")
            }
            line()
            block("readLong(): bigint") {
                line("this.checkRemaining(8, \"long\");")
                line("const val = this.view.getBigInt64(this.index, false);")
                line("this.index += 8;")
                line("return val;")
            }
            line()
            block("writeFloat(val: number): void") {
                line("this.ensureCapacity(4);")
                line("this.view.setFloat32(this.index, val, false);")
                line("this.index += 4;")
                line("this.size = Math.max(this.size, this.index);")
            }
            line()
            block("readFloat(): number") {
                line("this.checkRemaining(4, \"float\");")
                line("const val = this.view.getFloat32(this.index, false);")
                line("this.index += 4;")
                line("return val;")
            }
            line()
            block("writeBoolean(val: boolean): void") { line("this.writeByte(val ? 1 : 0);") }
            line()
            block("readBoolean(): boolean") { line("return this.readByte() !== 0;") }
            line()
            block("skipBytes(len: number): void") {
                line("this.checkRemaining(len, \"skip\");")
                line("this.index += len;")
            }
            line()
            block("writeUTF8(val: string): void") {
                line("const encoder = new TextEncoder();")
                line("const encoded = encoder.encode(val);")
                line("this.writeInt(encoded.length);")
                line("this.ensureCapacity(encoded.length);")
                line("this.buffer.set(encoded, this.index);")
                line("this.index += encoded.length;")
                line("this.size = Math.max(this.size, this.index);")
            }
            line()
            block("readUTF8(maxLength?: number): string") {
                line("const len = this.readInt();")
                block("if (len < 0)") {
                    line("throw new Error(\"Negative string length in WireBuffer\");")
                }
                block("if (maxLength !== undefined && len > maxLength)") {
                    block("throw new RangeError(", openSuffix = "", close = ");") {
                        line(
                            "\"WireBuffer UTF-8 string length exceeds maximum (\" + maxLength + \"): \" + len"
                        )
                    }
                }
                line("this.checkRemaining(len, \"UTF-8 string\");")
                line("const slice = this.buffer.slice(this.index, this.index + len);")
                block("if (slice.length !== len)") {
                    block("throw new RangeError(", openSuffix = "", close = ");") {
                        line(
                            "\"WireBuffer failed to slice UTF-8 string: expected \" + len + \" bytes, got \" + slice.length"
                        )
                    }
                }
                line("const decoded = WireBuffer.utf8Decoder.decode(slice);")
                line("this.index += len;")
                line("return decoded;")
            }
            line()
            block("writeBuffer(val: Uint8Array): void") {
                line("this.writeInt(val.length);")
                line("this.ensureCapacity(val.length);")
                line("this.buffer.set(val, this.index);")
                line("this.index += val.length;")
                line("this.size = Math.max(this.size, this.index);")
            }
            line()
            block("writeBytes(val: Uint8Array): void") {
                line("this.ensureCapacity(val.length);")
                line("this.buffer.set(val, this.index);")
                line("this.index += val.length;")
                line("this.size = Math.max(this.size, this.index);")
            }
            line()
            block("readBytes(len: number): Uint8Array") {
                block("if (len < 0)") {
                    line("throw new Error(\"Negative byte slice length in WireBuffer\");")
                }
                line("this.checkRemaining(len, \"bytes\");")
                line("const slice = this.buffer.slice(this.index, this.index + len);")
                line("this.index += len;")
                line("return slice;")
            }
            line()
            block("readBuffer(maxLength?: number): Uint8Array") {
                line("const len = this.readInt();")
                block("if (len < 0)") {
                    line("throw new Error(\"Negative buffer length in WireBuffer\");")
                }
                block("if (maxLength !== undefined && len > maxLength)") {
                    block("throw new RangeError(", openSuffix = "", close = ");") {
                        line(
                            "\"WireBuffer buffer length exceeds maximum (\" + maxLength + \"): \" + len"
                        )
                    }
                }
                line("this.checkRemaining(len, \"buffer\");")
                line("const slice = this.buffer.slice(this.index, this.index + len);")
                block("if (slice.length !== len)") {
                    block("throw new RangeError(", openSuffix = "", close = ");") {
                        line(
                            "\"WireBuffer failed to slice buffer: expected \" + len + \" bytes, got \" + slice.length"
                        )
                    }
                }
                line("this.index += len;")
                line("return slice;")
            }
        }
    }

    private fun emitCreateOperation(w: CodeWriter) {
        w.block("export function createOperation(opCode: OpCode): Operation | null") {
            block("switch (opCode)") {
                for (op in schema.operations) {
                    line("case OpCode.${op.name}: return new ${op.name}();")
                }
                line("default: return null;")
            }
        }
    }

    private fun emitRemoteDocument(w: CodeWriter) {
        w.line("/**")
        w.line(" * In-memory representation of a RemoteCompose document.")
        w.line(" */")
        w.block("export class RemoteDocument") {
            line("static readonly MAX_HEADER_PROPERTIES = 1000;")
            line("static readonly MAX_OPERATION_COUNT = 100000;")
            line()
            line("majorVersion: number = 1;")
            line("minorVersion: number = 1;")
            line("patchVersion: number = 0;")
            line("width: number = 0;")
            line("height: number = 0;")
            line("capabilities: bigint = 0n;")
            line("operations: Operation[] = [];")
            line()
            line("/** Loads and parses a RemoteDocument from binary bytes. */")
            block(
                "static load(",
                openSuffix = "",
                close = null,
            ) {
                line("bytes: Uint8Array,")
                line("maxOperations: number = RemoteDocument.MAX_OPERATION_COUNT,")
            }
            block("): RemoteDocument") {
                line("return RemoteDocument.loadImpl(bytes, maxOperations, false, 0, 0);")
            }
            line()
            line("/**")
            line(" * Loads and parses a RemoteDocument evaluating conditional skip operations")
            line(" * against the target player API level and profile bitmask.")
            line(" */")
            block(
                "static loadForPlayer(",
                openSuffix = "",
                close = null,
            ) {
                line("bytes: Uint8Array,")
                line("playerApiLevel: number,")
                line("playerProfiles: number = 0,")
                line("maxOperations: number = RemoteDocument.MAX_OPERATION_COUNT,")
            }
            block("): RemoteDocument") {
                block("return RemoteDocument.loadImpl(", openSuffix = "", close = ");") {
                    line("bytes,")
                    line("maxOperations,")
                    line("true,")
                    line("playerApiLevel,")
                    line("playerProfiles,")
                }
            }
            line()
            block(
                "private static loadImpl(",
                openSuffix = "",
                close = null,
            ) {
                line("bytes: Uint8Array,")
                line("maxOperations: number,")
                line("evaluateSkip: boolean,")
                line("playerApiLevel: number,")
                line("playerProfiles: number,")
            }
            block("): RemoteDocument") {
                line("const buffer = WireBuffer.fromBytes(bytes);")
                line("const doc = new RemoteDocument();")
                line("if (!buffer.available()) return doc;")
                line()
                line("const headerOp = buffer.readByte();")
                block("if (headerOp !== OpCode.Header)") {
                    line("throw new Error(\"Expected Header opcode 0, got \" + headerOp);")
                }
                line("const rawMajor = buffer.readInt();")
                line("doc.minorVersion = buffer.readInt();")
                line("doc.patchVersion = buffer.readInt();")
                block("if ((rawMajor & 0xFFFF0000) === 0x048C0000)", close = null) {
                    line("doc.majorVersion = rawMajor & 0xFFFF;")
                    line("doc.width = 256;")
                    line("doc.height = 256;")
                    line("const numProps = buffer.readInt();")
                    block("if (numProps < 0 || numProps > RemoteDocument.MAX_HEADER_PROPERTIES)") {
                        line("throw new Error(\"Invalid numProps in header: \" + numProps);")
                    }
                    block("if (numProps * 4 > buffer.remaining())") {
                        block("throw new RangeError(", openSuffix = "", close = ");") {
                            line(
                                "\"Header property count exceeds remaining WireBuffer size: \" + numProps"
                            )
                        }
                    }
                    block("for (let i = 0; i < numProps; i++)") {
                        line("const tag = buffer.readShort();")
                        line("buffer.readShort(); // itemLen (read and ignored)")
                        line("const dataType = tag >> 10;")
                        line("const key = tag & 0x3F;")
                        block("switch (dataType)") {
                            block("case 0:") {
                                line("const val = buffer.readInt();")
                                line("if (key === 5) doc.width = val;")
                                line("else if (key === 6) doc.height = val;")
                                line("else if (key === 14) doc.capabilities = BigInt(val >>> 0);")
                                block("else if (key === 31 && val !== 0)") {
                                    line(
                                        "throw new Error(\"Compressed RemoteCompose documents are not supported\");"
                                    )
                                }
                                line("break;")
                            }
                            line("case 1: buffer.readFloat(); break;")
                            block("case 2:") {
                                line("const val = buffer.readLong();")
                                line("if (key === 14) doc.capabilities = val;")
                                block("else if (key === 31 && val !== 0n)") {
                                    line(
                                        "throw new Error(\"Compressed RemoteCompose documents are not supported\");"
                                    )
                                }
                                line("break;")
                            }
                            line("case 3: buffer.readUTF8(4000); break;")
                            line("default:")
                            indent {
                                line("break;")
                            }
                        }
                    }
                }
                block("} else if (rawMajor >= 0 && rawMajor < 0x10000)", close = null) {
                    line("doc.majorVersion = rawMajor;")
                    line("doc.width = buffer.readInt();")
                    line("doc.height = buffer.readInt();")
                    line("doc.capabilities = buffer.readLong();")
                }
                block("} else") {
                    line("throw new Error(\"Invalid header magic number: \" + rawMajor);")
                }
                line()
                block("while (buffer.available())") {
                    line("const opByte = buffer.readByte();")
                    block("if (opByte === OpCode.Header)") {
                        line("throw new Error(\"Unexpected Header opcode in document body\");")
                    }
                    block("if (doc.operations.length >= maxOperations)") {
                        line(
                            "throw new Error(\"Document exceeds maximum allowed operation count: \" + maxOperations);"
                        )
                    }
                    line("const op = createOperation(opByte as OpCode);")
                    block("if (!op)") {
                        line("throw new Error(\"Unknown opcode in RemoteDocument: \" + opByte);")
                    }
                    block(
                        "if (evaluateSkip && typeof (op as any).readFieldsForPlayer === \"function\")",
                        close = null,
                    ) {
                        line(
                            "(op as any).readFieldsForPlayer(buffer, playerApiLevel, playerProfiles);"
                        )
                    }
                    block("} else") { line("(op as any).readFields(buffer);") }
                    line("doc.operations.push(op);")
                }
                line("return doc;")
            }
            line()
            line("/** Serializes this document to binary bytes. */")
            block("save(): Uint8Array") {
                line("const buffer = new WireBuffer();")
                line("buffer.writeByte(OpCode.Header);")
                line("buffer.writeInt(this.majorVersion);")
                line("buffer.writeInt(this.minorVersion);")
                line("buffer.writeInt(this.patchVersion);")
                line("buffer.writeInt(this.width);")
                line("buffer.writeInt(this.height);")
                line("buffer.writeLong(this.capabilities);")
                line()
                block("for (const op of this.operations)") { line("op.write(buffer);") }
                line("return buffer.getBytes();")
            }
        }
    }

    private fun emitAuxClass(w: CodeWriter, structDef: SchemaStruct) {
        val props = structDef.astProperties
        val desc = structDef.description.replace("\n", " ").trim()
        if (desc.isNotEmpty()) {
            w.line("/**")
            w.line(" * $desc")
            w.line(" */")
        }
        w.block("export class ${structDef.name}") {
            multiLang.emitTsOpEnumConstants(this, structDef.fields)
            if (props.isEmpty()) {
                line("constructor() {}")
                line()
            } else {
                block("constructor(", openSuffix = "", close = ") {}") {
                    for (prop in props) {
                        val tsType = mapToTsType(prop.type, prop.isNullable)
                        val defaultVal =
                            mapToTsDefault(prop.type, prop.isNullable, prop.defaultValue)
                        line("public ${prop.name}: $tsType = $defaultVal,")
                    }
                }
                line()
            }

            val nullableNames = props.filter { it.isNullable }.map { it.name }.toSet()
            for ((fieldName, bit) in structDef.computedBitProperties) {
                val getterName = "get" + bit.name.replaceFirstChar { it.uppercaseChar() }
                if (fieldName in nullableNames) {
                    block("$getterName(): number | null") {
                        line("if (this.$fieldName === null) return null;")
                        line(
                            "return ${CodegenExprUtils.extractBitExpr("this.$fieldName", bit, ExprLang.TYPESCRIPT)};"
                        )
                    }
                } else {
                    block("$getterName(): number") {
                        line(
                            "return ${CodegenExprUtils.extractBitExpr("this.$fieldName", bit, ExprLang.TYPESCRIPT)};"
                        )
                    }
                }
                line()
            }

            block("readFields(buffer: WireBuffer): void") {
                emitTsReadBody(this, structDef.fields, null, props)
            }
            line()

            block("static read(buffer: WireBuffer): ${structDef.name}") {
                line("const instance = new ${structDef.name}();")
                line("instance.readFields(buffer);")
                line("return instance;")
            }
            line()

            block("write(buffer: WireBuffer): void") {
                emitTsWriteBody(this, structDef.fields, null, props)
            }
        }
    }

    private fun emitClass(w: CodeWriter, op: SchemaOperation) {
        val props = op.astProperties
        val desc = op.description.replace("\n", " ").trim()
        if (desc.isNotEmpty()) {
            w.line("/**")
            w.line(" * $desc")
            w.line(" */")
        }
        w.block("export class ${op.name} implements Operation") {
            line("readonly opCode = OpCode.${op.name};")
            multiLang.emitTsOpEnumConstants(this, op.fields)
            line()

            if (props.isEmpty()) {
                line("constructor() {}")
                line()
            } else {
                line("/**")
                for (prop in props) {
                    val fieldDesc = prop.description.replace("\n", " ").trim()
                    line(" * @param ${prop.name} $fieldDesc")
                }
                line(" */")
                block("constructor(", openSuffix = "", close = ") {}") {
                    for (prop in props) {
                        val tsType = mapToTsType(prop.type, prop.isNullable)
                        val defaultVal =
                            mapToTsDefault(prop.type, prop.isNullable, prop.defaultValue)
                        line("public ${prop.name}: $tsType = $defaultVal,")
                    }
                }
                line()
            }

            val nullableNames = props.filter { it.isNullable }.map { it.name }.toSet()
            for ((fieldName, bit) in op.computedBitProperties) {
                val getterName = "get" + bit.name.replaceFirstChar { it.uppercaseChar() }
                if (fieldName in nullableNames) {
                    block("$getterName(): number | null") {
                        line("if (this.$fieldName === null) return null;")
                        line(
                            "return ${CodegenExprUtils.extractBitExpr("this.$fieldName", bit, ExprLang.TYPESCRIPT)};"
                        )
                    }
                } else {
                    block("$getterName(): number") {
                        line(
                            "return ${CodegenExprUtils.extractBitExpr("this.$fieldName", bit, ExprLang.TYPESCRIPT)};"
                        )
                    }
                }
                line()
            }

            multiLang.emitTsOpExtras(this, op)
            block("readFields(buffer: WireBuffer): void") {
                if (op.conditionalSkip != null) {
                    line("const skipTaken = true;")
                }
                emitTsReadBody(
                    this,
                    op.fields,
                    op.sparseParameters,
                    props,
                    op.sparseCountType,
                    op.sparseKeyType,
                )
            }
            line()

            if (op.conditionalSkip != null) {
                val cs = op.conditionalSkip
                val condExpr =
                    CodegenExprUtils.extractSkipConditionExpr(
                        cs,
                        cs.conditionField,
                        ExprLang.TYPESCRIPT,
                    )
                block(
                    "static shouldSkip(${cs.conditionField}: number, ${cs.valueField}: number, playerApiLevel: number, playerProfiles: number): boolean"
                ) {
                    block("switch ($condExpr)") {
                        for (b in cs.conditions) {
                            val brExpr =
                                CodegenExprUtils.evaluateSkipBranchExpr(
                                    b,
                                    cs.valueField,
                                    "playerApiLevel",
                                    "playerProfiles",
                                    ExprLang.TYPESCRIPT,
                                )
                            line("case ${b.whenValue}: return $brExpr;")
                        }
                        line("default: return ${cs.unknownConditionSkips};")
                    }
                }
                line()
                block(
                    "readFieldsForPlayer(buffer: WireBuffer, playerApiLevel: number, playerProfiles: number = 0): void"
                ) {
                    emitTsReadBody(
                        this,
                        op.fields,
                        op.sparseParameters,
                        props,
                        op.sparseCountType,
                        op.sparseKeyType,
                        conditionalSkip = cs,
                    )
                }
                line()
                block(
                    "static readForPlayer(buffer: WireBuffer, playerApiLevel: number, playerProfiles: number = 0): ${op.name}"
                ) {
                    line("const instance = new ${op.name}();")
                    line("instance.readFieldsForPlayer(buffer, playerApiLevel, playerProfiles);")
                    line("return instance;")
                }
                line()
            }

            line("/** Reads and decodes a [${op.name}] operation from the wire buffer. */")
            block("static read(buffer: WireBuffer): ${op.name}") {
                line("const instance = new ${op.name}();")
                line("instance.readFields(buffer);")
                line("return instance;")
            }
            line()

            line("/** Serializes this operation to the wire buffer. */")
            block("write(buffer: WireBuffer): void") {
                line("buffer.writeByte(this.opCode);")
                emitTsWriteBody(
                    this,
                    op.fields,
                    op.sparseParameters,
                    props,
                    op.sparseCountType,
                    op.sparseKeyType,
                    op.conditionalSkip,
                )
            }
        }
    }

    private fun emitTsScalarValidations(w: CodeWriter, f: SchemaField, varRef: String) {
        if (f.minValue != null) {
            w.block("if ($varRef < ${f.minValue})") {
                line(
                    "throw new Error(\"Invalid ${f.name} below minimum (${f.minValue}): \" + $varRef);"
                )
            }
        }
        if (f.mustBeZeroBits != null) {
            val badBits =
                CodegenExprUtils.nonZeroBitsCheckExpr(
                    varRef,
                    f.mustBeZeroBits,
                    ExprLang.TYPESCRIPT,
                )
            w.block("if ($badBits)") {
                line("throw new Error(\"Non-zero reserved bits in ${f.name}\");")
            }
        }
        emitTsStrictEnumCheck(w, f.name, varRef, f.strictEnum, f.enumValues)
        val bits = f.bits
        if (bits != null && !f.unpackBits) {
            for (b in bits) {
                if (b.strictEnum && !b.enumValues.isNullOrEmpty()) {
                    val bVar = "bit_${b.name}"
                    val extract = CodegenExprUtils.extractBitExpr(varRef, b, ExprLang.TYPESCRIPT)
                    w.line("const $bVar = $extract;")
                    emitTsStrictEnumCheck(w, b.name, bVar, b.strictEnum, b.enumValues)
                }
            }
        }
    }

    private fun emitTsReadBody(
        w: CodeWriter,
        fields: List<SchemaField>,
        sparseParameters: List<SchemaSparseParam>?,
        props: List<AstProperty>,
        sparseCountType: String? = null,
        sparseKeyType: String? = null,
        conditionalSkip: SchemaConditionalSkip? = null,
    ) {
        val propByName = props.associateBy { it.name }
        val localReadVars = mutableSetOf("skipTaken")

        for (f in fields) {
            if (conditionalSkip != null && f.name == conditionalSkip.payloadField) {
                w.line(
                    "const skipTaken = (this.constructor as any).shouldSkip(this.${conditionalSkip.conditionField}, this.${conditionalSkip.valueField}, playerApiLevel, playerProfiles);"
                )
            }
            val bits = f.bits
            if (bits != null && f.unpackBits) {
                val rawVar = "raw_${f.name}"
                w.line("const $rawVar = buffer.readInt();")
                if (f.mustBeZeroBits != null) {
                    val badBits =
                        CodegenExprUtils.nonZeroBitsCheckExpr(
                            rawVar,
                            f.mustBeZeroBits,
                            ExprLang.TYPESCRIPT,
                        )
                    w.block("if ($badBits)") {
                        line("throw new Error(\"Non-zero reserved bits in ${f.name}\");")
                    }
                }
                for (b in bits) {
                    val expr = CodegenExprUtils.extractBitExpr(rawVar, b, ExprLang.TYPESCRIPT)
                    val bRef: String
                    if (b.derivedFrom != null) {
                        w.line("const ${b.name} = $expr;")
                        localReadVars.add(b.name)
                        bRef = b.name
                    } else {
                        w.line("this.${b.name} = $expr;")
                        bRef = "this.${b.name}"
                    }
                    emitTsStrictEnumCheck(w, b.name, bRef, b.strictEnum, b.enumValues)
                }
                continue
            }

            val isLocalDerived = f.derivedFrom != null
            if (isLocalDerived) {
                localReadVars.add(f.name)
            }
            val isNullable = propByName[f.name]?.isNullable == true
            val lhsPrefix = if (isLocalDerived) "const ${f.name}" else "this.${f.name}"

            if (f.presentIf != null) {
                val cond =
                    CodegenExprUtils.translateCondition(f.presentIf, ExprLang.TYPESCRIPT) {
                        if (it in localReadVars) it else "this.$it"
                    }
                if (isLocalDerived) {
                    val defaultVal = mapToTsDefault(f.type, false, f.defaultValue)
                    w.line("const ${f.name} = ($cond) ? ${mapToTsReadExpr(f.type)} : $defaultVal;")
                } else {
                    w.block("if ($cond)", close = null) {
                        if (f.type.endsWith("[]")) {
                            emitTsArrayRead(this, f, "this.${f.name}", localReadVars)
                        } else {
                            line("this.${f.name} = ${mapToTsFieldReadExpr(f, localReadVars)};")
                            emitTsScalarValidations(this, f, "this.${f.name}")
                        }
                    }
                    w.block("} else") {
                        line(
                            "this.${f.name} = ${mapToTsDefault(f.type, isNullable, f.defaultValue)};"
                        )
                    }
                }
            } else if (f.type.endsWith("[]")) {
                emitTsArrayRead(w, f, lhsPrefix, localReadVars)
            } else {
                w.line("$lhsPrefix = ${mapToTsFieldReadExpr(f, localReadVars)};")
                val varRef = if (isLocalDerived) f.name else "this.${f.name}"
                emitTsScalarValidations(w, f, varRef)
            }
        }

        if (sparseParameters != null) {
            for (sp in sparseParameters) {
                w.line("this.${sp.name} = null;")
            }
            val effectiveCountType = sparseCountType ?: "ushort"
            val effectiveKeyType = sparseKeyType ?: "ubyte"
            when (effectiveCountType) {
                "int" -> {
                    w.line("const sparseCount = buffer.readInt();")
                    w.block("if (sparseCount < 0)") {
                        line(
                            "throw new Error(\"Negative sparse parameter count: \" + sparseCount);"
                        )
                    }
                }
                "short" -> {
                    w.line("const sparseCount = buffer.readShort();")
                    w.block("if (sparseCount < 0)") {
                        line(
                            "throw new Error(\"Negative sparse parameter count: \" + sparseCount);"
                        )
                    }
                }
                "byte" -> {
                    w.line("const sparseCount = (buffer.readByte() << 24) >> 24;")
                    w.block("if (sparseCount < 0)") {
                        line(
                            "throw new Error(\"Negative sparse parameter count: \" + sparseCount);"
                        )
                    }
                }
                "ubyte" -> w.line("const sparseCount = buffer.readByte();")
                else -> w.line("const sparseCount = buffer.readShort() & 0xFFFF;")
            }
            val minEntryBytes =
                when (effectiveKeyType) {
                    "int" -> 5
                    "short",
                    "ushort" -> 3
                    else -> 2
                }
            w.block("if (sparseCount * $minEntryBytes > buffer.remaining())") {
                line(
                    "throw new RangeError(\"Sparse parameter count exceeds remaining WireBuffer size: \" + sparseCount);"
                )
            }
            w.block("for (let s = 0; s < sparseCount; s++)") {
                when (effectiveKeyType) {
                    "int" -> line("const paramId = buffer.readInt();")
                    "ushort" -> line("const paramId = buffer.readShort() & 0xFFFF;")
                    "short" -> line("const paramId = buffer.readShort();")
                    "byte" -> line("const paramId = (buffer.readByte() << 24) >> 24;")
                    else -> line("const paramId = buffer.readByte();")
                }
                block("switch (paramId)") {
                    for (sp in sparseParameters) {
                        block("case ${sp.id}:") {
                            if (sp.type.endsWith("[]")) {
                                val synField =
                                    SchemaField(
                                        name = sp.name,
                                        type = sp.type,
                                        description = sp.description,
                                        enumValues = null,
                                        lengthType = sp.lengthType ?: "ushort",
                                    )
                                emitTsArrayRead(this, synField, "this.${sp.name}", localReadVars)
                            } else {
                                line("this.${sp.name} = ${mapToTsReadExpr(sp.type)};")
                            }
                            line("break;")
                        }
                    }
                    line("default:")
                    indent { line("throw new Error(\"Unknown sparse parameter id: \" + paramId);") }
                }
            }
        }
    }

    private fun emitTsStrictEnumCheck(
        w: CodeWriter,
        fieldName: String,
        varRef: String,
        strictEnum: Boolean,
        enumValues: Map<String, Int>?,
    ) {
        if (strictEnum && !enumValues.isNullOrEmpty()) {
            val allowed = enumValues.values.distinct().sorted()
            val check = allowed.joinToString(" && ") { "$varRef !== $it" }
            w.block("if ($check)") {
                line("throw new Error(\"Invalid enum value for $fieldName: \" + $varRef);")
            }
        }
    }

    private fun emitTsArrayRead(
        w: CodeWriter,
        f: SchemaField,
        targetLhs: String,
        localReadVars: Set<String>,
    ) {
        val lenVar = "_${f.name}Count"
        if (f.countFrom != null) {
            val countRef = if (f.countFrom in localReadVars) f.countFrom else "this.${f.countFrom}"
            w.line("const $lenVar = $countRef;")
        } else {
            when (f.effectiveLengthType) {
                "int" -> w.line("const $lenVar = buffer.readInt();")
                "ushort" -> w.line("const $lenVar = buffer.readShort() & 0xFFFF;")
                "ubyte" -> w.line("const $lenVar = buffer.readByte();")
                "byte" -> w.line("const $lenVar = (buffer.readByte() << 24) >> 24;")
                else -> w.line("const $lenVar = buffer.readShort();")
            }
        }
        w.block("if ($lenVar < 0)") {
            line("throw new Error(\"Invalid negative array length for ${f.name}: \" + $lenVar);")
        }
        if (f.minLength != null && f.minLength > 0) {
            w.block("if ($lenVar < ${f.minLength})") {
                line(
                    "throw new Error(\"Array length below minimum (${f.minLength}) for ${f.name}: \" + $lenVar);"
                )
            }
        }
        if (f.maxLength != null) {
            w.block("if ($lenVar > ${f.maxLength})") {
                line(
                    "throw new RangeError(\"Array length exceeds maximum (${f.maxLength}) for ${f.name}: \" + $lenVar);"
                )
            }
        }
        val elemType = f.type.removeSuffix("[]")
        val elemMinBytes = CodegenExprUtils.minWireElementBytes(elemType, schema)
        w.block("if ($lenVar * $elemMinBytes > buffer.remaining())") {
            line(
                "throw new RangeError(\"Array length exceeds remaining WireBuffer size for ${f.name}: \" + $lenVar);"
            )
        }
        when (f.type) {
            "int[]" -> {
                w.line("const ${f.name}Arr = new Int32Array($lenVar);")
                w.block("for (let i = 0; i < $lenVar; i++)") {
                    line("${f.name}Arr[i] = buffer.readInt();")
                }
                w.line("$targetLhs = ${f.name}Arr;")
            }
            "short[]" -> {
                w.line("const ${f.name}Arr = new Int16Array($lenVar);")
                w.block("for (let i = 0; i < $lenVar; i++)") {
                    line("${f.name}Arr[i] = buffer.readShort();")
                }
                w.line("$targetLhs = ${f.name}Arr;")
            }
            "float[]",
            "float_or_id[]" -> {
                w.line("const ${f.name}Arr = new Float32Array($lenVar);")
                w.block("for (let i = 0; i < $lenVar; i++)") {
                    line("${f.name}Arr[i] = buffer.readFloat();")
                }
                w.line("$targetLhs = ${f.name}Arr;")
            }
            else -> {
                val tsElem = mapToTsType(elemType, false)
                w.line("const ${f.name}Arr: $tsElem[] = [];")
                w.block("for (let i = 0; i < $lenVar; i++)") {
                    line("${f.name}Arr.push(${mapToTsReadExpr(elemType)});")
                }
                w.line("$targetLhs = ${f.name}Arr;")
            }
        }
    }

    private fun emitTsWriteBody(
        w: CodeWriter,
        fields: List<SchemaField>,
        sparseParameters: List<SchemaSparseParam>?,
        props: List<AstProperty>,
        sparseCountType: String? = null,
        sparseKeyType: String? = null,
        conditionalSkip: SchemaConditionalSkip? = null,
    ) {
        val propByName = props.associateBy { it.name }
        val localWriteVars = mutableSetOf<String>()

        for (f in fields) {
            val bits = f.bits
            if (bits != null && f.unpackBits) {
                val terms = mutableListOf<Pair<String, SchemaBitField>>()
                for (b in bits) {
                    if (b.derivedFrom != null) {
                        val expr = derivedExprToTs(DerivedExpr.parse(b.derivedFrom))
                        w.line("const ${b.name} = $expr;")
                        localWriteVars.add(b.name)
                        terms.add(b.name to b)
                    } else {
                        terms.add("this.${b.name}" to b)
                    }
                }
                val packed = CodegenExprUtils.packBitsExpr(terms, ExprLang.TYPESCRIPT)
                w.line("buffer.writeInt($packed);")
                continue
            }

            if (f.derivedFrom != null) {
                val expr = derivedExprToTs(DerivedExpr.parse(f.derivedFrom))
                if (f.presentIf != null) {
                    val cond =
                        CodegenExprUtils.translateCondition(f.presentIf, ExprLang.TYPESCRIPT) {
                            if (it in localWriteVars) it else "this.$it"
                        }
                    w.block("if ($cond)") { line("${mapToTsWriteExpr(f.type, expr)};") }
                } else {
                    w.line("const ${f.name} = $expr;")
                    localWriteVars.add(f.name)
                    w.line("${mapToTsWriteExpr(f.type, f.name)};")
                }
                continue
            }

            val isNullable = propByName[f.name]?.isNullable == true
            if (conditionalSkip != null && f.name == conditionalSkip.lengthField) {
                w.line(
                    "buffer.writeInt(this.${conditionalSkip.payloadField} !== null ? this.${conditionalSkip.payloadField}.length : this.${f.name});"
                )
                continue
            }
            if (conditionalSkip != null && f.name == conditionalSkip.payloadField) {
                w.block("if (this.${f.name} !== null)") {
                    line("buffer.writeBytes(this.${f.name});")
                }
                continue
            }
            if (f.presentIf != null) {
                val cond =
                    CodegenExprUtils.translateCondition(f.presentIf, ExprLang.TYPESCRIPT) {
                        if (it in localWriteVars) it else "this.$it"
                    }
                w.block("if ($cond)") {
                    if (isNullable) {
                        block("if (this.${f.name} === null)") {
                            line("throw new Error(\"Missing required field ${f.name}\");")
                        }
                    }
                    emitTsFieldWrite(this, f, "this.${f.name}")
                }
            } else {
                emitTsFieldWrite(w, f, "this.${f.name}")
            }
        }

        if (sparseParameters != null) {
            w.line("let sparseCount = 0;")
            for (sp in sparseParameters) {
                w.line("if (this.${sp.name} !== null) sparseCount++;")
            }
            when (sparseCountType ?: "ushort") {
                "int" -> w.line("buffer.writeInt(sparseCount);")
                "ubyte",
                "byte" -> w.line("buffer.writeByte(sparseCount);")
                else -> w.line("buffer.writeShort(sparseCount);")
            }
            val effectiveKeyType = sparseKeyType ?: "ubyte"
            for (sp in sparseParameters) {
                w.block("if (this.${sp.name} !== null)") {
                    when (effectiveKeyType) {
                        "int" -> line("buffer.writeInt(${sp.id});")
                        "ushort",
                        "short" -> line("buffer.writeShort(${sp.id});")
                        else -> line("buffer.writeByte(${sp.id});")
                    }
                    val synField =
                        SchemaField(
                            name = sp.name,
                            type = sp.type,
                            description = sp.description,
                            enumValues = null,
                            lengthType = sp.lengthType ?: "ushort",
                        )
                    emitTsFieldWrite(this, synField, "this.${sp.name}")
                }
            }
        }
    }

    private fun emitTsFieldWrite(w: CodeWriter, f: SchemaField, varExpr: String) {
        if (f.type.endsWith("[]")) {
            if (f.countFrom == null) {
                when (f.effectiveLengthType) {
                    "int" -> w.line("buffer.writeInt($varExpr.length);")
                    "ubyte",
                    "byte" -> w.line("buffer.writeByte($varExpr.length);")
                    else -> w.line("buffer.writeShort($varExpr.length);")
                }
            }
            val elemType = f.type.removeSuffix("[]")
            w.block("for (let i = 0; i < $varExpr.length; i++)") {
                line("${mapToTsWriteExpr(elemType, "$varExpr[i]")};")
            }
        } else if (f.type == "bytes" && f.countFrom != null) {
            w.line("buffer.writeBytes($varExpr);")
        } else {
            w.line("${mapToTsWriteExpr(f.type, varExpr)};")
        }
    }

    private fun mapToTsFieldReadExpr(f: SchemaField, localReadVars: Set<String>): String {
        if (f.type == "bytes" && f.countFrom != null) {
            val countRef = if (f.countFrom in localReadVars) f.countFrom else "this.${f.countFrom}"
            return "buffer.readBytes($countRef)"
        }
        return mapToTsReadExpr(f.type, f.maxLength)
    }

    private fun derivedExprToTs(expr: DerivedExpr): String {
        val target = "this.${expr.targetName}"
        return when (expr) {
            is DerivedExpr.LengthOf -> "$target.length"
            is DerivedExpr.PresentOf -> "($target !== null ? 1 : 0)"
            is DerivedExpr.NonEmptyOf -> "($target.length > 0 ? 1 : 0)"
        }
    }

    private fun mapToTsType(type: String, isNullable: Boolean): String {
        val base =
            when {
                type == "int[]" -> "Int32Array"
                type == "short[]" -> "Int16Array"
                type == "float[]" || type == "float_or_id[]" -> "Float32Array"
                type.endsWith("[]") -> "${mapToTsType(type.removeSuffix("[]"), false)}[]"
                type in setOf("int", "int_id", "short", "byte", "float", "color", "float_or_id") ->
                    "number"
                type == "long" -> "bigint"
                type == "boolean" -> "boolean"
                type == "string" -> "string"
                type == "bytes" -> "Uint8Array"
                schema.structs.containsKey(type) -> type
                else -> "number"
            }
        return if (isNullable) "$base | null" else base
    }

    private fun mapToTsDefault(
        type: String,
        isNullable: Boolean,
        explicitDefault: String?,
    ): String {
        if (isNullable) return "null"
        if (explicitDefault != null) return explicitDefault
        return when {
            type == "int[]" -> "new Int32Array(0)"
            type == "short[]" -> "new Int16Array(0)"
            type == "float[]" || type == "float_or_id[]" -> "new Float32Array(0)"
            type.endsWith("[]") -> "[]"
            type in setOf("int", "int_id", "short", "byte", "float", "color", "float_or_id") -> "0"
            type == "long" -> "0n"
            type == "boolean" -> "false"
            type == "string" -> "\"\""
            type == "bytes" -> "new Uint8Array(0)"
            schema.structs.containsKey(type) -> "new $type()"
            else -> "0"
        }
    }

    private fun mapToTsReadExpr(type: String, maxLength: Int? = null): String =
        when (type) {
            "int",
            "int_id",
            "color" -> "buffer.readInt()"
            "short" -> "buffer.readShort()"
            "byte" -> "buffer.readByte()"
            "long" -> "buffer.readLong()"
            "float",
            "float_or_id" -> "buffer.readFloat()"
            "boolean" -> "buffer.readBoolean()"
            "string" ->
                if (maxLength != null) "buffer.readUTF8($maxLength)" else "buffer.readUTF8()"
            "bytes" ->
                if (maxLength != null) "buffer.readBuffer($maxLength)" else "buffer.readBuffer()"
            else ->
                if (schema.structs.containsKey(type)) "$type.read(buffer)" else "buffer.readInt()"
        }

    private fun mapToTsWriteExpr(type: String, varName: String): String =
        when (type) {
            "int",
            "int_id",
            "color" -> "buffer.writeInt($varName)"
            "short" -> "buffer.writeShort($varName)"
            "byte" -> "buffer.writeByte($varName)"
            "long" -> "buffer.writeLong($varName)"
            "float",
            "float_or_id" -> "buffer.writeFloat($varName)"
            "boolean" -> "buffer.writeBoolean($varName)"
            "string" -> "buffer.writeUTF8($varName)"
            "bytes" -> "buffer.writeBuffer($varName)"
            else ->
                if (schema.structs.containsKey(type)) "$varName.write(buffer)"
                else "buffer.writeInt($varName)"
        }
}
