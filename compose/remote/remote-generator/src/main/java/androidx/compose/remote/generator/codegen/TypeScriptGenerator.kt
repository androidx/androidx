/**
 * Generator that transforms an [OperationSchema] into TypeScript bindings:
 * - OpCode enum
 * - Auxiliary struct classes and typed Operation classes with WireBuffer serialization
 * - RemoteDocument container
 * - Browser/Node compatible WireBuffer implementation
 */
internal class TypeScriptGenerator(private val schema: OperationSchema) {

    fun generate(): String {
        val sb = StringBuilder()
        sb.append(
            """
            // Generated by RemoteCompose Schema Codegen. DO NOT EDIT.

            /**
             * Operation wire identifiers for RemoteCompose.
             */
            export enum OpCode {
            """
                .trimIndent()
        )
        sb.append("\n")

        for (op in schema.operations) {
            val desc = op.description.replace("\n", " ").trim()
            if (desc.isNotEmpty()) {
                sb.append("  /** $desc */\n")
            }
            sb.append("  ${op.name} = ${op.id},\n")
        }

        sb.append(
            """
            }

            /**
             * Base interface for all RemoteCompose operations.
             */
            export interface Operation {
              readonly opCode: OpCode;
              write(buffer: WireBuffer): void;
            }

            export class WireBuffer {
              private static readonly utf8Decoder = new TextDecoder("utf-8", {
                fatal: true,
                ignoreBOM: true,
              });
              private buffer: Uint8Array;
              private view: DataView;
              private index: number = 0;
              private size: number = 0;

              constructor(initialCapacity: number = 1024) {
                this.buffer = new Uint8Array(initialCapacity);
                this.view = new DataView(this.buffer.buffer);
              }

              static fromBytes(bytes: Uint8Array): WireBuffer {
                const wb = new WireBuffer(bytes.length);
                wb.buffer.set(bytes);
                wb.size = bytes.length;
                wb.index = 0;
                return wb;
              }

              getBytes(): Uint8Array {
                return this.buffer.slice(0, this.size);
              }

              available(): boolean {
                return this.index < this.size;
              }

              remaining(): number {
                return this.index < this.size ? this.size - this.index : 0;
              }

              private checkRemaining(needed: number, label: string): void {
                if (needed < 0 || needed > this.remaining()) {
                  throw new RangeError(
                    "WireBuffer underflow reading " + label + ": needed " + needed + ", remaining " + this.remaining()
                  );
                }
              }

              private ensureCapacity(needed: number) {
                if (this.index + needed > this.buffer.length) {
                  const newCap = Math.max(this.buffer.length * 2, this.index + needed);
                  const newBuf = new Uint8Array(newCap);
                  newBuf.set(this.buffer);
                  this.buffer = newBuf;
                  this.view = new DataView(this.buffer.buffer);
                }
              }

              writeByte(val: number): void {
                this.ensureCapacity(1);
                this.view.setUint8(this.index++, val);
                this.size = Math.max(this.size, this.index);
              }

              readByte(): number {
                this.checkRemaining(1, "byte");
                return this.view.getUint8(this.index++);
              }

              writeShort(val: number): void {
                this.ensureCapacity(2);
                this.view.setInt16(this.index, val, false);
                this.index += 2;
                this.size = Math.max(this.size, this.index);
              }

              readShort(): number {
                this.checkRemaining(2, "short");
                const val = this.view.getInt16(this.index, false);
                this.index += 2;
                return val;
              }

              writeInt(val: number): void {
                this.ensureCapacity(4);
                this.view.setInt32(this.index, val, false);
                this.index += 4;
                this.size = Math.max(this.size, this.index);
              }

              readInt(): number {
                this.checkRemaining(4, "int");
                const val = this.view.getInt32(this.index, false);
                this.index += 4;
                return val;
              }

              writeLong(val: bigint): void {
                this.ensureCapacity(8);
                this.view.setBigInt64(this.index, val, false);
                this.index += 8;
                this.size = Math.max(this.size, this.index);
              }

              readLong(): bigint {
                this.checkRemaining(8, "long");
                const val = this.view.getBigInt64(this.index, false);
                this.index += 8;
                return val;
              }

              writeFloat(val: number): void {
                this.ensureCapacity(4);
                this.view.setFloat32(this.index, val, false);
                this.index += 4;
                this.size = Math.max(this.size, this.index);
              }

              readFloat(): number {
                this.checkRemaining(4, "float");
                const val = this.view.getFloat32(this.index, false);
                this.index += 4;
                return val;
              }

              writeBoolean(val: boolean): void {
                this.writeByte(val ? 1 : 0);
              }

              readBoolean(): boolean {
                return this.readByte() !== 0;
              }

              skipBytes(len: number): void {
                this.checkRemaining(len, "skip");
                this.index += len;
              }

              writeUTF8(val: string): void {
                const encoder = new TextEncoder();
                const encoded = encoder.encode(val);
                this.writeInt(encoded.length);
                this.ensureCapacity(encoded.length);
                this.buffer.set(encoded, this.index);
                this.index += encoded.length;
                this.size = Math.max(this.size, this.index);
              }

              readUTF8(maxLength?: number): string {
                const len = this.readInt();
                if (len < 0) {
                  throw new Error("Negative string length in WireBuffer");
                }
                if (maxLength !== undefined && len > maxLength) {
                  throw new RangeError(
                    "WireBuffer UTF-8 string length exceeds maximum (" + maxLength + "): " + len
                  );
                }
                this.checkRemaining(len, "UTF-8 string");
                const slice = this.buffer.slice(this.index, this.index + len);
                if (slice.length !== len) {
                  throw new RangeError(
                    "WireBuffer failed to slice UTF-8 string: expected " + len + " bytes, got " + slice.length
                  );
                }
                const decoded = WireBuffer.utf8Decoder.decode(slice);
                this.index += len;
                return decoded;
              }

              writeBuffer(val: Uint8Array): void {
                this.writeInt(val.length);
                this.ensureCapacity(val.length);
                this.buffer.set(val, this.index);
                this.index += val.length;
                this.size = Math.max(this.size, this.index);
              }

              readBuffer(maxLength?: number): Uint8Array {
                const len = this.readInt();
                if (len < 0) {
                  throw new Error("Negative buffer length in WireBuffer");
                }
                if (maxLength !== undefined && len > maxLength) {
                  throw new RangeError(
                    "WireBuffer buffer length exceeds maximum (" + maxLength + "): " + len
                  );
                }
                this.checkRemaining(len, "buffer");
                const slice = this.buffer.slice(this.index, this.index + len);
                if (slice.length !== len) {
                  throw new RangeError(
                    "WireBuffer failed to slice buffer: expected " + len + " bytes, got " + slice.length
                  );
                }
                this.index += len;
                return slice;
              }
            }

            """
                .trimIndent()
        )
        sb.append("\n\n")

        for ((_, structDef) in schema.structs) {
            sb.append(generateAuxClass(structDef))
            sb.append("\n\n")
        }

        for (op in schema.operations) {
            sb.append(generateClass(op))
            sb.append("\n\n")
        }

        sb.append(
            """
            export function createOperation(opCode: OpCode): Operation | null {
              switch (opCode) {
            """
                .trimIndent()
        )
        sb.append("\n")

        for (op in schema.operations) {
            sb.append("    case OpCode.${op.name}: return new ${op.name}();\n")
        }

        sb.append(
            """
                default: return null;
              }
            }

            /**
             * In-memory representation of a RemoteCompose document.
             */
            export class RemoteDocument {
              static readonly MAX_HEADER_PROPERTIES = 1000;
              static readonly MAX_OPERATION_COUNT = 100000;

              majorVersion: number = 1;
              minorVersion: number = 1;
              patchVersion: number = 0;
              width: number = 0;
              height: number = 0;
              capabilities: bigint = 0n;
              operations: Operation[] = [];

              /** Loads and parses a RemoteDocument from binary bytes. */
              static load(
                bytes: Uint8Array,
                maxOperations: number = RemoteDocument.MAX_OPERATION_COUNT,
              ): RemoteDocument {
                const buffer = WireBuffer.fromBytes(bytes);
                const doc = new RemoteDocument();
                if (!buffer.available()) return doc;

                const headerOp = buffer.readByte();
                if (headerOp !== OpCode.Header) {
                  throw new Error("Expected Header opcode 0, got " + headerOp);
                }
                const rawMajor = buffer.readInt();
                doc.minorVersion = buffer.readInt();
                doc.patchVersion = buffer.readInt();
                if ((rawMajor & 0xFFFF0000) === 0x048C0000) {
                  doc.majorVersion = rawMajor & 0xFFFF;
                  const numProps = buffer.readInt();
                  if (numProps < 0 || numProps > RemoteDocument.MAX_HEADER_PROPERTIES) {
                    throw new Error("Invalid numProps in header: " + numProps);
                  }
                  if (numProps * 4 > buffer.remaining()) {
                    throw new RangeError(
                      "Header property count exceeds remaining WireBuffer size: " + numProps
                    );
                  }
                  for (let i = 0; i < numProps; i++) {
                    const tag = buffer.readShort() & 0xFFFF;
                    const itemLen = buffer.readShort() & 0xFFFF;
                    const dataType = (tag >>> 10) & 0x3F;
                    const key = tag & 0x3FF;
                    switch (dataType) {
                      case 0: {
                        const val = buffer.readInt();
                        if (key === 5) doc.width = val;
                        else if (key === 6) doc.height = val;
                        else if (key === 14) doc.capabilities = BigInt(val >>> 0);
                        else if (key === 31 && val !== 0) {
                          throw new Error("Compressed RemoteCompose documents are not supported");
                        }
                        break;
                      }
                      case 1: buffer.readFloat(); break;
                      case 2: {
                        const val = buffer.readLong();
                        if (key === 14) doc.capabilities = val;
                        else if (key === 31 && val !== 0n) {
                          throw new Error("Compressed RemoteCompose documents are not supported");
                        }
                        break;
                      }
                      case 3: buffer.readUTF8(); break;
                      default:
                        buffer.skipBytes(itemLen);
                        break;
                    }
                  }
                } else if (rawMajor >= 0 && rawMajor < 0x10000) {
                  doc.majorVersion = rawMajor;
                  doc.width = buffer.readInt();
                  doc.height = buffer.readInt();
                  doc.capabilities = buffer.readLong();
                } else {
                  throw new Error("Invalid header magic number: " + rawMajor);
                }

                while (buffer.available()) {
                  const opByte = buffer.readByte();
                  if (opByte === OpCode.Header) {
                    throw new Error("Unexpected Header opcode in document body");
                  }
                  if (doc.operations.length >= maxOperations) {
                    throw new Error("Document exceeds maximum allowed operation count: " + maxOperations);
                  }
                  const op = createOperation(opByte as OpCode);
                  if (!op) {
                    throw new Error("Unknown opcode in RemoteDocument: " + opByte);
                  }
                  (op as any).readFields(buffer);
                  doc.operations.push(op);
                }
                return doc;
              }

              /** Serializes this document to binary bytes. */
              save(): Uint8Array {
                const buffer = new WireBuffer();
                buffer.writeByte(OpCode.Header);
                buffer.writeInt(this.majorVersion);
                buffer.writeInt(this.minorVersion);
                buffer.writeInt(this.patchVersion);
                buffer.writeInt(this.width);
                buffer.writeInt(this.height);
                buffer.writeLong(this.capabilities);

                for (const op of this.operations) {
                  op.write(buffer);
                }
                return buffer.getBytes();
              }
            }
            """
                .trimIndent()
        )
        sb.append("\n")
        return sb.toString()
    }

    private fun generateAuxClass(structDef: SchemaStruct): String {
        val sb = StringBuilder()
        val props = structDef.astProperties
        val desc = structDef.description.replace("\n", " ").trim()
        if (desc.isNotEmpty()) {
            sb.append("/**\n")
            sb.append(" * $desc\n")
            sb.append(" */\n")
        }
        sb.append("export class ${structDef.name} {\n")
        if (props.isEmpty()) {
            sb.append("  constructor() {}\n\n")
        } else {
            sb.append("  constructor(\n")
            for (prop in props) {
                val tsType = mapToTsType(prop.type, prop.isNullable)
                val defaultVal = mapToTsDefault(prop.type, prop.isNullable, prop.defaultValue)
                sb.append("    public ${prop.name}: $tsType = $defaultVal,\n")
            }
            sb.append("  ) {}\n\n")
        }

        for ((fieldName, bit) in structDef.computedBitProperties) {
            val getterName = "get" + bit.name.replaceFirstChar { it.uppercaseChar() }
            sb.append("  $getterName(): number {\n")
            sb.append(
                "    return ${CodegenExprUtils.extractBitExpr("this.$fieldName", bit, ExprLang.TYPESCRIPT)};\n"
            )
            sb.append("  }\n\n")
        }

        sb.append("  readFields(buffer: WireBuffer): void {\n")
        appendTsReadBody(sb, structDef.fields, null, props)
        sb.append("  }\n\n")

        sb.append("  static read(buffer: WireBuffer): ${structDef.name} {\n")
        sb.append("    const instance = new ${structDef.name}();\n")
        sb.append("    instance.readFields(buffer);\n")
        sb.append("    return instance;\n")
        sb.append("  }\n\n")

        sb.append("  write(buffer: WireBuffer): void {\n")
        appendTsWriteBody(sb, structDef.fields, null, props)
        sb.append("  }\n")
        sb.append("}")
        return sb.toString()
    }

    private fun generateClass(op: SchemaOperation): String {
        val sb = StringBuilder()
        val props = op.astProperties
        val desc = op.description.replace("\n", " ").trim()
        if (desc.isNotEmpty()) {
            sb.append("/**\n")
            sb.append(" * $desc\n")
            sb.append(" */\n")
        }
        sb.append("export class ${op.name} implements Operation {\n")
        sb.append("  readonly opCode = OpCode.${op.name};\n\n")

        if (props.isEmpty()) {
            sb.append("  constructor() {}\n\n")
        } else {
            sb.append("  /**\n")
            for (prop in props) {
                val fieldDesc = prop.description.replace("\n", " ").trim()
                sb.append("   * @param ${prop.name} $fieldDesc\n")
            }
            sb.append("   */\n")
            sb.append("  constructor(\n")
            for (prop in props) {
                val tsType = mapToTsType(prop.type, prop.isNullable)
                val defaultVal = mapToTsDefault(prop.type, prop.isNullable, prop.defaultValue)
                sb.append("    public ${prop.name}: $tsType = $defaultVal,\n")
            }
            sb.append("  ) {}\n\n")
        }

        for ((fieldName, bit) in op.computedBitProperties) {
            val getterName = "get" + bit.name.replaceFirstChar { it.uppercaseChar() }
            sb.append("  $getterName(): number {\n")
            sb.append(
                "    return ${CodegenExprUtils.extractBitExpr("this.$fieldName", bit, ExprLang.TYPESCRIPT)};\n"
            )
            sb.append("  }\n\n")
        }

        sb.append("  readFields(buffer: WireBuffer): void {\n")
        appendTsReadBody(sb, op.fields, op.sparseParameters, props)
        sb.append("  }\n\n")

        sb.append("  /** Reads and decodes a [${op.name}] operation from the wire buffer. */\n")
        sb.append("  static read(buffer: WireBuffer): ${op.name} {\n")
        sb.append("    const instance = new ${op.name}();\n")
        sb.append("    instance.readFields(buffer);\n")
        sb.append("    return instance;\n")
        sb.append("  }\n\n")

        sb.append("  /** Serializes this operation to the wire buffer. */\n")
        sb.append("  write(buffer: WireBuffer): void {\n")
        sb.append("    buffer.writeByte(this.opCode);\n")
        appendTsWriteBody(sb, op.fields, op.sparseParameters, props)
        sb.append("  }\n")
        sb.append("}")
        return sb.toString()
    }

    private fun appendTsReadBody(
        sb: StringBuilder,
        fields: List<SchemaField>,
        sparseParameters: List<SchemaSparseParam>?,
        props: List<AstProperty>,
    ) {
        val propByName = props.associateBy { it.name }
        val localReadVars = mutableSetOf<String>()

        for (f in fields) {
            val bits = f.bits
            if (bits != null && f.unpackBits) {
                val rawVar = "raw_${f.name}"
                sb.append("    const $rawVar = buffer.readInt();\n")
                for (b in bits) {
                    val expr = CodegenExprUtils.extractBitExpr(rawVar, b, ExprLang.TYPESCRIPT)
                    if (b.derivedFrom != null) {
                        sb.append("    const ${b.name} = $expr;\n")
                        localReadVars.add(b.name)
                    } else {
                        sb.append("    this.${b.name} = $expr;\n")
                    }
                }
                continue
            }

            val isLocalDerived = f.derivedFrom != null
            if (isLocalDerived) {
                localReadVars.add(f.name)
            }
            val isNullable = propByName[f.name]?.isNullable == true
            val lhsPrefix = if (isLocalDerived) "const ${f.name}" else "this.${f.name}"

            if (f.presentIf != null) {
                val cond =
                    CodegenExprUtils.translateCondition(f.presentIf, ExprLang.TYPESCRIPT) {
                        if (it in localReadVars) it else "this.$it"
                    }
                if (isLocalDerived) {
                    val defaultVal = mapToTsDefault(f.type, false, f.defaultValue)
                    sb.append(
                        "    const ${f.name} = ($cond) ? ${mapToTsReadExpr(f.type)} : $defaultVal;\n"
                    )
                } else {
                    sb.append("    if ($cond) {\n")
                    if (f.type.endsWith("[]")) {
                        appendTsArrayReadLines(
                            sb,
                            f,
                            "this.${f.name}",
                            localReadVars,
                            "      ",
                        )
                    } else {
                        sb.append(
                            "      this.${f.name} = ${mapToTsReadExpr(f.type, f.maxLength)};\n"
                        )
                        if (f.strictEnum && !f.enumValues.isNullOrEmpty()) {
                            val allowed = f.enumValues.values.distinct().sorted()
                            val check = allowed.joinToString(" && ") { "this.${f.name} !== $it" }
                            sb.append("      if ($check) {\n")
                            sb.append(
                                "        throw new Error(\"Invalid enum value for ${f.name}: \" + this.${f.name});\n"
                            )
                            sb.append("      }\n")
                        }
                    }
                    sb.append("    } else {\n")
                    sb.append(
                        "      this.${f.name} = ${mapToTsDefault(f.type, isNullable, f.defaultValue)};\n"
                    )
                    sb.append("    }\n")
                }
            } else if (f.type.endsWith("[]")) {
                appendTsArrayReadLines(sb, f, lhsPrefix, localReadVars, "    ")
            } else {
                sb.append("    $lhsPrefix = ${mapToTsReadExpr(f.type, f.maxLength)};\n")
                if (f.strictEnum && !f.enumValues.isNullOrEmpty()) {
                    val varRef = if (isLocalDerived) f.name else "this.${f.name}"
                    val allowed = f.enumValues.values.distinct().sorted()
                    val check = allowed.joinToString(" && ") { "$varRef !== $it" }
                    sb.append("    if ($check) {\n")
                    sb.append(
                        "      throw new Error(\"Invalid enum value for ${f.name}: \" + $varRef);\n"
                    )
                    sb.append("    }\n")
                }
            }
        }

        if (sparseParameters != null) {
            for (sp in sparseParameters) {
                sb.append("    this.${sp.name} = null;\n")
            }
            sb.append("    const sparseCount = buffer.readShort() & 0xFFFF;\n")
            sb.append("    if (sparseCount * 2 > buffer.remaining()) {\n")
            sb.append(
                "      throw new RangeError(\"Sparse parameter count exceeds remaining WireBuffer size: \" + sparseCount);\n"
            )
            sb.append("    }\n")
            sb.append("    for (let s = 0; s < sparseCount; s++) {\n")
            sb.append("      const paramId = buffer.readByte();\n")
            sb.append("      switch (paramId) {\n")
            for (sp in sparseParameters) {
                sb.append("        case ${sp.id}: {\n")
                if (sp.type.endsWith("[]")) {
                    val synField =
                        SchemaField(
                            name = sp.name,
                            type = sp.type,
                            description = sp.description,
                            enumValues = null,
                            lengthType = "ushort",
                        )
                    appendTsArrayReadLines(
                        sb,
                        synField,
                        "this.${sp.name}",
                        localReadVars,
                        "          ",
                    )
                } else {
                    sb.append("          this.${sp.name} = ${mapToTsReadExpr(sp.type)};\n")
                }
                sb.append("          break;\n")
                sb.append("        }\n")
            }
            sb.append("        default:\n")
            sb.append("          throw new Error(\"Unknown sparse parameter id: \" + paramId);\n")
            sb.append("      }\n")
            sb.append("    }\n")
        }
    }

    private fun appendTsArrayReadLines(
        sb: StringBuilder,
        f: SchemaField,
        targetLhs: String,
        localReadVars: Set<String>,
        indent: String,
    ) {
        val lenVar = "_${f.name}Count"
        if (f.countFrom != null) {
            val countRef = if (f.countFrom in localReadVars) f.countFrom else "this.${f.countFrom}"
            sb.append("${indent}const $lenVar = $countRef;\n")
        } else {
            when (f.effectiveLengthType) {
                "int" -> sb.append("${indent}const $lenVar = buffer.readInt();\n")
                "ushort" -> sb.append("${indent}const $lenVar = buffer.readShort() & 0xFFFF;\n")
                else -> sb.append("${indent}const $lenVar = buffer.readShort();\n")
            }
        }
        sb.append("${indent}if ($lenVar < 0) {\n")
        sb.append(
            "$indent  throw new Error(\"Invalid negative array length for ${f.name}: \" + $lenVar);\n"
        )
        sb.append("$indent}\n")
        if (f.maxLength != null) {
            sb.append("${indent}if ($lenVar > ${f.maxLength}) {\n")
            sb.append(
                "$indent  throw new RangeError(\"Array length exceeds maximum (${f.maxLength}) for ${f.name}: \" + $lenVar);\n"
            )
            sb.append("$indent}\n")
        }
        val elemType = f.type.removeSuffix("[]")
        val elemMinBytes = CodegenExprUtils.minWireElementBytes(elemType, schema)
        sb.append("${indent}if ($lenVar * $elemMinBytes > buffer.remaining()) {\n")
        sb.append(
            "$indent  throw new RangeError(\"Array length exceeds remaining WireBuffer size for ${f.name}: \" + $lenVar);\n"
        )
        sb.append("$indent}\n")
        when (f.type) {
            "int[]" -> {
                sb.append("${indent}const ${f.name}Arr = new Int32Array($lenVar);\n")
                sb.append("${indent}for (let i = 0; i < $lenVar; i++) {\n")
                sb.append("$indent  ${f.name}Arr[i] = buffer.readInt();\n")
                sb.append("$indent}\n")
                sb.append("$indent$targetLhs = ${f.name}Arr;\n")
            }
            "short[]" -> {
                sb.append("${indent}const ${f.name}Arr = new Int16Array($lenVar);\n")
                sb.append("${indent}for (let i = 0; i < $lenVar; i++) {\n")
                sb.append("$indent  ${f.name}Arr[i] = buffer.readShort();\n")
                sb.append("$indent}\n")
                sb.append("$indent$targetLhs = ${f.name}Arr;\n")
            }
            "float[]",
            "float_or_id[]" -> {
                sb.append("${indent}const ${f.name}Arr = new Float32Array($lenVar);\n")
                sb.append("${indent}for (let i = 0; i < $lenVar; i++) {\n")
                sb.append("$indent  ${f.name}Arr[i] = buffer.readFloat();\n")
                sb.append("$indent}\n")
                sb.append("$indent$targetLhs = ${f.name}Arr;\n")
            }
            else -> {
                val tsElem = mapToTsType(elemType, false)
                sb.append("${indent}const ${f.name}Arr: $tsElem[] = [];\n")
                sb.append("${indent}for (let i = 0; i < $lenVar; i++) {\n")
                sb.append("$indent  ${f.name}Arr.push(${mapToTsReadExpr(elemType)});\n")
                sb.append("$indent}\n")
                sb.append("$indent$targetLhs = ${f.name}Arr;\n")
            }
        }
    }

    private fun appendTsWriteBody(
        sb: StringBuilder,
        fields: List<SchemaField>,
        sparseParameters: List<SchemaSparseParam>?,
        props: List<AstProperty>,
    ) {
        val propByName = props.associateBy { it.name }
        val localWriteVars = mutableSetOf<String>()

        for (f in fields) {
            val bits = f.bits
            if (bits != null && f.unpackBits) {
                val terms = mutableListOf<Pair<String, SchemaBitField>>()
                for (b in bits) {
                    if (b.derivedFrom != null) {
                        val expr = derivedExprToTs(DerivedExpr.parse(b.derivedFrom))
                        sb.append("    const ${b.name} = $expr;\n")
                        localWriteVars.add(b.name)
                        terms.add(b.name to b)
                    } else {
                        terms.add("this.${b.name}" to b)
                    }
                }
                val packed = CodegenExprUtils.packBitsExpr(terms, ExprLang.TYPESCRIPT)
                sb.append("    buffer.writeInt($packed);\n")
                continue
            }

            if (f.derivedFrom != null) {
                val expr = derivedExprToTs(DerivedExpr.parse(f.derivedFrom))
                if (f.presentIf != null) {
                    val cond =
                        CodegenExprUtils.translateCondition(f.presentIf, ExprLang.TYPESCRIPT) {
                            if (it in localWriteVars) it else "this.$it"
                        }
                    sb.append("    if ($cond) {\n")
                    sb.append("      ${mapToTsWriteExpr(f.type, expr)};\n")
                    sb.append("    }\n")
                } else {
                    sb.append("    const ${f.name} = $expr;\n")
                    localWriteVars.add(f.name)
                    sb.append("    ${mapToTsWriteExpr(f.type, f.name)};\n")
                }
                continue
            }

            val isNullable = propByName[f.name]?.isNullable == true
            if (f.presentIf != null) {
                val cond =
                    CodegenExprUtils.translateCondition(f.presentIf, ExprLang.TYPESCRIPT) {
                        if (it in localWriteVars) it else "this.$it"
                    }
                if (isNullable) {
                    sb.append("    if (($cond) && this.${f.name} !== null) {\n")
                    appendTsFieldWriteLines(sb, f, "this.${f.name}", "      ")
                    sb.append("    }\n")
                } else {
                    sb.append("    if ($cond) {\n")
                    appendTsFieldWriteLines(sb, f, "this.${f.name}", "      ")
                    sb.append("    }\n")
                }
            } else {
                appendTsFieldWriteLines(sb, f, "this.${f.name}", "    ")
            }
        }

        if (sparseParameters != null) {
            sb.append("    let sparseCount = 0;\n")
            for (sp in sparseParameters) {
                sb.append("    if (this.${sp.name} !== null) sparseCount++;\n")
            }
            sb.append("    buffer.writeShort(sparseCount);\n")
            for (sp in sparseParameters) {
                sb.append("    if (this.${sp.name} !== null) {\n")
                sb.append("      buffer.writeByte(${sp.id});\n")
                val synField =
                    SchemaField(
                        name = sp.name,
                        type = sp.type,
                        description = sp.description,
                        enumValues = null,
                        lengthType = "short",
                    )
                appendTsFieldWriteLines(sb, synField, "this.${sp.name}", "      ")
                sb.append("    }\n")
            }
        }
    }

    private fun appendTsFieldWriteLines(
        sb: StringBuilder,
        f: SchemaField,
        varExpr: String,
        indent: String,
    ) {
        if (f.type.endsWith("[]")) {
            if (f.countFrom == null) {
                when (f.effectiveLengthType) {
                    "int" -> sb.append("${indent}buffer.writeInt($varExpr.length);\n")
                    else -> sb.append("${indent}buffer.writeShort($varExpr.length);\n")
                }
            }
            val elemType = f.type.removeSuffix("[]")
            sb.append("${indent}for (let i = 0; i < $varExpr.length; i++) {\n")
            sb.append("$indent  ${mapToTsWriteExpr(elemType, "$varExpr[i]")};\n")
            sb.append("$indent}\n")
        } else {
            sb.append("$indent${mapToTsWriteExpr(f.type, varExpr)};\n")
        }
    }

    private fun derivedExprToTs(expr: DerivedExpr): String {
        val target = "this.${expr.targetName}"
        return when (expr) {
            is DerivedExpr.LengthOf -> "$target.length"
            is DerivedExpr.PresentOf -> "($target !== null ? 1 : 0)"
            is DerivedExpr.NonEmptyOf -> "($target.length > 0 ? 1 : 0)"
        }
    }

    private fun mapToTsType(type: String, isNullable: Boolean): String {
        val base =
            when {
                type == "int[]" -> "Int32Array"
                type == "short[]" -> "Int16Array"
                type == "float[]" || type == "float_or_id[]" -> "Float32Array"
                type.endsWith("[]") -> "${mapToTsType(type.removeSuffix("[]"), false)}[]"
                type in setOf("int", "short", "byte", "float", "color", "float_or_id") -> "number"
                type == "long" -> "bigint"
                type == "boolean" -> "boolean"
                type == "string" -> "string"
                type == "bytes" -> "Uint8Array"
                schema.structs.containsKey(type) -> type
                else -> "number"
            }
        return if (isNullable) "$base | null" else base
    }

    private fun mapToTsDefault(
        type: String,
        isNullable: Boolean,
        explicitDefault: String?,
    ): String {
        if (isNullable) return "null"
        if (explicitDefault != null) return explicitDefault
        return when {
            type == "int[]" -> "new Int32Array(0)"
            type == "short[]" -> "new Int16Array(0)"
            type == "float[]" || type == "float_or_id[]" -> "new Float32Array(0)"
            type.endsWith("[]") -> "[]"
            type in setOf("int", "short", "byte", "float", "color", "float_or_id") -> "0"
            type == "long" -> "0n"
            type == "boolean" -> "false"
            type == "string" -> "\"\""
            type == "bytes" -> "new Uint8Array(0)"
            schema.structs.containsKey(type) -> "new $type()"
            else -> "0"
        }
    }

    private fun mapToTsReadExpr(type: String, maxLength: Int? = null): String =
        when (type) {
            "int",
            "color" -> "buffer.readInt()"
            "short" -> "buffer.readShort()"
            "byte" -> "buffer.readByte()"
            "long" -> "buffer.readLong()"
            "float",
            "float_or_id" -> "buffer.readFloat()"
            "boolean" -> "buffer.readBoolean()"
            "string" ->
                if (maxLength != null) "buffer.readUTF8($maxLength)" else "buffer.readUTF8()"
            "bytes" ->
                if (maxLength != null) "buffer.readBuffer($maxLength)" else "buffer.readBuffer()"
            else ->
                if (schema.structs.containsKey(type)) "$type.read(buffer)" else "buffer.readInt()"
        }

    private fun mapToTsWriteExpr(type: String, varName: String): String =
        when (type) {
            "int",
            "color" -> "buffer.writeInt($varName)"
            "short" -> "buffer.writeShort($varName)"
            "byte" -> "buffer.writeByte($varName)"
            "long" -> "buffer.writeLong($varName)"
            "float",
            "float_or_id" -> "buffer.writeFloat($varName)"
            "boolean" -> "buffer.writeBoolean($varName)"
            "string" -> "buffer.writeUTF8($varName)"
            "bytes" -> "buffer.writeBuffer($varName)"
            else ->
                if (schema.structs.containsKey(type)) "$varName.write(buffer)"
                else "buffer.writeInt($varName)"
        }
}
