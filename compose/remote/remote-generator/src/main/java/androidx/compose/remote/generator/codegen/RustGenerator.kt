package androidx.compose.remote.generator.codegen

import androidx.compose.remote.generator.AstProperty
import androidx.compose.remote.generator.DerivedExpr
import androidx.compose.remote.generator.OperationSchema
import androidx.compose.remote.generator.SchemaBitField
import androidx.compose.remote.generator.SchemaField
import androidx.compose.remote.generator.SchemaOperation
import androidx.compose.remote.generator.SchemaSparseParam
import androidx.compose.remote.generator.SchemaStruct

/**
 * Generator that transforms an [OperationSchema] into idiomatic Rust bindings:
 * - WireBuffer and WireError implementations
 * - OpId enum with from_u8 decoding, as_u8, and string name introspection
 * - Auxiliary structs and typed structs for each operation with WireBuffer read/write methods
 * - Unified Operation enum (sum type) with dynamic dispatch and opcode/name introspection
 * - RemoteDocument container with load and save methods
 */
internal class RustGenerator(private val schema: OperationSchema) {

    fun generate(): String = buildCode {
        line("// Generated by RemoteCompose Schema Codegen. DO NOT EDIT.")
        line("#![allow(unused_parens, clippy::identity_op, clippy::unnecessary_cast)]")
        line()
        emitWireBuffer(this)
        line()
        emitOpIdEnum(this, includeHeaderComment = false)
        line()
        for ((_, structDef) in schema.structs) {
            emitAuxStruct(this, structDef)
            line()
        }
        for (op in schema.operations) {
            emitStruct(this, op)
            line()
        }
        emitOperationEnum(this)
        line()
        emitRemoteDocument(this)
    }

    fun generateOpIdEnum(includeHeaderComment: Boolean = true): String = buildCode {
        emitOpIdEnum(this, includeHeaderComment)
    }

    private fun emitOpIdEnum(w: CodeWriter, includeHeaderComment: Boolean) {
        if (includeHeaderComment) {
            w.line("// Generated by RemoteCompose Schema Codegen. DO NOT EDIT.")
            w.line()
        }
        w.line("/// Operation wire identifiers for RemoteCompose operations.")
        w.line("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]")
        w.line("#[repr(u8)]")
        w.block("pub enum OpId") {
            for (op in schema.operations) {
                line("/// ${op.description.replace("\n", " ").trim()}")
                line("${op.name} = ${op.id},")
            }
        }
        w.line()
        w.block("impl OpId") {
            block("pub fn from_u8(value: u8) -> Option<Self>") {
                block("match value") {
                    for (op in schema.operations) {
                        line("${op.id} => Some(OpId::${op.name}),")
                    }
                    line("_ => None,")
                }
            }
            line()
            block("pub fn as_u8(&self) -> u8") {
                line("*self as u8")
            }
            line()
            block("pub fn name(&self) -> &'static str") {
                block("match self") {
                    for (op in schema.operations) {
                        line("OpId::${op.name} => \"${op.name}\",")
                    }
                }
            }
        }
        w.line()
        w.block("impl std::fmt::Display for OpId") {
            block("fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result") {
                line("write!(f, \"{}\", self.name())")
            }
        }
    }

    fun generateOpCodesModule(includeHeaderComment: Boolean = true): String = buildCode {
        if (includeHeaderComment) {
            line("// Generated by RemoteCompose RustGenerator. DO NOT EDIT.")
            line()
        }
        line("pub const PROFILE_BASELINE: i32 = 0x0;")
        line("pub const PROFILE_EXPERIMENTAL: i32 = 0x1;")
        line("pub const PROFILE_DEPRECATED: i32 = 0x2;")
        line("pub const PROFILE_WIDGETS: i32 = 0x100;")
        line("pub const PROFILE_ANDROIDX: i32 = 0x200;")
        line()
        line("#[derive(Debug, Copy, Clone, PartialEq)]")
        block("pub struct SupportedOperation") {
            line("pub id: u8,")
            line("pub name: &'static str,")
            line("pub profile_mask: i32,")
        }
        line()
        line("#[derive(num_derive::FromPrimitive, PartialEq, Clone, Copy, Debug)]")
        line("#[allow(clippy::upper_case_acronyms)]")
        line("#[repr(u8)]")
        block("pub enum OpId") {
            for (op in schema.operations) {
                val name = op.resolvedOpCodeName
                line("$name = ${op.id},")
            }
        }
        line()
        block("impl OpId") {
            block("pub fn from_u8(value: u8) -> Option<Self>") {
                block("match value") {
                    for (op in schema.operations) {
                        val name = op.resolvedOpCodeName
                        line("${op.id} => Some(OpId::$name),")
                    }
                    line("_ => None,")
                }
            }
            line()
            block("pub fn as_u8(&self) -> u8") {
                line("*self as u8")
            }
            line()
            block("pub fn name(&self) -> &'static str") {
                block("match self") {
                    for (op in schema.operations) {
                        val name = op.resolvedOpCodeName
                        line("OpId::$name => \"${op.name}\",")
                    }
                }
            }
        }
        line()
        block(
            "pub const SUPPORTED_OPERATIONS: [SupportedOperation; ${schema.operations.size}] =",
            openSuffix = " [",
            close = "];",
        ) {
            for (op in schema.operations) {
                var mask = 0
                if (op.profiles.contains("experimental")) mask = mask or 0x1
                if (op.profiles.contains("deprecated")) mask = mask or 0x2
                if (op.profiles.contains("widgets")) mask = mask or 0x100
                if (op.profiles.contains("androidx")) mask = mask or 0x200
                line(
                    "SupportedOperation { id: ${op.id}, name: \"${op.name}\", profile_mask: $mask },"
                )
            }
        }
    }

    private fun getRustProfileCfg(op: SchemaOperation): String? {
        if (op.profiles.contains("baseline") || op.profiles.isEmpty()) {
            return null
        }
        val platformTerms = mutableListOf<String>()
        if (op.profiles.contains("androidx")) {
            platformTerms.add("feature = \"profile_androidx\"")
            platformTerms.add("rc_profile_androidx")
        }
        if (op.profiles.contains("widgets")) {
            platformTerms.add("feature = \"profile_widgets\"")
            platformTerms.add("rc_profile_widgets")
        }
        if (op.profiles.contains("oem")) {
            platformTerms.add("feature = \"profile_oem\"")
            platformTerms.add("rc_profile_oem")
        }
        val clauses = mutableListOf<String>()
        if (platformTerms.isNotEmpty()) {
            clauses.add("any(${platformTerms.joinToString(", ")})")
        }
        if (op.profiles.contains("experimental")) {
            clauses.add("any(feature = \"profile_experimental\", rc_profile_experimental)")
        }
        if (op.profiles.contains("deprecated")) {
            clauses.add("any(feature = \"profile_deprecated\", rc_profile_deprecated)")
        }
        val allowedParts = mutableListOf("feature = \"profile_all\"", "rc_profile_all")
        if (clauses.size == 1) {
            allowedParts.add(clauses[0])
        } else if (clauses.size > 1) {
            allowedParts.add("all(${clauses.joinToString(", ")})")
        }
        val allowedStr = allowedParts.joinToString(", ")
        return "any($allowedStr, not(any(" +
            "feature = \"profile_baseline\", feature = \"profile_widgets\", " +
            "feature = \"profile_androidx\", feature = \"profile_experimental\", " +
            "feature = \"profile_deprecated\", feature = \"profile_oem\", " +
            "rc_profile_baseline, rc_profile_widgets, rc_profile_androidx, " +
            "rc_profile_experimental, rc_profile_deprecated, rc_profile_oem)))"
    }

    private fun shouldBoxVariant(op: SchemaOperation): Boolean {
        var estimatedBytes = 0
        for (prop in op.astProperties) {
            val base =
                when {
                    prop.type.endsWith("[]") || prop.type == "string" || prop.type == "bytes" -> 24
                    prop.type == "long" -> 8
                    prop.type in setOf("int", "color", "float", "float_or_id") -> 4
                    prop.type == "short" -> 2
                    prop.type in setOf("byte", "boolean") -> 1
                    else -> 24
                }
            estimatedBytes += if (prop.isNullable) base + if (base >= 8) 8 else base else base
        }
        return estimatedBytes > 64
    }

    private fun emitAuxStruct(w: CodeWriter, structDef: SchemaStruct) {
        val props = structDef.astProperties
        val desc = structDef.description.replace("\n", " ").trim()
        if (desc.isNotEmpty()) {
            w.line("/// $desc")
        }
        w.line("#[derive(Debug, Clone, PartialEq)]")
        w.block("pub struct ${structDef.name}") {
            emitRustStructFields(this, props)
        }
        w.line()
        w.block("impl ${structDef.name}") {
            block("pub fn read(buffer: &mut WireBuffer) -> Result<Self, WireError>") {
                emitRustReadBody(this, structDef.fields, null, props)
            }
            line()
            line("#[cfg($WRITER_CFG)]")
            block("pub fn write(&self, buffer: &mut WireBuffer) -> Result<(), WireError>") {
                emitRustWriteBody(this, structDef.fields, null, props)
            }
        }
    }

    fun generateStruct(op: SchemaOperation): String = buildCode {
        emitStruct(this, op)
    }

    private fun emitStruct(w: CodeWriter, op: SchemaOperation) {
        val cfg = getRustProfileCfg(op)
        val props = op.astProperties
        val desc = op.description.replace("\n", " ").trim()
        if (desc.isNotEmpty()) {
            w.line("/// $desc")
        }
        if (cfg != null) {
            w.line("#[cfg($cfg)]")
        }
        w.line("#[derive(Debug, Clone, PartialEq)]")
        w.block("pub struct ${op.name}") {
            emitRustStructFields(this, props)
        }
        w.line()
        if (cfg != null) {
            w.line("#[cfg($cfg)]")
        }
        w.block("impl ${op.name}") {
            line("/// Wire protocol opcode identifier.")
            line("pub const OP_CODE: u8 = ${op.id};")
            line()
            line("/// Reads and decodes a [${op.name}] operation from the wire buffer.")
            block("pub fn read(buffer: &mut WireBuffer) -> Result<Self, WireError>") {
                emitRustReadBody(
                    this,
                    op.fields,
                    op.sparseParameters,
                    props,
                    op.sparseCountType,
                    op.sparseKeyType,
                )
            }
            line()
            line("#[cfg($WRITER_CFG)]")
            line("/// Encodes and writes this operation to the wire buffer.")
            block("pub fn write(&self, buffer: &mut WireBuffer) -> Result<(), WireError>") {
                line("buffer.start(Self::OP_CODE);")
                emitRustWriteBody(
                    this,
                    op.fields,
                    op.sparseParameters,
                    props,
                    op.sparseCountType,
                    op.sparseKeyType,
                )
            }
        }
    }

    private fun emitRustStructFields(w: CodeWriter, props: List<AstProperty>) {
        for (prop in props) {
            val rustType = mapToRustType(prop.type, prop.isNullable)
            val snakeName = sanitizeRustIdentifier(prop.name)
            val fieldDesc = prop.description.replace("\n", " ").trim()
            if (fieldDesc.isNotEmpty()) {
                w.line("/// $fieldDesc")
            }
            w.line("pub $snakeName: $rustType,")
        }
    }

    private fun hasRustScalarReadValidations(field: SchemaField): Boolean {
        if (field.strictEnum && !field.enumValues.isNullOrEmpty()) return true
        val bits = field.bits
        return bits != null &&
            !field.unpackBits &&
            bits.any { it.strictEnum && !it.enumValues.isNullOrEmpty() }
    }

    private fun emitRustScalarValidations(w: CodeWriter, field: SchemaField, varName: String) {
        if (field.strictEnum && !field.enumValues.isNullOrEmpty()) {
            val allowed = field.enumValues.values.distinct().sorted().joinToString(" | ")
            w.block("if !matches!($varName, $allowed)") {
                line("return Err(WireError::InvalidData);")
            }
        }
        val bits = field.bits
        if (bits != null && !field.unpackBits) {
            val srcExpr =
                if (field.type == "byte" || field.type == "short") "($varName as i32)" else varName
            for (b in bits) {
                if (b.strictEnum && !b.enumValues.isNullOrEmpty()) {
                    val bVar = "bit_${toSnakeCase(b.name)}"
                    val extract = CodegenExprUtils.extractBitExpr(srcExpr, b, ExprLang.RUST)
                    val allowed = b.enumValues.values.distinct().sorted().joinToString(" | ")
                    w.line("let $bVar = $extract;")
                    w.block("if !matches!($bVar, $allowed)") {
                        line("return Err(WireError::InvalidData);")
                    }
                }
            }
        }
    }

    private fun emitRustReadBody(
        w: CodeWriter,
        fields: List<SchemaField>,
        sparseParameters: List<SchemaSparseParam>?,
        props: List<AstProperty>,
        sparseCountType: String? = null,
        sparseKeyType: String? = null,
    ) {
        if (fields.isEmpty() && sparseParameters.isNullOrEmpty()) {
            w.line("let _ = buffer;")
        }
        for (field in fields) {
            val bits = field.bits
            if (bits != null && field.unpackBits) {
                val rawVar = "raw_${toSnakeCase(field.name)}"
                w.line("let $rawVar = buffer.read_i32()?;")
                for (b in bits) {
                    val bName = sanitizeRustIdentifier(b.name)
                    val extract = CodegenExprUtils.extractBitExpr(rawVar, b, ExprLang.RUST)
                    w.line("let $bName = $extract;")
                    if (b.strictEnum && !b.enumValues.isNullOrEmpty()) {
                        val allowed = b.enumValues.values.distinct().sorted().joinToString(" | ")
                        w.block("if !matches!($bName, $allowed)") {
                            line("return Err(WireError::InvalidData);")
                        }
                    }
                }
                continue
            }

            val snakeName = sanitizeRustIdentifier(field.name)
            val isLocalDerived = field.derivedFrom != null
            val isNullable =
                !isLocalDerived &&
                    field.presentIf != null &&
                    !field.type.endsWith("[]") &&
                    field.defaultValue == null

            if (field.presentIf != null) {
                val cond =
                    CodegenExprUtils.translateCondition(field.presentIf, ExprLang.RUST) {
                        sanitizeRustIdentifier(it)
                    }
                w.block("let $snakeName = if $cond", close = null) {
                    if (field.type.endsWith("[]")) {
                        val baseSnake = toSnakeCase(field.name)
                        emitRustArrayReadLines(this, field, baseSnake)
                        line("${baseSnake}_vec")
                    } else {
                        val readExpr = mapToRustScalarReadExpr(field.type, field.maxLength)
                        if (hasRustScalarReadValidations(field)) {
                            line("let val = $readExpr;")
                            emitRustScalarValidations(this, field, "val")
                            line(if (isNullable) "Some(val)" else "val")
                        } else if (isNullable) {
                            line("Some($readExpr)")
                        } else {
                            line(readExpr)
                        }
                    }
                }
                w.block("} else", close = "};") {
                    line(mapToRustFallback(field.type, isNullable, field.defaultValue))
                }
            } else if (field.type.endsWith("[]")) {
                val baseSnake = toSnakeCase(field.name)
                emitRustArrayReadLines(w, field, baseSnake)
                w.line("let $snakeName = ${baseSnake}_vec;")
            } else {
                w.line("let $snakeName = ${mapToRustScalarReadExpr(field.type, field.maxLength)};")
                emitRustScalarValidations(w, field, snakeName)
            }
        }

        if (sparseParameters != null) {
            for (sp in sparseParameters) {
                val spName = sanitizeRustIdentifier(sp.name)
                val spType = mapToRustType(sp.type, true)
                w.line("let mut $spName: $spType = None;")
            }
            val effectiveCountType = sparseCountType ?: "ushort"
            val effectiveKeyType = sparseKeyType ?: "ubyte"
            when (effectiveCountType) {
                "int" -> {
                    w.line("let sparse_raw_count = buffer.read_i32()?;")
                    w.block("if sparse_raw_count < 0") {
                        line("return Err(WireError::InvalidData);")
                    }
                    w.line("let sparse_count = sparse_raw_count as usize;")
                }
                "short" -> {
                    w.line("let sparse_raw_count = buffer.read_i16()?;")
                    w.block("if sparse_raw_count < 0") {
                        line("return Err(WireError::InvalidData);")
                    }
                    w.line("let sparse_count = sparse_raw_count as usize;")
                }
                "byte" -> {
                    w.line("let sparse_raw_count = buffer.read_u8()? as i8;")
                    w.block("if sparse_raw_count < 0") {
                        line("return Err(WireError::InvalidData);")
                    }
                    w.line("let sparse_count = sparse_raw_count as usize;")
                }
                "ubyte" -> w.line("let sparse_count = buffer.read_u8()? as usize;")
                else -> w.line("let sparse_count = (buffer.read_i16()? as u16) as usize;")
            }
            val minEntryBytes =
                when (effectiveKeyType) {
                    "int" -> 5
                    "short",
                    "ushort" -> 3
                    else -> 2
                }
            w.block("if sparse_count > buffer.remaining() / $minEntryBytes") {
                line("return Err(WireError::Underflow);")
            }
            w.block("for _ in 0..sparse_count") {
                when (effectiveKeyType) {
                    "int" -> line("let param_id = buffer.read_i32()?;")
                    "ushort" -> line("let param_id = buffer.read_i16()? as u16;")
                    "short" -> line("let param_id = buffer.read_i16()?;")
                    "byte" -> line("let param_id = buffer.read_u8()? as i8;")
                    else -> line("let param_id = buffer.read_u8()?;")
                }
                block("match param_id") {
                    for (sp in sparseParameters) {
                        val spName = sanitizeRustIdentifier(sp.name)
                        if (sp.type.endsWith("[]")) {
                            block("${sp.id} =>") {
                                val synField =
                                    SchemaField(
                                        name = sp.name,
                                        type = sp.type,
                                        description = sp.description,
                                        enumValues = null,
                                        lengthType = sp.lengthType ?: "ushort",
                                    )
                                val baseSnake = toSnakeCase(sp.name)
                                emitRustArrayReadLines(this, synField, baseSnake)
                                line("$spName = Some(${baseSnake}_vec);")
                            }
                        } else {
                            line(
                                "${sp.id} => { $spName = Some(${mapToRustScalarReadExpr(sp.type)}); }"
                            )
                        }
                    }
                    line("_ => return Err(WireError::InvalidData),")
                }
            }
        }

        w.block("Ok(Self", close = "})") {
            for (prop in props) {
                line("${sanitizeRustIdentifier(prop.name)},")
            }
        }
    }

    private fun emitRustArrayReadLines(
        w: CodeWriter,
        field: SchemaField,
        baseSnake: String,
    ) {
        if (field.countFrom != null) {
            val countIdent = sanitizeRustIdentifier(field.countFrom)
            w.block("if $countIdent < 0") {
                line("return Err(WireError::InvalidData);")
            }
            w.line("let ${baseSnake}_len = $countIdent as usize;")
        } else {
            when (field.effectiveLengthType) {
                "int" -> {
                    w.line("let ${baseSnake}_raw_len = buffer.read_i32()?;")
                    w.block("if ${baseSnake}_raw_len < 0") {
                        line("return Err(WireError::InvalidData);")
                    }
                    w.line("let ${baseSnake}_len = ${baseSnake}_raw_len as usize;")
                }
                "ushort" -> {
                    w.line("let ${baseSnake}_len = (buffer.read_i16()? as u16) as usize;")
                }
                "ubyte" -> {
                    w.line("let ${baseSnake}_len = buffer.read_u8()? as usize;")
                }
                "byte" -> {
                    w.line("let ${baseSnake}_raw_len = buffer.read_u8()? as i8;")
                    w.block("if ${baseSnake}_raw_len < 0") {
                        line("return Err(WireError::InvalidData);")
                    }
                    w.line("let ${baseSnake}_len = ${baseSnake}_raw_len as usize;")
                }
                else -> {
                    w.line("let ${baseSnake}_raw_len = buffer.read_i16()?;")
                    w.block("if ${baseSnake}_raw_len < 0") {
                        line("return Err(WireError::InvalidData);")
                    }
                    w.line("let ${baseSnake}_len = ${baseSnake}_raw_len as usize;")
                }
            }
        }
        val elemType = field.type.removeSuffix("[]")
        val elemMinBytes = CodegenExprUtils.minWireElementBytes(elemType, schema)
        if (field.maxLength != null) {
            w.block("if ${baseSnake}_len > ${field.maxLength}") {
                line("return Err(WireError::InvalidData);")
            }
        }
        w.block("if ${baseSnake}_len > buffer.remaining() / $elemMinBytes") {
            line("return Err(WireError::Underflow);")
        }
        w.line("let mut ${baseSnake}_vec = Vec::with_capacity(${baseSnake}_len.min(4096));")
        w.block("for _ in 0..${baseSnake}_len") {
            line("${baseSnake}_vec.push(${mapToRustScalarReadExpr(elemType)});")
        }
    }

    private fun emitRustWriteBody(
        w: CodeWriter,
        fields: List<SchemaField>,
        sparseParameters: List<SchemaSparseParam>?,
        props: List<AstProperty>,
        sparseCountType: String? = null,
        sparseKeyType: String? = null,
    ) {
        val propByName = props.associateBy { it.name }
        val localVars = mutableSetOf<String>()

        for (field in fields) {
            val bits = field.bits
            if (bits != null && field.unpackBits) {
                val terms = mutableListOf<Pair<String, SchemaBitField>>()
                for (b in bits) {
                    val bSnake = sanitizeRustIdentifier(b.name)
                    if (b.derivedFrom != null) {
                        val expr = derivedExprToRust(DerivedExpr.parse(b.derivedFrom))
                        w.line("let $bSnake: i32 = $expr;")
                        localVars.add(b.name)
                        terms.add(bSnake to b)
                    } else {
                        terms.add("self.$bSnake" to b)
                    }
                }
                val packed = CodegenExprUtils.packBitsExpr(terms, ExprLang.RUST)
                w.line("buffer.write_i32($packed);")
                continue
            }

            if (field.derivedFrom != null) {
                val derivedVal = derivedExprToRust(DerivedExpr.parse(field.derivedFrom))
                if (field.presentIf != null) {
                    val cond =
                        CodegenExprUtils.translateCondition(field.presentIf, ExprLang.RUST) {
                            if (it in localVars) sanitizeRustIdentifier(it)
                            else "self.${sanitizeRustIdentifier(it)}"
                        }
                    w.block("if $cond") {
                        line(
                            "${mapToRustScalarWriteExpr(field.type, derivedVal, isOwnedOrValue = true)};"
                        )
                    }
                } else {
                    val fSnake = sanitizeRustIdentifier(field.name)
                    w.line("let $fSnake: i32 = $derivedVal;")
                    localVars.add(field.name)
                    w.line(
                        "${mapToRustScalarWriteExpr(field.type, fSnake, isOwnedOrValue = true)};"
                    )
                }
                continue
            }

            val snakeName = sanitizeRustIdentifier(field.name)
            val isNullable = propByName[field.name]?.isNullable == true

            if (field.presentIf != null) {
                val cond =
                    CodegenExprUtils.translateCondition(field.presentIf, ExprLang.RUST) {
                        if (it in localVars) sanitizeRustIdentifier(it)
                        else "self.${sanitizeRustIdentifier(it)}"
                    }
                w.block("if $cond") {
                    if (isNullable) {
                        line(
                            "let val = self.$snakeName.as_ref().ok_or(WireError::MissingRequiredField(\"${field.name}\"))?;"
                        )
                        emitRustFieldWriteLines(this, field, "val", isRef = true)
                    } else {
                        emitRustFieldWriteLines(this, field, "self.$snakeName", isRef = false)
                    }
                }
            } else {
                emitRustFieldWriteLines(w, field, "self.$snakeName", isRef = false)
            }
        }

        if (sparseParameters != null) {
            w.line("let mut sparse_count: usize = 0;")
            for (sp in sparseParameters) {
                val spName = sanitizeRustIdentifier(sp.name)
                w.line("if self.$spName.is_some() { sparse_count += 1; }")
            }
            when (sparseCountType ?: "ushort") {
                "int" -> w.line("buffer.write_i32(sparse_count as i32);")
                "ubyte",
                "byte" -> w.line("buffer.write_u8(sparse_count as u8);")
                else -> w.line("buffer.write_i16(sparse_count as i16);")
            }
            val effectiveKeyType = sparseKeyType ?: "ubyte"
            for (sp in sparseParameters) {
                val spName = sanitizeRustIdentifier(sp.name)
                w.block("if let Some(ref val) = self.$spName") {
                    when (effectiveKeyType) {
                        "int" -> line("buffer.write_i32(${sp.id});")
                        "ushort",
                        "short" -> line("buffer.write_i16(${sp.id});")
                        else -> line("buffer.write_u8(${sp.id});")
                    }
                    val synField =
                        SchemaField(
                            name = sp.name,
                            type = sp.type,
                            description = sp.description,
                            enumValues = null,
                            lengthType = sp.lengthType ?: "ushort",
                        )
                    emitRustFieldWriteLines(this, synField, "val", isRef = true)
                }
            }
        }
        w.line("Ok(())")
    }

    private fun emitRustFieldWriteLines(
        w: CodeWriter,
        field: SchemaField,
        expr: String,
        isRef: Boolean,
    ) {
        if (field.type.endsWith("[]")) {
            if (field.countFrom == null) {
                when (field.effectiveLengthType) {
                    "int" -> w.line("buffer.write_i32($expr.len() as i32);")
                    "ubyte",
                    "byte" -> w.line("buffer.write_u8($expr.len() as u8);")
                    else -> w.line("buffer.write_i16($expr.len() as i16);")
                }
            }
            val elemType = field.type.removeSuffix("[]")
            val iterExpr = if (isRef) expr else "&$expr"
            if (
                schema.structs.containsKey(elemType) || elemType == "string" || elemType == "bytes"
            ) {
                w.block("for item in $iterExpr") {
                    line("${mapToRustScalarWriteExpr(elemType, "item", isOwnedOrValue = false)};")
                }
            } else {
                w.block("for &item in $iterExpr") {
                    line("${mapToRustScalarWriteExpr(elemType, "item", isOwnedOrValue = true)};")
                }
            }
        } else {
            val valExpr =
                if (
                    isRef &&
                        field.type !in setOf("string", "bytes") &&
                        !schema.structs.containsKey(field.type)
                ) {
                    "*$expr"
                } else {
                    expr
                }
            w.line("${mapToRustScalarWriteExpr(field.type, valExpr, isOwnedOrValue = !isRef)};")
        }
    }

    private fun derivedExprToRust(expr: DerivedExpr): String {
        val target = "self.${sanitizeRustIdentifier(expr.targetName)}"
        return when (expr) {
            is DerivedExpr.LengthOf -> "$target.len() as i32"
            is DerivedExpr.PresentOf -> "if $target.is_some() { 1 } else { 0 }"
            is DerivedExpr.NonEmptyOf -> "if !$target.is_empty() { 1 } else { 0 }"
        }
    }

