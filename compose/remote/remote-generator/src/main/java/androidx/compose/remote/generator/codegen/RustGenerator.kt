            line("pub patch_version: i32,")
            line("pub width: i32,")
            line("pub height: i32,")
            line("pub capabilities: i64,")
            line("pub operations: Vec<Operation>,")
        }
        w.line()
        w.block("impl Default for RemoteDocument") {
            block("fn default() -> Self") {
                line("Self::new()")
            }
        }
        w.line()
        w.block("impl RemoteDocument") {
            line("pub const MAX_HEADER_PROPERTIES: usize = 1000;")
            line("pub const MAX_OPERATION_COUNT: usize = 100_000;")
            line()
            line("/// Creates a new, empty [RemoteDocument].")
            block("pub fn new() -> Self") {
                block("Self") {
                    line("major_version: 1,")
                    line("minor_version: 1,")
                    line("patch_version: 0,")
                    line("width: 0,")
                    line("height: 0,")
                    line("capabilities: 0,")
                    line("operations: Vec::new(),")
                }
            }
            line()
            line(
                "/// Loads and deserializes a [RemoteDocument] from the wire buffer with default limits."
            )
            block("pub fn load(buffer: &mut WireBuffer) -> Result<Self, WireError>") {
                line("Self::load_with_limits(buffer, Self::MAX_OPERATION_COUNT)")
            }
            line()
            line(
                "/// Loads and deserializes a [RemoteDocument] from the wire buffer with an explicit"
            )
            line("/// maximum operation count.")
            line("pub fn load_with_limits(")
            indent {
                line("buffer: &mut WireBuffer,")
                line("max_operations: usize,")
            }
            block(") -> Result<Self, WireError>") {
                line("let mut doc = Self::new();")
                block("if !buffer.available()") {
                    line("return Ok(doc);")
                }
                line()
                line("let header_op = buffer.read_u8()?;")
                block("if header_op != OpId::Header.as_u8()") {
                    line("return Err(WireError::InvalidHeader(header_op));")
                }
                line()
                line("let raw_major = buffer.read_i32()?;")
                line("doc.minor_version = buffer.read_i32()?;")
                line("doc.patch_version = buffer.read_i32()?;")
                block("if (raw_major as u32 & 0xFFFF0000) == 0x048C0000", close = null) {
                    line("doc.major_version = raw_major & 0xFFFF;")
                    line("doc.width = 256;")
                    line("doc.height = 256;")
                    line("let num_props = buffer.read_i32()?;")
                    block(
                        "if num_props < 0 || (num_props as usize) > Self::MAX_HEADER_PROPERTIES"
                    ) {
                        line("return Err(WireError::InvalidData);")
                    }
                    block("if (num_props as usize) > buffer.remaining() / 4") {
                        line("return Err(WireError::Underflow);")
                    }
                    block("for _ in 0..num_props") {
                        line("let tag = buffer.read_i16()? as i32;")
                        line("let _item_len = buffer.read_i16()?;")
                        line("let data_type = tag >> 10;")
                        line("let key = tag & 0x3F;")
                        block("match data_type") {
                            block("0 =>") {
                                line("let val = buffer.read_i32()?;")
                                line("if key == 5 { doc.width = val; }")
                                line("else if key == 6 { doc.height = val; }")
                                line(
                                    "else if key == 14 { doc.capabilities = (val as u32) as i64; }"
                                )
                                block("else if key == 31 && val != 0") {
                                    line("return Err(WireError::UnsupportedCompression);")
                                }
                            }
                            line("1 => { let _ = buffer.read_f32()?; }")
                            block("2 =>") {
                                line("let val = buffer.read_i64()?;")
                                line("if key == 14 { doc.capabilities = val; }")
                                block("else if key == 31 && val != 0") {
                                    line("return Err(WireError::UnsupportedCompression);")
                                }
                            }
                            line("3 => { buffer.skip_utf8_limited(4000)?; }")
                            line("_ => {}")
                        }
                    }
                }
                block("} else if (0..0x10000).contains(&raw_major)", close = null) {
                    line("doc.major_version = raw_major;")
                    line("doc.width = buffer.read_i32()?;")
                    line("doc.height = buffer.read_i32()?;")
                    line("doc.capabilities = buffer.read_i64()?;")
                }
                block("} else") {
                    line("return Err(WireError::InvalidHeaderMagic(raw_major));")
                }
                line()
                block("while buffer.available()") {
                    line("let op_byte = buffer.read_u8()?;")
                    block("if op_byte == OpId::Header.as_u8()") {
                        line("return Err(WireError::InvalidHeader(op_byte));")
                    }
                    block("if doc.operations.len() >= max_operations") {
                        line("return Err(WireError::LimitExceeded);")
                    }
                    line(
                        "let op_id = OpId::from_u8(op_byte).ok_or(WireError::UnknownOpCode(op_byte))?;"
                    )
                    line("let op = Operation::read(op_id, buffer)?;")
                    line("doc.operations.push(op);")
                }
                line("Ok(doc)")
            }
            line()
            line("#[cfg($WRITER_CFG)]")
            line("/// Serializes this document into the wire buffer.")
            block("pub fn save(&self, buffer: &mut WireBuffer) -> Result<(), WireError>") {
                line("buffer.write_u8(OpId::Header.as_u8());")
                line("buffer.write_i32(self.major_version);")
                line("buffer.write_i32(self.minor_version);")
                line("buffer.write_i32(self.patch_version);")
                line("buffer.write_i32(self.width);")
                line("buffer.write_i32(self.height);")
                line("buffer.write_i64(self.capabilities);")
                line()
                block("for op in &self.operations") {
                    line("op.write(buffer)?;")
                }
                line("Ok(())")
            }
        }
    }

