/**
 * Generator that transforms an [OperationSchema] into idiomatic Rust bindings:
 * - WireBuffer and WireError implementations
 * - OpId enum with from_u8 decoding, as_u8, and string name introspection
 * - Auxiliary structs and typed structs for each operation with WireBuffer read/write methods
 * - Unified Operation enum (sum type) with dynamic dispatch and opcode/name introspection
 * - RemoteDocument container with load and save methods
 */
internal class RustGenerator(private val schema: OperationSchema) {

    fun generate(): String {
        val sb = StringBuilder()
        sb.append("// Generated by RemoteCompose Schema Codegen. DO NOT EDIT.\n")
        sb.append("#![allow(unused_parens, clippy::identity_op, clippy::unnecessary_cast)]\n\n")
        sb.append(generateWireBuffer())
        sb.append("\n\n")
        sb.append(generateOpIdEnum(includeHeaderComment = false))
        sb.append("\n\n")
        for ((_, structDef) in schema.structs) {
            sb.append(generateAuxStruct(structDef))
            sb.append("\n\n")
        }
        for (op in schema.operations) {
            sb.append(generateStruct(op))
            sb.append("\n\n")
        }
        sb.append(generateOperationEnum())
        sb.append("\n\n")
        sb.append(generateRemoteDocument())
        sb.append("\n")
        return sb.toString()
    }

    fun generateOpIdEnum(includeHeaderComment: Boolean = true): String {
        val sb = StringBuilder()
        if (includeHeaderComment) {
            sb.append("// Generated by RemoteCompose Schema Codegen. DO NOT EDIT.\n\n")
        }
        sb.append("/// Operation wire identifiers for RemoteCompose operations.\n")
        sb.append("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n")
        sb.append("#[repr(u8)]\n")
        sb.append("pub enum OpId {\n")
        for (op in schema.operations) {
            sb.append("    /// ${op.description.replace("\n", " ").trim()}\n")
            sb.append("    ${op.name} = ${op.id},\n")
        }
        sb.append("}\n\n")

        sb.append("impl OpId {\n")
        sb.append("    pub fn from_u8(value: u8) -> Option<Self> {\n")
        sb.append("        match value {\n")
        for (op in schema.operations) {
            sb.append("            ${op.id} => Some(OpId::${op.name}),\n")
        }
        sb.append("            _ => None,\n")
        sb.append("        }\n")
        sb.append("    }\n\n")

        sb.append("    pub fn as_u8(&self) -> u8 {\n")
        sb.append("        *self as u8\n")
        sb.append("    }\n\n")

        sb.append("    pub fn name(&self) -> &'static str {\n")
        sb.append("        match self {\n")
        for (op in schema.operations) {
            sb.append("            OpId::${op.name} => \"${op.name}\",\n")
        }
        sb.append("        }\n")
        sb.append("    }\n")
        sb.append("}\n\n")

        sb.append("impl std::fmt::Display for OpId {\n")
        sb.append("    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {\n")
        sb.append("        write!(f, \"{}\", self.name())\n")
        sb.append("    }\n")
        sb.append("}\n")
        return sb.toString()
    }

    fun generateOpCodesModule(includeHeaderComment: Boolean = true): String {
        val sb = StringBuilder()
        if (includeHeaderComment) {
            sb.append("// Generated by RemoteCompose RustGenerator. DO NOT EDIT.\n\n")
        }
        sb.append(
            """
            pub const PROFILE_BASELINE: i32 = 0x0;
            pub const PROFILE_EXPERIMENTAL: i32 = 0x1;
            pub const PROFILE_DEPRECATED: i32 = 0x2;
            pub const PROFILE_WIDGETS: i32 = 0x100;
            pub const PROFILE_ANDROIDX: i32 = 0x200;

            #[derive(Debug, Copy, Clone, PartialEq)]
            pub struct SupportedOperation {
                pub id: u8,
                pub name: &'static str,
                pub profile_mask: i32,
            }

            #[derive(num_derive::FromPrimitive, PartialEq, Clone, Copy, Debug)]
            #[allow(clippy::upper_case_acronyms)]
            #[repr(u8)]
            pub enum OpId {
            """
                .trimIndent()
        )
        sb.append("\n")
        for (op in schema.operations) {
            val name = op.resolvedOpCodeName
            sb.append("    $name = ${op.id},\n")
        }
        sb.append("}\n\n")

        sb.append("impl OpId {\n")
        sb.append("    pub fn from_u8(value: u8) -> Option<Self> {\n")
        sb.append("        match value {\n")
        for (op in schema.operations) {
            val name = op.resolvedOpCodeName
            sb.append("            ${op.id} => Some(OpId::$name),\n")
        }
        sb.append("            _ => None,\n")
        sb.append("        }\n")
        sb.append("    }\n\n")

        sb.append("    pub fn as_u8(&self) -> u8 {\n")
        sb.append("        *self as u8\n")
        sb.append("    }\n\n")

        sb.append("    pub fn name(&self) -> &'static str {\n")
        sb.append("        match self {\n")
        for (op in schema.operations) {
            val name = op.resolvedOpCodeName
            sb.append("            OpId::$name => \"${op.name}\",\n")
        }
        sb.append("        }\n")
        sb.append("    }\n")
        sb.append("}\n\n")

        sb.append(
            "pub const SUPPORTED_OPERATIONS: [SupportedOperation; ${schema.operations.size}] = [\n"
        )
        for (op in schema.operations) {
            var mask = 0
            if (op.profiles.contains("experimental")) mask = mask or 0x1
            if (op.profiles.contains("deprecated")) mask = mask or 0x2
            if (op.profiles.contains("widgets")) mask = mask or 0x100
            if (op.profiles.contains("androidx")) mask = mask or 0x200
            sb.append(
                "    SupportedOperation { id: ${op.id}, name: \"${op.name}\", profile_mask: $mask },\n"
            )
        }
        sb.append("];\n")
        return sb.toString()
    }

    private fun getRustProfileCfg(op: SchemaOperation): String? {
        if (op.profiles.contains("baseline") || op.profiles.isEmpty()) {
            return null
        }
        val platformTerms = mutableListOf<String>()
        if (op.profiles.contains("androidx")) {
            platformTerms.add("feature = \"profile_androidx\"")
            platformTerms.add("rc_profile_androidx")
        }
        if (op.profiles.contains("widgets")) {
            platformTerms.add("feature = \"profile_widgets\"")
            platformTerms.add("rc_profile_widgets")
        }
        if (op.profiles.contains("oem")) {
            platformTerms.add("feature = \"profile_oem\"")
            platformTerms.add("rc_profile_oem")
        }
        val clauses = mutableListOf<String>()
        if (platformTerms.isNotEmpty()) {
            clauses.add("any(${platformTerms.joinToString(", ")})")
        }
        if (op.profiles.contains("experimental")) {
            clauses.add("any(feature = \"profile_experimental\", rc_profile_experimental)")
        }
        if (op.profiles.contains("deprecated")) {
            clauses.add("any(feature = \"profile_deprecated\", rc_profile_deprecated)")
        }
        val allowedParts = mutableListOf("feature = \"profile_all\"", "rc_profile_all")
        if (clauses.size == 1) {
            allowedParts.add(clauses[0])
        } else if (clauses.size > 1) {
            allowedParts.add("all(${clauses.joinToString(", ")})")
        }
        val allowedStr = allowedParts.joinToString(", ")
        return "any($allowedStr, not(any(" +
            "feature = \"profile_baseline\", feature = \"profile_widgets\", " +
            "feature = \"profile_androidx\", feature = \"profile_experimental\", " +
            "feature = \"profile_deprecated\", feature = \"profile_oem\", " +
            "rc_profile_baseline, rc_profile_widgets, rc_profile_androidx, " +
            "rc_profile_experimental, rc_profile_deprecated, rc_profile_oem)))"
    }

    private fun shouldBoxVariant(op: SchemaOperation): Boolean {
        var estimatedBytes = 0
        for (prop in op.astProperties) {
            val base =
                when {
                    prop.type.endsWith("[]") || prop.type == "string" || prop.type == "bytes" -> 24
                    prop.type == "long" -> 8
                    prop.type in setOf("int", "color", "float", "float_or_id") -> 4
                    prop.type == "short" -> 2
                    prop.type in setOf("byte", "boolean") -> 1
                    else -> 24
                }
            estimatedBytes += if (prop.isNullable) base + if (base >= 8) 8 else base else base
        }
        return estimatedBytes > 64
    }

    private fun generateAuxStruct(structDef: SchemaStruct): String {
        val sb = StringBuilder()
        val props = structDef.astProperties
        val desc = structDef.description.replace("\n", " ").trim()
        if (desc.isNotEmpty()) {
            sb.append("/// $desc\n")
        }
        sb.append("#[derive(Debug, Clone, PartialEq)]\n")
        sb.append("pub struct ${structDef.name} {\n")
        for (prop in props) {
            val rustType = mapToRustType(prop.type, prop.isNullable)
            val snakeName = sanitizeRustIdentifier(prop.name)
            val fieldDesc = prop.description.replace("\n", " ").trim()
            if (fieldDesc.isNotEmpty()) {
                sb.append("    /// $fieldDesc\n")
            }
            sb.append("    pub $snakeName: $rustType,\n")
        }
        sb.append("}\n\n")

        sb.append("impl ${structDef.name} {\n")
        sb.append("    pub fn read(buffer: &mut WireBuffer) -> Result<Self, WireError> {\n")
        appendRustReadBody(sb, structDef.fields, null, props)
        sb.append("    }\n\n")

        sb.append("    #[cfg($WRITER_CFG)]\n")
        sb.append("    pub fn write(&self, buffer: &mut WireBuffer) {\n")
        appendRustWriteBody(sb, structDef.fields, null, props)
        sb.append("    }\n")
        sb.append("}")
        return sb.toString()
    }

    fun generateStruct(op: SchemaOperation): String {
        val sb = StringBuilder()
        val cfg = getRustProfileCfg(op)
        val props = op.astProperties
        val desc = op.description.replace("\n", " ").trim()
        if (desc.isNotEmpty()) {
            sb.append("/// $desc\n")
        }
        if (cfg != null) {
            sb.append("#[cfg($cfg)]\n")
        }
        sb.append("#[derive(Debug, Clone, PartialEq)]\n")
        sb.append("pub struct ${op.name} {\n")
        for (prop in props) {
            val rustType = mapToRustType(prop.type, prop.isNullable)
            val snakeName = sanitizeRustIdentifier(prop.name)
            val fieldDesc = prop.description.replace("\n", " ").trim()
            if (fieldDesc.isNotEmpty()) {
                sb.append("    /// $fieldDesc\n")
            }
            sb.append("    pub $snakeName: $rustType,\n")
        }
        sb.append("}\n\n")

        if (cfg != null) {
            sb.append("#[cfg($cfg)]\n")
        }
        sb.append("impl ${op.name} {\n")
        sb.append("    /// Wire protocol opcode identifier.\n")
        sb.append("    pub const OP_CODE: u8 = ${op.id};\n\n")
        sb.append("    /// Reads and decodes a [${op.name}] operation from the wire buffer.\n")
        sb.append("    pub fn read(buffer: &mut WireBuffer) -> Result<Self, WireError> {\n")
        appendRustReadBody(sb, op.fields, op.sparseParameters, props)
        sb.append("    }\n\n")

        sb.append("    #[cfg($WRITER_CFG)]\n")
        sb.append("    /// Encodes and writes this operation to the wire buffer.\n")
        sb.append("    pub fn write(&self, buffer: &mut WireBuffer) {\n")
        sb.append("        buffer.start(Self::OP_CODE);\n")
        appendRustWriteBody(sb, op.fields, op.sparseParameters, props)
        sb.append("    }\n")
        sb.append("}\n")
        return sb.toString()
    }

    private fun appendRustReadBody(
        sb: StringBuilder,
        fields: List<SchemaField>,
        sparseParameters: List<SchemaSparseParam>?,
        props: List<AstProperty>,
    ) {
        if (fields.isEmpty() && sparseParameters.isNullOrEmpty()) {
            sb.append("        let _ = buffer;\n")
        }
        for (field in fields) {
            val bits = field.bits
            if (bits != null && field.unpackBits) {
                val rawVar = "raw_${toSnakeCase(field.name)}"
                sb.append("        let $rawVar = buffer.read_i32()?;\n")
                for (b in bits) {
                    val bName = sanitizeRustIdentifier(b.name)
                    val extract = CodegenExprUtils.extractBitExpr(rawVar, b, ExprLang.RUST)
                    sb.append("        let $bName = $extract;\n")
                }
                continue
            }

            val snakeName = sanitizeRustIdentifier(field.name)
            val isLocalDerived = field.derivedFrom != null
            val isNullable =
                !isLocalDerived &&
                    field.presentIf != null &&
                    !field.type.endsWith("[]") &&
                    field.defaultValue == null

            if (field.presentIf != null) {
                val cond =
                    CodegenExprUtils.translateCondition(field.presentIf, ExprLang.RUST) {
                        sanitizeRustIdentifier(it)
                    }
                sb.append("        let $snakeName = if $cond {\n")
                if (field.type.endsWith("[]")) {
                    appendRustArrayReadLines(sb, field, toSnakeCase(field.name), "            ")
                    sb.append("            ${toSnakeCase(field.name)}_vec\n")
                } else {
                    val readExpr = mapToRustScalarReadExpr(field.type, field.maxLength)
                    if (field.strictEnum && !field.enumValues.isNullOrEmpty()) {
                        val allowed =
                            field.enumValues.values.distinct().sorted().joinToString(" | ")
                        sb.append("            let val = $readExpr;\n")
                        sb.append("            if !matches!(val, $allowed) {\n")
                        sb.append("                return Err(WireError::InvalidData);\n")
                        sb.append("            }\n")
                        sb.append(
                            if (isNullable) "            Some(val)\n" else "            val\n"
                        )
                    } else if (isNullable) {
                        sb.append("            Some($readExpr)\n")
                    } else {
                        sb.append("            $readExpr\n")
                    }
                }
                sb.append("        } else {\n")
                sb.append(
                    "            ${mapToRustFallback(field.type, isNullable, field.defaultValue)}\n"
                )
                sb.append("        };\n")
            } else if (field.type.endsWith("[]")) {
                appendRustArrayReadLines(sb, field, toSnakeCase(field.name), "        ")
                sb.append("        let $snakeName = ${toSnakeCase(field.name)}_vec;\n")
            } else {
                sb.append(
                    "        let $snakeName = ${mapToRustScalarReadExpr(field.type, field.maxLength)};\n"
                )
                if (field.strictEnum && !field.enumValues.isNullOrEmpty()) {
                    val allowed = field.enumValues.values.distinct().sorted().joinToString(" | ")
                    sb.append("        if !matches!($snakeName, $allowed) {\n")
                    sb.append("            return Err(WireError::InvalidData);\n")
                    sb.append("        }\n")
                }
            }
        }

        if (sparseParameters != null) {
            for (sp in sparseParameters) {
                val spName = sanitizeRustIdentifier(sp.name)
                val spType = mapToRustType(sp.type, true)
                sb.append("        let mut $spName: $spType = None;\n")
            }
            sb.append("        let sparse_count = (buffer.read_i16()? as u16) as usize;\n")
            sb.append("        if sparse_count > buffer.remaining() / 2 {\n")
            sb.append("            return Err(WireError::Underflow);\n")
            sb.append("        }\n")
            sb.append("        for _ in 0..sparse_count {\n")
            sb.append("            let param_id = buffer.read_u8()?;\n")
            sb.append("            match param_id {\n")
            for (sp in sparseParameters) {
                val spName = sanitizeRustIdentifier(sp.name)
                if (sp.type.endsWith("[]")) {
                    sb.append("                ${sp.id} => {\n")
                    val synField =
                        SchemaField(
                            name = sp.name,
                            type = sp.type,
                            description = sp.description,
                            enumValues = null,
                            lengthType = "ushort",
                        )
                    appendRustArrayReadLines(
                        sb,
                        synField,
                        toSnakeCase(sp.name),
                        "                    ",
                    )
                    sb.append("                    $spName = Some(${toSnakeCase(sp.name)}_vec);\n")
                    sb.append("                }\n")
                } else {
                    sb.append(
                        "                ${sp.id} => { $spName = Some(${mapToRustScalarReadExpr(sp.type)}); }\n"
                    )
                }
            }
            sb.append("                _ => return Err(WireError::InvalidData),\n")
            sb.append("            }\n")
            sb.append("        }\n")
        }

        sb.append("        Ok(Self {\n")
        for (prop in props) {
            val snakeName = sanitizeRustIdentifier(prop.name)
            sb.append("            $snakeName,\n")
        }
        sb.append("        })\n")
    }

    private fun appendRustArrayReadLines(
        sb: StringBuilder,
        field: SchemaField,
        baseSnake: String,
        indent: String,
    ) {
        if (field.countFrom != null) {
            val countIdent = sanitizeRustIdentifier(field.countFrom)
            sb.append("${indent}if $countIdent < 0 {\n")
            sb.append("${indent}    return Err(WireError::InvalidData);\n")
            sb.append("$indent}\n")
            sb.append("${indent}let ${baseSnake}_len = $countIdent as usize;\n")
        } else {
            when (field.effectiveLengthType) {
                "int" -> {
                    sb.append("${indent}let ${baseSnake}_raw_len = buffer.read_i32()?;\n")
                    sb.append("${indent}if ${baseSnake}_raw_len < 0 {\n")
                    sb.append("${indent}    return Err(WireError::InvalidData);\n")
                    sb.append("$indent}\n")
                    sb.append("${indent}let ${baseSnake}_len = ${baseSnake}_raw_len as usize;\n")
                }
                "ushort" -> {
                    sb.append(
                        "${indent}let ${baseSnake}_len = (buffer.read_i16()? as u16) as usize;\n"
                    )
                }
                else -> {
                    sb.append("${indent}let ${baseSnake}_raw_len = buffer.read_i16()?;\n")
                    sb.append("${indent}if ${baseSnake}_raw_len < 0 {\n")
                    sb.append("${indent}    return Err(WireError::InvalidData);\n")
                    sb.append("$indent}\n")
                    sb.append("${indent}let ${baseSnake}_len = ${baseSnake}_raw_len as usize;\n")
                }
            }
        }
        val elemType = field.type.removeSuffix("[]")
        val elemMinBytes = CodegenExprUtils.minWireElementBytes(elemType, schema)
        if (field.maxLength != null) {
            sb.append("${indent}if ${baseSnake}_len > ${field.maxLength} {\n")
            sb.append("${indent}    return Err(WireError::InvalidData);\n")
            sb.append("$indent}\n")
        }
        sb.append("${indent}if ${baseSnake}_len > buffer.remaining() / $elemMinBytes {\n")
        sb.append("${indent}    return Err(WireError::Underflow);\n")
        sb.append("$indent}\n")
        sb.append(
            "${indent}let mut ${baseSnake}_vec = Vec::with_capacity(${baseSnake}_len.min(4096));\n"
        )
        sb.append("${indent}for _ in 0..${baseSnake}_len {\n")
        sb.append("$indent    ${baseSnake}_vec.push(${mapToRustScalarReadExpr(elemType)});\n")
        sb.append("$indent}\n")
    }

    private fun appendRustWriteBody(
        sb: StringBuilder,
        fields: List<SchemaField>,
        sparseParameters: List<SchemaSparseParam>?,
        props: List<AstProperty>,
    ) {
        val propByName = props.associateBy { it.name }
        val localVars = mutableSetOf<String>()

        for (field in fields) {
            val bits = field.bits
            if (bits != null && field.unpackBits) {
                val terms = mutableListOf<Pair<String, SchemaBitField>>()
                for (b in bits) {
                    val bSnake = sanitizeRustIdentifier(b.name)
                    if (b.derivedFrom != null) {
                        val expr = derivedExprToRust(DerivedExpr.parse(b.derivedFrom))
                        sb.append("        let $bSnake: i32 = $expr;\n")
                        localVars.add(b.name)
                        terms.add(bSnake to b)
                    } else {
                        terms.add("self.$bSnake" to b)
                    }
                }
                val packed = CodegenExprUtils.packBitsExpr(terms, ExprLang.RUST)
                sb.append("        buffer.write_i32($packed);\n")
                continue
            }

            if (field.derivedFrom != null) {
                val derivedVal = derivedExprToRust(DerivedExpr.parse(field.derivedFrom))
                if (field.presentIf != null) {
                    val cond =
                        CodegenExprUtils.translateCondition(field.presentIf, ExprLang.RUST) {
                            if (it in localVars) sanitizeRustIdentifier(it)
                            else "self.${sanitizeRustIdentifier(it)}"
                        }
                    sb.append("        if $cond {\n")
                    sb.append(
                        "            ${mapToRustScalarWriteExpr(field.type, derivedVal, isOwnedOrValue = true)};\n"
                    )
                    sb.append("        }\n")
                } else {
                    val fSnake = sanitizeRustIdentifier(field.name)
                    sb.append("        let $fSnake: i32 = $derivedVal;\n")
                    localVars.add(field.name)
                    sb.append(
                        "        ${mapToRustScalarWriteExpr(field.type, fSnake, isOwnedOrValue = true)};\n"
                    )
                }
                continue
            }

            val snakeName = sanitizeRustIdentifier(field.name)
            val isNullable = propByName[field.name]?.isNullable == true

            if (field.presentIf != null) {
                val cond =
                    CodegenExprUtils.translateCondition(field.presentIf, ExprLang.RUST) {
                        if (it in localVars) sanitizeRustIdentifier(it)
                        else "self.${sanitizeRustIdentifier(it)}"
                    }
                if (isNullable) {
                    sb.append("        if $cond {\n")
                    sb.append("            if let Some(ref val) = self.$snakeName {\n")
                    appendRustFieldWriteLines(
                        sb,
                        field,
                        "val",
                        isRef = true,
                        indent = "                ",
                    )
                    sb.append("            }\n")
                    sb.append("        }\n")
                } else {
                    sb.append("        if $cond {\n")
                    appendRustFieldWriteLines(
                        sb,
                        field,
                        "self.$snakeName",
                        isRef = false,
                        indent = "            ",
                    )
                    sb.append("        }\n")
                }
            } else {
                appendRustFieldWriteLines(
                    sb,
                    field,
                    "self.$snakeName",
                    isRef = false,
                    indent = "        ",
                )
            }
        }

        if (sparseParameters != null) {
            sb.append("        let mut sparse_count: i16 = 0;\n")
            for (sp in sparseParameters) {
                val spName = sanitizeRustIdentifier(sp.name)
                sb.append("        if self.$spName.is_some() { sparse_count += 1; }\n")
            }
            sb.append("        buffer.write_i16(sparse_count);\n")
            for (sp in sparseParameters) {
                val spName = sanitizeRustIdentifier(sp.name)
                sb.append("        if let Some(ref val) = self.$spName {\n")
                sb.append("            buffer.write_u8(${sp.id});\n")
                val synField =
                    SchemaField(
                        name = sp.name,
                        type = sp.type,
                        description = sp.description,
                        enumValues = null,
                        lengthType = "short",
                    )
                appendRustFieldWriteLines(
                    sb,
                    synField,
                    "val",
                    isRef = true,
                    indent = "            ",
                )
                sb.append("        }\n")
            }
        }
    }

    private fun appendRustFieldWriteLines(
        sb: StringBuilder,
        field: SchemaField,
        expr: String,
        isRef: Boolean,
        indent: String,
    ) {
        if (field.type.endsWith("[]")) {
            if (field.countFrom == null) {
                when (field.effectiveLengthType) {
                    "int" -> sb.append("${indent}buffer.write_i32($expr.len() as i32);\n")
                    else -> sb.append("${indent}buffer.write_i16($expr.len() as i16);\n")
                }
            }
            val elemType = field.type.removeSuffix("[]")
            val iterExpr = if (isRef) expr else "&$expr"
            if (
                schema.structs.containsKey(elemType) || elemType == "string" || elemType == "bytes"
            ) {
                sb.append("${indent}for item in $iterExpr {\n")
                sb.append(
                    "$indent    ${mapToRustScalarWriteExpr(elemType, "item", isOwnedOrValue = false)};\n"
                )
                sb.append("$indent}\n")
            } else {
                sb.append("${indent}for &item in $iterExpr {\n")
                sb.append(
                    "$indent    ${mapToRustScalarWriteExpr(elemType, "item", isOwnedOrValue = true)};\n"
                )
                sb.append("$indent}\n")
            }
        } else {
            val valExpr =
                if (
                    isRef &&
                        field.type !in setOf("string", "bytes") &&
                        !schema.structs.containsKey(field.type)
                ) {
                    "*$expr"
                } else {
                    expr
                }
            sb.append(
                "$indent${mapToRustScalarWriteExpr(field.type, valExpr, isOwnedOrValue = !isRef)};\n"
            )
        }
    }

    private fun derivedExprToRust(expr: DerivedExpr): String {
        val target = "self.${sanitizeRustIdentifier(expr.targetName)}"
        return when (expr) {
            is DerivedExpr.LengthOf -> "$target.len() as i32"
            is DerivedExpr.PresentOf -> "if $target.is_some() { 1 } else { 0 }"
            is DerivedExpr.NonEmptyOf -> "if !$target.is_empty() { 1 } else { 0 }"
        }
    }

    fun generateOperationEnum(): String {
        val sb = StringBuilder()
        sb.append("/// Unified polymorphic sum type representing any RemoteCompose operation.\n")
        sb.append("#[derive(Debug, Clone, PartialEq)]\n")
        sb.append("pub enum Operation {\n")
        for (op in schema.operations) {
            val cfg = getRustProfileCfg(op)
            if (cfg != null) {
                sb.append("    #[cfg($cfg)]\n")
            }
            val payloadType = if (shouldBoxVariant(op)) "Box<${op.name}>" else op.name
            sb.append("    ${op.name}($payloadType),\n")
        }
        sb.append("}\n\n")

        sb.append("impl Operation {\n")
        sb.append("    pub fn op_id(&self) -> OpId {\n")
        sb.append("        match self {\n")
        for (op in schema.operations) {
            val cfg = getRustProfileCfg(op)
            if (cfg != null) {
                sb.append("            #[cfg($cfg)]\n")
            }
            sb.append("            Operation::${op.name}(_) => OpId::${op.name},\n")
        }
        sb.append("        }\n")
        sb.append("    }\n\n")

        sb.append("    pub fn op_code(&self) -> u8 {\n")
        sb.append("        self.op_id().as_u8()\n")
        sb.append("    }\n\n")

        sb.append("    pub fn op_name(&self) -> &'static str {\n")
        sb.append("        self.op_id().name()\n")
        sb.append("    }\n\n")

        sb.append(
            "    pub fn read(op_id: OpId, buffer: &mut WireBuffer) -> Result<Self, WireError> {\n"
        )
        sb.append("        match op_id {\n")
        for (op in schema.operations) {
            val cfg = getRustProfileCfg(op)
            if (cfg != null) {
                sb.append("            #[cfg($cfg)]\n")
            }
            val readExpr =
                if (shouldBoxVariant(op)) "Box::new(${op.name}::read(buffer)?)"
                else "${op.name}::read(buffer)?"
            sb.append("            OpId::${op.name} => Ok(Operation::${op.name}($readExpr)),\n")
        }
        sb.append("            #[allow(unreachable_patterns)]\n")
        sb.append("            _ => Err(WireError::UnknownOpCode(op_id.as_u8())),\n")
        sb.append("        }\n")
        sb.append("    }\n\n")

        sb.append("    #[cfg($WRITER_CFG)]\n")
        sb.append("    pub fn write(&self, buffer: &mut WireBuffer) {\n")
        sb.append("        match self {\n")
        for (op in schema.operations) {
            val cfg = getRustProfileCfg(op)
            if (cfg != null) {
                sb.append("            #[cfg($cfg)]\n")
            }
            sb.append("            Operation::${op.name}(op) => op.write(buffer),\n")
        }
        sb.append("        }\n")
        sb.append("    }\n")
        sb.append("}\n")
        return sb.toString()
    }

    fun generateRemoteDocument(): String {
        return """
        /// Top-level RemoteCompose document container in Rust.
        #[derive(Debug, Clone, PartialEq)]
        pub struct RemoteDocument {
            pub major_version: i32,
            pub minor_version: i32,
            pub patch_version: i32,
            pub width: i32,
            pub height: i32,
            pub capabilities: i64,
            pub operations: Vec<Operation>,
        }

        impl Default for RemoteDocument {
            fn default() -> Self {
                Self::new()
            }
        }

        impl RemoteDocument {
            pub const MAX_HEADER_PROPERTIES: usize = 1000;
            pub const MAX_OPERATION_COUNT: usize = 100_000;

            /// Creates a new, empty [RemoteDocument].
            pub fn new() -> Self {
                Self {
                    major_version: 1,
                    minor_version: 1,
                    patch_version: 0,
                    width: 0,
                    height: 0,
                    capabilities: 0,
                    operations: Vec::new(),
                }
            }

            /// Loads and deserializes a [RemoteDocument] from the wire buffer with default limits.
            pub fn load(buffer: &mut WireBuffer) -> Result<Self, WireError> {
                Self::load_with_limits(buffer, Self::MAX_OPERATION_COUNT)
            }

            /// Loads and deserializes a [RemoteDocument] from the wire buffer with an explicit
            /// maximum operation count.
            pub fn load_with_limits(
                buffer: &mut WireBuffer,
                max_operations: usize,
            ) -> Result<Self, WireError> {
                let mut doc = Self::new();
                if !buffer.available() {
                    return Ok(doc);
                }

                let header_op = buffer.read_u8()?;
                if header_op != OpId::Header.as_u8() {
                    return Err(WireError::InvalidHeader(header_op));
                }

                let raw_major = buffer.read_i32()?;
                doc.minor_version = buffer.read_i32()?;
                doc.patch_version = buffer.read_i32()?;
                if (raw_major as u32 & 0xFFFF0000) == 0x048C0000 {
                    doc.major_version = raw_major & 0xFFFF;
                    let num_props = buffer.read_i32()?;
                    if num_props < 0 || (num_props as usize) > Self::MAX_HEADER_PROPERTIES {
                        return Err(WireError::InvalidData);
                    }
                    if (num_props as usize) > buffer.remaining() / 4 {
                        return Err(WireError::Underflow);
                    }
                    for _ in 0..num_props {
                        let tag = buffer.read_i16()? as u16;
                        let item_len = (buffer.read_i16()? as u16) as usize;
                        let data_type = (tag >> 10) & 0x3F;
                        let key = tag & 0x3FF;
                        match data_type {
                            0 => {
                                let val = buffer.read_i32()?;
                                if key == 5 { doc.width = val; }
                                else if key == 6 { doc.height = val; }
                                else if key == 14 { doc.capabilities = (val as u32) as i64; }
                                else if key == 31 && val != 0 {
                                    return Err(WireError::UnsupportedCompression);
                                }
                            }
                            1 => { let _ = buffer.read_f32()?; }
                            2 => {
                                let val = buffer.read_i64()?;
                                if key == 14 { doc.capabilities = val; }
                                else if key == 31 && val != 0 {
                                    return Err(WireError::UnsupportedCompression);
                                }
                            }
                            3 => { buffer.skip_utf8()?; }
                            _ => { buffer.skip_bytes(item_len)?; }
                        }
                    }
                } else if (0..0x10000).contains(&raw_major) {
                    doc.major_version = raw_major;
                    doc.width = buffer.read_i32()?;
                    doc.height = buffer.read_i32()?;
                    doc.capabilities = buffer.read_i64()?;
                } else {
                    return Err(WireError::InvalidHeaderMagic(raw_major));
                }

                while buffer.available() {
                    let op_byte = buffer.read_u8()?;
                    if op_byte == OpId::Header.as_u8() {
                        return Err(WireError::InvalidHeader(op_byte));
                    }
                    if doc.operations.len() >= max_operations {
                        return Err(WireError::LimitExceeded);
                    }
                    let op_id = OpId::from_u8(op_byte).ok_or(WireError::UnknownOpCode(op_byte))?;
                    let op = Operation::read(op_id, buffer)?;
                    doc.operations.push(op);
                }
                Ok(doc)
            }

            #[cfg($WRITER_CFG)]
            /// Serializes this document into the wire buffer.
            pub fn save(&self, buffer: &mut WireBuffer) {
                buffer.write_u8(OpId::Header.as_u8());
                buffer.write_i32(self.major_version);
                buffer.write_i32(self.minor_version);
                buffer.write_i32(self.patch_version);
                buffer.write_i32(self.width);
                buffer.write_i32(self.height);
                buffer.write_i64(self.capabilities);

                for op in &self.operations {
                    op.write(buffer);
                }
            }
        }
        """
            .trimIndent()
    }

    fun generateWireBuffer(): String {
        return """
        #[derive(Debug, PartialEq, Eq)]
        pub enum WireError {
            Underflow,
            InvalidHeader(u8),
            InvalidHeaderMagic(i32),
            UnsupportedCompression,
            UnknownOpCode(u8),
            InvalidUtf8,
            InvalidData,
            LimitExceeded,
        }

        impl std::fmt::Display for WireError {
            fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
                match self {
                    WireError::Underflow => write!(f, "WireBuffer underflow"),
                    WireError::InvalidHeader(b) => write!(f, "Invalid header opcode: {}", b),
                    WireError::InvalidHeaderMagic(m) => write!(f, "Invalid header magic: {:#x}", m),
                    WireError::UnsupportedCompression => {
                        write!(f, "Compressed RemoteCompose documents are not supported")
                    }
                    WireError::UnknownOpCode(b) => write!(f, "Unknown opcode: {}", b),
                    WireError::InvalidUtf8 => write!(f, "Invalid UTF-8 sequence"),
                    WireError::InvalidData => write!(f, "Invalid data or negative length"),
                    WireError::LimitExceeded => write!(f, "Document exceeds maximum allowed limit"),
                }
            }
        }

        impl std::error::Error for WireError {}

        #[derive(Debug, Clone, Default)]
        pub struct WireBuffer {
            data: Vec<u8>,
            index: usize,
        }

        impl WireBuffer {
            pub fn new() -> Self {
                Self { data: Vec::new(), index: 0 }
            }

            pub fn from_bytes(bytes: &[u8]) -> Self {
                Self { data: bytes.to_vec(), index: 0 }
            }

            pub fn as_bytes(&self) -> &[u8] {
                &self.data
            }

            pub fn to_bytes(&self) -> Vec<u8> {
                self.data.clone()
            }

            pub fn available(&self) -> bool {
                self.index < self.data.len()
            }

            pub fn remaining(&self) -> usize {
                self.data.len().saturating_sub(self.index)
            }

            pub fn reset(&mut self) {
                self.index = 0;
            }

            pub fn start(&mut self, op_code: u8) {
                self.write_u8(op_code);
            }

            pub fn write_u8(&mut self, val: u8) {
                self.data.push(val);
            }

            pub fn read_u8(&mut self) -> Result<u8, WireError> {
                if self.index < self.data.len() {
                    let b = self.data[self.index];
                    self.index += 1;
                    Ok(b)
                } else {
                    Err(WireError::Underflow)
                }
            }

            pub fn write_i16(&mut self, val: i16) {
                self.data.extend_from_slice(&val.to_be_bytes());
            }

            pub fn read_i16(&mut self) -> Result<i16, WireError> {
                if self.index + 2 <= self.data.len() {
                    let bytes = [self.data[self.index], self.data[self.index + 1]];
                    self.index += 2;
                    Ok(i16::from_be_bytes(bytes))
                } else {
                    Err(WireError::Underflow)
                }
            }

            pub fn write_i32(&mut self, val: i32) {
                self.data.extend_from_slice(&val.to_be_bytes());
            }

            pub fn read_i32(&mut self) -> Result<i32, WireError> {
                if self.index + 4 <= self.data.len() {
                    let mut bytes = [0u8; 4];
                    bytes.copy_from_slice(&self.data[self.index..self.index + 4]);
                    self.index += 4;
                    Ok(i32::from_be_bytes(bytes))
                } else {
                    Err(WireError::Underflow)
                }
            }

            pub fn write_u32(&mut self, val: u32) {
                self.data.extend_from_slice(&val.to_be_bytes());
            }

            pub fn read_u32(&mut self) -> Result<u32, WireError> {
                if self.index + 4 <= self.data.len() {
                    let mut bytes = [0u8; 4];
                    bytes.copy_from_slice(&self.data[self.index..self.index + 4]);
                    self.index += 4;
                    Ok(u32::from_be_bytes(bytes))
                } else {
                    Err(WireError::Underflow)
                }
            }

            pub fn write_i64(&mut self, val: i64) {
                self.data.extend_from_slice(&val.to_be_bytes());
            }

            pub fn read_i64(&mut self) -> Result<i64, WireError> {
                if self.index + 8 <= self.data.len() {
                    let mut bytes = [0u8; 8];
                    bytes.copy_from_slice(&self.data[self.index..self.index + 8]);
                    self.index += 8;
                    Ok(i64::from_be_bytes(bytes))
                } else {
                    Err(WireError::Underflow)
                }
            }

            pub fn write_f32(&mut self, val: f32) {
                self.data.extend_from_slice(&val.to_bits().to_be_bytes());
            }

            pub fn read_f32(&mut self) -> Result<f32, WireError> {
                let bits = self.read_u32()?;
                Ok(f32::from_bits(bits))
            }

            pub fn write_bool(&mut self, val: bool) {
                self.write_u8(if val { 1 } else { 0 });
            }

            pub fn read_bool(&mut self) -> Result<bool, WireError> {
                Ok(self.read_u8()? != 0)
            }

            pub fn skip_bytes(&mut self, len: usize) -> Result<(), WireError> {
                if len <= self.remaining() {
                    self.index += len;
                    Ok(())
                } else {
                    Err(WireError::Underflow)
                }
            }

            pub fn skip_utf8(&mut self) -> Result<(), WireError> {
                let len = self.read_i32()?;
                if len < 0 {
                    return Err(WireError::InvalidData);
                }
                let len = len as usize;
                if len <= self.remaining() {
                    let slice = &self.data[self.index..self.index + len];
                    std::str::from_utf8(slice).map_err(|_| WireError::InvalidUtf8)?;
                    self.index += len;
                    Ok(())
                } else {
                    Err(WireError::Underflow)
                }
            }

            pub fn write_utf8(&mut self, val: &str) {
                let bytes = val.as_bytes();
                self.write_i32(bytes.len() as i32);
                self.data.extend_from_slice(bytes);
            }

            pub fn read_utf8(&mut self) -> Result<String, WireError> {
                self.read_utf8_limited(usize::MAX)
            }

            pub fn read_utf8_limited(&mut self, max_len: usize) -> Result<String, WireError> {
                let len = self.read_i32()?;
                if len < 0 {
                    return Err(WireError::InvalidData);
                }
                let len = len as usize;
                if len > max_len {
                    return Err(WireError::InvalidData);
                }
                if len <= self.remaining() {
                    let slice = &self.data[self.index..self.index + len];
                    let s = std::str::from_utf8(slice).map_err(|_| WireError::InvalidUtf8)?;
                    let owned = s.to_owned();
                    self.index += len;
                    Ok(owned)
                } else {
                    Err(WireError::Underflow)
                }
            }

            pub fn write_buffer(&mut self, val: &[u8]) {
                self.write_i32(val.len() as i32);
                self.data.extend_from_slice(val);
            }

            pub fn read_buffer(&mut self) -> Result<Vec<u8>, WireError> {
                self.read_buffer_limited(usize::MAX)
            }

            pub fn read_buffer_limited(&mut self, max_len: usize) -> Result<Vec<u8>, WireError> {
                let len = self.read_i32()?;
                if len < 0 {
                    return Err(WireError::InvalidData);
                }
                let len = len as usize;
                if len > max_len {
                    return Err(WireError::InvalidData);
                }
                if len <= self.remaining() {
                    let slice = &self.data[self.index..self.index + len];
                    self.index += len;
                    Ok(slice.to_vec())
                } else {
                    Err(WireError::Underflow)
                }
            }

            pub fn write_nan_id(&mut self, val: f32) {
                self.write_f32(val);
            }

            pub fn read_nan_id(&mut self) -> Result<f32, WireError> {
                self.read_f32()
            }
        }
        """
            .trimIndent()
    }

    private fun mapToRustType(type: String, isNullable: Boolean = false): String {
        val base =
            when (type) {
                "int" -> "i32"
                "short" -> "i16"
                "byte" -> "u8"
                "long" -> "i64"
                "float",
                "float_or_id" -> "f32"
                "boolean" -> "bool"
                "string" -> "String"
                "color" -> "u32"
                "bytes" -> "Vec<u8>"
                "int[]" -> "Vec<i32>"
                "short[]" -> "Vec<i16>"
                "float[]",
                "float_or_id[]" -> "Vec<f32>"
                else ->
                    if (type.endsWith("[]")) {
                        "Vec<${type.removeSuffix("[]")}>"
                    } else {
                        type
                    }
            }
        return if (isNullable) "Option<$base>" else base
    }

    private fun mapToRustFallback(
        type: String,
        isNullable: Boolean,
        defaultValue: String?,
    ): String {
        if (isNullable) return "None"
        if (type.endsWith("[]") || type == "bytes") return "Vec::new()"
        if (defaultValue != null) {
            val dv = defaultValue.trim()
            return when (type) {
                "float",
                "float_or_id" -> {
                    val clean = dv.trimEnd('f', 'F')
                    if ('.' in clean) clean else "$clean.0"
                }
                "string" -> "\"$dv\".to_string()"
                else -> dv
            }
        }
        return when (type) {
            "float",
            "float_or_id" -> "0.0"
            "boolean" -> "false"
            "string" -> "String::new()"
            else -> "0"
        }
    }

    private fun mapToRustScalarReadExpr(type: String, maxLength: Int? = null): String =
        when (type) {
            "int" -> "buffer.read_i32()?"
            "short" -> "buffer.read_i16()?"
            "byte" -> "buffer.read_u8()?"
            "long" -> "buffer.read_i64()?"
            "float" -> "buffer.read_f32()?"
            "boolean" -> "buffer.read_bool()?"
            "string" ->
                if (maxLength != null) "buffer.read_utf8_limited($maxLength)?"
                else "buffer.read_utf8()?"
            "float_or_id" -> "buffer.read_nan_id()?"
            "color" -> "buffer.read_u32()?"
            "bytes" ->
                if (maxLength != null) "buffer.read_buffer_limited($maxLength)?"
                else "buffer.read_buffer()?"
            else -> "$type::read(buffer)?"
        }

    private fun mapToRustScalarWriteExpr(
        type: String,
        varName: String,
        isOwnedOrValue: Boolean,
    ): String =
        when (type) {
            "int" -> "buffer.write_i32($varName)"
            "short" -> "buffer.write_i16($varName)"
            "byte" -> "buffer.write_u8($varName)"
            "long" -> "buffer.write_i64($varName)"
            "float" -> "buffer.write_f32($varName)"
            "boolean" -> "buffer.write_bool($varName)"
            "string" ->
                if (isOwnedOrValue) "buffer.write_utf8(&$varName)"
                else "buffer.write_utf8($varName)"
            "float_or_id" -> "buffer.write_nan_id($varName)"
            "color" -> "buffer.write_u32($varName)"
            "bytes" ->
                if (isOwnedOrValue) "buffer.write_buffer(&$varName)"
                else "buffer.write_buffer($varName)"
            else -> "$varName.write(buffer)"
        }

