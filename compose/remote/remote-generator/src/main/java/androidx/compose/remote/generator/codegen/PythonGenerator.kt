package androidx.compose.remote.generator.codegen

import androidx.compose.remote.generator.AstProperty
import androidx.compose.remote.generator.DerivedExpr
import androidx.compose.remote.generator.OperationSchema
import androidx.compose.remote.generator.SchemaBitField
import androidx.compose.remote.generator.SchemaField
import androidx.compose.remote.generator.SchemaOperation
import androidx.compose.remote.generator.SchemaSparseParam
import androidx.compose.remote.generator.SchemaStruct

/**
 * Generator that transforms an [OperationSchema] into Python bindings:
 * - OpCode IntEnum
 * - Auxiliary structs, Operation base class, and typed dataclasses with WireBuffer serialization
 * - WireBuffer implementation with big-endian struct packing
 * - RemoteDocument container with load/save
 * - OPERATION_REGISTRY and create_operation factory
 */
internal class PythonGenerator(private val schema: OperationSchema) {

    fun generate(): String {
        val sb = StringBuilder()
        sb.append(
            """
            # Generated by RemoteCompose Schema Codegen. DO NOT EDIT.
            from __future__ import annotations

            from dataclasses import dataclass, field
            import enum
            import struct
            from typing import ClassVar, Dict, List, Optional, Type


            class OpCode(enum.IntEnum):
                $TQ Operation wire identifiers for RemoteCompose.$TQ
            """
                .trimIndent()
        )
        sb.append("\n")

        for (op in schema.operations) {
            val desc = op.description.replace("\n", " ").trim()
            if (desc.isNotEmpty()) {
                sb.append("    # $desc\n")
            }
            sb.append("    ${op.name} = ${op.id}\n")
        }

        sb.append(
            """


            class Operation:
                $TQ Base class for all RemoteCompose operations.$TQ
                op_code: ClassVar[OpCode]

                def write(self, buffer: WireBuffer) -> None:
                    raise NotImplementedError

                def read_fields(self, buffer: WireBuffer) -> None:
                    raise NotImplementedError


            class WireBuffer:
                $TQ Big-endian binary buffer for reading and writing RemoteCompose wire format.$TQ

                def __init__(self, data: Optional[bytes] = None):
                    if data is not None:
                        self._buffer = bytearray(data)
                        self._index = 0
                        self._size = len(data)
                    else:
                        self._buffer = bytearray(1024)
                        self._index = 0
                        self._size = 0

                @classmethod
                def from_bytes(cls, data: bytes) -> WireBuffer:
                    return cls(data)

                def get_bytes(self) -> bytes:
                    return bytes(self._buffer[:self._size])

                def available(self) -> bool:
                    return self._index < self._size

                def remaining(self) -> int:
                    return max(0, self._size - self._index)

                def skip_bytes(self, length: int) -> None:
                    if length < 0:
                        raise ValueError(f"Negative skip length in WireBuffer: {length}")
                    if length > self.remaining():
                        raise EOFError("WireBuffer underflow skipping bytes")
                    self._index += length

                @property
                def position(self) -> int:
                    return self._index

                @position.setter
                def position(self, pos: int) -> None:
                    if pos < 0 or pos > self._size:
                        raise ValueError(f"WireBuffer position out of bounds: {pos} (size={self._size})")
                    self._index = pos

                @property
                def size(self) -> int:
                    return self._size

                def _ensure_capacity(self, needed: int) -> None:
                    required = self._index + needed
                    if required > len(self._buffer):
                        new_capacity = max(len(self._buffer) * 2, required)
                        self._buffer.extend(b"\x00" * (new_capacity - len(self._buffer)))

                def write_byte(self, val: int) -> None:
                    self._ensure_capacity(1)
                    struct.pack_into(">B", self._buffer, self._index, val & 0xFF)
                    self._index += 1
                    if self._index > self._size:
                        self._size = self._index

                def read_byte(self) -> int:
                    if 1 > self.remaining():
                        raise EOFError("WireBuffer underflow reading byte")
                    val = struct.unpack_from(">B", self._buffer, self._index)[0]
                    self._index += 1
                    return val

                def write_short(self, val: int) -> None:
                    self._ensure_capacity(2)
                    v = val & 0xFFFF
                    if v >= 0x8000:
                        v -= 0x10000
                    struct.pack_into(">h", self._buffer, self._index, v)
                    self._index += 2
                    if self._index > self._size:
                        self._size = self._index

                def read_short(self) -> int:
                    if 2 > self.remaining():
                        raise EOFError("WireBuffer underflow reading short")
                    val = struct.unpack_from(">h", self._buffer, self._index)[0]
                    self._index += 2
                    return val

                def write_int(self, val: int) -> None:
                    self._ensure_capacity(4)
                    v = val & 0xFFFFFFFF
                    if v >= 0x80000000:
                        v -= 0x100000000
                    struct.pack_into(">i", self._buffer, self._index, v)
                    self._index += 4
                    if self._index > self._size:
                        self._size = self._index

                def read_int(self) -> int:
                    if 4 > self.remaining():
                        raise EOFError("WireBuffer underflow reading int")
                    val = struct.unpack_from(">i", self._buffer, self._index)[0]
                    self._index += 4
                    return val

                def write_long(self, val: int) -> None:
                    self._ensure_capacity(8)
                    struct.pack_into(">q", self._buffer, self._index, val)
                    self._index += 8
                    if self._index > self._size:
                        self._size = self._index

                def read_long(self) -> int:
                    if 8 > self.remaining():
                        raise EOFError("WireBuffer underflow reading long")
                    val = struct.unpack_from(">q", self._buffer, self._index)[0]
                    self._index += 8
                    return val

                def write_float(self, val: float) -> None:
                    self._ensure_capacity(4)
                    struct.pack_into(">f", self._buffer, self._index, val)
                    self._index += 4
                    if self._index > self._size:
                        self._size = self._index

                def read_float(self) -> float:
                    if 4 > self.remaining():
                        raise EOFError("WireBuffer underflow reading float")
                    val = struct.unpack_from(">f", self._buffer, self._index)[0]
                    self._index += 4
                    return val

                def write_nan_id(self, val: float) -> None:
                    self.write_float(val)

                def read_nan_id(self) -> float:
                    return self.read_float()

                def write_boolean(self, val: bool) -> None:
                    self.write_byte(1 if val else 0)

                def read_boolean(self) -> bool:
                    return self.read_byte() != 0

                def write_utf8(self, val: str) -> None:
                    encoded = val.encode("utf-8")
                    self.write_int(len(encoded))
                    self._ensure_capacity(len(encoded))
                    self._buffer[self._index : self._index + len(encoded)] = encoded
                    self._index += len(encoded)
                    if self._index > self._size:
                        self._size = self._index

                def read_utf8(self, max_length: Optional[int] = None) -> str:
                    length = self.read_int()
                    if length < 0:
                        raise ValueError(f"Negative string length in WireBuffer: {length}")
                    if max_length is not None and length > max_length:
                        raise ValueError(f"String length {length} exceeds maximum ({max_length})")
                    if length > self.remaining():
                        raise EOFError("WireBuffer underflow reading utf8 string")
                    raw = self._buffer[self._index : self._index + length]
                    decoded = raw.decode("utf-8")
                    self._index += length
                    return decoded

                def write_buffer(self, val: bytes) -> None:
                    self.write_int(len(val))
                    self._ensure_capacity(len(val))
                    self._buffer[self._index : self._index + len(val)] = val
                    self._index += len(val)
                    if self._index > self._size:
                        self._size = self._index

                def read_buffer(self, max_length: Optional[int] = None) -> bytes:
                    length = self.read_int()
                    if length < 0:
                        raise ValueError(f"Negative buffer length in WireBuffer: {length}")
                    if max_length is not None and length > max_length:
                        raise ValueError(f"Buffer length {length} exceeds maximum ({max_length})")
                    if length > self.remaining():
                        raise EOFError("WireBuffer underflow reading buffer")
                    raw = bytes(self._buffer[self._index : self._index + length])
                    self._index += length
                    return raw
            """
                .trimIndent()
        )
        sb.append("\n\n")

        for ((_, structDef) in schema.structs) {
            sb.append(generateAuxStruct(structDef))
            sb.append("\n\n")
        }

        for (op in schema.operations) {
            sb.append(generateClass(op))
            sb.append("\n\n")
        }

        sb.append("OPERATION_REGISTRY: Dict[OpCode, Type[Operation]] = {\n")
        for (op in schema.operations) {
            sb.append("    OpCode.${op.name}: ${op.name},\n")
        }
        sb.append("}\n\n")

        sb.append(
            """
            def create_operation(op_code: OpCode) -> Optional[Operation]:
                cls = OPERATION_REGISTRY.get(op_code)
                return cls() if cls is not None else None


            @dataclass
            class RemoteDocument:
                $TQ In-memory representation of a RemoteCompose document.$TQ
                MAX_HEADER_PROPERTIES: ClassVar[int] = 1000
                MAX_OPERATION_COUNT: ClassVar[int] = 100_000
                major_version: int = 1
                minor_version: int = 1
                patch_version: int = 0
                width: int = 0
                height: int = 0
                capabilities: int = 0
                operations: List[Operation] = field(default_factory=list)

                @classmethod
                def load(cls, data: bytes, max_operations: int = MAX_OPERATION_COUNT) -> RemoteDocument:
                    buffer = WireBuffer.from_bytes(data)
                    doc = cls()
                    if not buffer.available():
                        return doc

                    header_op = buffer.read_byte()
                    if header_op != OpCode.Header.value:
                        raise ValueError(f"Expected Header opcode 0, got {header_op}")

                    raw_major = buffer.read_int()
                    doc.minor_version = buffer.read_int()
                    doc.patch_version = buffer.read_int()

                    if (raw_major & 0xFFFF0000) == 0x048C0000:
                        doc.major_version = raw_major & 0xFFFF
                        num_props = buffer.read_int()
                        if num_props < 0 or num_props > cls.MAX_HEADER_PROPERTIES:
                            raise ValueError(f"Invalid header property count: {num_props}")
                        if num_props > buffer.remaining() // 4:
                            raise EOFError(
                                f"Header property count {num_props} exceeds remaining buffer ({buffer.remaining()})"
                            )
                        for _ in range(num_props):
                            tag = buffer.read_short() & 0xFFFF
                            item_len = buffer.read_short() & 0xFFFF
                            data_type = (tag >> 10) & 0x3F
                            key = tag & 0x3FF
                            if data_type == 0:
                                val = buffer.read_int()
                                if key == 5:
                                    doc.width = val
                                elif key == 6:
                                    doc.height = val
                                elif key == 14:
                                    doc.capabilities = val & 0xFFFFFFFF
                                elif key == 31 and val != 0:
                                    raise ValueError("Compressed RemoteCompose documents are not supported")
                            elif data_type == 1:
                                buffer.read_float()
                            elif data_type == 2:
                                val = buffer.read_long()
                                if key == 14:
                                    doc.capabilities = val
                                elif key == 31 and val != 0:
                                    raise ValueError("Compressed RemoteCompose documents are not supported")
                            elif data_type == 3:
                                buffer.read_utf8()
                            else:
                                buffer.skip_bytes(item_len)
                    elif 0 <= raw_major < 0x10000:
                        doc.major_version = raw_major
                        doc.width = buffer.read_int()
                        doc.height = buffer.read_int()
                        doc.capabilities = buffer.read_long()
                    else:
                        raise ValueError(f"Invalid header magic number: {raw_major:#x}")

                    while buffer.available():
                        if len(doc.operations) >= max_operations:
                            raise ValueError(f"Operation count exceeds limit {max_operations}")
                        op_byte = buffer.read_byte()
                        try:
                            op_code = OpCode(op_byte)
                        except ValueError:
                            raise ValueError(f"Unknown opcode in RemoteDocument: {op_byte}") from None
                        if op_code == OpCode.Header:
                            raise ValueError("Unexpected Header opcode inside document body")
                        op = create_operation(op_code)
                        if op is None:
                            raise ValueError(f"Unsupported opcode in RemoteDocument: {op_byte}")
                        op.read_fields(buffer)
                        doc.operations.append(op)

                    return doc

                def save(self) -> bytes:
                    buffer = WireBuffer()
                    buffer.write_byte(OpCode.Header.value)
                    buffer.write_int(self.major_version)
                    buffer.write_int(self.minor_version)
                    buffer.write_int(self.patch_version)
                    buffer.write_int(self.width)
                    buffer.write_int(self.height)
                    buffer.write_long(self.capabilities)

                    for op in self.operations:
                        op.write(buffer)

                    return buffer.get_bytes()
            """
                .trimIndent()
        )
        sb.append("\n")
        return sb.toString()
    }

    private fun generateAuxStruct(structDef: SchemaStruct): String {
        val sb = StringBuilder()
        val props = structDef.astProperties
        sb.append("@dataclass\n")
        sb.append("class ${structDef.name}:\n")
        val desc = structDef.description.replace("\n", " ").trim()
        if (desc.isNotEmpty()) {
            sb.append("    \"\"\"$desc\"\"\"\n")
        }
        if (props.isEmpty()) {
            sb.append("    pass\n")
        } else {
            for (p in props) {
                val pName = sanitizePythonIdentifier(p.name)
                val pyType = mapToPyType(p.type, p.isNullable)
                val defaultVal = mapToPyDefault(p.type, p.isNullable, p.defaultValue)
                sb.append("    $pName: $pyType = $defaultVal\n")
            }
        }
        sb.append("\n")
        sb.append("    def read_fields(self, buffer: WireBuffer) -> None:\n")
        appendPyReadBody(sb, structDef.fields, null)
        sb.append("\n")
        sb.append("    @classmethod\n")
        sb.append("    def read(cls, buffer: WireBuffer) -> ${structDef.name}:\n")
        sb.append("        inst = cls()\n")
        sb.append("        inst.read_fields(buffer)\n")
        sb.append("        return inst\n\n")
        sb.append("    def write(self, buffer: WireBuffer) -> None:\n")
        appendPyWriteBody(sb, structDef.fields, null, props, writeOpcode = false)
        return sb.toString()
    }

    private fun generateClass(op: SchemaOperation): String {
        val sb = StringBuilder()
        val props = op.astProperties
        sb.append("@dataclass\n")
        sb.append("class ${op.name}(Operation):\n")
        val desc = op.description.replace("\n", " ").trim()
        if (desc.isNotEmpty()) {
            sb.append("    \"\"\"$desc\"\"\"\n")
        }
        sb.append("    op_code: ClassVar[OpCode] = OpCode.${op.name}\n")
        for (p in props) {
            val fieldName = sanitizePythonIdentifier(p.name)
            val pyType = mapToPyType(p.type, p.isNullable)
            val defaultVal = mapToPyDefault(p.type, p.isNullable, p.defaultValue)
            sb.append("    $fieldName: $pyType = $defaultVal\n")
        }
        sb.append("\n")

        sb.append("    def read_fields(self, buffer: WireBuffer) -> None:\n")
        appendPyReadBody(sb, op.fields, op.sparseParameters)
        sb.append("\n")

        sb.append("    def write(self, buffer: WireBuffer) -> None:\n")
        appendPyWriteBody(sb, op.fields, op.sparseParameters, props, writeOpcode = true)
        return sb.toString()
    }

    private fun appendPyReadBody(
        sb: StringBuilder,
        fields: List<SchemaField>,
        sparseParameters: List<SchemaSparseParam>?,
    ) {
        if (fields.isEmpty() && sparseParameters.isNullOrEmpty()) {
            sb.append("        pass\n")
            return
        }
        val localVars = mutableSetOf<String>()

        for (f in fields) {
            val bits = f.bits
            if (bits != null && f.unpackBits) {
                val rawVar = "_raw_${sanitizePythonIdentifier(f.name)}"
                sb.append("        $rawVar = buffer.read_int()\n")
                for (b in bits) {
                    val bSnake = sanitizePythonIdentifier(b.name)
                    val extract = CodegenExprUtils.extractBitExpr(rawVar, b, ExprLang.PYTHON)
                    if (b.derivedFrom != null) {
                        sb.append("        $bSnake = $extract\n")
                        localVars.add(b.name)
                    } else {
                        sb.append("        self.$bSnake = $extract\n")
                    }
                }
                continue
            }

            val fSnake = sanitizePythonIdentifier(f.name)
            val isLocalDerived = f.derivedFrom != null
            val isNullable =
                !isLocalDerived &&
                    f.presentIf != null &&
                    !f.type.endsWith("[]") &&
                    f.defaultValue == null

            if (f.presentIf != null) {
                val cond =
                    CodegenExprUtils.translateCondition(f.presentIf, ExprLang.PYTHON) {
                        if (it in localVars) sanitizePythonIdentifier(it)
                        else "self.${sanitizePythonIdentifier(it)}"
                    }
                sb.append("        if $cond:\n")
                if (isLocalDerived) {
                    localVars.add(f.name)
                    sb.append("            $fSnake = ${mapToPyScalarReadExpr(f.type)}\n")
                } else {
                    appendPyFieldReadAssign(sb, f, "self.$fSnake", "            ", localVars)
                }
                sb.append("        else:\n")
                if (isLocalDerived) {
                    sb.append("            $fSnake = 0\n")
                } else if (f.type.endsWith("[]")) {
                    sb.append("            self.$fSnake = []\n")
                } else {
                    sb.append(
                        "            self.$fSnake = ${mapToPyFallbackLiteral(f.type, isNullable, f.defaultValue)}\n"
                    )
                }
            } else if (isLocalDerived) {
                localVars.add(f.name)
                sb.append("        $fSnake = ${mapToPyScalarReadExpr(f.type)}\n")
            } else {
                appendPyFieldReadAssign(sb, f, "self.$fSnake", "        ", localVars)
            }
        }

        if (sparseParameters != null) {
            for (sp in sparseParameters) {
                sb.append("        self.${sanitizePythonIdentifier(sp.name)} = None\n")
            }
            sb.append("        _sparse_count = buffer.read_short() & 0xFFFF\n")
            sb.append("        if _sparse_count > buffer.remaining() // 2:\n")
            sb.append(
                "            raise EOFError(f\"Sparse parameter count {_sparse_count} exceeds remaining buffer ({buffer.remaining()})\")\n"
            )
            sb.append("        for _ in range(_sparse_count):\n")
            sb.append("            _param_id = buffer.read_byte()\n")
            for ((idx, sp) in sparseParameters.withIndex()) {
                val kw = if (idx == 0) "if" else "elif"
                val spSnake = sanitizePythonIdentifier(sp.name)
                sb.append("            $kw _param_id == ${sp.id}:\n")
                val synField =
                    SchemaField(
                        name = sp.name,
                        type = sp.type,
                        description = sp.description,
                        enumValues = null,
                        lengthType = "ushort",
                    )
                appendPyFieldReadAssign(
                    sb,
                    synField,
                    "self.$spSnake",
                    "                ",
                    localVars,
                )
            }
            sb.append("            else:\n")
            sb.append(
                "                raise ValueError(f\"Unknown sparse parameter ID: {_param_id}\")\n"
            )
        }
    }

    private fun appendPyFieldReadAssign(
        sb: StringBuilder,
        f: SchemaField,
        targetExpr: String,
        indent: String,
        localVars: Set<String>,
    ) {
        val baseSnake = sanitizePythonIdentifier(f.name)
        if (f.type.endsWith("[]")) {
            val lenExpr =
                if (f.countFrom != null) {
                    if (f.countFrom in localVars) sanitizePythonIdentifier(f.countFrom)
                    else "self.${sanitizePythonIdentifier(f.countFrom)}"
                } else {
                    when (f.effectiveLengthType) {
                        "int" -> "buffer.read_int()"
                        "ushort" -> "(buffer.read_short() & 0xFFFF)"
                        else -> "buffer.read_short()"
                    }
                }
            val elemType = f.type.removeSuffix("[]")
            val elemMinBytes = CodegenExprUtils.minWireElementBytes(elemType, schema)
            val countVar = "_${baseSnake}_count"
            sb.append("$indent$countVar = $lenExpr\n")
            sb.append("${indent}if $countVar < 0:\n")
            sb.append(
                "${indent}    raise ValueError(f\"Invalid negative array length for $baseSnake: {$countVar}\")\n"
            )
            if (f.maxLength != null) {
                sb.append("${indent}if $countVar > ${f.maxLength}:\n")
                sb.append(
                    "${indent}    raise ValueError(f\"Array length {$countVar} for $baseSnake exceeds maximum (${f.maxLength})\")\n"
                )
            }
            sb.append("${indent}if $countVar > buffer.remaining() // $elemMinBytes:\n")
            sb.append(
                "${indent}    raise EOFError(f\"Array length {$countVar} for $baseSnake exceeds remaining buffer ({buffer.remaining()})\")\n"
            )
            sb.append(
                "$indent$targetExpr = [${mapToPyScalarReadExpr(elemType)} for _ in range($countVar)]\n"
            )
        } else {
            sb.append("$indent$targetExpr = ${mapToPyScalarReadExpr(f.type, f.maxLength)}\n")
            if (f.strictEnum && !f.enumValues.isNullOrEmpty()) {
                val allowed = f.enumValues.values.distinct().sorted().joinToString(", ")
                val tupleExpr =
                    if (f.enumValues.values.distinct().size == 1) "($allowed,)" else "($allowed)"
                sb.append("${indent}if $targetExpr not in $tupleExpr:\n")
                sb.append(
                    "${indent}    raise ValueError(f\"Invalid enum value for $baseSnake: {$targetExpr}\")\n"
                )
            }
        }
    }

    private fun appendPyWriteBody(
        sb: StringBuilder,
        fields: List<SchemaField>,
        sparseParameters: List<SchemaSparseParam>?,
        props: List<AstProperty>,
        writeOpcode: Boolean,
    ) {
        if (writeOpcode) {
            sb.append("        buffer.write_byte(self.op_code.value)\n")
        } else if (fields.isEmpty() && sparseParameters.isNullOrEmpty()) {
            sb.append("        pass\n")
            return
        }

        val propByName = props.associateBy { it.name }
        val localVars = mutableSetOf<String>()

        for (f in fields) {
            val bits = f.bits
            if (bits != null && f.unpackBits) {
                val terms = mutableListOf<Pair<String, SchemaBitField>>()
                for (b in bits) {
                    val bSnake = sanitizePythonIdentifier(b.name)
                    if (b.derivedFrom != null) {
                        val expr = derivedExprToPy(DerivedExpr.parse(b.derivedFrom))
                        sb.append("        $bSnake = $expr\n")
                        localVars.add(b.name)
                        terms.add(bSnake to b)
                    } else {
                        terms.add("self.$bSnake" to b)
                    }
                }
                val packed = CodegenExprUtils.packBitsExpr(terms, ExprLang.PYTHON)
                sb.append("        buffer.write_int($packed)\n")
                continue
            }

            if (f.derivedFrom != null) {
                val derivedVal = derivedExprToPy(DerivedExpr.parse(f.derivedFrom))
                if (f.presentIf != null) {
                    val cond =
                        CodegenExprUtils.translateCondition(f.presentIf, ExprLang.PYTHON) {
                            if (it in localVars) sanitizePythonIdentifier(it)
                            else "self.${sanitizePythonIdentifier(it)}"
                        }
                    sb.append("        if $cond:\n")
                    sb.append("            ${mapToPyScalarWriteStmt(f.type, derivedVal)}\n")
                } else {
                    val fSnake = sanitizePythonIdentifier(f.name)
                    sb.append("        $fSnake = $derivedVal\n")
                    localVars.add(f.name)
                    sb.append("        ${mapToPyScalarWriteStmt(f.type, fSnake)}\n")
                }
                continue
            }

            val fSnake = sanitizePythonIdentifier(f.name)
            val isNullable = propByName[f.name]?.isNullable == true

            if (f.presentIf != null) {
                val cond =
                    CodegenExprUtils.translateCondition(f.presentIf, ExprLang.PYTHON) {
                        if (it in localVars) sanitizePythonIdentifier(it)
                        else "self.${sanitizePythonIdentifier(it)}"
                    }
                if (isNullable) {
                    sb.append("        if ($cond) and self.$fSnake is not None:\n")
                } else {
                    sb.append("        if $cond:\n")
                }
                appendPyFieldWriteLines(sb, f, "self.$fSnake", "            ")
            } else {
                appendPyFieldWriteLines(sb, f, "self.$fSnake", "        ")
            }
        }

        if (sparseParameters != null) {
            sb.append("        _sparse_count = 0\n")
            for (sp in sparseParameters) {
                val spSnake = sanitizePythonIdentifier(sp.name)
                sb.append("        if self.$spSnake is not None:\n")
                sb.append("            _sparse_count += 1\n")
            }
            sb.append("        buffer.write_short(_sparse_count)\n")
            for (sp in sparseParameters) {
                val spSnake = sanitizePythonIdentifier(sp.name)
                sb.append("        if self.$spSnake is not None:\n")
                sb.append("            buffer.write_byte(${sp.id})\n")
                val synField =
                    SchemaField(
                        name = sp.name,
                        type = sp.type,
                        description = sp.description,
                        enumValues = null,
                        lengthType = "short",
                    )
                appendPyFieldWriteLines(sb, synField, "self.$spSnake", "            ")
            }
        }
    }

    private fun appendPyFieldWriteLines(
        sb: StringBuilder,
        f: SchemaField,
        varExpr: String,
        indent: String,
    ) {
        if (f.type.endsWith("[]")) {
            if (f.countFrom == null) {
                when (f.effectiveLengthType) {
                    "int" -> sb.append("${indent}buffer.write_int(len($varExpr))\n")
                    else -> sb.append("${indent}buffer.write_short(len($varExpr))\n")
                }
            }
            val elemType = f.type.removeSuffix("[]")
            sb.append("${indent}for item in $varExpr:\n")
            sb.append("$indent    ${mapToPyScalarWriteStmt(elemType, "item")}\n")
        } else {
            sb.append("$indent${mapToPyScalarWriteStmt(f.type, varExpr)}\n")
        }
    }

    private fun derivedExprToPy(expr: DerivedExpr): String {
        val target = "self.${sanitizePythonIdentifier(expr.targetName)}"
        return when (expr) {
            is DerivedExpr.LengthOf -> "len($target)"
            is DerivedExpr.PresentOf -> "(1 if $target is not None else 0)"
            is DerivedExpr.NonEmptyOf -> "(1 if len($target) > 0 else 0)"
        }
    }

    private fun mapToPyScalarReadExpr(type: String, maxLength: Int? = null): String =
        when (type) {
            "int",
            "color" -> "buffer.read_int()"
            "short" -> "buffer.read_short()"
            "byte" -> "buffer.read_byte()"
            "long" -> "buffer.read_long()"
            "float" -> "buffer.read_float()"
            "float_or_id" -> "buffer.read_nan_id()"
            "boolean" -> "buffer.read_boolean()"
            "string" ->
                if (maxLength != null) "buffer.read_utf8($maxLength)" else "buffer.read_utf8()"
            "bytes" ->
                if (maxLength != null) "buffer.read_buffer($maxLength)" else "buffer.read_buffer()"
            else -> "$type.read(buffer)"
        }

    private fun mapToPyScalarWriteStmt(type: String, varExpr: String): String =
        when (type) {
            "int",
            "color" -> "buffer.write_int($varExpr)"
            "short" -> "buffer.write_short($varExpr)"
            "byte" -> "buffer.write_byte($varExpr)"
            "long" -> "buffer.write_long($varExpr)"
            "float" -> "buffer.write_float($varExpr)"
            "float_or_id" -> "buffer.write_nan_id($varExpr)"
            "boolean" -> "buffer.write_boolean($varExpr)"
            "string" -> "buffer.write_utf8($varExpr)"
            "bytes" -> "buffer.write_buffer($varExpr)"
            else -> "$varExpr.write(buffer)"
        }

    companion object {
        private const val TQ = "\"\"\""

        private val PYTHON_KEYWORDS =
            setOf(
                "False",
                "None",
                "True",
                "and",
                "as",
                "assert",
                "async",
                "await",
                "break",
                "class",
                "continue",
                "def",
                "del",
                "elif",
                "else",
                "except",
                "finally",
                "for",
                "from",
                "global",
                "if",
                "import",
                "in",
                "is",
                "lambda",
                "nonlocal",
                "not",
                "or",
                "pass",
                "raise",
                "return",
                "try",
                "while",
                "with",
                "yield",
            )

        fun sanitizePythonIdentifier(name: String): String {
            val snake = CodegenExprUtils.toSnakeCase(CodegenExprUtils.cleanSchemaIdentifier(name))
            return if (snake in PYTHON_KEYWORDS) "${snake}_" else snake
        }

        fun mapToPyType(type: String, isNullable: Boolean = false): String {
            val base =
                when (type) {
                    "int",
                    "short",
                    "byte",
                    "color",
                    "long" -> "int"
                    "float",
                    "float_or_id" -> "float"
                    "boolean" -> "bool"
                    "string" -> "str"
                    "bytes" -> "bytes"
                    "int[]",
                    "short[]" -> "List[int]"
                    "float[]",
                    "float_or_id[]" -> "List[float]"
                    else ->
                        if (type.endsWith("[]")) {
                            "List[${type.removeSuffix("[]")}]"
                        } else {
                            type
                        }
                }
            return if (isNullable) "Optional[$base]" else base
        }

        fun mapToPyFallbackLiteral(
            type: String,
            isNullable: Boolean,
            defaultValue: String?,
        ): String {
            if (isNullable) return "None"
            if (defaultValue != null) {
                val dv = defaultValue.trim()
                return when (type) {
                    "float",
                    "float_or_id" -> dv.trimEnd('f', 'F')
                    "boolean" -> if (dv.equals("true", ignoreCase = true)) "True" else "False"
                    "string" -> "\"$dv\""
                    else -> dv
                }
            }
            return when (type) {
                "float",
                "float_or_id" -> "0.0"
                "boolean" -> "False"
                "string" -> "\"\""
                "bytes" -> "b\"\""
                else -> "0"
            }
        }

        fun mapToPyDefault(
            type: String,
            isNullable: Boolean = false,
            defaultValue: String? = null,
        ): String {
            if (isNullable) return "None"
            if (type.endsWith("[]")) return "field(default_factory=list)"
            if (
                defaultValue == null &&
                    type !in
                        setOf(
                            "int",
                            "short",
                            "byte",
                            "color",
                            "long",
                            "float",
                            "float_or_id",
                            "boolean",
                            "string",
                            "bytes",
                        )
            ) {
                return "field(default_factory=$type)"
            }
            return mapToPyFallbackLiteral(type, false, defaultValue)
        }
    }
}
