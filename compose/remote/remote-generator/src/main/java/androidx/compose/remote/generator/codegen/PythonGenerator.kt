/**
 * Generator that transforms an [OperationSchema] into Python bindings:
 * - OpCode IntEnum
 * - Auxiliary structs, Operation base class, and typed dataclasses with WireBuffer serialization
 * - WireBuffer implementation with big-endian struct packing
 * - RemoteDocument container with load/save
 * - OPERATION_REGISTRY and create_operation factory
 */
internal class PythonGenerator(private val schema: OperationSchema) {

    fun generate(): String = buildCode {
        line("# Generated by RemoteCompose Schema Codegen. DO NOT EDIT.")
        line("from __future__ import annotations")
        line()
        line("from dataclasses import dataclass, field")
        line("import enum")
        line("import struct")
        line("from typing import ClassVar, Dict, List, Optional, Type")
        line()
        line()
        pyBlock("class OpCode(enum.IntEnum)") {
            line("${TQ}Operation wire identifiers for RemoteCompose.$TQ")
            for (op in schema.operations) {
                val desc = op.description.replace("\n", " ").trim()
                if (desc.isNotEmpty()) {
                    line("# $desc")
                }
                line("${op.name} = ${op.id}")
            }
        }
        line()
        line()
        pyBlock("class Operation") {
            line("${TQ}Base class for all RemoteCompose operations.$TQ")
            line("op_code: ClassVar[OpCode]")
            line()
            pyBlock("def write(self, buffer: WireBuffer) -> None") {
                line("raise NotImplementedError")
            }
            line()
            pyBlock("def read_fields(self, buffer: WireBuffer) -> None") {
                line("raise NotImplementedError")
            }
        }
        line()
        line()
        emitWireBuffer(this)
        line()
        line()
        for ((_, structDef) in schema.structs) {
            emitAuxStruct(this, structDef)
            line()
            line()
        }
        for (op in schema.operations) {
            emitClass(this, op)
            line()
            line()
        }
        block("OPERATION_REGISTRY: Dict[OpCode, Type[Operation]] =", close = "}") {
            for (op in schema.operations) {
                line("OpCode.${op.name}: ${op.name},")
            }
        }
        line()
        line()
        pyBlock("def create_operation(op_code: OpCode) -> Optional[Operation]") {
            line("cls = OPERATION_REGISTRY.get(op_code)")
            line("return cls() if cls is not None else None")
        }
        line()
        line()
        emitRemoteDocument(this)
    }

    private fun emitWireBuffer(w: CodeWriter) {
        w.pyBlock("class WireBuffer") {
            line(
                "${TQ}Big-endian binary buffer for reading and writing RemoteCompose wire format.$TQ"
            )
            line()
            pyBlock("def __init__(self, data: Optional[bytes] = None)") {
                pyBlock("if data is not None") {
                    line("self._buffer = bytearray(data)")
                    line("self._index = 0")
                    line("self._size = len(data)")
                }
                pyBlock("else") {
                    line("self._buffer = bytearray(1024)")
                    line("self._index = 0")
                    line("self._size = 0")
                }
            }
            line()
            line("@classmethod")
            pyBlock("def from_bytes(cls, data: bytes) -> WireBuffer") { line("return cls(data)") }
            line()
            pyBlock("def get_bytes(self) -> bytes") {
                line("return bytes(self._buffer[:self._size])")
            }
            line()
            pyBlock("def available(self) -> bool") { line("return self._index < self._size") }
            line()
            pyBlock("def remaining(self) -> int") {
                line("return max(0, self._size - self._index)")
            }
            line()
            pyBlock("def skip_bytes(self, length: int) -> None") {
                pyBlock("if length < 0") {
                    line("raise ValueError(f\"Negative skip length in WireBuffer: {length}\")")
                }
                pyBlock("if length > self.remaining()") {
                    line("raise EOFError(\"WireBuffer underflow skipping bytes\")")
                }
                line("self._index += length")
            }
            line()
            line("@property")
            pyBlock("def position(self) -> int") { line("return self._index") }
            line()
            line("@position.setter")
            pyBlock("def position(self, pos: int) -> None") {
                pyBlock("if pos < 0 or pos > self._size") {
                    line(
                        "raise ValueError(f\"WireBuffer position out of bounds: {pos} (size={self._size})\")"
                    )
                }
                line("self._index = pos")
            }
            line()
            line("@property")
            pyBlock("def size(self) -> int") { line("return self._size") }
            line()
            pyBlock("def _ensure_capacity(self, needed: int) -> None") {
                line("required = self._index + needed")
                pyBlock("if required > len(self._buffer)") {
                    line("new_capacity = max(len(self._buffer) * 2, required)")
                    line("self._buffer.extend(b\"\\x00\" * (new_capacity - len(self._buffer)))")
                }
            }
            line()
            pyBlock("def write_byte(self, val: int) -> None") {
                line("self._ensure_capacity(1)")
                line("struct.pack_into(\">B\", self._buffer, self._index, val & 0xFF)")
                line("self._index += 1")
                pyBlock("if self._index > self._size") { line("self._size = self._index") }
            }
            line()
            pyBlock("def read_byte(self) -> int") {
                pyBlock("if 1 > self.remaining()") {
                    line("raise EOFError(\"WireBuffer underflow reading byte\")")
                }
                line("val = struct.unpack_from(\">B\", self._buffer, self._index)[0]")
                line("self._index += 1")
                line("return val")
            }
            line()
            pyBlock("def write_short(self, val: int) -> None") {
                line("self._ensure_capacity(2)")
                line("v = val & 0xFFFF")
                pyBlock("if v >= 0x8000") { line("v -= 0x10000") }
                line("struct.pack_into(\">h\", self._buffer, self._index, v)")
                line("self._index += 2")
                pyBlock("if self._index > self._size") { line("self._size = self._index") }
            }
            line()
            pyBlock("def read_short(self) -> int") {
                pyBlock("if 2 > self.remaining()") {
                    line("raise EOFError(\"WireBuffer underflow reading short\")")
                }
                line("val = struct.unpack_from(\">h\", self._buffer, self._index)[0]")
                line("self._index += 2")
                line("return val")
            }
            line()
            pyBlock("def write_int(self, val: int) -> None") {
                line("self._ensure_capacity(4)")
                line("v = val & 0xFFFFFFFF")
                pyBlock("if v >= 0x80000000") { line("v -= 0x100000000") }
                line("struct.pack_into(\">i\", self._buffer, self._index, v)")
                line("self._index += 4")
                pyBlock("if self._index > self._size") { line("self._size = self._index") }
            }
            line()
            pyBlock("def read_int(self) -> int") {
                pyBlock("if 4 > self.remaining()") {
                    line("raise EOFError(\"WireBuffer underflow reading int\")")
                }
                line("val = struct.unpack_from(\">i\", self._buffer, self._index)[0]")
                line("self._index += 4")
                line("return val")
            }
            line()
            pyBlock("def write_long(self, val: int) -> None") {
                line("self._ensure_capacity(8)")
                line("struct.pack_into(\">q\", self._buffer, self._index, val)")
                line("self._index += 8")
                pyBlock("if self._index > self._size") { line("self._size = self._index") }
            }
            line()
            pyBlock("def read_long(self) -> int") {
                pyBlock("if 8 > self.remaining()") {
                    line("raise EOFError(\"WireBuffer underflow reading long\")")
                }
                line("val = struct.unpack_from(\">q\", self._buffer, self._index)[0]")
                line("self._index += 8")
                line("return val")
            }
            line()
            pyBlock("def write_float(self, val: float) -> None") {
                line("self._ensure_capacity(4)")
                line("struct.pack_into(\">f\", self._buffer, self._index, val)")
                line("self._index += 4")
                pyBlock("if self._index > self._size") { line("self._size = self._index") }
            }
            line()
            pyBlock("def read_float(self) -> float") {
                pyBlock("if 4 > self.remaining()") {
                    line("raise EOFError(\"WireBuffer underflow reading float\")")
                }
                line("val = struct.unpack_from(\">f\", self._buffer, self._index)[0]")
                line("self._index += 4")
                line("return val")
            }
            line()
            pyBlock("def write_nan_id(self, val: float) -> None") { line("self.write_float(val)") }
            line()
            pyBlock("def read_nan_id(self) -> float") { line("return self.read_float()") }
            line()
            pyBlock("def write_boolean(self, val: bool) -> None") {
                line("self.write_byte(1 if val else 0)")
            }
            line()
            pyBlock("def read_boolean(self) -> bool") { line("return self.read_byte() != 0") }
            line()
            pyBlock("def write_utf8(self, val: str) -> None") {
                line("encoded = val.encode(\"utf-8\")")
                line("self.write_int(len(encoded))")
                line("self._ensure_capacity(len(encoded))")
                line("self._buffer[self._index : self._index + len(encoded)] = encoded")
                line("self._index += len(encoded)")
                pyBlock("if self._index > self._size") { line("self._size = self._index") }
            }
            line()
            pyBlock("def read_utf8(self, max_length: Optional[int] = None) -> str") {
                line("length = self.read_int()")
                pyBlock("if length < 0") {
                    line("raise ValueError(f\"Negative string length in WireBuffer: {length}\")")
                }
                pyBlock("if max_length is not None and length > max_length") {
                    line(
                        "raise ValueError(f\"String length {length} exceeds maximum ({max_length})\")"
                    )
                }
                pyBlock("if length > self.remaining()") {
                    line("raise EOFError(\"WireBuffer underflow reading utf8 string\")")
                }
                line("raw = self._buffer[self._index : self._index + length]")
                line("decoded = raw.decode(\"utf-8\")")
                line("self._index += length")
                line("return decoded")
            }
            line()
            pyBlock("def write_buffer(self, val: bytes) -> None") {
                line("self.write_int(len(val))")
                line("self._ensure_capacity(len(val))")
                line("self._buffer[self._index : self._index + len(val)] = val")
                line("self._index += len(val)")
                pyBlock("if self._index > self._size") { line("self._size = self._index") }
            }
            line()
            pyBlock("def read_buffer(self, max_length: Optional[int] = None) -> bytes") {
                line("length = self.read_int()")
                pyBlock("if length < 0") {
                    line("raise ValueError(f\"Negative buffer length in WireBuffer: {length}\")")
                }
                pyBlock("if max_length is not None and length > max_length") {
                    line(
                        "raise ValueError(f\"Buffer length {length} exceeds maximum ({max_length})\")"
                    )
                }
                pyBlock("if length > self.remaining()") {
                    line("raise EOFError(\"WireBuffer underflow reading buffer\")")
                }
                line("raw = bytes(self._buffer[self._index : self._index + length])")
                line("self._index += length")
                line("return raw")
            }
        }
    }

    private fun emitRemoteDocument(w: CodeWriter) {
        w.line("@dataclass")
        w.pyBlock("class RemoteDocument") {
            line("${TQ}In-memory representation of a RemoteCompose document.$TQ")
            line("MAX_HEADER_PROPERTIES: ClassVar[int] = 1000")
            line("MAX_OPERATION_COUNT: ClassVar[int] = 100_000")
            line("major_version: int = 1")
            line("minor_version: int = 1")
            line("patch_version: int = 0")
            line("width: int = 0")
            line("height: int = 0")
            line("capabilities: int = 0")
            line("operations: List[Operation] = field(default_factory=list)")
            line()
            line("@classmethod")
            pyBlock(
                "def load(cls, data: bytes, max_operations: int = MAX_OPERATION_COUNT) -> RemoteDocument"
            ) {
                line("buffer = WireBuffer.from_bytes(data)")
                line("doc = cls()")
                pyBlock("if not buffer.available()") { line("return doc") }
                line()
                line("header_op = buffer.read_byte()")
                pyBlock("if header_op != OpCode.Header.value") {
                    line("raise ValueError(f\"Expected Header opcode 0, got {header_op}\")")
                }
                line()
                line("raw_major = buffer.read_int()")
                line("doc.minor_version = buffer.read_int()")
                line("doc.patch_version = buffer.read_int()")
                line()
                pyBlock("if (raw_major & 0xFFFF0000) == 0x048C0000") {
                    line("doc.major_version = raw_major & 0xFFFF")
                    line("doc.width = 256")
                    line("doc.height = 256")
                    line("num_props = buffer.read_int()")
                    pyBlock("if num_props < 0 or num_props > cls.MAX_HEADER_PROPERTIES") {
                        line("raise ValueError(f\"Invalid header property count: {num_props}\")")
                    }
                    pyBlock("if num_props > buffer.remaining() // 4") {
                        block("raise EOFError(", openSuffix = "", close = ")") {
                            line(
                                "f\"Header property count {num_props} exceeds remaining buffer ({buffer.remaining()})\""
                            )
                        }
                    }
                    pyBlock("for _ in range(num_props)") {
                        line("tag = buffer.read_short()")
                        line("buffer.read_short()  # item_len (read and ignored)")
                        line("data_type = tag >> 10")
                        line("key = tag & 0x3F")
                        pyBlock("if data_type == 0") {
                            line("val = buffer.read_int()")
                            pyBlock("if key == 5") { line("doc.width = val") }
                            pyBlock("elif key == 6") { line("doc.height = val") }
                            pyBlock("elif key == 14") {
                                line("doc.capabilities = val & 0xFFFFFFFF")
                            }
                            pyBlock("elif key == 31 and val != 0") {
                                line(
                                    "raise ValueError(\"Compressed RemoteCompose documents are not supported\")"
                                )
                            }
                        }
                        pyBlock("elif data_type == 1") { line("buffer.read_float()") }
                        pyBlock("elif data_type == 2") {
                            line("val = buffer.read_long()")
                            pyBlock("if key == 14") { line("doc.capabilities = val") }
                            pyBlock("elif key == 31 and val != 0") {
                                line(
                                    "raise ValueError(\"Compressed RemoteCompose documents are not supported\")"
                                )
                            }
                        }
                        pyBlock("elif data_type == 3") { line("buffer.read_utf8(4000)") }
                    }
                }
                pyBlock("elif 0 <= raw_major < 0x10000") {
                    line("doc.major_version = raw_major")
                    line("doc.width = buffer.read_int()")
                    line("doc.height = buffer.read_int()")
                    line("doc.capabilities = buffer.read_long()")
                }
                pyBlock("else") {
                    line("raise ValueError(f\"Invalid header magic number: {raw_major:#x}\")")
                }
                line()
                pyBlock("while buffer.available()") {
                    pyBlock("if len(doc.operations) >= max_operations") {
                        line(
                            "raise ValueError(f\"Operation count exceeds limit {max_operations}\")"
                        )
                    }
                    line("op_byte = buffer.read_byte()")
                    pyBlock("try") { line("op_code = OpCode(op_byte)") }
                    pyBlock("except ValueError") {
                        line(
                            "raise ValueError(f\"Unknown opcode in RemoteDocument: {op_byte}\") from None"
                        )
                    }
                    pyBlock("if op_code == OpCode.Header") {
                        line("raise ValueError(\"Unexpected Header opcode inside document body\")")
                    }
                    line("op = create_operation(op_code)")
                    pyBlock("if op is None") {
                        line(
                            "raise ValueError(f\"Unsupported opcode in RemoteDocument: {op_byte}\")"
                        )
                    }
                    line("op.read_fields(buffer)")
                    line("doc.operations.append(op)")
                }
                line()
                line("return doc")
            }
            line()
            pyBlock("def save(self) -> bytes") {
                line("buffer = WireBuffer()")
                line("buffer.write_byte(OpCode.Header.value)")
                line("buffer.write_int(self.major_version)")
                line("buffer.write_int(self.minor_version)")
                line("buffer.write_int(self.patch_version)")
                line("buffer.write_int(self.width)")
                line("buffer.write_int(self.height)")
                line("buffer.write_long(self.capabilities)")
                line()
                pyBlock("for op in self.operations") { line("op.write(buffer)") }
                line()
                line("return buffer.get_bytes()")
            }
        }
    }

    private fun emitAuxStruct(w: CodeWriter, structDef: SchemaStruct) {
        val props = structDef.astProperties
        w.line("@dataclass")
        w.pyBlock("class ${structDef.name}") {
            val desc = structDef.description.replace("\n", " ").trim()
            if (desc.isNotEmpty()) {
                line("$TQ$desc$TQ")
            }
            if (props.isEmpty()) {
                line("pass")
            } else {
                for (p in props) {
                    val pName = sanitizePythonIdentifier(p.name)
                    val pyType = mapToPyType(p.type, p.isNullable)
                    val defaultVal = mapToPyDefault(p.type, p.isNullable, p.defaultValue)
                    line("$pName: $pyType = $defaultVal")
                }
            }
            line()
            pyBlock("def read_fields(self, buffer: WireBuffer) -> None") {
                emitPyReadBody(this, structDef.fields, null)
            }
            line()
            line("@classmethod")
            pyBlock("def read(cls, buffer: WireBuffer) -> ${structDef.name}") {
                line("inst = cls()")
                line("inst.read_fields(buffer)")
                line("return inst")
            }
            line()
            pyBlock("def write(self, buffer: WireBuffer) -> None") {
                emitPyWriteBody(this, structDef.fields, null, props, writeOpcode = false)
            }
        }
    }

    private fun emitClass(w: CodeWriter, op: SchemaOperation) {
        val props = op.astProperties
        w.line("@dataclass")
        w.pyBlock("class ${op.name}(Operation)") {
            val desc = op.description.replace("\n", " ").trim()
            if (desc.isNotEmpty()) {
                line("$TQ$desc$TQ")
            }
            line("op_code: ClassVar[OpCode] = OpCode.${op.name}")
            for (p in props) {
                val fieldName = sanitizePythonIdentifier(p.name)
                val pyType = mapToPyType(p.type, p.isNullable)
                val defaultVal = mapToPyDefault(p.type, p.isNullable, p.defaultValue)
                line("$fieldName: $pyType = $defaultVal")
            }
            line()
            pyBlock("def read_fields(self, buffer: WireBuffer) -> None") {
                emitPyReadBody(
                    this,
                    op.fields,
                    op.sparseParameters,
                    op.sparseCountType,
                    op.sparseKeyType,
                )
            }
            line()
            pyBlock("def write(self, buffer: WireBuffer) -> None") {
                emitPyWriteBody(
                    this,
                    op.fields,
                    op.sparseParameters,
                    props,
                    writeOpcode = true,
                    sparseCountType = op.sparseCountType,
                    sparseKeyType = op.sparseKeyType,
                )
            }
        }
    }

    private fun emitPyReadBody(
        w: CodeWriter,
        fields: List<SchemaField>,
        sparseParameters: List<SchemaSparseParam>?,
        sparseCountType: String? = null,
        sparseKeyType: String? = null,
    ) {
        if (fields.isEmpty() && sparseParameters.isNullOrEmpty()) {
            w.line("pass")
            return
        }
        val localVars = mutableSetOf<String>()

        for (f in fields) {
            val bits = f.bits
            if (bits != null && f.unpackBits) {
                val rawVar = "_raw_${sanitizePythonIdentifier(f.name)}"
                w.line("$rawVar = buffer.read_int()")
                for (b in bits) {
                    val bSnake = sanitizePythonIdentifier(b.name)
                    val extract = CodegenExprUtils.extractBitExpr(rawVar, b, ExprLang.PYTHON)
                    val bRef: String
                    if (b.derivedFrom != null) {
                        w.line("$bSnake = $extract")
                        localVars.add(b.name)
                        bRef = bSnake
                    } else {
                        w.line("self.$bSnake = $extract")
                        bRef = "self.$bSnake"
                    }
                    emitPyStrictEnumCheck(w, bSnake, bRef, b.strictEnum, b.enumValues)
                }
                continue
            }

            val fSnake = sanitizePythonIdentifier(f.name)
            val isLocalDerived = f.derivedFrom != null
            val isNullable =
                !isLocalDerived &&
                    f.presentIf != null &&
                    !f.type.endsWith("[]") &&
                    f.defaultValue == null

            if (f.presentIf != null) {
                val cond =
                    CodegenExprUtils.translateCondition(f.presentIf, ExprLang.PYTHON) {
                        if (it in localVars) sanitizePythonIdentifier(it)
                        else "self.${sanitizePythonIdentifier(it)}"
                    }
                w.pyBlock("if $cond") {
                    if (isLocalDerived) {
                        localVars.add(f.name)
                        line("$fSnake = ${mapToPyScalarReadExpr(f.type)}")
                    } else {
                        emitPyFieldReadAssign(this, f, "self.$fSnake", localVars)
                    }
                }
                w.pyBlock("else") {
                    if (isLocalDerived) {
                        line("$fSnake = 0")
                    } else if (f.type.endsWith("[]")) {
                        line("self.$fSnake = []")
                    } else {
                        line(
                            "self.$fSnake = ${mapToPyFallbackLiteral(f.type, isNullable, f.defaultValue)}"
                        )
                    }
                }
            } else if (isLocalDerived) {
                localVars.add(f.name)
                w.line("$fSnake = ${mapToPyScalarReadExpr(f.type)}")
            } else {
                emitPyFieldReadAssign(w, f, "self.$fSnake", localVars)
            }
        }

        if (sparseParameters != null) {
            for (sp in sparseParameters) {
                w.line("self.${sanitizePythonIdentifier(sp.name)} = None")
            }
            val effectiveCountType = sparseCountType ?: "ushort"
            val effectiveKeyType = sparseKeyType ?: "ubyte"
            when (effectiveCountType) {
                "int" -> {
                    w.line("_sparse_count = buffer.read_int()")
                    w.pyBlock("if _sparse_count < 0") {
                        line(
                            "raise ValueError(f\"Invalid negative sparse parameter count: {_sparse_count}\")"
                        )
                    }
                }
                "short" -> {
                    w.line("_sparse_count = buffer.read_short()")
                    w.pyBlock("if _sparse_count < 0") {
                        line(
                            "raise ValueError(f\"Invalid negative sparse parameter count: {_sparse_count}\")"
                        )
                    }
                }
                "byte" -> {
                    w.line("_sparse_count = (buffer.read_byte() ^ 0x80) - 0x80")
                    w.pyBlock("if _sparse_count < 0") {
                        line(
                            "raise ValueError(f\"Invalid negative sparse parameter count: {_sparse_count}\")"
                        )
                    }
                }
                "ubyte" -> w.line("_sparse_count = buffer.read_byte()")
                else -> w.line("_sparse_count = buffer.read_short() & 0xFFFF")
            }
            val minEntryBytes =
                when (effectiveKeyType) {
                    "int" -> 5
                    "short",
                    "ushort" -> 3
                    else -> 2
                }
            w.pyBlock("if _sparse_count > buffer.remaining() // $minEntryBytes") {
                line(
                    "raise EOFError(f\"Sparse parameter count {_sparse_count} exceeds remaining buffer ({buffer.remaining()})\")"
                )
            }
            w.pyBlock("for _ in range(_sparse_count)") {
                when (effectiveKeyType) {
                    "int" -> line("_param_id = buffer.read_int()")
                    "ushort" -> line("_param_id = buffer.read_short() & 0xFFFF")
                    "short" -> line("_param_id = buffer.read_short()")
                    "byte" -> line("_param_id = (buffer.read_byte() ^ 0x80) - 0x80")
                    else -> line("_param_id = buffer.read_byte()")
                }
                for ((idx, sp) in sparseParameters.withIndex()) {
                    val kw = if (idx == 0) "if" else "elif"
                    val spSnake = sanitizePythonIdentifier(sp.name)
                    pyBlock("$kw _param_id == ${sp.id}") {
                        val synField =
                            SchemaField(
                                name = sp.name,
                                type = sp.type,
                                description = sp.description,
                                enumValues = null,
                                lengthType = sp.lengthType ?: "ushort",
                            )
                        emitPyFieldReadAssign(this, synField, "self.$spSnake", localVars)
                    }
                }
                pyBlock("else") {
                    line("raise ValueError(f\"Unknown sparse parameter ID: {_param_id}\")")
                }
            }
        }
    }

    private fun emitPyStrictEnumCheck(
        w: CodeWriter,
        fieldSnake: String,
        varRef: String,
        strictEnum: Boolean,
        enumValues: Map<String, Int>?,
    ) {
        if (strictEnum && !enumValues.isNullOrEmpty()) {
            val distinctVals = enumValues.values.distinct().sorted()
            val allowed = distinctVals.joinToString(", ")
            val tupleExpr = if (distinctVals.size == 1) "($allowed,)" else "($allowed)"
            w.pyBlock("if $varRef not in $tupleExpr") {
                line("raise ValueError(f\"Invalid enum value for $fieldSnake: {$varRef}\")")
            }
        }
    }

    private fun emitPyFieldReadAssign(
        w: CodeWriter,
        f: SchemaField,
        targetExpr: String,
        localVars: Set<String>,
    ) {
        val baseSnake = sanitizePythonIdentifier(f.name)
        if (f.type.endsWith("[]")) {
            val lenExpr =
                if (f.countFrom != null) {
                    if (f.countFrom in localVars) sanitizePythonIdentifier(f.countFrom)
                    else "self.${sanitizePythonIdentifier(f.countFrom)}"
                } else {
                    when (f.effectiveLengthType) {
                        "int" -> "buffer.read_int()"
                        "ushort" -> "(buffer.read_short() & 0xFFFF)"
                        "ubyte" -> "buffer.read_byte()"
                        "byte" -> "((buffer.read_byte() ^ 0x80) - 0x80)"
                        else -> "buffer.read_short()"
                    }
                }
            val elemType = f.type.removeSuffix("[]")
            val elemMinBytes = CodegenExprUtils.minWireElementBytes(elemType, schema)
            val countVar = "_${baseSnake}_count"
            w.line("$countVar = $lenExpr")
            w.pyBlock("if $countVar < 0") {
                line(
                    "raise ValueError(f\"Invalid negative array length for $baseSnake: {$countVar}\")"
                )
            }
            if (f.maxLength != null) {
                w.pyBlock("if $countVar > ${f.maxLength}") {
                    line(
                        "raise ValueError(f\"Array length {$countVar} for $baseSnake exceeds maximum (${f.maxLength})\")"
                    )
                }
            }
            w.pyBlock("if $countVar > buffer.remaining() // $elemMinBytes") {
                line(
                    "raise EOFError(f\"Array length {$countVar} for $baseSnake exceeds remaining buffer ({buffer.remaining()})\")"
                )
            }
            w.line("$targetExpr = [${mapToPyScalarReadExpr(elemType)} for _ in range($countVar)]")
        } else {
            w.line("$targetExpr = ${mapToPyScalarReadExpr(f.type, f.maxLength)}")
            emitPyStrictEnumCheck(w, baseSnake, targetExpr, f.strictEnum, f.enumValues)
            val bits = f.bits
            if (bits != null && !f.unpackBits) {
                for (b in bits) {
                    if (b.strictEnum && !b.enumValues.isNullOrEmpty()) {
                        val bSnake = sanitizePythonIdentifier(b.name)
                        val bVar = "_bit_$bSnake"
                        val extract =
                            CodegenExprUtils.extractBitExpr(targetExpr, b, ExprLang.PYTHON)
                        w.line("$bVar = $extract")
                        emitPyStrictEnumCheck(w, bSnake, bVar, b.strictEnum, b.enumValues)
                    }
                }
            }
        }
    }

    private fun emitPyWriteBody(
        w: CodeWriter,
        fields: List<SchemaField>,
        sparseParameters: List<SchemaSparseParam>?,
        props: List<AstProperty>,
        writeOpcode: Boolean,
        sparseCountType: String? = null,
        sparseKeyType: String? = null,
    ) {
        if (writeOpcode) {
            w.line("buffer.write_byte(self.op_code.value)")
        } else if (fields.isEmpty() && sparseParameters.isNullOrEmpty()) {
            w.line("pass")
            return
        }

        val propByName = props.associateBy { it.name }
        val localVars = mutableSetOf<String>()

        for (f in fields) {
            val bits = f.bits
            if (bits != null && f.unpackBits) {
                val terms = mutableListOf<Pair<String, SchemaBitField>>()
                for (b in bits) {
                    val bSnake = sanitizePythonIdentifier(b.name)
                    if (b.derivedFrom != null) {
                        val expr = derivedExprToPy(DerivedExpr.parse(b.derivedFrom))
                        w.line("$bSnake = $expr")
                        localVars.add(b.name)
                        terms.add(bSnake to b)
                    } else {
                        terms.add("self.$bSnake" to b)
                    }
                }
                val packed = CodegenExprUtils.packBitsExpr(terms, ExprLang.PYTHON)
                w.line("buffer.write_int($packed)")
                continue
            }

            if (f.derivedFrom != null) {
                val derivedVal = derivedExprToPy(DerivedExpr.parse(f.derivedFrom))
                if (f.presentIf != null) {
                    val cond =
                        CodegenExprUtils.translateCondition(f.presentIf, ExprLang.PYTHON) {
                            if (it in localVars) sanitizePythonIdentifier(it)
                            else "self.${sanitizePythonIdentifier(it)}"
                        }
                    w.pyBlock("if $cond") { line(mapToPyScalarWriteStmt(f.type, derivedVal)) }
                } else {
                    val fSnake = sanitizePythonIdentifier(f.name)
                    w.line("$fSnake = $derivedVal")
                    localVars.add(f.name)
                    w.line(mapToPyScalarWriteStmt(f.type, fSnake))
                }
                continue
            }

            val fSnake = sanitizePythonIdentifier(f.name)
            val isNullable = propByName[f.name]?.isNullable == true

            if (f.presentIf != null) {
                val cond =
                    CodegenExprUtils.translateCondition(f.presentIf, ExprLang.PYTHON) {
                        if (it in localVars) sanitizePythonIdentifier(it)
                        else "self.${sanitizePythonIdentifier(it)}"
                    }
                w.pyBlock("if $cond") {
                    if (isNullable) {
                        pyBlock("if self.$fSnake is None") {
                            line("raise ValueError(\"Missing required field ${f.name}\")")
                        }
                    }
                    emitPyFieldWrite(this, f, "self.$fSnake")
                }
            } else {
                emitPyFieldWrite(w, f, "self.$fSnake")
            }
        }

        if (sparseParameters != null) {
            w.line("_sparse_count = 0")
            for (sp in sparseParameters) {
                val spSnake = sanitizePythonIdentifier(sp.name)
                w.pyBlock("if self.$spSnake is not None") { line("_sparse_count += 1") }
            }
            when (sparseCountType ?: "ushort") {
                "int" -> w.line("buffer.write_int(_sparse_count)")
                "ubyte",
                "byte" -> w.line("buffer.write_byte(_sparse_count)")
                else -> w.line("buffer.write_short(_sparse_count)")
            }
            val effectiveKeyType = sparseKeyType ?: "ubyte"
            for (sp in sparseParameters) {
                val spSnake = sanitizePythonIdentifier(sp.name)
                w.pyBlock("if self.$spSnake is not None") {
                    when (effectiveKeyType) {
                        "int" -> line("buffer.write_int(${sp.id})")
                        "ushort",
                        "short" -> line("buffer.write_short(${sp.id})")
                        else -> line("buffer.write_byte(${sp.id})")
                    }
                    val synField =
                        SchemaField(
                            name = sp.name,
                            type = sp.type,
                            description = sp.description,
                            enumValues = null,
                            lengthType = sp.lengthType ?: "ushort",
                        )
                    emitPyFieldWrite(this, synField, "self.$spSnake")
                }
            }
        }
    }

    private fun emitPyFieldWrite(w: CodeWriter, f: SchemaField, varExpr: String) {
        if (f.type.endsWith("[]")) {
            if (f.countFrom == null) {
                when (f.effectiveLengthType) {
                    "int" -> w.line("buffer.write_int(len($varExpr))")
                    "ubyte",
                    "byte" -> w.line("buffer.write_byte(len($varExpr))")
                    else -> w.line("buffer.write_short(len($varExpr))")
                }
            }
            val elemType = f.type.removeSuffix("[]")
            w.pyBlock("for item in $varExpr") { line(mapToPyScalarWriteStmt(elemType, "item")) }
        } else {
            w.line(mapToPyScalarWriteStmt(f.type, varExpr))
        }
    }

    private fun derivedExprToPy(expr: DerivedExpr): String {
        val target = "self.${sanitizePythonIdentifier(expr.targetName)}"
        return when (expr) {
            is DerivedExpr.LengthOf -> "len($target)"
            is DerivedExpr.PresentOf -> "(1 if $target is not None else 0)"
            is DerivedExpr.NonEmptyOf -> "(1 if len($target) > 0 else 0)"
        }
    }

    private fun mapToPyScalarReadExpr(type: String, maxLength: Int? = null): String =
        when (type) {
            "int",
            "color" -> "buffer.read_int()"
            "short" -> "buffer.read_short()"
            "byte" -> "buffer.read_byte()"
            "long" -> "buffer.read_long()"
            "float" -> "buffer.read_float()"
            "float_or_id" -> "buffer.read_nan_id()"
            "boolean" -> "buffer.read_boolean()"
            "string" ->
                if (maxLength != null) "buffer.read_utf8($maxLength)" else "buffer.read_utf8()"
            "bytes" ->
                if (maxLength != null) "buffer.read_buffer($maxLength)" else "buffer.read_buffer()"
            else -> "$type.read(buffer)"
        }

    private fun mapToPyScalarWriteStmt(type: String, varExpr: String): String =
        when (type) {
            "int",
            "color" -> "buffer.write_int($varExpr)"
            "short" -> "buffer.write_short($varExpr)"
            "byte" -> "buffer.write_byte($varExpr)"
            "long" -> "buffer.write_long($varExpr)"
            "float" -> "buffer.write_float($varExpr)"
            "float_or_id" -> "buffer.write_nan_id($varExpr)"
            "boolean" -> "buffer.write_boolean($varExpr)"
            "string" -> "buffer.write_utf8($varExpr)"
            "bytes" -> "buffer.write_buffer($varExpr)"
            else -> "$varExpr.write(buffer)"
        }

    companion object {
        private const val TQ = "\"\"\""

        private val PYTHON_KEYWORDS =
            setOf(
                "False",
                "None",
                "True",
                "and",
                "as",
                "assert",
                "async",
                "await",
                "break",
                "class",
                "continue",
                "def",
                "del",
                "elif",
                "else",
                "except",
                "finally",
                "for",
                "from",
                "global",
                "if",
                "import",
                "in",
                "is",
                "lambda",
                "nonlocal",
                "not",
                "or",
                "pass",
                "raise",
                "return",
                "try",
                "while",
                "with",
                "yield",
            )

        fun sanitizePythonIdentifier(name: String): String {
            val snake = CodegenExprUtils.toSnakeCase(CodegenExprUtils.cleanSchemaIdentifier(name))
            return if (snake in PYTHON_KEYWORDS) "${snake}_" else snake
        }

        fun mapToPyType(type: String, isNullable: Boolean = false): String {
            val base =
                when (type) {
                    "int",
                    "short",
                    "byte",
                    "color",
                    "long" -> "int"
                    "float",
                    "float_or_id" -> "float"
                    "boolean" -> "bool"
                    "string" -> "str"
                    "bytes" -> "bytes"
                    "int[]",
                    "short[]" -> "List[int]"
                    "float[]",
                    "float_or_id[]" -> "List[float]"
                    else ->
                        if (type.endsWith("[]")) {
                            "List[${type.removeSuffix("[]")}]"
                        } else {
                            type
                        }
                }
            return if (isNullable) "Optional[$base]" else base
        }

        fun mapToPyFallbackLiteral(
            type: String,
            isNullable: Boolean,
            defaultValue: String?,
        ): String {
            if (isNullable) return "None"
            if (defaultValue != null) {
                val dv = defaultValue.trim()
                return when (type) {
                    "float",
                    "float_or_id" -> dv.trimEnd('f', 'F')
                    "boolean" -> if (dv.equals("true", ignoreCase = true)) "True" else "False"
                    "string" -> "\"$dv\""
                    else -> dv
                }
            }
            return when (type) {
                "float",
                "float_or_id" -> "0.0"
                "boolean" -> "False"
                "string" -> "\"\""
                "bytes" -> "b\"\""
                else -> "0"
            }
        }

        fun mapToPyDefault(
            type: String,
            isNullable: Boolean = false,
            defaultValue: String? = null,
        ): String {
            if (isNullable) return "None"
            if (type.endsWith("[]")) return "field(default_factory=list)"
            if (
                defaultValue == null &&
                    type !in
                        setOf(
                            "int",
                            "short",
                            "byte",
                            "color",
                            "long",
                            "float",
                            "float_or_id",
                            "boolean",
                            "string",
                            "bytes",
                        )
            ) {
                return "field(default_factory=$type)"
            }
            return mapToPyFallbackLiteral(type, false, defaultValue)
        }
    }
}
