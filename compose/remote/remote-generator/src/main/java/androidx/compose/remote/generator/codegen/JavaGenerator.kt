                op.profiles.joinToString(" || ") { "\"$it\".equalsIgnoreCase(profile)" }
            sb.append("            case $screamingName:\n")
            sb.append("                return $profileChecks;\n")
        }
        sb.append("            default:\n")
        sb.append("                return false;\n")
        sb.append("        }\n")
