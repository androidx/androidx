package androidx.compose.remote.generator.codegen

import androidx.compose.remote.generator.OperationSchema
import androidx.compose.remote.generator.SchemaOperation

/**
 * Generator that transforms an [OperationSchema] into idiomatic, pure Java (Java 8/11/17) bindings
 * for `:compose:remote:remote-core`:
 * - Abstract base classes (`<OpName>Base.java`) containing mechanical boilerplate:
 *     - OpCode & class name constants
 *     - Wire serialization (`apply`, `write`)
 *     - Deserialization (`read`)
 *     - Metadata & documentation (`documentation`)
 *     - Map serialization (`serialize`)
 * - Pure data operation classes for operations with no custom layout or rendering logic
 * - Central `GeneratedOperations.java` with OpCode constants, profile bitmasks, and dispatch
 *   tables.
 */
internal class JavaGenerator(private val schema: OperationSchema) {

    /**
     * Generates an abstract base class for an operation containing all wire serialization,
     * documentation, and map serialization boilerplate.
     */
    fun generateBaseClass(
        op: SchemaOperation,
        packageName: String = "androidx.compose.remote.core.operations",
        superClassName: String = "Operation",
    ): String {
        val sb = StringBuilder()
        val className = "${op.name}Base"

        sb.append(
            """
            /*
             * Copyright 2026 The Android Open Source Project
             *
             * Licensed under the Apache License, Version 2.0 (the "License");
             * you may not use this file except in compliance with the License.
             * You may obtain a copy of the License at
             *
             *      http://www.apache.org/licenses/LICENSE-2.0
             *
             * Unless required by applicable law or agreed to in writing, software
             * distributed under the License is distributed on an "AS IS" BASIS,
             * WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
             * See the License for the specific language governing permissions and
             * limitations under the License.
             */
            // Generated by RemoteCompose JavaGenerator. DO NOT EDIT.

            package $packageName;

            import androidx.annotation.RestrictTo;
            import androidx.compose.remote.core.Operation;
            import androidx.compose.remote.core.WireBuffer;
            import androidx.compose.remote.core.documentation.DocumentationBuilder;
            import androidx.compose.remote.core.documentation.DocumentedOperation;
            import androidx.compose.remote.core.serialize.MapSerializer;
            import androidx.compose.remote.core.serialize.Serializable;

            import org.jspecify.annotations.NonNull;
            import org.jspecify.annotations.Nullable;

            import java.util.List;
            import java.util.Objects;

            /**
             * Base class for ${op.name} operation.
             * ${op.description.replace("\n", "\n * ")}
             */
            @RestrictTo(RestrictTo.Scope.LIBRARY_GROUP)
            public abstract class $className extends $superClassName implements Serializable {
                public static final int OP_CODE = ${op.id};
                public static final String CLASS_NAME = "${op.name}";

            """
                .trimIndent()
        )
        sb.append("\n")

        // Fields
        for (f in op.fields) {
            val javaType = mapToJavaType(f.type)
            val memberName = "m${f.name.replaceFirstChar { it.uppercaseChar() }}"
            sb.append("    protected final $javaType $memberName;\n")
        }
        sb.append("\n")

        // Constructor
        if (op.fields.isNotEmpty()) {
            val params =
                op.fields.joinToString(", ") {
                    "${mapToJavaType(it.type)} ${sanitizeIdentifier(it.name)}"
                }
            sb.append("    protected $className($params) {\n")
            for (f in op.fields) {
                val memberName = "m${f.name.replaceFirstChar { it.uppercaseChar() }}"
                sb.append("        this.$memberName = ${sanitizeIdentifier(f.name)};\n")
            }
            sb.append("    }\n\n")
        } else {
            sb.append("    protected $className() {}\n\n")
        }

        // Getters
        for (f in op.fields) {
            val javaType = mapToJavaType(f.type)
            val getterName = "get${f.name.replaceFirstChar { it.uppercaseChar() }}"
            val memberName = "m${f.name.replaceFirstChar { it.uppercaseChar() }}"
            sb.append("    public $javaType $getterName() {\n")
            sb.append("        return $memberName;\n")
            sb.append("    }\n\n")
        }

        // Static id & name
        sb.append("    public static int id() {\n")
        sb.append("        return OP_CODE;\n")
        sb.append("    }\n\n")

        sb.append("    @NonNull\n")
        sb.append("    public static String name() {\n")
        sb.append("        return CLASS_NAME;\n")
        sb.append("    }\n\n")

        // Static apply() method
        val applyParams =
            if (op.fields.isEmpty()) {
                "@NonNull WireBuffer buffer"
            } else {
                "@NonNull WireBuffer buffer, " +
                    op.fields.joinToString(", ") {
                        "${mapToJavaType(it.type)} ${sanitizeIdentifier(it.name)}"
                    }
            }
        sb.append("    /** Writes out the operation to the buffer. */\n")
        sb.append("    public static void apply($applyParams) {\n")
        sb.append("        buffer.start(OP_CODE);\n")
        for (f in op.fields) {
            val writeExpr = mapToJavaWriteExpr(f.type, sanitizeIdentifier(f.name))
            sb.append("        $writeExpr;\n")
        }
        sb.append("    }\n\n")

        // Instance write() method
        sb.append("    @Override\n")
        sb.append("    public void write(@NonNull WireBuffer buffer) {\n")
        if (op.fields.isEmpty()) {
            sb.append("        apply(buffer);\n")
        } else {
            val args =
                op.fields.joinToString(", ") {
                    "m${it.name.replaceFirstChar { c -> c.uppercaseChar() }}"
                }
            sb.append("        apply(buffer, $args);\n")
        }
        sb.append("    }\n\n")

        // Documentation method
        sb.append("    /** Populates documentation for this operation. */\n")
        sb.append("    public static void documentation(@NonNull DocumentationBuilder doc) {\n")
        sb.append("        doc.operation(\"${op.category}\", OP_CODE, CLASS_NAME)\n")
        sb.append(
            "                .description(\"${op.description.replace("\"", "\\\"").replace("\n", " ")}\")"
        )
        for (f in op.fields) {
            val docType = mapToJavaDocType(f.type)
            val desc = f.description.replace("\"", "\\\"").replace("\n", " ")
            sb.append("\n                .field($docType, \"${f.name}\", \"$desc\")")
        }
        sb.append(";\n")
        sb.append("    }\n\n")

        // MapSerializer serialize() method
        sb.append("    @Override\n")
        sb.append("    public void serialize(@NonNull MapSerializer serializer) {\n")
        sb.append("        serializer.addType(CLASS_NAME);\n")
        for (f in op.fields) {
            val memberName = "m${f.name.replaceFirstChar { it.uppercaseChar() }}"
            sb.append("        serializer.add(\"${f.name}\", $memberName);\n")
        }
        sb.append("    }\n\n")

        // deepToString & toString
        sb.append("    @NonNull\n")
        sb.append("    @Override\n")
        sb.append("    public String deepToString(@NonNull String indent) {\n")
        sb.append("        return indent + toString();\n")
        sb.append("    }\n\n")

        sb.append("    @NonNull\n")
        sb.append("    @Override\n")
        sb.append("    public String toString() {\n")
        if (op.fields.isEmpty()) {
            sb.append("        return CLASS_NAME;\n")
        } else {
            val fieldFormats =
                op.fields.joinToString(" + \", ") {
                    val memberName = "m${it.name.replaceFirstChar { c -> c.uppercaseChar() }}"
                    "${it.name}=\" + $memberName"
                }
            sb.append("        return CLASS_NAME + \"(\" + $fieldFormats + \")\";\n")
        }
        sb.append("    }\n")

        sb.append("}\n")
        return sb.toString()
    }

    /**
     * Generates a concrete operation class inheriting from the base class for operations that
     * require no custom layout or rendering logic.
     */
    fun generateConcreteClass(
        op: SchemaOperation,
        packageName: String = "androidx.compose.remote.core.operations",
        superClassName: String = "${op.name}Base",
    ): String {
        val sb = StringBuilder()
        val className = op.name

        sb.append(
            """
            /*
             * Copyright 2026 The Android Open Source Project
             *
             * Licensed under the Apache License, Version 2.0 (the "License");
             * you may not use this file except in compliance with the License.
             * You may obtain a copy of the License at
             *
             *      http://www.apache.org/licenses/LICENSE-2.0
             *
             * Unless required by applicable law or agreed to in writing, software
             * distributed under the License is distributed on an "AS IS" BASIS,
             * WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
             * See the License for the specific language governing permissions and
             * limitations under the License.
             */
            // Generated by RemoteCompose JavaGenerator. DO NOT EDIT.

            package $packageName;

            import androidx.annotation.RestrictTo;
            import androidx.compose.remote.core.Operation;
            import androidx.compose.remote.core.RemoteContext;
            import androidx.compose.remote.core.WireBuffer;

            import org.jspecify.annotations.NonNull;

            import java.util.List;

            /**
             * ${op.description.replace("\n", "\n * ")}
             */
            @RestrictTo(RestrictTo.Scope.LIBRARY_GROUP)
            public class $className extends $superClassName {

            """
                .trimIndent()
        )
        sb.append("\n")

        // Constructor
        if (op.fields.isNotEmpty()) {
            val params =
                op.fields.joinToString(", ") {
                    "${mapToJavaType(it.type)} ${sanitizeIdentifier(it.name)}"
                }
            val superArgs = op.fields.joinToString(", ") { sanitizeIdentifier(it.name) }
            sb.append("    public $className($params) {\n")
            sb.append("        super($superArgs);\n")
            sb.append("    }\n\n")
        } else {
            sb.append("    public $className() {\n")
            sb.append("        super();\n")
            sb.append("    }\n\n")
        }

        // Static read() method
        sb.append("    /** Reads a [$className] from [buffer] and appends it to [operations]. */\n")
        sb.append(
            "    public static void read(@NonNull WireBuffer buffer, @NonNull List<Operation> operations) {\n"
        )
        for (f in op.fields) {
            val javaType = mapToJavaType(f.type)
            val readExpr = mapToJavaReadExpr(f.type)
            sb.append("        $javaType ${sanitizeIdentifier(f.name)} = $readExpr;\n")
        }
        val constructorArgs = op.fields.joinToString(", ") { sanitizeIdentifier(it.name) }
        sb.append("        operations.add(new $className($constructorArgs));\n")
        sb.append("    }\n\n")

        // apply(RemoteContext context)
        sb.append("    @Override\n")
        sb.append("    public void apply(@NonNull RemoteContext context) {\n")
        sb.append("        // Default no-op for non-rendering operations\n")
        sb.append("    }\n")

        sb.append("}\n")
        return sb.toString()
    }

    /** Generates a central GeneratedOperations.java providing OpCode constants and profile maps. */
