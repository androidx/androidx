        fun sanitizeIdentifier(name: String): String {
            val clean =
                name.replace("[0..n]", "Array").replace("[", "_").replace("]", "").replace(".", "_")
            return if (clean in JAVA_KEYWORDS) "${clean}Val" else clean
        }

        fun toScreamingSnakeCase(name: String): String {
            val sb = StringBuilder()
            for (i in name.indices) {
                val c = name[i]
                if (c.isUpperCase() && i > 0 && !name[i - 1].isUpperCase()) {
                    sb.append('_')
                }
                sb.append(c.uppercaseChar())
            }
            return sb.toString()
        }
