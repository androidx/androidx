    companion object {
        fun mapToJavaType(type: String): String =
            when (type) {
                "int",
                "color" -> "int"
                "short" -> "short"
                "byte" -> "byte"
                "long" -> "long"
                "float",
                "float_or_id" -> "float"
                "boolean" -> "boolean"
                "string" -> "String"
                "bytes" -> "byte[]"
                else -> "int"
            }

        fun mapToJavaDocType(type: String): String =
            when (type) {
                "int",
                "color" -> "DocumentedOperation.INT"
                "short" -> "DocumentedOperation.SHORT"
                "byte" -> "DocumentedOperation.BYTE"
                "long" -> "DocumentedOperation.LONG"
                "float",
                "float_or_id" -> "DocumentedOperation.FLOAT"
                "boolean" -> "DocumentedOperation.BOOLEAN"
                "string" -> "DocumentedOperation.STRING"
                "bytes" -> "DocumentedOperation.BUFFER"
                else -> "DocumentedOperation.INT"
            }

        fun mapToJavaWriteExpr(type: String, fieldVar: String): String =
            when (type) {
                "int",
                "color" -> "buffer.writeInt($fieldVar)"
                "short" -> "buffer.writeShort($fieldVar)"
                "byte" -> "buffer.writeByte($fieldVar)"
                "long" -> "buffer.writeLong($fieldVar)"
                "float",
                "float_or_id" -> "buffer.writeFloat($fieldVar)"
                "boolean" -> "buffer.writeBoolean($fieldVar)"
                "string" -> "buffer.writeUTF8($fieldVar)"
                "bytes" -> "buffer.writeBuffer($fieldVar)"
                else -> "buffer.writeInt($fieldVar)"
            }

        fun mapToJavaReadExpr(type: String): String =
            when (type) {
                "int",
                "color" -> "buffer.readInt()"
                "short" -> "buffer.readShort()"
                "byte" -> "buffer.readByte()"
                "long" -> "buffer.readLong()"
                "float",
                "float_or_id" -> "buffer.readFloat()"
                "boolean" -> "buffer.readBoolean()"
                "string" -> "buffer.readUTF8()"
                "bytes" -> "buffer.readBuffer()"
                else -> "buffer.readInt()"
            }

