/**
 * Generator that transforms an [OperationSchema] into idiomatic Swift bindings:
 * - OpCode enum with UInt8 raw values
 * - RemoteOperation protocol
 * - Auxiliary structs and typed structs for each operation with WireBuffer read/write methods
 * - RemoteDocument container and WireBuffer implementation
 */
internal class SwiftGenerator(private val schema: OperationSchema) {

    private val multiLang = MultiLangProtocolGenerator(schema)

    fun generate(): String = buildCode {
        line("// Generated by RemoteCompose Schema Codegen. DO NOT EDIT.")
        line("import Foundation")
        line()
        line("/// Operation wire identifiers for RemoteCompose.")
        block("public enum OpCode: UInt8, CaseIterable") {
            for (op in schema.operations) {
                val swiftCase = toCamelCase(op.name)
                val desc = op.description.replace("\n", " ").trim()
                if (desc.isNotEmpty()) {
                    line("/// $desc")
                }
                line("case $swiftCase = ${op.id}")
            }
        }
        line()
        line("/// Protocol adopted by all RemoteCompose operation types.")
        block("public protocol RemoteOperation") {
            line("var opCode: OpCode { get }")
            line("func write(to buffer: inout WireBuffer) throws")
        }
        line()
        emitWireBuffer(this)
        line()
        multiLang.emitSwiftProtocol(this)
        for ((_, structDef) in schema.structs) {
            emitAuxStruct(this, structDef)
            line()
        }
        for (op in schema.operations) {
            emitStruct(this, op)
            line()
        }
        emitRemoteDocument(this)
    }

    private fun emitWireBuffer(w: CodeWriter) {
        w.block("public struct WireBuffer") {
            line("public private(set) var data: Data")
            line("public private(set) var index: Int = 0")
            line()
            block("public init(data: Data = Data())") {
                line("self.data = data.startIndex == 0 ? data : Data(data)")
                line("self.index = 0")
            }
            line()
            block("public var remaining: Int") { line("return max(0, data.count - index)") }
            line()
            block("public var available: Bool") { line("return index < data.count") }
            line()
            block("public mutating func setIndex(_ newIndex: Int) throws") {
                block("guard newIndex >= 0 && newIndex <= data.count else") {
                    line(
                        "throw NSError(domain: \"WireBuffer\", code: 2, userInfo: [NSLocalizedDescriptionKey: \"Index out of bounds: \\(newIndex)\"])"
                    )
                }
                line("index = newIndex")
            }
            line()
            block("public mutating func skipBytes(_ count: Int) throws") {
                block("guard count >= 0 else") {
                    line(
                        "throw NSError(domain: \"WireBuffer\", code: 3, userInfo: [NSLocalizedDescriptionKey: \"Invalid negative skip length\"])"
                    )
                }
                block("guard count <= remaining else") {
                    line(
                        "throw NSError(domain: \"WireBuffer\", code: 1, userInfo: [NSLocalizedDescriptionKey: \"Underflow\"])"
                    )
                }
                line("index += count")
            }
            line()
            block("public mutating func writeByte(_ value: UInt8)") { line("data.append(value)") }
            line()
            block("public mutating func readByte() throws -> UInt8") {
                block("guard 1 <= remaining else") {
                    line(
                        "throw NSError(domain: \"WireBuffer\", code: 1, userInfo: [NSLocalizedDescriptionKey: \"Underflow\"])"
                    )
                }
                line("let byte = data[index]")
                line("index += 1")
                line("return byte")
            }
            line()
            block("public mutating func writeShort(_ value: Int16)") {
                line("var val = value.bigEndian")
                line("withUnsafeBytes(of: &val) { data.append(contentsOf: \$0) }")
            }
            line()
            block("public mutating func readShort() throws -> Int16") {
                block("guard 2 <= remaining else") {
                    line(
                        "throw NSError(domain: \"WireBuffer\", code: 1, userInfo: [NSLocalizedDescriptionKey: \"Underflow\"])"
                    )
                }
                line("let bits = (UInt16(data[index]) << 8) | UInt16(data[index + 1])")
                line("index += 2")
                line("return Int16(bitPattern: bits)")
            }
            line()
            block("public mutating func writeInt(_ value: Int32)") {
                line("var val = value.bigEndian")
                line("withUnsafeBytes(of: &val) { data.append(contentsOf: \$0) }")
            }
            line()
            block("public mutating func readInt() throws -> Int32") {
                block("guard 4 <= remaining else") {
                    line(
                        "throw NSError(domain: \"WireBuffer\", code: 1, userInfo: [NSLocalizedDescriptionKey: \"Underflow\"])"
                    )
                }
                line("let bits = (UInt32(data[index]) << 24)")
                indent {
                    line("| (UInt32(data[index + 1]) << 16)")
                    line("| (UInt32(data[index + 2]) << 8)")
                    line("| UInt32(data[index + 3])")
                }
                line("index += 4")
                line("return Int32(bitPattern: bits)")
            }
            line()
            block("public mutating func writeLong(_ value: Int64)") {
                line("var val = value.bigEndian")
                line("withUnsafeBytes(of: &val) { data.append(contentsOf: \$0) }")
            }
            line()
            block("public mutating func readLong() throws -> Int64") {
                block("guard 8 <= remaining else") {
                    line(
                        "throw NSError(domain: \"WireBuffer\", code: 1, userInfo: [NSLocalizedDescriptionKey: \"Underflow\"])"
                    )
                }
                line("var bits: UInt64 = 0")
                block("for i in 0..<8") { line("bits = (bits << 8) | UInt64(data[index + i])") }
                line("index += 8")
                line("return Int64(bitPattern: bits)")
            }
            line()
            block("public mutating func writeFloat(_ value: Float)") {
                line("var bitVal = value.bitPattern.bigEndian")
                line("withUnsafeBytes(of: &bitVal) { data.append(contentsOf: \$0) }")
            }
            line()
            block("public mutating func readFloat() throws -> Float") {
                line("let bitVal = UInt32(bitPattern: try readInt())")
                line("return Float(bitPattern: bitVal)")
            }
            line()
            block("public mutating func writeBoolean(_ value: Bool)") {
                line("writeByte(value ? 1 : 0)")
            }
            line()
            block("public mutating func readBoolean() throws -> Bool") {
                line("return (try readByte()) != 0")
            }
            line()
            block("public mutating func writeUTF8(_ value: String)") {
                line("let utf8Data = Data(value.utf8)")
                line("writeInt(Int32(utf8Data.count))")
                line("data.append(utf8Data)")
            }
            line()
            block("public mutating func readUTF8(maxLength: Int? = nil) throws -> String") {
                line("let len = Int(try readInt())")
                block("guard len >= 0 else") {
                    line(
                        "throw NSError(domain: \"WireBuffer\", code: 3, userInfo: [NSLocalizedDescriptionKey: \"Invalid negative UTF-8 length\"])"
                    )
                }
                block("if let maxLen = maxLength, len > maxLen") {
                    line(
                        "throw NSError(domain: \"WireBuffer\", code: 5, userInfo: [NSLocalizedDescriptionKey: \"UTF-8 length exceeds maximum\"])"
                    )
                }
                block("guard len <= remaining else") {
                    line(
                        "throw NSError(domain: \"WireBuffer\", code: 1, userInfo: [NSLocalizedDescriptionKey: \"Underflow\"])"
                    )
                }
                line("let strData = data.subdata(in: index..<(index + len))")
                block("guard let str = String(data: strData, encoding: .utf8) else") {
                    line(
                        "throw NSError(domain: \"WireBuffer\", code: 4, userInfo: [NSLocalizedDescriptionKey: \"Invalid UTF-8 byte sequence\"])"
                    )
                }
                line("index += len")
                line("return str")
            }
            line()
            block("public mutating func writeBuffer(_ value: Data)") {
                line("writeInt(Int32(value.count))")
                line("data.append(value)")
            }
            line()
            block("public mutating func writeBytes(_ value: Data)") { line("data.append(value)") }
            line()
            block("public mutating func readBytes(count: Int) throws -> Data") {
                block("guard count >= 0 else") {
                    line(
                        "throw NSError(domain: \"WireBuffer\", code: 3, userInfo: [NSLocalizedDescriptionKey: \"Invalid negative byte count\"])"
                    )
                }
                block("guard count <= remaining else") {
                    line(
                        "throw NSError(domain: \"WireBuffer\", code: 1, userInfo: [NSLocalizedDescriptionKey: \"Underflow\"])"
                    )
                }
                line("let bufData = data.subdata(in: index..<(index + count))")
                line("index += count")
                line("return bufData")
            }
            line()
            block("public mutating func readBuffer(maxLength: Int? = nil) throws -> Data") {
                line("let len = Int(try readInt())")
                block("guard len >= 0 else") {
                    line(
                        "throw NSError(domain: \"WireBuffer\", code: 3, userInfo: [NSLocalizedDescriptionKey: \"Invalid negative buffer length\"])"
                    )
                }
                block("if let maxLen = maxLength, len > maxLen") {
                    line(
                        "throw NSError(domain: \"WireBuffer\", code: 5, userInfo: [NSLocalizedDescriptionKey: \"Buffer length exceeds maximum\"])"
                    )
                }
                block("guard len <= remaining else") {
                    line(
                        "throw NSError(domain: \"WireBuffer\", code: 1, userInfo: [NSLocalizedDescriptionKey: \"Underflow\"])"
                    )
                }
                line("let bufData = data.subdata(in: index..<(index + len))")
                line("index += len")
                line("return bufData")
            }
        }
    }

    private fun emitRemoteDocument(w: CodeWriter) {
        w.line("/// In-memory representation of a RemoteCompose document.")
        w.block("public struct RemoteDocument") {
            line("public static let MAX_HEADER_PROPERTIES: Int = 1000")
            line("public static let MAX_OPERATION_COUNT: Int = 100_000")
            line()
            line("public var majorVersion: Int32 = 1")
            line("public var minorVersion: Int32 = 1")
            line("public var patchVersion: Int32 = 0")
            line("public var width: Int32 = 0")
            line("public var height: Int32 = 0")
            line("public var capabilities: Int64 = 0")
            line("public var operations: [RemoteOperation] = []")
            line()
            line("public init() {}")
            line()
            line("/// Deserializes a RemoteDocument from raw binary data.")
            block(
                "public static func load(from data: Data, maxOperations: Int = MAX_OPERATION_COUNT) throws -> RemoteDocument"
            ) {
                line(
                    "return try loadImpl(from: data, maxOperations: maxOperations, evaluateSkip: false, playerApiLevel: 0, playerProfiles: 0)"
                )
            }
            line()
            line(
                "/// Deserializes a RemoteDocument evaluating conditional skip operations against the target player."
            )
            block(
                "public static func loadForPlayer(",
                openSuffix = "",
                close = null,
            ) {
                line("from data: Data,")
                line("playerApiLevel: Int32,")
                line("playerProfiles: Int32 = 0,")
                line("maxOperations: Int = MAX_OPERATION_COUNT")
            }
            block(") throws -> RemoteDocument") {
                block("return try loadImpl(", openSuffix = "", close = ")") {
                    line("from: data,")
                    line("maxOperations: maxOperations,")
                    line("evaluateSkip: true,")
                    line("playerApiLevel: playerApiLevel,")
                    line("playerProfiles: playerProfiles")
                }
            }
            line()
            block(
                "private static func loadImpl(",
                openSuffix = "",
                close = null,
            ) {
                line("from data: Data,")
                line("maxOperations: Int,")
                line("evaluateSkip: Bool,")
                line("playerApiLevel: Int32,")
                line("playerProfiles: Int32")
            }
            block(") throws -> RemoteDocument") {
                line("var buffer = WireBuffer(data: data)")
                line("var doc = RemoteDocument()")
                line("guard buffer.available else { return doc }")
                line()
                line("let headerOp = try buffer.readByte()")
                block("guard headerOp == OpCode.header.rawValue else") {
                    line(
                        "throw NSError(domain: \"RemoteDocument\", code: 2, userInfo: [NSLocalizedDescriptionKey: \"Expected header opcode\"])"
                    )
                }
                line("let rawMajor = try buffer.readInt()")
                line("doc.minorVersion = try buffer.readInt()")
                line("doc.patchVersion = try buffer.readInt()")
                block(
                    "if (UInt32(bitPattern: rawMajor) & 0xFFFF0000) == 0x048C0000",
                    close = null,
                ) {
                    line("doc.majorVersion = rawMajor & 0xFFFF")
                    line("doc.width = 256")
                    line("doc.height = 256")
                    line("let numProps = Int(try buffer.readInt())")
                    block("guard numProps >= 0 && numProps <= MAX_HEADER_PROPERTIES else") {
                        line(
                            "throw NSError(domain: \"RemoteDocument\", code: 3, userInfo: [NSLocalizedDescriptionKey: \"Invalid header property count: \\(numProps)\"])"
                        )
                    }
                    block("guard numProps <= buffer.remaining / 4 else") {
                        line(
                            "throw NSError(domain: \"RemoteDocument\", code: 3, userInfo: [NSLocalizedDescriptionKey: \"Header property count exceeds remaining buffer\"])"
                        )
                    }
                    block("for _ in 0..<numProps") {
                        line("let tag = Int32(try buffer.readShort())")
                        line("_ = try buffer.readShort() // itemLen (read and ignored)")
                        line("let dataType = tag >> 10")
                        line("let key = tag & 0x3F")
                        swiftSwitch("dataType") {
                            swiftCase("case 0") {
                                line("let val = try buffer.readInt()")
                                line("if key == 5 { doc.width = val }")
                                line("else if key == 6 { doc.height = val }")
                                line(
                                    "else if key == 14 { doc.capabilities = Int64(UInt32(bitPattern: val)) }"
                                )
                                block("else if key == 31 && val != 0") {
                                    line(
                                        "throw NSError(domain: \"RemoteDocument\", code: 6, userInfo: [NSLocalizedDescriptionKey: \"Compressed RemoteCompose documents are not supported\"])"
                                    )
                                }
                            }
                            swiftCase("case 1") { line("_ = try buffer.readFloat()") }
                            swiftCase("case 2") {
                                line("let val = try buffer.readLong()")
                                line("if key == 14 { doc.capabilities = val }")
                                block("else if key == 31 && val != 0") {
                                    line(
                                        "throw NSError(domain: \"RemoteDocument\", code: 6, userInfo: [NSLocalizedDescriptionKey: \"Compressed RemoteCompose documents are not supported\"])"
                                    )
                                }
                            }
                            swiftCase("case 3") { line("_ = try buffer.readUTF8(maxLength: 4000)") }
                            swiftCase("default") { line("break") }
                        }
                    }
                }
                block("} else if rawMajor >= 0 && rawMajor < 0x10000", close = null) {
                    line("doc.majorVersion = rawMajor")
                    line("doc.width = try buffer.readInt()")
                    line("doc.height = try buffer.readInt()")
                    line("doc.capabilities = try buffer.readLong()")
                }
                block("} else") {
                    line(
                        "throw NSError(domain: \"RemoteDocument\", code: 7, userInfo: [NSLocalizedDescriptionKey: \"Invalid header magic number: \\(rawMajor)\"])"
                    )
                }
                line()
                block("while buffer.available") {
                    block("guard doc.operations.count < maxOperations else") {
                        line(
                            "throw NSError(domain: \"RemoteDocument\", code: 8, userInfo: [NSLocalizedDescriptionKey: \"Operation count exceeds limit \\(maxOperations)\"])"
                        )
                    }
                    line("let opByte = try buffer.readByte()")
                    block("guard let opCode = OpCode(rawValue: opByte) else") {
                        line(
                            "throw NSError(domain: \"RemoteDocument\", code: 5, userInfo: [NSLocalizedDescriptionKey: \"Unknown opcode: \\(opByte)\"])"
                        )
                    }
                    swiftSwitch("opCode") {
                        for (op in schema.operations) {
                            val swiftCase = toCamelCase(op.name)
                            swiftCase("case .$swiftCase") {
                                if (op.id == 0) {
                                    line(
                                        "throw NSError(domain: \"RemoteDocument\", code: 2, userInfo: [NSLocalizedDescriptionKey: \"Unexpected Header opcode inside document body\"])"
                                    )
                                } else if (op.conditionalSkip != null) {
                                    block("if evaluateSkip", close = null) {
                                        line(
                                            "doc.operations.append(try ${op.name}.readForPlayer(from: &buffer, playerApiLevel: playerApiLevel, playerProfiles: playerProfiles))"
                                        )
                                    }
                                    block("} else") {
                                        line(
                                            "doc.operations.append(try ${op.name}.read(from: &buffer))"
                                        )
                                    }
                                } else {
                                    line(
                                        "doc.operations.append(try ${op.name}.read(from: &buffer))"
                                    )
                                }
                            }
                        }
                    }
                }
                line("return doc")
            }
            line()
            line("/// Serializes this document to raw binary data.")
            block("public func save() throws -> Data") {
                line("var buffer = WireBuffer()")
                line("buffer.writeByte(OpCode.header.rawValue)")
                line("buffer.writeInt(majorVersion)")
                line("buffer.writeInt(minorVersion)")
                line("buffer.writeInt(patchVersion)")
                line("buffer.writeInt(width)")
                line("buffer.writeInt(height)")
                line("buffer.writeLong(capabilities)")
                line()
                block("for op in operations") { line("try op.write(to: &buffer)") }
                line("return buffer.data")
            }
        }
    }

    private fun emitAuxStruct(w: CodeWriter, structDef: SchemaStruct) {
        val props = structDef.astProperties
        val desc = structDef.description.replace("\n", " ").trim()
        if (desc.isNotEmpty()) {
            w.line("/// $desc")
        }
        w.block("public struct ${structDef.name}: Equatable") {
            multiLang.emitSwiftOpEnumConstants(this, structDef.fields)
            for (prop in props) {
                val swiftType = mapToSwiftType(prop.type, prop.isNullable)
                val fieldDesc = prop.description.replace("\n", " ").trim()
                if (fieldDesc.isNotEmpty()) {
                    line("/// $fieldDesc")
                }
                line("public var ${prop.name}: $swiftType")
            }
            val structByteOrShort =
                structDef.fields
                    .filter { it.type == "byte" || it.type == "short" }
                    .map { it.name }
                    .toSet()
            val structNullable = props.filter { it.isNullable }.map { it.name }.toSet()
            for ((fieldName, bit) in structDef.computedBitProperties) {
                if (fieldName in structNullable) {
                    val srcExpr = if (fieldName in structByteOrShort) "Int32(\$0)" else "\$0"
                    block("public var ${bit.name}: Int32?") {
                        line(
                            "return $fieldName.map { ${CodegenExprUtils.extractBitExpr(srcExpr, bit, ExprLang.SWIFT)} }"
                        )
                    }
                } else {
                    val srcExpr =
                        if (fieldName in structByteOrShort) "Int32($fieldName)" else fieldName
                    block("public var ${bit.name}: Int32") {
                        line(
                            "return ${CodegenExprUtils.extractBitExpr(srcExpr, bit, ExprLang.SWIFT)}"
                        )
                    }
                }
            }
            line()

            val params =
                props.joinToString(", ") {
                    "${it.name}: ${mapToSwiftType(it.type, it.isNullable)} = ${mapToSwiftDefault(it.type, it.isNullable, it.defaultValue)}"
                }
            block("public init($params)") {
                for (prop in props) {
                    line("self.${prop.name} = ${prop.name}")
                }
            }
            line()

            block(
                "public static func read(from buffer: inout WireBuffer) throws -> ${structDef.name}"
            ) {
                emitSwiftReadBody(this, structDef.name, structDef.fields, null, props)
            }
            line()

            block("public func write(to buffer: inout WireBuffer) throws") {
                emitSwiftWriteBody(this, structDef.name, structDef.fields, null, props)
            }
        }
    }

    private fun emitStruct(w: CodeWriter, op: SchemaOperation) {
        val props = op.astProperties
        val desc = op.description.replace("\n", " ").trim()
        if (desc.isNotEmpty()) {
            w.line("/// $desc")
        }
        val swiftCase = toCamelCase(op.name)
        w.block("public struct ${op.name}: RemoteOperation, Equatable") {
            line("public let opCode: OpCode = .$swiftCase")
            multiLang.emitSwiftOpEnumConstants(this, op.fields)
            line()

            for (prop in props) {
                val swiftType = mapToSwiftType(prop.type, prop.isNullable)
                val fieldDesc = prop.description.replace("\n", " ").trim()
                if (fieldDesc.isNotEmpty()) {
                    line("/// $fieldDesc")
                }
                line("public var ${prop.name}: $swiftType")
            }
            val opByteOrShort =
                op.fields.filter { it.type == "byte" || it.type == "short" }.map { it.name }.toSet()
            val opNullable = props.filter { it.isNullable }.map { it.name }.toSet()
            for ((fieldName, bit) in op.computedBitProperties) {
                if (fieldName in opNullable) {
                    val srcExpr = if (fieldName in opByteOrShort) "Int32(\$0)" else "\$0"
                    block("public var ${bit.name}: Int32?") {
                        line(
                            "return $fieldName.map { ${CodegenExprUtils.extractBitExpr(srcExpr, bit, ExprLang.SWIFT)} }"
                        )
                    }
                } else {
                    val srcExpr = if (fieldName in opByteOrShort) "Int32($fieldName)" else fieldName
                    block("public var ${bit.name}: Int32") {
                        line(
                            "return ${CodegenExprUtils.extractBitExpr(srcExpr, bit, ExprLang.SWIFT)}"
                        )
                    }
                }
            }
            multiLang.emitSwiftOpExtras(this, op)
            line()

            val params =
                props.joinToString(", ") {
                    "${it.name}: ${mapToSwiftType(it.type, it.isNullable)} = ${mapToSwiftDefault(it.type, it.isNullable, it.defaultValue)}"
                }
            line("/// Creates a new [${op.name}] operation.")
            if (props.isNotEmpty()) {
                line("/// - Parameters:")
                for (prop in props) {
                    val fieldDesc = prop.description.replace("\n", " ").trim()
                    line("///   - ${prop.name}: $fieldDesc")
                }
            }
            block("public init($params)") {
                for (prop in props) {
                    line("self.${prop.name} = ${prop.name}")
                }
            }
            line()

            line("/// Reads and decodes a [${op.name}] from the wire buffer.")
            block("public static func read(from buffer: inout WireBuffer) throws -> ${op.name}") {
                if (op.conditionalSkip != null) {
                    line("let skipTaken = true")
                }
                emitSwiftReadBody(
                    this,
                    op.name,
                    op.fields,
                    op.sparseParameters,
                    props,
                    op.sparseCountType,
                    op.sparseKeyType,
                )
            }
            line()

            if (op.conditionalSkip != null) {
                val cs = op.conditionalSkip
                val condExpr =
                    CodegenExprUtils.extractSkipConditionExpr(cs, cs.conditionField, ExprLang.SWIFT)
                block(
                    "public static func shouldSkip(${cs.conditionField}: Int32, ${cs.valueField}: Int32, playerApiLevel: Int32, playerProfiles: Int32) -> Bool"
                ) {
                    swiftSwitch(condExpr) {
                        for (b in cs.conditions) {
                            val brExpr =
                                CodegenExprUtils.evaluateSkipBranchExpr(
                                    b,
                                    cs.valueField,
                                    "playerApiLevel",
                                    "playerProfiles",
                                    ExprLang.SWIFT,
                                )
                            line("case ${b.whenValue}: return $brExpr")
                        }
                        line("default: return ${cs.unknownConditionSkips}")
                    }
                }
                line()
                block(
                    "public static func readForPlayer(from buffer: inout WireBuffer, playerApiLevel: Int32, playerProfiles: Int32 = 0) throws -> ${op.name}"
                ) {
                    emitSwiftReadBody(
                        this,
                        op.name,
                        op.fields,
                        op.sparseParameters,
                        props,
                        op.sparseCountType,
                        op.sparseKeyType,
                        conditionalSkip = cs,
                    )
                }
                line()
            }

            line("/// Serializes this operation to the wire buffer.")
            block("public func write(to buffer: inout WireBuffer) throws") {
                line("buffer.writeByte(opCode.rawValue)")
                emitSwiftWriteBody(
                    this,
                    op.name,
                    op.fields,
                    op.sparseParameters,
                    props,
                    op.sparseCountType,
                    op.sparseKeyType,
                    op.conditionalSkip,
                )
            }
        }
    }

    private fun hasSwiftScalarValidations(f: SchemaField): Boolean {
        if (f.minValue != null) return true
        if (f.mustBeZeroBits != null) return true
        if (f.strictEnum && !f.enumValues.isNullOrEmpty()) return true
        val bits = f.bits
        return bits != null &&
            !f.unpackBits &&
            bits.any { it.strictEnum && !it.enumValues.isNullOrEmpty() }
    }

    private fun emitSwiftScalarValidations(
        w: CodeWriter,
        ownerName: String,
        f: SchemaField,
        varExpr: String,
    ) {
        val intExpr = if (f.type == "byte" || f.type == "short") "Int32($varExpr)" else varExpr
        if (f.minValue != null) {
            w.block("guard $intExpr >= ${f.minValue} else") {
                line(
                    "throw NSError(domain: \"$ownerName\", code: 2, userInfo: [NSLocalizedDescriptionKey: \"Invalid ${f.name} below minimum (${f.minValue})\"])"
                )
            }
        }
        if (f.mustBeZeroBits != null) {
            val badBits =
                CodegenExprUtils.nonZeroBitsCheckExpr(
                    intExpr,
                    f.mustBeZeroBits,
                    ExprLang.SWIFT,
                )
            w.block("if $badBits") {
                line(
                    "throw NSError(domain: \"$ownerName\", code: 2, userInfo: [NSLocalizedDescriptionKey: \"Non-zero reserved bits in ${f.name}\"])"
                )
            }
        }
        emitSwiftStrictEnumCheck(w, ownerName, f.name, varExpr, f.strictEnum, f.enumValues)
        val bits = f.bits
        if (bits != null && !f.unpackBits) {
            for (b in bits) {
                if (b.strictEnum && !b.enumValues.isNullOrEmpty()) {
                    val bVar = "bit_${b.name}"
                    val extract = CodegenExprUtils.extractBitExpr(intExpr, b, ExprLang.SWIFT)
                    w.line("let $bVar = $extract")
                    emitSwiftStrictEnumCheck(
                        w,
                        ownerName,
                        b.name,
                        bVar,
                        b.strictEnum,
                        b.enumValues,
                    )
                }
            }
        }
    }

    private fun emitSwiftReadBody(
        w: CodeWriter,
        ownerName: String,
        fields: List<SchemaField>,
        sparseParameters: List<SchemaSparseParam>?,
        props: List<AstProperty>,
        sparseCountType: String? = null,
        sparseKeyType: String? = null,
        conditionalSkip: SchemaConditionalSkip? = null,
    ) {
        for (f in fields) {
            if (conditionalSkip != null && f.name == conditionalSkip.payloadField) {
                w.line(
                    "let skipTaken = shouldSkip(${conditionalSkip.conditionField}: ${conditionalSkip.conditionField}, ${conditionalSkip.valueField}: ${conditionalSkip.valueField}, playerApiLevel: playerApiLevel, playerProfiles: playerProfiles)"
                )
            }
            val bits = f.bits
            if (bits != null && f.unpackBits) {
                val rawVar = "raw_${f.name}"
                w.line("let $rawVar = try buffer.readInt()")
                if (f.mustBeZeroBits != null) {
                    val badBits =
                        CodegenExprUtils.nonZeroBitsCheckExpr(
                            rawVar,
                            f.mustBeZeroBits,
                            ExprLang.SWIFT,
                        )
                    w.block("if $badBits") {
                        line(
                            "throw NSError(domain: \"$ownerName\", code: 2, userInfo: [NSLocalizedDescriptionKey: \"Non-zero reserved bits in ${f.name}\"])"
                        )
                    }
                }
                for (b in bits) {
                    w.line(
                        "let ${b.name} = ${CodegenExprUtils.extractBitExpr(rawVar, b, ExprLang.SWIFT)}"
                    )
                    emitSwiftStrictEnumCheck(
                        w,
                        ownerName,
                        b.name,
                        b.name,
                        b.strictEnum,
                        b.enumValues,
                    )
                }
                continue
            }

            val isLocalDerived = f.derivedFrom != null
            val isNullable =
                !isLocalDerived &&
                    f.presentIf != null &&
                    !f.type.endsWith("[]") &&
                    f.defaultValue == null

            if (f.presentIf != null) {
                val cond = CodegenExprUtils.translateCondition(f.presentIf, ExprLang.SWIFT) { it }
                val swiftType = mapToSwiftType(f.type, isNullable)
                w.line("let ${f.name}: $swiftType")
                w.block("if $cond", close = null) {
                    if (f.type.endsWith("[]")) {
                        emitSwiftArrayRead(this, ownerName, f, "${f.name}Tmp")
                        line("${f.name} = ${f.name}Tmp")
                    } else if (hasSwiftScalarValidations(f)) {
                        line("let parsed = try ${mapToSwiftFieldReadExpr(f)}")
                        emitSwiftScalarValidations(this, ownerName, f, "parsed")
                        line("${f.name} = parsed")
                    } else {
                        line("${f.name} = try ${mapToSwiftFieldReadExpr(f)}")
                    }
                }
                w.block("} else") {
                    line("${f.name} = ${mapToSwiftDefault(f.type, isNullable, f.defaultValue)}")
                }
            } else if (f.type.endsWith("[]")) {
                emitSwiftArrayRead(w, ownerName, f, f.name)
            } else {
                w.line("let ${f.name} = try ${mapToSwiftFieldReadExpr(f)}")
                emitSwiftScalarValidations(w, ownerName, f, f.name)
            }
        }

        if (sparseParameters != null) {
            for (sp in sparseParameters) {
                w.line("var ${sp.name}: ${mapToSwiftType(sp.type, true)} = nil")
            }
            val effectiveCountType = sparseCountType ?: "ushort"
            val effectiveKeyType = sparseKeyType ?: "ubyte"
            when (effectiveCountType) {
                "int" -> {
                    w.line("let sparseCount = Int(try buffer.readInt())")
                    w.block("guard sparseCount >= 0 else") {
                        line(
                            "throw NSError(domain: \"$ownerName\", code: 1, userInfo: [NSLocalizedDescriptionKey: \"Invalid negative sparse parameter count\"])"
                        )
                    }
                }
                "short" -> {
                    w.line("let sparseCount = Int(try buffer.readShort())")
                    w.block("guard sparseCount >= 0 else") {
                        line(
                            "throw NSError(domain: \"$ownerName\", code: 1, userInfo: [NSLocalizedDescriptionKey: \"Invalid negative sparse parameter count\"])"
                        )
                    }
                }
                "byte" -> {
                    w.line("let sparseCount = Int(Int8(bitPattern: try buffer.readByte()))")
                    w.block("guard sparseCount >= 0 else") {
                        line(
                            "throw NSError(domain: \"$ownerName\", code: 1, userInfo: [NSLocalizedDescriptionKey: \"Invalid negative sparse parameter count\"])"
                        )
                    }
                }
                "ubyte" -> w.line("let sparseCount = Int(try buffer.readByte())")
                else -> w.line("let sparseCount = Int(UInt16(bitPattern: try buffer.readShort()))")
            }
            val minEntryBytes =
                when (effectiveKeyType) {
                    "int" -> 5
                    "short",
                    "ushort" -> 3
                    else -> 2
                }
            w.block("guard sparseCount <= buffer.remaining / $minEntryBytes else") {
                line(
                    "throw NSError(domain: \"$ownerName\", code: 1, userInfo: [NSLocalizedDescriptionKey: \"Sparse parameter count exceeds remaining buffer\"])"
                )
            }
            w.block("for _ in 0..<sparseCount") {
                when (effectiveKeyType) {
                    "int" -> line("let paramId = Int(try buffer.readInt())")
                    "ushort" ->
                        line("let paramId = Int(UInt16(bitPattern: try buffer.readShort()))")
                    "short" -> line("let paramId = Int(try buffer.readShort())")
                    "byte" -> line("let paramId = Int(Int8(bitPattern: try buffer.readByte()))")
                    else -> line("let paramId = Int(try buffer.readByte())")
                }
                swiftSwitch("paramId") {
                    for (sp in sparseParameters) {
                        swiftCase("case ${sp.id}") {
                            if (sp.type.endsWith("[]")) {
                                val synField =
                                    SchemaField(
                                        name = sp.name,
                                        type = sp.type,
                                        description = sp.description,
                                        enumValues = null,
                                        lengthType = sp.lengthType ?: "ushort",
                                    )
                                emitSwiftArrayRead(this, ownerName, synField, "${sp.name}Tmp")
                                line("${sp.name} = ${sp.name}Tmp")
                            } else {
                                line("${sp.name} = try ${mapToSwiftReadExpr(sp.type)}")
                            }
                        }
                    }
                    swiftCase("default") {
                        line(
                            "throw NSError(domain: \"$ownerName\", code: 2, userInfo: [NSLocalizedDescriptionKey: \"Unknown sparse parameter\"])"
                        )
                    }
                }
            }
        }

        val args = props.joinToString(", ") { "${it.name}: ${it.name}" }
        w.line("return $ownerName($args)")
    }

    private fun emitSwiftStrictEnumCheck(
        w: CodeWriter,
        ownerName: String,
        fieldName: String,
        varExpr: String,
        strictEnum: Boolean,
        enumValues: Map<String, Int>?,
    ) {
        if (strictEnum && !enumValues.isNullOrEmpty()) {
            val allowed = enumValues.values.distinct().sorted().joinToString(", ")
            w.swiftSwitch(varExpr) {
                swiftCase("case $allowed") { line("break") }
                swiftCase("default") {
                    line(
                        "throw NSError(domain: \"$ownerName\", code: 2, userInfo: [NSLocalizedDescriptionKey: \"Invalid enum value for $fieldName\"])"
                    )
                }
            }
        }
    }

    private fun emitSwiftArrayRead(
        w: CodeWriter,
        ownerName: String,
        f: SchemaField,
        targetVar: String,
    ) {
        val lenVar = "_${f.name}Count"
        if (f.countFrom != null) {
            w.line("let $lenVar = Int(${f.countFrom})")
        } else {
            when (f.effectiveLengthType) {
                "int" -> w.line("let $lenVar = Int(try buffer.readInt())")
                "ushort" -> w.line("let $lenVar = Int(UInt16(bitPattern: try buffer.readShort()))")
                "ubyte" -> w.line("let $lenVar = Int(try buffer.readByte())")
                "byte" -> w.line("let $lenVar = Int(Int8(bitPattern: try buffer.readByte()))")
                else -> w.line("let $lenVar = Int(try buffer.readShort())")
            }
        }
        val elemType = f.type.removeSuffix("[]")
        val elemMinBytes = CodegenExprUtils.minWireElementBytes(elemType, schema)
        w.block("guard $lenVar >= 0 else") {
            line(
                "throw NSError(domain: \"$ownerName\", code: 1, userInfo: [NSLocalizedDescriptionKey: \"Invalid negative array length\"])"
            )
        }
        if (f.minLength != null && f.minLength > 0) {
            w.block("guard $lenVar >= ${f.minLength} else") {
                line(
                    "throw NSError(domain: \"$ownerName\", code: 1, userInfo: [NSLocalizedDescriptionKey: \"Array length below minimum (${f.minLength})\"])"
                )
            }
        }
        if (f.maxLength != null) {
            w.block("guard $lenVar <= ${f.maxLength} else") {
                line(
                    "throw NSError(domain: \"$ownerName\", code: 1, userInfo: [NSLocalizedDescriptionKey: \"Array length exceeds maximum (${f.maxLength})\"])"
                )
            }
        }
        w.block("guard $lenVar <= buffer.remaining / $elemMinBytes else") {
            line(
                "throw NSError(domain: \"$ownerName\", code: 1, userInfo: [NSLocalizedDescriptionKey: \"Array length exceeds remaining buffer\"])"
            )
        }
        val swiftElemType = mapToSwiftType(elemType, false)
        w.line("var $targetVar = [$swiftElemType]()")
        w.line("$targetVar.reserveCapacity(min($lenVar, 4096))")
        w.block("for _ in 0..<$lenVar") {
            line("$targetVar.append(try ${mapToSwiftReadExpr(elemType)})")
        }
    }

    private fun emitSwiftWriteBody(
        w: CodeWriter,
        ownerName: String,
        fields: List<SchemaField>,
        sparseParameters: List<SchemaSparseParam>?,
        props: List<AstProperty>,
        sparseCountType: String? = null,
        sparseKeyType: String? = null,
        conditionalSkip: SchemaConditionalSkip? = null,
    ) {
        val propByName = props.associateBy { it.name }
        val localVars = mutableSetOf<String>()

        for (f in fields) {
            val bits = f.bits
            if (bits != null && f.unpackBits) {
                val terms = mutableListOf<Pair<String, SchemaBitField>>()
                for (b in bits) {
                    if (b.derivedFrom != null) {
                        val expr = derivedExprToSwift(DerivedExpr.parse(b.derivedFrom))
                        w.line("let ${b.name}: Int32 = $expr")
                        localVars.add(b.name)
                        terms.add(b.name to b)
                    } else {
                        terms.add(b.name to b)
                    }
                }
                val packed = CodegenExprUtils.packBitsExpr(terms, ExprLang.SWIFT)
                w.line("buffer.writeInt($packed)")
                continue
            }

            if (f.derivedFrom != null) {
                val expr = derivedExprToSwift(DerivedExpr.parse(f.derivedFrom))
                if (f.presentIf != null) {
                    val cond =
                        CodegenExprUtils.translateCondition(f.presentIf, ExprLang.SWIFT) { it }
                    w.block("if $cond") { line(mapToSwiftDerivedWrite(f.type, expr)) }
                } else {
                    w.line("let ${f.name}: Int32 = $expr")
                    localVars.add(f.name)
                    w.line(mapToSwiftDerivedWrite(f.type, f.name))
                }
                continue
            }

            val isNullable = propByName[f.name]?.isNullable == true
            if (conditionalSkip != null && f.name == conditionalSkip.lengthField) {
                w.line(
                    "buffer.writeInt(${conditionalSkip.payloadField} != nil ? Int32(${conditionalSkip.payloadField}!.count) : ${f.name})"
                )
                continue
            }
            if (conditionalSkip != null && f.name == conditionalSkip.payloadField) {
                w.block("if let val = ${f.name}") { line("buffer.writeBytes(val)") }
                continue
            }
            if (f.presentIf != null) {
                val cond = CodegenExprUtils.translateCondition(f.presentIf, ExprLang.SWIFT) { it }
                w.block("if $cond") {
                    if (isNullable) {
                        block("guard let val = ${f.name} else") {
                            line(
                                "throw NSError(domain: \"$ownerName\", code: 3, userInfo: [NSLocalizedDescriptionKey: \"Missing required field ${f.name}\"])"
                            )
                        }
                        emitSwiftFieldWrite(this, f, "val")
                    } else {
                        emitSwiftFieldWrite(this, f, f.name)
                    }
                }
            } else {
                emitSwiftFieldWrite(w, f, f.name)
            }
        }

        if (sparseParameters != null) {
            w.line("var sparseCount: Int32 = 0")
            for (sp in sparseParameters) {
                w.line("if ${sp.name} != nil { sparseCount += 1 }")
            }
            when (sparseCountType ?: "ushort") {
                "int" -> w.line("buffer.writeInt(sparseCount)")
                "ubyte",
                "byte" -> w.line("buffer.writeByte(UInt8(truncatingIfNeeded: sparseCount))")
                else -> w.line("buffer.writeShort(Int16(truncatingIfNeeded: sparseCount))")
            }
            val effectiveKeyType = sparseKeyType ?: "ubyte"
            for (sp in sparseParameters) {
                w.block("if let val = ${sp.name}") {
                    when (effectiveKeyType) {
                        "int" -> line("buffer.writeInt(${sp.id})")
                        "ushort",
                        "short" -> line("buffer.writeShort(Int16(truncatingIfNeeded: ${sp.id}))")
                        else -> line("buffer.writeByte(UInt8(truncatingIfNeeded: ${sp.id}))")
                    }
                    val synField =
                        SchemaField(
                            name = sp.name,
                            type = sp.type,
                            description = sp.description,
                            enumValues = null,
                            lengthType = sp.lengthType ?: "ushort",
                        )
                    emitSwiftFieldWrite(this, synField, "val")
                }
            }
        }
    }

    private fun emitSwiftFieldWrite(w: CodeWriter, f: SchemaField, varExpr: String) {
        if (f.type.endsWith("[]")) {
            if (f.countFrom == null) {
                when (f.effectiveLengthType) {
                    "int" -> w.line("buffer.writeInt(Int32($varExpr.count))")
                    "ubyte",
                    "byte" -> w.line("buffer.writeByte(UInt8(truncatingIfNeeded: $varExpr.count))")
                    else -> w.line("buffer.writeShort(Int16(truncatingIfNeeded: $varExpr.count))")
                }
            }
            val elemType = f.type.removeSuffix("[]")
            w.block("for item in $varExpr") { line(mapToSwiftWriteExpr(elemType, "item")) }
        } else if (f.type == "bytes" && f.countFrom != null) {
            w.line("buffer.writeBytes($varExpr)")
        } else {
            w.line(mapToSwiftWriteExpr(f.type, varExpr))
        }
    }

    private fun mapToSwiftFieldReadExpr(f: SchemaField): String {
        if (f.type == "bytes" && f.countFrom != null) {
            return "buffer.readBytes(count: Int(${f.countFrom}))"
        }
        return mapToSwiftReadExpr(f.type, f.maxLength)
    }

    private inline fun CodeWriter.swiftSwitch(expr: String, body: CodeWriter.() -> Unit) {
        line("switch $expr {")
        body()
        line("}")
    }

    private inline fun CodeWriter.swiftCase(label: String, body: CodeWriter.() -> Unit) {
        line("$label:")
        indent(body)
    }

    private fun derivedExprToSwift(expr: DerivedExpr): String {
        val target = expr.targetName
        return when (expr) {
            is DerivedExpr.LengthOf -> "Int32($target.count)"
            is DerivedExpr.PresentOf -> "($target != nil ? 1 : 0)"
            is DerivedExpr.NonEmptyOf -> "(!$target.isEmpty ? 1 : 0)"
        }
    }

    private fun mapToSwiftDerivedWrite(type: String, int32Expr: String): String =
        when (type) {
            "short" -> "buffer.writeShort(Int16(truncatingIfNeeded: $int32Expr))"
            "byte" -> "buffer.writeByte(UInt8(truncatingIfNeeded: $int32Expr))"
            else -> "buffer.writeInt($int32Expr)"
        }

    private fun mapToSwiftType(type: String, isNullable: Boolean): String {
        val base =
            if (type.endsWith("[]")) {
                "[${mapToSwiftType(type.removeSuffix("[]"), false)}]"
            } else {
                when (type) {
                    "int",
                    "int_id",
                    "color" -> "Int32"
                    "short" -> "Int16"
                    "byte" -> "UInt8"
                    "long" -> "Int64"
                    "float",
                    "float_or_id" -> "Float"
                    "boolean" -> "Bool"
                    "string" -> "String"
                    "bytes" -> "Data"
                    else -> if (schema.structs.containsKey(type)) type else "Int32"
                }
            }
        return if (isNullable) "$base?" else base
    }

    private fun mapToSwiftDefault(
        type: String,
        isNullable: Boolean,
        explicitDefault: String?,
    ): String {
        if (isNullable) return "nil"
        if (explicitDefault != null) {
            return when (type) {
                "float",
                "float_or_id" ->
                    if (explicitDefault.contains('.')) explicitDefault else "$explicitDefault.0"
                else -> explicitDefault
            }
        }
        if (type.endsWith("[]")) return "[]"
        return when (type) {
            "int",
            "int_id",
            "color",
            "short",
            "byte" -> "0"
            "long" -> "0"
            "float",
            "float_or_id" -> "0.0"
            "boolean" -> "false"
            "string" -> "\"\""
            "bytes" -> "Data()"
            else -> if (schema.structs.containsKey(type)) "$type()" else "0"
        }
    }

    private fun mapToSwiftReadExpr(type: String, maxLength: Int? = null): String =
        when (type) {
            "int",
            "int_id",
            "color" -> "buffer.readInt()"
            "short" -> "buffer.readShort()"
            "byte" -> "buffer.readByte()"
            "long" -> "buffer.readLong()"
            "float",
            "float_or_id" -> "buffer.readFloat()"
            "boolean" -> "buffer.readBoolean()"
            "string" ->
                if (maxLength != null) "buffer.readUTF8(maxLength: $maxLength)"
                else "buffer.readUTF8()"
            "bytes" ->
                if (maxLength != null) "buffer.readBuffer(maxLength: $maxLength)"
                else "buffer.readBuffer()"
            else ->
                if (schema.structs.containsKey(type)) "$type.read(from: &buffer)"
                else "buffer.readInt()"
        }

    private fun mapToSwiftWriteExpr(type: String, varName: String): String =
        when (type) {
            "int",
            "int_id",
            "color" -> "buffer.writeInt($varName)"
            "short" -> "buffer.writeShort($varName)"
            "byte" -> "buffer.writeByte($varName)"
            "long" -> "buffer.writeLong($varName)"
            "float",
            "float_or_id" -> "buffer.writeFloat($varName)"
            "boolean" -> "buffer.writeBoolean($varName)"
            "string" -> "buffer.writeUTF8($varName)"
            "bytes" -> "buffer.writeBuffer($varName)"
            else ->
                if (schema.structs.containsKey(type)) "try $varName.write(to: &buffer)"
                else "buffer.writeInt($varName)"
        }

    companion object {
        fun toCamelCase(name: String): String = name.replaceFirstChar { it.lowercaseChar() }
    }
}
