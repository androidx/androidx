/**
 * Generator that transforms an [OperationSchema] into idiomatic Swift bindings:
 * - OpCode enum with UInt8 raw values
 * - RemoteOperation protocol
 * - Auxiliary structs and typed structs for each operation with WireBuffer read/write methods
 * - RemoteDocument container and WireBuffer implementation
 */
internal class SwiftGenerator(private val schema: OperationSchema) {

    fun generate(): String {
        val sb = StringBuilder()
        sb.append(
            """
            // Generated by RemoteCompose Schema Codegen. DO NOT EDIT.
            import Foundation

            /// Operation wire identifiers for RemoteCompose.
            public enum OpCode: UInt8, CaseIterable {
            """
                .trimIndent()
        )
        sb.append("\n")

        for (op in schema.operations) {
            val swiftCase = toCamelCase(op.name)
            val desc = op.description.replace("\n", " ").trim()
            if (desc.isNotEmpty()) {
                sb.append("    /// $desc\n")
            }
            sb.append("    case $swiftCase = ${op.id}\n")
        }

        sb.append(
            """
            }

            /// Protocol adopted by all RemoteCompose operation types.
            public protocol RemoteOperation {
                var opCode: OpCode { get }
                func write(to buffer: inout WireBuffer)
            }

            public struct WireBuffer {
                public private(set) var data: Data
                public private(set) var index: Int = 0

                public init(data: Data = Data()) {
                    self.data = data.startIndex == 0 ? data : Data(data)
                    self.index = 0
                }

                public var remaining: Int {
                    return max(0, data.count - index)
                }

                public var available: Bool {
                    return index < data.count
                }

                public mutating func setIndex(_ newIndex: Int) throws {
                    guard newIndex >= 0 && newIndex <= data.count else {
                        throw NSError(domain: "WireBuffer", code: 2, userInfo: [NSLocalizedDescriptionKey: "Index out of bounds: \(newIndex)"])
                    }
                    index = newIndex
                }

                public mutating func skipBytes(_ count: Int) throws {
                    guard count >= 0 else {
                        throw NSError(domain: "WireBuffer", code: 3, userInfo: [NSLocalizedDescriptionKey: "Invalid negative skip length"])
                    }
                    guard count <= remaining else {
                        throw NSError(domain: "WireBuffer", code: 1, userInfo: [NSLocalizedDescriptionKey: "Underflow"])
                    }
                    index += count
                }

                public mutating func writeByte(_ value: UInt8) {
                    data.append(value)
                }

                public mutating func readByte() throws -> UInt8 {
                    guard 1 <= remaining else {
                        throw NSError(domain: "WireBuffer", code: 1, userInfo: [NSLocalizedDescriptionKey: "Underflow"])
                    }
                    let byte = data[index]
                    index += 1
                    return byte
                }

                public mutating func writeShort(_ value: Int16) {
                    var val = value.bigEndian
                    withUnsafeBytes(of: &val) { data.append(contentsOf: $0) }
                }

                public mutating func readShort() throws -> Int16 {
                    guard 2 <= remaining else {
                        throw NSError(domain: "WireBuffer", code: 1, userInfo: [NSLocalizedDescriptionKey: "Underflow"])
                    }
                    let bits = (UInt16(data[index]) << 8) | UInt16(data[index + 1])
                    index += 2
                    return Int16(bitPattern: bits)
                }

                public mutating func writeInt(_ value: Int32) {
                    var val = value.bigEndian
                    withUnsafeBytes(of: &val) { data.append(contentsOf: $0) }
                }

                public mutating func readInt() throws -> Int32 {
                    guard 4 <= remaining else {
                        throw NSError(domain: "WireBuffer", code: 1, userInfo: [NSLocalizedDescriptionKey: "Underflow"])
                    }
                    let bits = (UInt32(data[index]) << 24)
                        | (UInt32(data[index + 1]) << 16)
                        | (UInt32(data[index + 2]) << 8)
                        | UInt32(data[index + 3])
                    index += 4
                    return Int32(bitPattern: bits)
                }

                public mutating func writeLong(_ value: Int64) {
                    var val = value.bigEndian
                    withUnsafeBytes(of: &val) { data.append(contentsOf: $0) }
                }

                public mutating func readLong() throws -> Int64 {
                    guard 8 <= remaining else {
                        throw NSError(domain: "WireBuffer", code: 1, userInfo: [NSLocalizedDescriptionKey: "Underflow"])
                    }
                    var bits: UInt64 = 0
                    for i in 0..<8 {
                        bits = (bits << 8) | UInt64(data[index + i])
                    }
                    index += 8
                    return Int64(bitPattern: bits)
                }

                public mutating func writeFloat(_ value: Float) {
                    var bitVal = value.bitPattern.bigEndian
                    withUnsafeBytes(of: &bitVal) { data.append(contentsOf: $0) }
                }

                public mutating func readFloat() throws -> Float {
                    let bitVal = UInt32(bitPattern: try readInt())
                    return Float(bitPattern: bitVal)
                }

                public mutating func writeBoolean(_ value: Bool) {
                    writeByte(value ? 1 : 0)
                }

                public mutating func readBoolean() throws -> Bool {
                    return (try readByte()) != 0
                }

                public mutating func writeUTF8(_ value: String) {
                    let utf8Data = Data(value.utf8)
                    writeInt(Int32(utf8Data.count))
                    data.append(utf8Data)
                }

                public mutating func readUTF8(maxLength: Int? = nil) throws -> String {
                    let len = Int(try readInt())
                    guard len >= 0 else {
                        throw NSError(domain: "WireBuffer", code: 3, userInfo: [NSLocalizedDescriptionKey: "Invalid negative UTF-8 length"])
                    }
                    if let maxLen = maxLength, len > maxLen {
                        throw NSError(domain: "WireBuffer", code: 5, userInfo: [NSLocalizedDescriptionKey: "UTF-8 length exceeds maximum"])
                    }
                    guard len <= remaining else {
                        throw NSError(domain: "WireBuffer", code: 1, userInfo: [NSLocalizedDescriptionKey: "Underflow"])
                    }
                    let strData = data.subdata(in: index..<(index + len))
                    guard let str = String(data: strData, encoding: .utf8) else {
                        throw NSError(domain: "WireBuffer", code: 4, userInfo: [NSLocalizedDescriptionKey: "Invalid UTF-8 byte sequence"])
                    }
                    index += len
                    return str
                }

                public mutating func writeBuffer(_ value: Data) {
                    writeInt(Int32(value.count))
                    data.append(value)
                }

                public mutating func readBuffer(maxLength: Int? = nil) throws -> Data {
                    let len = Int(try readInt())
                    guard len >= 0 else {
                        throw NSError(domain: "WireBuffer", code: 3, userInfo: [NSLocalizedDescriptionKey: "Invalid negative buffer length"])
                    }
                    if let maxLen = maxLength, len > maxLen {
                        throw NSError(domain: "WireBuffer", code: 5, userInfo: [NSLocalizedDescriptionKey: "Buffer length exceeds maximum"])
                    }
                    guard len <= remaining else {
                        throw NSError(domain: "WireBuffer", code: 1, userInfo: [NSLocalizedDescriptionKey: "Underflow"])
                    }
                    let bufData = data.subdata(in: index..<(index + len))
                    index += len
                    return bufData
                }
            }

            """
                .trimIndent()
        )
        sb.append("\n\n")

        for ((_, structDef) in schema.structs) {
            sb.append(generateAuxStruct(structDef))
            sb.append("\n\n")
        }

        for (op in schema.operations) {
            sb.append(generateStruct(op))
            sb.append("\n\n")
        }

        sb.append(
            """
            /// In-memory representation of a RemoteCompose document.
            public struct RemoteDocument {
                public static let MAX_HEADER_PROPERTIES: Int = 1000
                public static let MAX_OPERATION_COUNT: Int = 100_000

                public var majorVersion: Int32 = 1
                public var minorVersion: Int32 = 1
                public var patchVersion: Int32 = 0
                public var width: Int32 = 0
                public var height: Int32 = 0
                public var capabilities: Int64 = 0
                public var operations: [RemoteOperation] = []

                public init() {}

                /// Deserializes a RemoteDocument from raw binary data.
                public static func load(from data: Data, maxOperations: Int = MAX_OPERATION_COUNT) throws -> RemoteDocument {
