                .trimIndent()
        )
        sb.append("\n")

        for (op in schema.operations) {
            val swiftCase = toCamelCase(op.name)
            sb.append("            case .$swiftCase:\n")
            if (op.id == 0) {
                sb.append(
                    "                throw NSError(domain: \"RemoteDocument\", code: 2, userInfo: [NSLocalizedDescriptionKey: \"Unexpected Header opcode inside document body\"])\n"
                )
            } else {
                sb.append(
                    "                doc.operations.append(try ${op.name}.read(from: &buffer))\n"
                )
            }
        }

        sb.append(
            """
                        }
                    }
                    return doc
                }

                /// Serializes this document to raw binary data.
                public func save() -> Data {
                    var buffer = WireBuffer()
                    buffer.writeByte(OpCode.header.rawValue)
                    buffer.writeInt(majorVersion)
                    buffer.writeInt(minorVersion)
                    buffer.writeInt(patchVersion)
                    buffer.writeInt(width)
                    buffer.writeInt(height)
                    buffer.writeLong(capabilities)

                    for op in operations {
                        op.write(to: &buffer)
                    }
                    return buffer.data
                }
            }
            """
                .trimIndent()
        )
        sb.append("\n")
        return sb.toString()
    }

    private fun generateAuxStruct(structDef: SchemaStruct): String {
        val sb = StringBuilder()
        val props = structDef.astProperties
        val desc = structDef.description.replace("\n", " ").trim()
        if (desc.isNotEmpty()) {
            sb.append("/// $desc\n")
        }
        sb.append("public struct ${structDef.name}: Equatable {\n")
        for (prop in props) {
            val swiftType = mapToSwiftType(prop.type, prop.isNullable)
            val fieldDesc = prop.description.replace("\n", " ").trim()
            if (fieldDesc.isNotEmpty()) {
                sb.append("    /// $fieldDesc\n")
            }
            sb.append("    public var ${prop.name}: $swiftType\n")
        }
        for ((fieldName, bit) in structDef.computedBitProperties) {
            sb.append("    public var ${bit.name}: Int32 {\n")
            sb.append(
                "        return ${CodegenExprUtils.extractBitExpr(fieldName, bit, ExprLang.SWIFT)}\n"
            )
            sb.append("    }\n")
        }
        sb.append("\n")

        val params =
            props.joinToString(", ") {
                "${it.name}: ${mapToSwiftType(it.type, it.isNullable)} = ${mapToSwiftDefault(it.type, it.isNullable, it.defaultValue)}"
            }
        sb.append("    public init($params) {\n")
        for (prop in props) {
            sb.append("        self.${prop.name} = ${prop.name}\n")
        }
        sb.append("    }\n\n")

        sb.append(
            "    public static func read(from buffer: inout WireBuffer) throws -> ${structDef.name} {\n"
        )
        appendSwiftReadBody(sb, structDef.name, structDef.fields, null, props)
        sb.append("    }\n\n")

        sb.append("    public func write(to buffer: inout WireBuffer) {\n")
        appendSwiftWriteBody(sb, structDef.fields, null, props)
        sb.append("    }\n")
        sb.append("}")
        return sb.toString()
    }

    private fun generateStruct(op: SchemaOperation): String {
        val sb = StringBuilder()
        val props = op.astProperties
        val desc = op.description.replace("\n", " ").trim()
        if (desc.isNotEmpty()) {
            sb.append("/// $desc\n")
        }
        val swiftCase = toCamelCase(op.name)
        sb.append("public struct ${op.name}: RemoteOperation, Equatable {\n")
        sb.append("    public let opCode: OpCode = .$swiftCase\n\n")

        for (prop in props) {
            val swiftType = mapToSwiftType(prop.type, prop.isNullable)
            val fieldDesc = prop.description.replace("\n", " ").trim()
            if (fieldDesc.isNotEmpty()) {
                sb.append("    /// $fieldDesc\n")
            }
            sb.append("    public var ${prop.name}: $swiftType\n")
        }
        for ((fieldName, bit) in op.computedBitProperties) {
            sb.append("    public var ${bit.name}: Int32 {\n")
            sb.append(
                "        return ${CodegenExprUtils.extractBitExpr(fieldName, bit, ExprLang.SWIFT)}\n"
            )
            sb.append("    }\n")
        }
        sb.append("\n")

        val params =
            props.joinToString(", ") {
                "${it.name}: ${mapToSwiftType(it.type, it.isNullable)} = ${mapToSwiftDefault(it.type, it.isNullable, it.defaultValue)}"
            }
        sb.append("    /// Creates a new [${op.name}] operation.\n")
        if (props.isNotEmpty()) {
            sb.append("    /// - Parameters:\n")
            for (prop in props) {
                val fieldDesc = prop.description.replace("\n", " ").trim()
                sb.append("    ///   - ${prop.name}: $fieldDesc\n")
            }
        }
        sb.append("    public init($params) {\n")
        for (prop in props) {
            sb.append("        self.${prop.name} = ${prop.name}\n")
        }
        sb.append("    }\n\n")

        sb.append("    /// Reads and decodes a [${op.name}] from the wire buffer.\n")
        sb.append(
            "    public static func read(from buffer: inout WireBuffer) throws -> ${op.name} {\n"
        )
        appendSwiftReadBody(sb, op.name, op.fields, op.sparseParameters, props)
        sb.append("    }\n\n")

        sb.append("    /// Serializes this operation to the wire buffer.\n")
        sb.append("    public func write(to buffer: inout WireBuffer) {\n")
        sb.append("        buffer.writeByte(opCode.rawValue)\n")
        appendSwiftWriteBody(sb, op.fields, op.sparseParameters, props)
        sb.append("    }\n")
        sb.append("}")
        return sb.toString()
    }

    private fun appendSwiftReadBody(
        sb: StringBuilder,
        ownerName: String,
        fields: List<SchemaField>,
        sparseParameters: List<SchemaSparseParam>?,
        props: List<AstProperty>,
    ) {
        for (f in fields) {
            val bits = f.bits
            if (bits != null && f.unpackBits) {
                val rawVar = "raw_${f.name}"
                sb.append("        let $rawVar = try buffer.readInt()\n")
                for (b in bits) {
                    sb.append(
                        "        let ${b.name} = ${CodegenExprUtils.extractBitExpr(rawVar, b, ExprLang.SWIFT)}\n"
                    )
                }
                continue
            }

            val isLocalDerived = f.derivedFrom != null
            val isNullable =
                !isLocalDerived &&
                    f.presentIf != null &&
                    !f.type.endsWith("[]") &&
                    f.defaultValue == null

            if (f.presentIf != null) {
                val cond = CodegenExprUtils.translateCondition(f.presentIf, ExprLang.SWIFT) { it }
                val swiftType = mapToSwiftType(f.type, isNullable)
                sb.append("        let ${f.name}: $swiftType\n")
                sb.append("        if $cond {\n")
                if (f.type.endsWith("[]")) {
                    appendSwiftArrayReadLines(sb, ownerName, f, "${f.name}Tmp", "            ")
                    sb.append("            ${f.name} = ${f.name}Tmp\n")
                } else {
                    sb.append(
                        "            ${f.name} = try ${mapToSwiftReadExpr(f.type, f.maxLength)}\n"
                    )
                    if (f.strictEnum && !f.enumValues.isNullOrEmpty()) {
                        val allowed = f.enumValues.values.distinct().sorted().joinToString(", ")
                        sb.append("            switch ${f.name} {\n")
                        sb.append("            case $allowed:\n")
                        sb.append("                break\n")
                        sb.append("            default:\n")
                        sb.append(
                            "                throw NSError(domain: \"$ownerName\", code: 2, userInfo: [NSLocalizedDescriptionKey: \"Invalid enum value for ${f.name}\"])\n"
                        )
                        sb.append("            }\n")
                    }
                }
                sb.append("        } else {\n")
                sb.append(
                    "            ${f.name} = ${mapToSwiftDefault(f.type, isNullable, f.defaultValue)}\n"
                )
                sb.append("        }\n")
            } else if (f.type.endsWith("[]")) {
                appendSwiftArrayReadLines(sb, ownerName, f, f.name, "        ")
            } else {
                sb.append(
                    "        let ${f.name} = try ${mapToSwiftReadExpr(f.type, f.maxLength)}\n"
                )
                if (f.strictEnum && !f.enumValues.isNullOrEmpty()) {
                    val allowed = f.enumValues.values.distinct().sorted().joinToString(", ")
                    sb.append("        switch ${f.name} {\n")
                    sb.append("        case $allowed:\n")
                    sb.append("            break\n")
                    sb.append("        default:\n")
                    sb.append(
                        "            throw NSError(domain: \"$ownerName\", code: 2, userInfo: [NSLocalizedDescriptionKey: \"Invalid enum value for ${f.name}\"])\n"
                    )
                    sb.append("        }\n")
                }
            }
        }

        if (sparseParameters != null) {
            for (sp in sparseParameters) {
                sb.append("        var ${sp.name}: ${mapToSwiftType(sp.type, true)} = nil\n")
            }
            sb.append("        let sparseCount = Int(UInt16(bitPattern: try buffer.readShort()))\n")
            sb.append("        guard sparseCount <= buffer.remaining / 2 else {\n")
            sb.append(
                "            throw NSError(domain: \"$ownerName\", code: 1, userInfo: [NSLocalizedDescriptionKey: \"Sparse parameter count exceeds remaining buffer\"])\n"
            )
            sb.append("        }\n")
            sb.append("        for _ in 0..<sparseCount {\n")
            sb.append("            let paramId = Int(try buffer.readByte())\n")
            sb.append("            switch paramId {\n")
            for (sp in sparseParameters) {
                sb.append("            case ${sp.id}:\n")
                if (sp.type.endsWith("[]")) {
                    val synField =
                        SchemaField(
                            name = sp.name,
                            type = sp.type,
                            description = sp.description,
                            enumValues = null,
                            lengthType = "ushort",
                        )
                    appendSwiftArrayReadLines(
                        sb,
                        ownerName,
                        synField,
                        "${sp.name}Tmp",
                        "                ",
                    )
                    sb.append("                ${sp.name} = ${sp.name}Tmp\n")
                } else {
                    sb.append("                ${sp.name} = try ${mapToSwiftReadExpr(sp.type)}\n")
                }
            }
            sb.append("            default:\n")
            sb.append(
                "                throw NSError(domain: \"$ownerName\", code: 2, userInfo: [NSLocalizedDescriptionKey: \"Unknown sparse parameter\"])\n"
            )
            sb.append("            }\n")
            sb.append("        }\n")
        }

        val args = props.joinToString(", ") { "${it.name}: ${it.name}" }
        sb.append("        return $ownerName($args)\n")
    }

    private fun appendSwiftArrayReadLines(
        sb: StringBuilder,
        ownerName: String,
        f: SchemaField,
        targetVar: String,
        indent: String,
    ) {
        val lenVar = "_${f.name}Count"
        if (f.countFrom != null) {
            sb.append("${indent}let $lenVar = Int(${f.countFrom})\n")
        } else {
            when (f.effectiveLengthType) {
                "int" -> sb.append("${indent}let $lenVar = Int(try buffer.readInt())\n")
                "ushort" ->
                    sb.append(
                        "${indent}let $lenVar = Int(UInt16(bitPattern: try buffer.readShort()))\n"
                    )
                else -> sb.append("${indent}let $lenVar = Int(try buffer.readShort())\n")
            }
        }
        val elemType = f.type.removeSuffix("[]")
        val elemMinBytes = CodegenExprUtils.minWireElementBytes(elemType, schema)
        sb.append("${indent}guard $lenVar >= 0 else {\n")
        sb.append(
            "$indent    throw NSError(domain: \"$ownerName\", code: 1, userInfo: [NSLocalizedDescriptionKey: \"Invalid negative array length\"])\n"
        )
        sb.append("$indent}\n")
        if (f.maxLength != null) {
            sb.append("${indent}guard $lenVar <= ${f.maxLength} else {\n")
            sb.append(
                "$indent    throw NSError(domain: \"$ownerName\", code: 1, userInfo: [NSLocalizedDescriptionKey: \"Array length exceeds maximum (${f.maxLength})\"])\n"
            )
            sb.append("$indent}\n")
        }
        sb.append("${indent}guard $lenVar <= buffer.remaining / $elemMinBytes else {\n")
        sb.append(
            "$indent    throw NSError(domain: \"$ownerName\", code: 1, userInfo: [NSLocalizedDescriptionKey: \"Array length exceeds remaining buffer\"])\n"
        )
        sb.append("$indent}\n")
        val swiftElemType = mapToSwiftType(elemType, false)
        sb.append("${indent}var $targetVar = [$swiftElemType]()\n")
        sb.append("${indent}$targetVar.reserveCapacity(min($lenVar, 4096))\n")
        sb.append("${indent}for _ in 0..<$lenVar {\n")
        sb.append("$indent    $targetVar.append(try ${mapToSwiftReadExpr(elemType)})\n")
        sb.append("$indent}\n")
    }

    private fun appendSwiftWriteBody(
        sb: StringBuilder,
        fields: List<SchemaField>,
        sparseParameters: List<SchemaSparseParam>?,
        props: List<AstProperty>,
    ) {
        val propByName = props.associateBy { it.name }
        val localVars = mutableSetOf<String>()

        for (f in fields) {
            val bits = f.bits
            if (bits != null && f.unpackBits) {
                val terms = mutableListOf<Pair<String, SchemaBitField>>()
                for (b in bits) {
                    if (b.derivedFrom != null) {
                        val expr = derivedExprToSwift(DerivedExpr.parse(b.derivedFrom))
                        sb.append("        let ${b.name}: Int32 = $expr\n")
                        localVars.add(b.name)
                        terms.add(b.name to b)
                    } else {
                        terms.add(b.name to b)
                    }
                }
                val packed = CodegenExprUtils.packBitsExpr(terms, ExprLang.SWIFT)
                sb.append("        buffer.writeInt($packed)\n")
                continue
            }

            if (f.derivedFrom != null) {
                val expr = derivedExprToSwift(DerivedExpr.parse(f.derivedFrom))
                if (f.presentIf != null) {
                    val cond =
                        CodegenExprUtils.translateCondition(f.presentIf, ExprLang.SWIFT) { it }
                    sb.append("        if $cond {\n")
                    sb.append("            ${mapToSwiftDerivedWrite(f.type, expr)}\n")
                    sb.append("        }\n")
                } else {
                    sb.append("        let ${f.name}: Int32 = $expr\n")
                    localVars.add(f.name)
                    sb.append("        ${mapToSwiftDerivedWrite(f.type, f.name)}\n")
                }
                continue
            }

            val isNullable = propByName[f.name]?.isNullable == true
            if (f.presentIf != null) {
                val cond = CodegenExprUtils.translateCondition(f.presentIf, ExprLang.SWIFT) { it }
                if (isNullable) {
                    sb.append("        if $cond, let val = ${f.name} {\n")
                    appendSwiftFieldWriteLines(sb, f, "val", "            ")
                    sb.append("        }\n")
                } else {
                    sb.append("        if $cond {\n")
                    appendSwiftFieldWriteLines(sb, f, f.name, "            ")
                    sb.append("        }\n")
                }
            } else {
                appendSwiftFieldWriteLines(sb, f, f.name, "        ")
            }
        }

        if (sparseParameters != null) {
            sb.append("        var sparseCount: Int16 = 0\n")
            for (sp in sparseParameters) {
                sb.append("        if ${sp.name} != nil { sparseCount += 1 }\n")
            }
            sb.append("        buffer.writeShort(sparseCount)\n")
            for (sp in sparseParameters) {
                sb.append("        if let val = ${sp.name} {\n")
                sb.append("            buffer.writeByte(${sp.id})\n")
                val synField =
                    SchemaField(
                        name = sp.name,
                        type = sp.type,
                        description = sp.description,
                        enumValues = null,
                        lengthType = "short",
                    )
                appendSwiftFieldWriteLines(sb, synField, "val", "            ")
                sb.append("        }\n")
            }
        }
    }

    private fun appendSwiftFieldWriteLines(
        sb: StringBuilder,
        f: SchemaField,
        varExpr: String,
        indent: String,
    ) {
        if (f.type.endsWith("[]")) {
            if (f.countFrom == null) {
                when (f.effectiveLengthType) {
                    "int" -> sb.append("${indent}buffer.writeInt(Int32($varExpr.count))\n")
                    else ->
                        sb.append(
                            "${indent}buffer.writeShort(Int16(truncatingIfNeeded: $varExpr.count))\n"
                        )
                }
            }
            val elemType = f.type.removeSuffix("[]")
            sb.append("${indent}for item in $varExpr {\n")
            sb.append("$indent    ${mapToSwiftWriteExpr(elemType, "item")}\n")
            sb.append("$indent}\n")
        } else {
            sb.append("$indent${mapToSwiftWriteExpr(f.type, varExpr)}\n")
        }
    }

    private fun derivedExprToSwift(expr: DerivedExpr): String {
        val target = expr.targetName
        return when (expr) {
            is DerivedExpr.LengthOf -> "Int32($target.count)"
            is DerivedExpr.PresentOf -> "($target != nil ? 1 : 0)"
            is DerivedExpr.NonEmptyOf -> "(!$target.isEmpty ? 1 : 0)"
        }
    }

    private fun mapToSwiftDerivedWrite(type: String, int32Expr: String): String =
        when (type) {
            "short" -> "buffer.writeShort(Int16(truncatingIfNeeded: $int32Expr))"
            "byte" -> "buffer.writeByte(UInt8(truncatingIfNeeded: $int32Expr))"
            else -> "buffer.writeInt($int32Expr)"
        }

    private fun mapToSwiftType(type: String, isNullable: Boolean): String {
        val base =
            if (type.endsWith("[]")) {
                "[${mapToSwiftType(type.removeSuffix("[]"), false)}]"
            } else {
                when (type) {
                    "int",
                    "color" -> "Int32"
                    "short" -> "Int16"
                    "byte" -> "UInt8"
                    "long" -> "Int64"
                    "float",
                    "float_or_id" -> "Float"
                    "boolean" -> "Bool"
                    "string" -> "String"
                    "bytes" -> "Data"
                    else -> if (schema.structs.containsKey(type)) type else "Int32"
                }
            }
        return if (isNullable) "$base?" else base
    }

    private fun mapToSwiftDefault(
        type: String,
        isNullable: Boolean,
        explicitDefault: String?,
    ): String {
        if (isNullable) return "nil"
        if (explicitDefault != null) {
            return when (type) {
                "float",
                "float_or_id" ->
                    if (explicitDefault.contains('.')) explicitDefault else "$explicitDefault.0"
                else -> explicitDefault
            }
        }
        if (type.endsWith("[]")) return "[]"
        return when (type) {
            "int",
            "color",
            "short",
            "byte" -> "0"
            "long" -> "0"
            "float",
            "float_or_id" -> "0.0"
            "boolean" -> "false"
            "string" -> "\"\""
            "bytes" -> "Data()"
            else -> if (schema.structs.containsKey(type)) "$type()" else "0"
        }
    }

    private fun mapToSwiftReadExpr(type: String, maxLength: Int? = null): String =
        when (type) {
            "int",
            "color" -> "buffer.readInt()"
            "short" -> "buffer.readShort()"
            "byte" -> "buffer.readByte()"
            "long" -> "buffer.readLong()"
            "float",
            "float_or_id" -> "buffer.readFloat()"
            "boolean" -> "buffer.readBoolean()"
            "string" ->
                if (maxLength != null) "buffer.readUTF8(maxLength: $maxLength)"
                else "buffer.readUTF8()"
            "bytes" ->
                if (maxLength != null) "buffer.readBuffer(maxLength: $maxLength)"
                else "buffer.readBuffer()"
            else ->
                if (schema.structs.containsKey(type)) "$type.read(from: &buffer)"
                else "buffer.readInt()"
        }

    private fun mapToSwiftWriteExpr(type: String, varName: String): String =
        when (type) {
            "int",
            "color" -> "buffer.writeInt($varName)"
            "short" -> "buffer.writeShort($varName)"
            "byte" -> "buffer.writeByte($varName)"
            "long" -> "buffer.writeLong($varName)"
            "float",
            "float_or_id" -> "buffer.writeFloat($varName)"
            "boolean" -> "buffer.writeBoolean($varName)"
            "string" -> "buffer.writeUTF8($varName)"
            "bytes" -> "buffer.writeBuffer($varName)"
            else ->
                if (schema.structs.containsKey(type)) "$varName.write(to: &buffer)"
                else "buffer.writeInt($varName)"
        }

    companion object {
        fun toCamelCase(name: String): String = name.replaceFirstChar { it.lowercaseChar() }
    }
}
