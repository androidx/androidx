                    var doc = RemoteDocument()
                    guard buffer.available else { return doc }

                    let headerOp = try buffer.readByte()
                    guard headerOp == OpCode.header.rawValue else {
                        throw NSError(domain: "RemoteDocument", code: 2, userInfo: [NSLocalizedDescriptionKey: "Expected header opcode"])
